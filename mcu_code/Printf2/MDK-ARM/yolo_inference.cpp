// n==6 补位这一轮的诊断。 只有本轮 ② 给出 6 个框时才有内容 (返回 11), 否则 0。
//   buf[0] = 6 (框数)          buf[1] = 1 走 A / 2 走 B / 0 没补
//   buf[2] = B 丢掉的框下标    buf[3] = 拟合 pitch x10
//   buf[4] = 最大残差 / pitch x100 (999 = 拟合退化)
//   buf[5..10] = 补位**之前**的 6 个框中心 (320 空间)
int yolo_cascade_ch6_diag(int* buf, int cap)
{
    // s_ch6_round != s_cas_round 说明这一轮在走到补位之前就返回了 (没框/② 没跑),
    // 此时 s_ch6_* 还是**上一轮**的数 —— 打印端会看到连着几行一模一样的 ch6,
    // 误以为是"这轮又掉框了"。 直接返回 0。
    if (buf == nullptr || cap < YOLO_CH6_AKEYS) return 0;
    if (s_ch6_n != 6 || s_ch6_round != s_cas_round) return 0;
    buf[0] = s_ch6_n;
    buf[1] = s_ch6_kind;
    buf[2] = s_ch6_drop;
    buf[3] = s_ch6_px10;
    buf[4] = s_ch6_rx100;
    for (int i = 0; i < 6; i++) buf[5 + i] = s_ch6_c[i];
    return YOLO_CH6_AKEYS;
}

void yolo_cascade_crop_rect(int* x0, int* y0, int* x1, int* y1)
{
    if (x0 != nullptr) *x0 = s_cas_rect[0];
    if (y0 != nullptr) *y0 = s_cas_rect[1];
    if (x1 != nullptr) *x1 = s_cas_rect[2];
    if (y1 != nullptr) *y1 = s_cas_rect[3];
}

void yolo_cascade_stat(uint32_t* plate_us, uint32_t* crop_us,
                       uint32_t* resample_us, uint32_t* crop_infer_us,
                       uint32_t* char_us)
{
    if (plate_us     != nullptr) *plate_us     = s_cas_t_plate;
    if (crop_us      != nullptr) *crop_us      = s_cas_t_crop;
    if (resample_us  != nullptr) *resample_us  = s_cas_t_resample;
    if (crop_infer_us != nullptr) *crop_infer_us = s_cas_t_cropinf;
    if (char_us      != nullptr) *char_us      = s_cas_t_char3;
}

