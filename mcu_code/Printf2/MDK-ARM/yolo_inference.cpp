// ---------------------------------------------------------------------------
// Tensor arena. Put it in SDRAM (0xC0000000). M7_TCM.sct:
//   RW_SDRAM1 0xC0000000 UNINIT 0x00200000 { .ANY(.bss.tensor_arena_area) }
// ---------------------------------------------------------------------------
// 2 MB rather than the full 8 MB: the camera needs two 800x480 RGB565 frame
// buffers (768,000 bytes each) directly above the arena, because no on-chip SRAM
// can hold even one and the SDRAM is the only place big enough.  This size and
// the RW_SDRAM1 size in M7_TCM.sct are the same number - change them together,
// or the linker will happily place the arena over the frame buffers.
// The size is measured, not guessed: yolo_plate_init() prints it (see the arena
// trace below) and the board reports 1,303,080 bytes used, so 2 MB leaves ~790KB
// spare.  If a future model needs more, TFLM says by how much on the trace; if
// the arena grows past 2 MB, the frame buffers have to come down or move.
#ifndef TENSOR_ARENA_SIZE
#define TENSOR_ARENA_SIZE (0x200000)          // 2 MB
#endif
// NOTE: the section name MUST start with ".bss." (Arm Compiler 6).
// A plain name like "tensor_arena_area" makes armclang emit SHT_PROGBITS (RW
// initialised data), so the C library startup (__main) tries to copy 8 MB of
// zeros into SDRAM 0xC0000000 *before* main() runs.  SDRAM is not initialised
// at that point -> HardFault before main, with no UART output.
// With the ".bss." prefix armclang emits SHT_NOBITS (ZI), and because the
// scatter region is UNINIT nothing is copied/zeroed at startup.
// (AC5's 'zero_init' attribute is NOT supported by armclang and is ignored.)
static uint8_t tensor_arena[TENSOR_ARENA_SIZE]
    __attribute__((section(".bss.tensor_arena_area"), aligned(16)));

