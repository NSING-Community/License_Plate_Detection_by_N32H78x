// n == 6 时, 用牌面格点把漏掉的那一位补回来。
//
// 现象 (2026-10-19 第三次上板, 粤R888G8, 15 轮里 12 轮 n=6):
//   串是 粤R8888 / 粤R888沪 / 粤R888湘 —— 末位要么没了, 要么读成省字。
//   最后那个框宽 34..54 (正常 26), 中心 241, 而格点上它该在 230 (位5) 或
//   259 (位6) —— 是**末两位粘连成一个框**, 不是 ③ 读错。
//   同一块牌在别的轮次 (n=7) 又完全正常, 说明是检测的边界状态。
//
// 关键点: patch 是按**框的位置**从冻结帧里抠的, 抠到什么内容由位置决定,
// 不由检测结果决定。 所以只要能估出格点, 补出来的槽抠到的就是那个字。
//
// 只处理 n==6, 而且要过两道闸 (残差都相对 pitch):
//   A: 6 个框直接套 7 槽 (缺 1 槽),        残差 <= 0.15
//   B: 丢 1 个框, 5 个点套 7 槽 (缺 2 槽), 残差 <= 0.08  (点更少, 门槛更紧)
// 真·6 字牌 (字距全等) 在 A 上残差约 0.26、在 B 上约 0.13, 两道都过不去 ——
// 这就是"不把 6 字牌硬掰成 7 字"的保险。 另加一条 p 的合理性闸: 拟合出的
// pitch 必须落在中位间隔的 0.7~1.4 倍之间, 否则 5 个点能拟合出任何东西。
//
// 补出来的 7 个框**全部**按格点重定位, 不是只补缺的那个 —— 粘连的那个框
// 位置本来就不对, 一起摆正才对齐。
#define YOLO_LATTICE_A6   0.15f
#define YOLO_LATTICE_B6   0.08f
// 相对判据 —— **这条才是"不把 6 字牌掰成 7 字"的主保险**, 绝对门槛挡不住:
// 7 槽里的 2..6 是等距的, 所以任何 6 个等距的框都能完美套进某 5 个槽。
//   离线对拍 (training/_row6_check.py):
//     板上真实失败 (位5粘连+位6丢失)  r7 0.015 / r_uniform 0.112  -> 收
//     干净地缺最后一位                r7 0.000 / r_uniform 0.148  -> 收
//     干净地缺第一位 / 缺中间一位      r7 0.000 / 0.162 / 0.336    -> 收
//     真 6 字牌 (等距)                 r_uniform 0.000            -> 拒
//     真 6 字牌 +-1 / +-2 px 噪声      r_uniform 0.042 / 0.093    -> 拒
#define YOLO_LATTICE_REL    0.40f   // r7 必须 <= 0.40 * r_uniform
#define YOLO_LATTICE_RMIN   0.10f   // 且等距模型本身要明显不成立
#define YOLO_CH6_AKEYS    11

static int s_ch6_n     = -1;   // -1 = 本轮不是 6 框 (日志用)
static int s_ch6_round = -1;   // 上一次真的分析过 6 框的轮次; 和当前轮次不等就是陈旧数据
static int s_ch6_kind  = 0;    // 0 = 没补, 1 = 走 A, 2 = 走 B
static int s_ch6_drop  = -1;   // B: 丢掉的框下标; A: -1
static int s_ch6_px10  = 0;    // 拟合出的 pitch x10
static int s_ch6_rx100 = 0;    // 最大残差 / pitch x100
static int s_ch6_c[6]  = {0, 0, 0, 0, 0, 0};   // 补位**之前**的 6 个中心

// 把 n 个中心按 map[] 指定的槽位做最小二乘 (a, p), 返回 max 残差 / p。
// map[i] = 第 i 个观测框用的槽位下标。
static float fit_slots(const float* xs, const float* c, const int* map, int n,
                       float* a_out, float* p_out)
{
    float sx = 0.0f, sc = 0.0f, sxx = 0.0f, sxc = 0.0f;
    for (int i = 0; i < n; i++) {
        const float x = xs[map[i]];
        sx += x; sc += c[i]; sxx += x * x; sxc += x * c[i];
    }
    const float den = (float)n * sxx - sx * sx;
    if (den <= 1e-6f) return 1e9f;
    const float p = ((float)n * sxc - sx * sc) / den;
    const float a = (sc - p * sx) / (float)n;
    if (p <= 1.0f) return 1e9f;
    float rmax = 0.0f;
    for (int i = 0; i < n; i++) {
        const float r = fabsf(c[i] - (a + p * xs[map[i]]));
        if (r > rmax) rmax = r;
    }
    *a_out = a;
    *p_out = p;
    return rmax / p;
}

static int popcount7(int m)
{
    int k = 0;
    for (int i = 0; i < 7; i++) if (m & (1 << i)) k++;
    return k;
}

// 返回这 7 个框的个数 (6 = 没补, 7 = 补上了)。 b[] 容量 >= 7。
static int rebuild_row_7(YoloBox* b, int n)
{
#if YOLO_LATTICE_ON
    s_ch6_n = -1;
    s_ch6_kind = 0;
    s_ch6_drop = -1;
    s_ch6_px10 = 0;
    s_ch6_rx100 = 0;
    if (n != 6) return n;

    float c[6], w[6], y1[6], y2[6];
    for (int i = 0; i < 6; i++) {
        c[i]  = (b[i].x1 + b[i].x2) * 0.5f;
        w[i]  = b[i].x2 - b[i].x1;
        y1[i] = b[i].y1;
        y2[i] = b[i].y2;
        s_ch6_c[i] = (int)(c[i] + 0.5f);
    }
    s_ch6_n = 6;
    s_ch6_round = s_cas_round;

    float xs[7];
    for (int i = 0; i < 7; i++) xs[i] = (float)i + ((i >= 2) ? YOLO_LATTICE_F : 0.0f);

    float gs[5];
    for (int i = 0; i < 5; i++) gs[i] = c[i + 1] - c[i];
    for (int i = 1; i < 5; i++) {              // 插入排序取中位间隔
        const float k = gs[i];
        int j = i - 1;
        while (j >= 0 && gs[j] > k) { gs[j + 1] = gs[j]; j--; }
        gs[j + 1] = k;
    }
    const float gm = gs[2];
    if (gm < 4.0f) return n;                    // 框全挤在一起, 不是一排字

    // ---- 闸 A: 6 个框 -> 7 槽里缺 1 个 ----
    float ba = 0.0f, bp = 0.0f, br = 1e9f;
    int   bmask = 0;
    for (int mask = 1; mask < 128; mask++) {
        if (popcount7(mask) != 6) continue;
        int map[6], k = 0;
        for (int s = 0; s < 7; s++) if (mask & (1 << s)) map[k++] = s;
        float a, p;
        const float r = fit_slots(xs, c, map, 6, &a, &p);
        if (r < br) { br = r; ba = a; bp = p; bmask = mask; }
    }
    s_ch6_px10  = (int)(bp * 10.0f + 0.5f);
    s_ch6_rx100 = (br < 9.0f) ? (int)(br * 100.0f + 0.5f) : 999;
    if (br <= YOLO_LATTICE_A6 && bp > 0.7f * gm && bp < 1.4f * gm) {
        s_ch6_kind = 1;
    } else {
        // ---- 闸 B: 丢 1 个框, 5 个点 -> 7 槽里缺 2 个 ----
        float ca = 0.0f, cp = 0.0f, cr = 1e9f;
        int   cmask = 0, cdrop = -1;
        for (int d = 0; d < 6; d++) {
            float cd[5];
            int ci = 0;
            for (int i = 0; i < 6; i++) if (i != d) cd[ci++] = c[i];
            for (int mask = 1; mask < 128; mask++) {
                if (popcount7(mask) != 5) continue;
                int map[5], k = 0;
                for (int s = 0; s < 7; s++) if (mask & (1 << s)) map[k++] = s;
                float a, p;
                const float r = fit_slots(xs, cd, map, 5, &a, &p);
                if (r < cr) { cr = r; ca = a; cp = p; cmask = mask; cdrop = d; }
            }
        }
        s_ch6_px10  = (int)(cp * 10.0f + 0.5f);
        s_ch6_rx100 = (cr < 9.0f) ? (int)(cr * 100.0f + 0.5f) : 999;
        if (cr > YOLO_LATTICE_B6 || cp <= 0.7f * gm || cp >= 1.4f * gm) return n;

        ba = ca; bp = cp; br = cr; bmask = cmask;
        s_ch6_kind = 2;
        s_ch6_drop = cdrop;
    }
    (void)bmask;

    // ---- 相对判据: 等距 6 槽模型必须明显不成立, 且 7 槽要明显更好 ----
    // 绝对残差门槛单独用不够: 7 槽里 2..6 本来就等距, 一块**真 6 字牌**
    // 能完美套进那 5 个槽 (离线对拍: r 0.000)。 所以这里先算等距模型的
    // 残差 r_uniform, 要求它 >= 0.10 (这个排不是等距的), 且 r7 <= 0.40*r_u。
    {
        static const float xu[6] = {0.0f, 1.0f, 2.0f, 3.0f, 4.0f, 5.0f};
        static const int   mu[6] = {0, 1, 2, 3, 4, 5};
        float ua, up;
        const float ru = fit_slots(xu, c, mu, 6, &ua, &up);
        if (!(ru >= YOLO_LATTICE_RMIN && ru < 1.0f && br <= YOLO_LATTICE_REL * ru)) {
            s_ch6_kind = 0;
            return n;
        }
    }

    // 补出来的首末位必须还在裁剪里 (外推 2 格时最容易飞)
    if (ba + bp * xs[0] < -8.0f || ba + bp * xs[6] > 328.0f) {
        s_ch6_kind = 0;
        return n;
    }

    // 宽度: 6 个框的中位数 (粘连的那个是野值, 中位数免疫)
    float ts[6];
    for (int i = 0; i < 6; i++) ts[i] = w[i];
    for (int i = 1; i < 6; i++) {
        const float k = ts[i];
        int j = i - 1;
        while (j >= 0 && ts[j] > k) { ts[j + 1] = ts[j]; j--; }
        ts[j + 1] = k;
    }
    float wt = (ts[2] + ts[3]) * 0.5f;
    if (wt < YOLO_LATTICE_WMIN * bp) wt = YOLO_LATTICE_WMIN * bp;
    if (wt > YOLO_LATTICE_WMAX * bp) wt = YOLO_LATTICE_WMAX * bp;
    const float half = wt * 0.5f;

    // 纵向: 中位数, 7 个字在同一行上
    float ty1[6], ty2[6];
    for (int i = 0; i < 6; i++) { ty1[i] = y1[i]; ty2[i] = y2[i]; }
    for (int i = 1; i < 6; i++) {
        const float k = ty1[i];
        int j = i - 1;
        while (j >= 0 && ty1[j] > k) { ty1[j + 1] = ty1[j]; j--; }
        ty1[j + 1] = k;
    }
    for (int i = 1; i < 6; i++) {
        const float k = ty2[i];
        int j = i - 1;
        while (j >= 0 && ty2[j] > k) { ty2[j + 1] = ty2[j]; j--; }
        ty2[j + 1] = k;
    }
    const float my1 = (ty1[2] + ty1[3]) * 0.5f;
    const float my2 = (ty2[2] + ty2[3]) * 0.5f;

    for (int i = 0; i < 7; i++) {
        const float cx = ba + bp * xs[i];
        b[i].x1 = cx - half;
        b[i].x2 = cx + half;
        b[i].y1 = my1;
        b[i].y2 = my2;
        b[i].class_id = 1;          // ③ 会覆盖; ③ 没起来时至少是"非 0"
        b[i].score = 0.5f;
    }
    return 7;
#else
    (void)b;
    s_ch6_n = -1;
    return n;
#endif
}

