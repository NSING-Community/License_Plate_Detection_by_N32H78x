// anchors per stride (training voc.data)
static const float ANCHORS[2][3][2] = {
    {{11.03f, 24.54f}, {14.40f, 36.74f}, {20.08f, 52.82f}}, // stride 16 (20x20)
    {{27.04f, 78.23f}, {144.02f, 96.56f}, {239.25f, 195.42f}} // stride 32 (10x10)
};
static const int   STRIDES[2]   = {16, 32};
static const int   GRID_W[2]    = {YOLO_GRID0, YOLO_GRID1};
static const int   GRID_H[2]    = {YOLO_GRID0, YOLO_GRID1};

// ---------------------------------------------------------------------------
static inline float dequant_i8(int8_t q) { return (float)(q + 128) * (1.0f / 255.0f); }

static float iou(const YoloBox& a, const YoloBox& b)
{
    float ix1 = a.x1 > b.x1 ? a.x1 : b.x1;
    float iy1 = a.y1 > b.y1 ? a.y1 : b.y1;
    float ix2 = a.x2 < b.x2 ? a.x2 : b.x2;
    float iy2 = a.y2 < b.y2 ? a.y2 : b.y2;
    if (ix1 >= ix2 || iy1 >= iy2) return 0.0f;
    float inter = (ix2 - ix1) * (iy2 - iy1);
    float u = (a.x2 - a.x1) * (a.y2 - a.y1) + (b.x2 - b.x1) * (b.y2 - b.y1) - inter;
    return u > 0 ? inter / u : 0.0f;
}

// decode one head (output tensor already layout-A [h,w,85]).
//
// `anchors` and `conf_thresh` became PARAMETERS when ② arrived, and that is the
// whole of the change: ① and ② share this layout but share neither of these two
// numbers.  The tables come from different voc.data files (data/ vs data_crop/),
// and ② runs at conf 0.10 against ①'s 0.25 - a glyph that is 2-3 px wide inside
// ②'s own 320x320 crop is exactly what 0.25 throws away.
// ①'s call site passes ANCHORS[sid] / YOLO_CONF_THRESH, i.e. the values that
// used to be spelled here, so ①'s output is unchanged down to the bit.
// `keep_top` 决定 max_box 满了以后怎么办 —— 这**不是**性能开关, 是两边链路对不对得上的问题:
//
//   keep_top = 0 (①): 光栅序直接截。 ① 在 conf 0.25 下一帧就几个候选, 永远
//                      到不了 max_box, 所以这条路与冻结基线**逐字节相同**。
//   keep_top = 1 (②): 按**分数**留最高的 max_box 个。 PC 上冻结出 78.99% 的那条
//                      链路就是"按分数取 16 -> cap 7"; 光栅序截断拿到的是完全
//                      另一批框 (图的上半部分先占满 64 个名额, 下半部分的真字
//                      一个都进不来), 这是板子和 PC 之间一个**静默**的分歧。
//
// 2026-10-20 现场: 161 轮里 109 轮候选数摸到了 64, 所以光栅序截断一直在生效,
// 不是理论风险。 同一份日志里 `why` 打出 1118525714 —— 也是这个位置溢出的:
// 老代码只在进格子时查 `cnt < max_box`, 而一个格子里 3 个 anchor 各写一次,
// 从 cnt = 63 的格子进来会越界写 2 个 YoloBox; 越界写的是第 65 个的 x1 (float),
// 而 s_cas_box 正下方 4 字节就是 s_cas_why。
//
// `seen` 累计**过 conf 的候选总数** (不截断, 纯诊断) —— 它大于 max_box 就说明
// 截断生效了, 用来判断是不是该把 max_box 调大。 ② 的日志里 n2 的第二个数就是它。
static void decode_head(const int8_t* feat, int sid, const float anchors[3][2],
                        float conf_thresh, YoloBox* boxes, int& cnt, int max_box,
                        int keep_top, int& seen)
{
    const int stride  = STRIDES[sid];
    const int gw      = GRID_W[sid];
    const int gh      = GRID_H[sid];
    if (max_box <= 0) return;          // keep_top 分支要读 boxes[max_box-1]

    for (int gy = 0; gy < gh && (keep_top || cnt < max_box); gy++) {
        for (int gx = 0; gx < gw && (keep_top || cnt < max_box); gx++) {
            const int8_t* c = feat + (size_t)(gy * gw + gx) * YOLO_CHAN;
            // best class over cls[15:85]
            int   cid = 0;
            float csc = -1.0f;
            for (int k = 0; k < YOLO_CLS_NUM; k++) {
                float s = dequant_i8(c[15 + k]);
                if (s > csc) { csc = s; cid = k; }
            }
            for (int a = 0; a < YOLO_OBJ_NUM; a++) {
                float obj = dequant_i8(c[12 + a]);         // already sigmoid in model
                float sc  = obj * csc;
                if (sc < conf_thresh) continue;
                seen++;

                float bx = dequant_i8(c[a * 4 + 0]);       // sigmoid(reg) already in model
                float by = dequant_i8(c[a * 4 + 1]);
                float bw = dequant_i8(c[a * 4 + 2]);
                float bh = dequant_i8(c[a * 4 + 3]);

                float cx = (bx * 2.0f - 0.5f + gx) * stride;
                float cy = (by * 2.0f - 0.5f + gy) * stride;
                float w  = (bw * 2.0f) * (bw * 2.0f) * anchors[a][0];
                float h  = (bh * 2.0f) * (bh * 2.0f) * anchors[a][1];

                YoloBox b;
                b.x1 = cx - w * 0.5f; b.y1 = cy - h * 0.5f;
                b.x2 = cx + w * 0.5f; b.y2 = cy + h * 0.5f;
                b.score = sc; b.class_id = cid;

                if (!keep_top) {
                    boxes[cnt++] = b;                      // ①: 老路径, 一位不动
                    continue;
                }
                // ②: 维持 boxes[] 按分数降序, 满了就只挤掉最差的那个
                int i;
                if (cnt < max_box)                           i = cnt++;
                else if (b.score > boxes[max_box - 1].score) i = max_box - 1;
                else                                         continue;
                while (i > 0 && boxes[i - 1].score < b.score) { boxes[i] = boxes[i - 1]; i--; }
                boxes[i] = b;
            }
        }
    }
}

// `nms_thresh` is a parameter for the same reason decode_head's threshold is:
// ② needs 0.30 where ① wants 0.45.  A plate's glyphs sit close enough together
// that a 0.45 threshold merges two neighbouring characters into one, and ① has
// nothing to merge (it finds one box).
static void nms(YoloBox* boxes, int& cnt, float nms_thresh)
{
    // insertion sort desc by score
    for (int i = 1; i < cnt; i++) {
        YoloBox key = boxes[i];
        int j = i - 1;
        while (j >= 0 && boxes[j].score < key.score) { boxes[j + 1] = boxes[j]; j--; }
        boxes[j + 1] = key;
    }
    int keep = 0;
    for (int i = 0; i < cnt; i++) {
        bool ok = true;
        for (int j = 0; j < keep; j++) {
            if (iou(boxes[i], boxes[j]) > nms_thresh) { ok = false; break; }
        }
        if (ok) boxes[keep++] = boxes[i];
    }
    cnt = keep;
}

