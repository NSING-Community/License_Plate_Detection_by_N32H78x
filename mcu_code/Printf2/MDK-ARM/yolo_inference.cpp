int yolo_cascade_view_slope_x1000(void)
{
    const float v = s_cas_slope_meas * 1000.0f;
    return (int)((v < 0.0f) ? (v - 0.5f) : (v + 0.5f));
}

// 本轮**真正用上**的横滚角度, 单位 0.001 rad (正 = 右边低)。
// 和 slope 的区别: slope 是 320 空间里量到的**残余**倾斜, roll 是已经转过的
// 总角度。 两个都接近 0 才是真的正; 一个是 0、一个很大说明正在收敛。
int yolo_cascade_roll_x1000(void)
{
    const float v = s_cas_roll_used * 1000.0f;
    return (int)((v < 0.0f) ? (v - 0.5f) : (v + 0.5f));
}

