// ---------------------------------------------------------------------------
// 选牌框: 复刻 training/full_pipeline_e2e.py 的 pick_plate(rule="area_conf",
// conf_margin=0.20)。
//
// 先在所有 class_id==0 (整牌框) 里找出最高分 smax, 只留下分数 >= smax-0.20
// 的那几个, 再取面积最大的。 为什么不直接取面积最大: 横跨整幅画面的幻觉框
// 面积最大, 分数却往往不高; 这一条把"分数掉队太多"的先排除掉, 面积才只在
// 势均力敌的几个之间做决定。
//
// 顺序也必须照抄: 先按分数筛, 再按面积取 —— 反过来的结果不一样。
// ---------------------------------------------------------------------------
static bool pick_plate_area_conf(const YoloBox* boxes, int n, YoloBox* out)
{
    float smax = -1.0f;
    for (int i = 0; i < n; i++) {
        if (boxes[i].class_id == 0 && boxes[i].score > smax) smax = boxes[i].score;
    }
    if (smax < 0.0f) return false;                 // 一个整牌框都没有

    const float lo = smax - YOLO_PLATE_PICK_MARGIN;
    int   best      = -1;
    float best_area = -1.0f;
    for (int i = 0; i < n; i++) {
        if (boxes[i].class_id != 0 || boxes[i].score < lo) continue;
        const float a = (boxes[i].x2 - boxes[i].x1) * (boxes[i].y2 - boxes[i].y1);
        if (a > best_area) { best_area = a; best = i; }   // > 而不是 >=: 平局取先出现的, 与 Python 的 max() 一致
    }
    if (best < 0) {
        // Python 那一行写的是 `c0 = keep_in or c0`。 理论上进不来 (smax 自己
        // 必然在区间里), 但照抄下来, 免得以后有人把 margin 调大到边界上时
        // 两边分叉而没人发现。
        for (int i = 0; i < n; i++) {
            if (boxes[i].class_id != 0) continue;
            const float a = (boxes[i].x2 - boxes[i].x1) * (boxes[i].y2 - boxes[i].y1);
            if (a > best_area) { best_area = a; best = i; }
        }
    }
    if (best < 0) return false;
    *out = boxes[best];
    return true;
}

// ---- 形状闸 (2026-10-19 重启后那次日志) ----
// 那次前 9 轮 ① 把画面正中的 88x109 竖框当成了车牌 (宽高比 0.81), 每轮复用
// 同一个位置, ②③ 在那一小块上编出 15 / 170 / 616 / 1T7 / 51学 —— 不是"读得
// 差", 是根本没框到牌。 中国车牌**全部宽大于高** (蓝/黄 440x140、双层绿
// 440x220、摩托 220x140), 所以高大于宽的框不可能是车牌。
//
// **必须在 camera_map_box() 之后判**: 检测帧是相机画面硬拉成 320x320 的
// (kx=800/320, ky=480/320), 两轴比例不同 —— 320 空间里的宽高比是相机空间的
// 0.6 倍, 一块 2.5 的正经车牌在 320 空间只有 1.5。 拿 320 空间套阈值会误杀。
// 极端转角下框会被压扁, 但那种牌本来也读不出来 —— 宁可打 (no char)。
#define YOLO_PLATE_MIN_ASPECT  1.0f

static bool plate_shaped_cam(const YoloBox& b)
{
    const float w = b.x2 - b.x1;
    const float h = b.y2 - b.y1;
    return (w > 0.0f) && (h > 0.0f) && (w >= YOLO_PLATE_MIN_ASPECT * h);
}

// ---------------------------------------------------------------------------
// 裁剪矩形: 复刻 full_pipeline_e2e.py 的 crop_by_plate()。
//
// 左上 floor、右下 ceil、各自 clip 到图内 —— 这四个取整方向不是风格问题:
// 用 int() 截断代替 floor 会让矩形在负坐标那一侧差一个像素, 而 10% 外扩本来
// 就常常把左上角推到图外。 外扩 10% 本身是**模型契约**: 裁紧掉 16.5 个点
// (字符更大反而更差), 板子上照抄, 别自作聪明裁紧。
//
// 注意右下是开区间 [x1, y1), 与 numpy 切片一致。
// ---------------------------------------------------------------------------
static void crop_rect_from_plate(const YoloBox& b, int fw, int fh, float margin,
                                 int* x0, int* y0, int* x1, int* y1)
{
    const float mx = (b.x2 - b.x1) * margin;
    const float my = (b.y2 - b.y1) * margin;

    int ax0 = (int)floorf(b.x1 - mx);
    int ay0 = (int)floorf(b.y1 - my);
    if (ax0 < 0)    ax0 = 0;
    if (ax0 > fw - 1) ax0 = fw - 1;
    if (ay0 < 0)    ay0 = 0;
    if (ay0 > fh - 1) ay0 = fh - 1;

    int ax1 = (int)ceilf(b.x2 + mx);
    int ay1 = (int)ceilf(b.y2 + my);
    if (ax1 < ax0 + 1) ax1 = ax0 + 1;
    if (ax1 > fw)      ax1 = fw;
    if (ay1 < ay0 + 1) ay1 = ay0 + 1;
    if (ay1 > fh)      ay1 = fh;

    *x0 = ax0; *y0 = ay0; *x1 = ax1; *y1 = ay1;
}

// ---------------------------------------------------------------------------
// 双线性重采样: 任意矩形 -> dw x dh, 直接写进 int8 输入张量 (每通道 -128)。
//
// 两个静默掉分的地方, 都在这里:
//
//   (a) **半像素约定**。 OpenCV 的 dst(x) 对应 src 上的 (x+0.5)*scale-0.5,
//       不是 x*scale。 在 320x320 这种大图上差半像素只是糊一点; ③ 那边要
//       缩到 32x64, 半像素就足够翻转 argmax 了 —— 所以从一开始就用对。
//   (b) **通道序**。 训练用的是 cv2 读的 BGR 还是 PIL 的 RGB, 取决于造
//       data_crop 的脚本; 这里固定按 RGB 取 (与 ① 的相机通路一致)。 要是有
//       一天发现红蓝反了, 症状是"字全认错但框很准", 改的是这里。
//
// 与 OpenCV 的差别: OpenCV 是定点权重 (INTER_BITS=5), 这里是浮点。 逐通道
// 差 <= 1 个灰阶, 对 ② 这种检测头无影响; ③ 上要盯的是 argmax 有没有翻。
//
// 缩小时**不做抗锯齿** —— 这不是偷懒: cv2.resize(INTER_LINEAR) 同样不做
// (做抗锯齿的是 INTER_AREA), 而 ② 训练时用的就是 INTER_LINEAR。
// ---------------------------------------------------------------------------
static void resample_rect_to_i8(const uint8_t* src, int fw, int fh,
                                int rx0, int ry0, int rx1, int ry1,
                                int8_t* dst, int dw, int dh)
{
    const int   rw = rx1 - rx0;
    const int   rh = ry1 - ry0;
    const float sx = (float)rw / (float)dw;
    const float sy = (float)rh / (float)dh;
    const int   max_x = rw - 1;
    const int   max_y = rh - 1;

    for (int dy = 0; dy < dh; dy++) {
        float fy = ((float)dy + 0.5f) * sy - 0.5f;
        if (fy < 0.0f)       fy = 0.0f;
        if (fy > (float)max_y) fy = (float)max_y;
        const int   ya = (int)fy;
        const int   yb = (ya < max_y) ? (ya + 1) : ya;
        const float wy = fy - (float)ya;
        const uint8_t* ra = src + ((size_t)(ry0 + ya) * (size_t)fw + (size_t)rx0) * 3u;
        const uint8_t* rb = src + ((size_t)(ry0 + yb) * (size_t)fw + (size_t)rx0) * 3u;
        int8_t* out = dst + (size_t)dy * (size_t)dw * 3u;

        for (int dx = 0; dx < dw; dx++) {
            float fx = ((float)dx + 0.5f) * sx - 0.5f;
            if (fx < 0.0f)        fx = 0.0f;
            if (fx > (float)max_x) fx = (float)max_x;
            const int   xa = (int)fx;
            const int   xb = (xa < max_x) ? (xa + 1) : xa;
            const float wx = fx - (float)xa;
            const uint8_t* pa = ra + (size_t)xa * 3u;
            const uint8_t* pb = ra + (size_t)xb * 3u;
            const uint8_t* qa = rb + (size_t)xa * 3u;
            const uint8_t* qb = rb + (size_t)xb * 3u;

            for (int ch = 0; ch < 3; ch++) {
                const float ta = (float)pa[ch];
                const float tb = (float)pb[ch];
                const float tc = (float)qa[ch];
                const float td = (float)qb[ch];
                const float top = ta + (tb - ta) * wx;
                const float bot = tc + (td - tc) * wx;
                int v = (int)(top + (bot - top) * wy + 0.5f);   // 非负, 故 +0.5 就是四舍五入
                if (v < 0)   v = 0;
                if (v > 255) v = 255;
                out[ch] = (int8_t)(v - 128);
            }
            out += 3;
        }
    }
}

// ---------------------------------------------------------------------------
// 仿射重采样: 沿**牌面自己的两个轴**取样 (横滚校正)。
//
// 坐标: (u,v) 是牌面坐标, u 沿字行、v 垂直, 单位都是**帧像素**:
//     frame = (ox,oy) + u*(co,si) + v*(-si,co)
// co/si 就是横滚角的 cos/sin。 半像素约定与 resample_rect_to_i8 一致,
// 所以 co=1,si=0 时两者逐像素相同 —— 竖直的车牌仍然走原来那条路。
//
// 逐像素夹到帧内: 裁剪矩形本身已经 clip 过, 但转过一个角度之后四个角会出去,
// 出界处取边缘像素 (BORDER_REPLICATE), 这是 cv2.warpAffine 的默认退化方式。
//
// 为什么必须做: 倾斜只在 320 空间里看着吓人、在帧里其实不大, 反过来也一样。
//   2026-10-19 第四次上板, 黑B45678 那块牌 slope_320 = -0.41 (22 度), 看着像
//   转了一大截, 但裁剪 280x95 被拉成 320x320, 帧里的真实横滚只有 -7.9 度。
//   可是 ② 看到的**就是** 320 空间那个 22 度 —— 字框的轴对齐外接矩形从
//   26 宽涨到 ~54 宽, 已经远超 anchors 的最大宽 27.7, 于是整行框全崩。
// ---------------------------------------------------------------------------
static void resample_aff_to_i8(const uint8_t* src, int fw, int fh,
                               float ox, float oy, float co, float si,
                               float uw, float uh,
                               int8_t* dst, int dw, int dh)
{
    const float su = uw / (float)dw;
    const float sv = uh / (float)dh;
    const float max_x = (float)(fw - 1);
    const float max_y = (float)(fh - 1);

    for (int dy = 0; dy < dh; dy++) {
        const float v = ((float)dy + 0.5f) * sv - 0.5f;
        int8_t* out = dst + (size_t)dy * (size_t)dw * 3u;

        for (int dx = 0; dx < dw; dx++) {
            const float u = ((float)dx + 0.5f) * su - 0.5f;

            float fx = ox + u * co - v * si;
            float fy = oy + u * si + v * co;
            if (fx < 0.0f)       fx = 0.0f;
            if (fx > max_x)      fx = max_x;
            if (fy < 0.0f)       fy = 0.0f;
            if (fy > max_y)      fy = max_y;

            const int   xa = (int)fx;
            const int   ya = (int)fy;
            const int   xb = (xa < fw - 1) ? (xa + 1) : xa;
            const int   yb = (ya < fh - 1) ? (ya + 1) : ya;
            const float wx = fx - (float)xa;
            const float wy = fy - (float)ya;
            const uint8_t* ra = src + ((size_t)ya * (size_t)fw + (size_t)xa) * 3u;
            const uint8_t* rb = src + ((size_t)yb * (size_t)fw + (size_t)xa) * 3u;
            const uint8_t* pa = ra;
            const uint8_t* pb = ra + (size_t)(xb - xa) * 3u;
            const uint8_t* qa = rb;
            const uint8_t* qb = rb + (size_t)(xb - xa) * 3u;

            for (int ch = 0; ch < 3; ch++) {
                const float top = (float)pa[ch] + ((float)pb[ch] - (float)pa[ch]) * wx;
                const float bot = (float)qa[ch] + ((float)qb[ch] - (float)qa[ch]) * wx;
                int t = (int)(top + (bot - top) * wy + 0.5f);
                if (t < 0)   t = 0;
                if (t > 255) t = 255;
                out[ch] = (int8_t)(t - 128);
            }
            out += 3;
        }
    }
}

// ---------------------------------------------------------------------------
// 一次裁剪的坐标: 轴对齐矩形 + 可选的取样轴旋转。
//
// rot = 0 时 ox/oy/co/si 全部不用, 所有取值都走原来的整数路径 (逐像素等于
// 冻结基线)。 rot = 1 时 (u,v) 是牌面坐标, 与轴对齐下的 (x,y) 一一对应:
//     u <=> 裁剪矩形内相对横坐标, v <=> 相对纵坐标
// 所以 ② 的框 (320 空间) 换算成 u/v 时用的还是 cw/320、ch/320 这两个比例。
//
// 唯一的差别在**裁剪图边界**: 轴对齐时它是矩形 [0,cw]x[0,ch]; 旋转之后它仍然
// 是 u/v 平面上的同一个矩形, 所以 clip 的写法完全可以照抄 —— 这也是为什么
// charhead_cut_patch 里那段 floor/ceil/clip 一行都没改, 只是最后取样时换了轴。
// ---------------------------------------------------------------------------
struct CropXform {
    int   rot;                        // 0 = 轴对齐, 1 = 沿牌面轴取样
    int   rx0, ry0, rx1, ry1;         // 轴对齐裁剪矩形 (帧坐标); 叠加框/日志仍用它
    float ox, oy, co, si;             // 取样轴原点与方向 (帧空间)
    int   uw, uh;                     // 取样区域宽高 (牌面像素) = rx1-rx0 / ry1-ry0
};

// 整块裁剪 -> dw x dh 的 int8 输入张量。
static void cx_apply(const CropXform& X, const uint8_t* src, int fw, int fh,
                     int8_t* dst, int dw, int dh)
{
    if (!X.rot)
        resample_rect_to_i8(src, fw, fh, X.rx0, X.ry0, X.rx1, X.ry1, dst, dw, dh);
    else
        resample_aff_to_i8(src, fw, fh, X.ox, X.oy, X.co, X.si,
                           (float)X.uw, (float)X.uh, dst, dw, dh);
}

// ---------------------------------------------------------------------------
// 选字符框: 复刻 training/two_stage_e2e.py 的 select_idx(geo=False, maxchars=7)。
//
// boxes[] 进来时已按**分数**降序 (nms 排好的)。 先取 class_id>0 的前 16 个
// (Python 的 16 上限), 再截到前 7 个, 最后按 x1 升序 —— 因为 7 < 16, 那个
// 16 永远不生效, 等价于"按分数取前 7 个"。
//
// **顺序不能换**: 先按分数截断, 再按 x 排。 反过来的话, 留下的会是"最靠左的
// 7 个", 而那些位置上的低分框正是旁边的字漏检时冒出来的噪声。
//
// geo=False 是故意的: yolo_plate_geo_set 那个几何分组是给**整图**① 的幻觉框
// 用的, 而现在这些框已经是从一块车牌里裁出来的 ② 的输出了, 前提不一样。
// 本函数不读那个开关, 但最后拼串用的是 yolo_plate_read(), 它**会**读 —— 所以
// main.c 里那个开关保持关闭, 这也是头文件里点名的那条。
// ---------------------------------------------------------------------------
static int select_chars_7(const YoloBox* boxes, int n, YoloBox* out)
{
    int idx[YOLO_PLATE_MAXBOX];
    int m = 0;
    for (int i = 0; i < n && m < YOLO_PLATE_MAXBOX; i++) {
        if (boxes[i].class_id > 0) idx[m++] = i;
    }
    if (m > YOLO_CHAR_MAX) m = YOLO_CHAR_MAX;

    for (int i = 1; i < m; i++) {                  // insertion sort by x1
        const int   key = idx[i];
        const float kx  = boxes[key].x1;
        int j = i - 1;
        while (j >= 0 && boxes[idx[j]].x1 > kx) { idx[j + 1] = idx[j]; j--; }
        idx[j + 1] = key;
    }
    for (int i = 0; i < m; i++) out[i] = boxes[idx[i]];
    return m;
}

// ---------------------------------------------------------------------------
// 7 字牌的中线格点: 把 ② 的字符框中心吸回牌面结构上。
//
// 为什么需要 (2026-10-19 上板, 同一个 crop、静止画面、chg 2):
//
//   第 3 位的框在两个位置之间跳, 而**类别跟着框跳**:
//       142,96 170,223 (中心 156)   -> '8', margin 47..54
//       128,98 161,224 (中心 144.5) -> '2'/'5'/'C', margin 0..5
//   同一个字, 两个框相差 11 px, 一个读对、一个每轮掷硬币。 旁边第 4 位
//   158..195 (宽 37, 比 pitch 宽 25%, 中心偏左 6 px) 的 margin 只有 5..12。
//
//   病根是牌面上的**隔离点**: 第 2、3 位之间比别处多一个点 (用户指出的
//   印刷结构), ② 有时会把框勾到点 + 空档上, 整体左移。 这不是模型读不准,
//   是抠图内容错了 —— 所以改框比改模型便宜得多。
//
// 牌面结构:  位 0 省份汉字 | 位 1 字母 | 点 | 位 2..6 序号
//   中心满足  c_i = a + p * (i + f * [i >= 2])
//
// 只拟合 (a, p) 两个自由参数: 7 个点、一个坏框拉不歪。 三参数版本 (f 也放开)
// 实测在坏框那一轮 f 从 +0.27 翻到 -0.05, 反过来把末位推出 -11 px —— 那比
// 不吸更坏。 f 固定成训练标签上量出来的 0.357 (见宏定义处的统计)。
//
// **中心、宽度分开处理。 宽度是无条件归一的; 中心只在整行明显歪时才投影。**
//
// 2026-10-19 第二次上板把主次排清楚了 —— **宽度才是主因, 中心是次要的**:
//   宽度 29 px 的那一轮: 位 5 读 'G', m 41
//   宽度 48 px 的那一轮: 位 5 读 '8', m 3
// 同样的位置、同样的中心 (242 附近), 只差框宽。 48 px 是 pitch 的 1.6 倍,
// 25% pad 之后 ③ 看到的是 2 倍宽的一格 —— 字在 patch 里被缩小, 判决就飘了。
// 这和 PC 上查到的结论是同一条: **坏框只有"太宽"这一种**。
//
// 所以宽度**不看中心残差**, 只要这一行位次可信就统一归一到中位数。 正常框
// (26..32, pitch ≈ 30) 本来就贴着中位数, 几乎不动; 只有 1.6 倍那种被拉回来。
//
// 中心的判据必须是**整行**的, 不能逐位设门限: 实测第 6 位好轮残差 +3.5、
// 坏轮 +4.8, 而 0.15*pitch = 4.4 恰好卡在中间, 逐位门限会一轮吸一轮不吸,
// 框就凭空跳 5 px, 等于自己制造新的抖动。 整行判据:
//   行内最大残差 <= 0.20*pitch  -> 中心本来就准, 一个像素都不动
//   行内最大残差 >  0.20*pitch  -> 7 个中心一起投影到格点上
// 投影是拟合结果的连续函数, 不会在门限上跳。 实测好轮最大残差 4.1/29.4=0.14,
// 坏轮 9.9/29.4=0.34, 两边都不贴门限。
//
// 宽度目标 **不用**印刷比 0.79: 检测框自带边距, 和字面宽度不是一回事; 硬套
// 0.79 会把每个正常框缩掉 20%, 而 25% pad 是叠在这之上抠 patch 的 —— 等于
// 整体改变 ③ 看到的图。 用这 7 个框自己的中位数, 再夹到 [0.85, 1.10]*pitch。
//
// 只对 n==7 生效 —— 6 字/8 字位次对不上这套结构, 猜比不动更坏。
//
// 2026-10-19 第二次上板 (重新上电后) 补的一条: **位次判错位时不要整行放弃**。
// 那几轮的 ② 在省份字上出了两个重叠框 (IoU 0.14, 类无关 NMS 0.30 两个都留),
// 行内残差 19 px = 0.64*pitch, 以前直接 return 0 -> 宽度也没归一 -> 框宽
// 26/36/25/32/30/28/27, ③ 的 margin 全在 0..10, 串全错。
// 现在先丢一个框重拟合 (残差降到 0.18*pitch), 再按新格点把 **7 个**框全部重定位。
// 关键点: patch 是在重定位后的位置上抠的, 所以"多出来的那个框"被推到它该在的
// 槽上以后, 抠出来的就是那个槽的字 —— 丢谁不影响结果, 只影响格点估计。
#define YOLO_LATTICE_ON      1
// YOLO_LATTICE_F (隔离点间隔 0.357) 定义在**文件靠前**的取景自适应那一段 ——
// 那里量 pitch 的时候就要除 6.357, 比这里早用。
#define YOLO_LATTICE_GATE    0.20f   // 行内最大残差超过这个比例才投影中心
#define YOLO_LATTICE_BAD     0.15f   // 残差超过 0.15*pitch 的位记进 sn (仅诊断)
#define YOLO_LATTICE_MAXRES  0.45f   // 超过近半个字距 -> 位次错位 (多检/漏检), 放弃
#define YOLO_LATTICE_WMIN    0.85f
#define YOLO_LATTICE_WMAX    1.10f
#define YOLO_LATTICE_PROJ    0x80000000u   // sn 的最高位 = 本轮投影了中心

// bit0..6 = 残差超过 0.15*pitch 的位; bit31 = 本轮投影了中心 (否则只是"有点偏")
static uint32_t s_ch3_snap = 0u;

// 返回 1 = 这 7 个框像一条正常的牌面 (位次可信, 可以按位限定类别);
//          包括"丢一个框重拟合后救回来"的情况 —— 格点对, 位次就可信。
// 返回 0 = 不是 7 字, 或者丢一个还是对不齐 —— 下游不要按 pos 猜类别。
static int snap_char_centers_7(YoloBox* b, int n)
{
    s_ch3_snap = 0u;
#if YOLO_LATTICE_ON
    if (n != 7) return 0;

    float xs[7], cs[7], ws[7];
    float sx = 0.0f, sc = 0.0f, sxx = 0.0f, sxc = 0.0f;
    for (int i = 0; i < 7; i++) {
        xs[i] = (float)i + ((i >= 2) ? YOLO_LATTICE_F : 0.0f);
        cs[i] = (b[i].x1 + b[i].x2) * 0.5f;
        ws[i] = b[i].x2 - b[i].x1;
        sx += xs[i]; sc += cs[i]; sxx += xs[i] * xs[i]; sxc += xs[i] * cs[i];
    }
    const float den = 7.0f * sxx - sx * sx;
    if (den <= 1e-6f) return 0;
    const float p = (7.0f * sxc - sx * sc) / den;
    const float a = (sc - p * sx) / 7.0f;
    if (p <= 1.0f) return 0;           // 退化的框 (全挤在一起), 不动

    float rmax = 0.0f;
    for (int i = 0; i < 7; i++) {
        const float r = fabsf(cs[i] - (a + p * xs[i]));
        if (r > rmax) rmax = r;
    }

    float pf = p, af = a;
    int   robust = 0;                  // 1 = 整行拟合不通过, 靠丢一个框救回来的

    if (rmax > YOLO_LATTICE_MAXRES * p) {
        // 位次自检没通过时, 先试**丢掉残差最大的那一个框**重拟合一次。
        // 第二次上板最常见的失败就是这样: 省份字被检成两个重叠框
        //   (74,88 100,226) + (92,80 128,223)
        // 两个都留下 -> 行内残差 19 px = 0.64*pitch -> 以前整行直接放弃,
        // 连宽度归一都不做, 7 个框宽 26/36/25/32/30/28/27 参差不齐, ③ 的
        // margin 全掉到 0..10。 丢一个重新拟合就干净了 (残差 0.18*pitch)。
        //
        // 丢的是"最不像格点的那个", 不一定是"多出来的那个" —— 这不要紧:
        // 下面 **7 个框全部**按格点重新定位, patch 是在新位置上抠的, 内容由
        // 格点决定, 不由它原来的检测位置决定。 只要格点对, 每一格抠到的字就对。
        int wi = 0; float wr = -1.0f;
        for (int i = 0; i < 7; i++) {
            const float r = fabsf(cs[i] - (a + p * xs[i]));
            if (r > wr) { wr = r; wi = i; }
        }
        const float sx2  = sx  - xs[wi];
        const float sxx2 = sxx - xs[wi] * xs[wi];
        const float sc2  = sc  - cs[wi];
        const float sxc2 = sxc - xs[wi] * cs[wi];
        const float den2 = 6.0f * sxx2 - sx2 * sx2;
        int ok6 = 0;
        if (den2 > 1e-6f) {
            pf = (6.0f * sxc2 - sx2 * sc2) / den2;
            af = (sc2 - pf * sx2) / 6.0f;
            if (pf > 1.0f) {
                float rm2 = 0.0f;
                for (int i = 0; i < 7; i++) {
                    if (i == wi) continue;
                    const float r = fabsf(cs[i] - (af + pf * xs[i]));
                    if (r > rm2) rm2 = r;
                }
                // 只剩 6 个点, 门槛收紧到 0.30 —— 松了就等于用一个坏格点
                // 强推 7 个位置, 那比不吸更坏。
                if (rm2 <= 0.30f * pf) ok6 = 1;
            }
        }
        if (!ok6) return 0;            // 丢一个还是不齐: 真·错位, 不套结构
        robust = 1;
    }

    // sn 的逐位标记按**最终**格点算 (救回来的那轮 p 变了)。
    s_ch3_snap = 0u;
    for (int i = 0; i < 7; i++) {
        if (fabsf(cs[i] - (af + pf * xs[i])) > YOLO_LATTICE_BAD * pf)
            s_ch3_snap |= (1u << i);
    }

    // ---------------------------- 宽度归一 (无条件) ----------------------------
    // 不跟中心门限走，也不跟"位次可信"走 —— 只要 n==7 就做。
    // 实测: 位次被判错位的那几轮，7 个框宽是 26/36/25/32/30/28/27，③ 的
    // margin 0..10; 同一块牌位次干净的那几轮归一后 margin 10..49。
    // 中位数本身对 1 个野框免疫, 归一化不会把好行改坏。
    float t[7];
    for (int i = 0; i < 7; i++) t[i] = ws[i];
    for (int i = 1; i < 7; i++) {               // 插入排序, 取中位数
        const float k = t[i];
        int j = i - 1;
        while (j >= 0 && t[j] > k) { t[j + 1] = t[j]; j--; }
        t[j + 1] = k;
    }
    float wt = t[3];
    if (wt < YOLO_LATTICE_WMIN * pf) wt = YOLO_LATTICE_WMIN * pf;
    if (wt > YOLO_LATTICE_WMAX * pf) wt = YOLO_LATTICE_WMAX * pf;

    // 宽度先归一到**当前中心**上; 中心要不要动由下面决定。
    const float half = wt * 0.5f;
    for (int i = 0; i < 7; i++) {
        b[i].x1 = cs[i] - half;
        b[i].x2 = cs[i] + half;
    }

    // ---------------------------- 中心投影 (整行判据) --------------------------
    if (!robust && rmax <= YOLO_LATTICE_GATE * pf) return 1;   // 中心本来就准, 不动

    for (int i = 0; i < 7; i++) {
        const float want = af + pf * xs[i];
        b[i].x1 = want - half;
        b[i].x2 = want + half;
    }
    s_ch3_snap |= YOLO_LATTICE_PROJ;
    return 1;
#else
    (void)b; (void)n;
    return 0;
#endif
}

