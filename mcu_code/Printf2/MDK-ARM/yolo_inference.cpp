// ---- 取景自适应: ② 的输入尺度 --------------------------------------------
//
// ② 只在**一种取景**下训练过。 在 training/data_crop 上量 (见 _crop_stats.py):
//   pitch (字中心间距, 320 空间)  p50 25.8  p99 31.5
//   裁剪宽高比                    p50 1.78
//   anchors 最大也只是 27.7 x 133.9 (stride 32)
// 而板上 ① 的框比训练标签紧 (训练 GT 框 ≈ 1.25 x 车牌宽, 板上 ≈ 1.0),
// 于是同一个"框 + 10%"在板上把字放大了: 实测 pitch 29..36, 字框 32x140 ——
// 比最大的 anchor 还大, ② 的回归只能往外推, 框宽/框高顶在上限上。
//
// 修法: 用**上一轮 ② 自己量到的 pitch** 反过来定这一轮的裁剪宽, 每轮修正一次。
// ② 本来就每轮都跑, 所以这**不增加任何推理**, 相当于自动变焦。
// 只动**外扩比例** (两个轴同比例), 不动宽高比: 板上 ② 的框本身就是被尺度
// 带歪的 (原生宽高比 0.70, 训练标签 0.555), 这时硬把裁剪拧到训练的 1.78
// 会二次失真 —— 先修尺度, 框的形状会自己跟着回来。
#define YOLO_VIEW_ADAPT   1
#define YOLO_VIEW_PITCH   25.8f   // 目标: 训练 p50 (320 空间)
// 下限 0.02 = 裁剪比 ① 框宽 4%。它**不是**训练契约 (那是 10%), 只是一个
// 别裁进 ① 框里面的保险。 为什么不守在 0.10:
//   2026-10-19 第四次上板, 远牌 (① 框 293~313 px) 的 pitch 只有 18.7~22.7,
//   而这一轮算出来的**需要的**外扩比例是 0.028~0.058 —— 全被 0.10 夹掉,
//   于是 pitch 永远够不到目标, 末两位粘连 (n=6)、省字位每轮翻。
// 注意这里量的是 pitch (≈字的实际大小), 不是"裁得多紧": 夹在 0.10 的时候
// 字**比训练小 27%**, 并不是"守住了训练取景"。 让它落到 pitch=25.8, 字的
// 大小才和训练对齐; 那时裁剪宽 = 框宽 x 1.06, 与训练 1.20 相差 12%, 而
// 字框宽仍在 anchor 上限 27.7 之内 (pitch 25.8 对应字宽 ≈24, 训练 p50)。
#define YOLO_VIEW_MINM    0.02f
#define YOLO_VIEW_MAXM    0.70f   // 上限: 再大就把背景/另一块牌拉进来了
#define YOLO_VIEW_MIX     0.50f   // 一阶滤波, 防止某一轮 ② 抽风把尺度带飞

// 隔离点带来的额外间隔 / pitch。 这个数是**训练标签**上量出来的, 不是板上估的:
// data_crop 的 4363 张 7 字单行裁剪图, 6 个相邻间隔各除以本行中位间隔 ——
//   档 0 (位0->1) 0.984 | **档 1 (位1->2) 1.357 (p10 1.282 / p90 1.433)** |
//   档 2..5      1.000 / 1.000 / 1.000 / 0.986
// 即多出来的是 0.357*pitch。 之前取 0.30 (从板上单行估的, 那行有 ±3 px 噪声),
// 用 0.30 拟合出来的格点会把首末位各推偏 0.03*pitch ≈ 1 px。
//
// 定义在这里而不是格点那一段, 是因为**这里更早用**: 由 7 个框中心跨度量 pitch
// 时除的就是 6+F。 格点、补位、取景三处共用这一个数, 不能有第二份。
#define YOLO_LATTICE_F     0.357f

static float s_cas_view_margin = 0.0f;  // 自适应外扩比例; 0 = 还没量到, 用默认值
static float s_cas_pitch_meas  = 0.0f;  // 上一轮量到的 pitch (320 空间), 只给日志
static float s_cas_slope_meas  = 0.0f;  // 字行倾斜 dy/dx (320 空间), 只给日志; 正 = 右边低
static float s_view_m_target   = -1.0f; // 最近一次量到的**目标**外扩比例; <0 = 还没量到

// 由 7 个字符框的中心跨度和 ① 框宽反推外扩比例。
//
// 这里**只更新目标, 不动当前值** —— 真正的滤波在 view_adapt_tick(), 每轮都调。
// 拆开是有原因的: 量 pitch 需要恰好 7 个框, 而 ② 掉框 (n=6/5) 恰恰是尺度不对
// 的症状。 旧写法把两者绑在一起, 于是"因为尺度不对所以掉框, 因为掉框所以不
// 更新尺度"—— 2026-10-19 第三次上板 #17..#23 连续 7 轮 `vp` 一字不差、
// 第四次上板 #17..#21 又是 5 轮 16 不动, 都是这个死循环。
// 现在: 没量到就沿用上一次的目标, 每轮都往目标收敛半步。
static void view_adapt_update(const YoloBox* ch, float bw, int cw)
{
    const float c0 = (ch[0].x1 + ch[0].x2) * 0.5f;
    const float c6 = (ch[6].x1 + ch[6].x2) * 0.5f;
    const float span = c6 - c0;
    if (span <= 8.0f || bw <= 1.0f) return;

    const float pitch = span / (6.0f + YOLO_LATTICE_F);
    // pitch ∝ 1/裁剪宽, 所以想让 pitch 落到目标, 裁剪宽就按比例反着改。
    float m = (((float)cw * pitch / YOLO_VIEW_PITCH) / bw - 1.0f) * 0.5f;
    if (m < YOLO_VIEW_MINM) m = YOLO_VIEW_MINM;
    if (m > YOLO_VIEW_MAXM) m = YOLO_VIEW_MAXM;
    s_view_m_target = m;
    s_cas_pitch_meas = pitch;
}

// 每轮一次: 把当前外扩比例朝最近的目标推半步。 没量到过目标就什么都不做
// (裁剪走训练契约 10%)。 第一次量到目标直接跳过去, 不从 0 慢慢爬。
static void view_adapt_tick(void)
{
    if (s_view_m_target < 0.0f) return;
    s_cas_view_margin = (s_cas_view_margin > 0.0f)
                      ? (s_cas_view_margin * (1.0f - YOLO_VIEW_MIX)
                         + s_view_m_target * YOLO_VIEW_MIX)
                      : s_view_m_target;
}

// ---- 横滚自适应: ② 的输入角度 --------------------------------------------
//
// 先分清两个角度, 这是这一节存在的全部理由:
//
//   ② 的输入是把裁剪矩形 (cw x ch) **硬拉**成 320x320, 两个轴的缩放不一样。
//   所以一条在帧里 dy/dx 是 s 的字行, 在 320 空间里是 s*cw/ch; 反过来,
//   320 空间里的倾斜 s720 折回帧里只有 s720*ch/cw。
//
//   2026-10-19 第四次上板 #27..#30 (黑B45678 / 粤A56TA9 / 津BA5618):
//   日志 `vp` 的 slope 是 -411 / -371 / -336 / -345 (x1000), 字行在 320 空间
//   里斜了 19~22 度, 看着像转过一大截; 而裁剪大约 280x95, 帧里的真实横滚
//   只有 6.5~7.9 度 —— 就是"手稍微转一下"的量级。 同一份日志里能读对的
//   那些轮次 slope <= 0.05 (3 度以内)。
//
//   击中模型的是**320 空间**那个 20 度: ② 的 anchors 是按竖着的字标定的
//   (ANCHORS_CROP 最大 27.7 x 133.9), 一行斜 20 度的字, 每个框的轴对齐
//   外接矩形从 26 宽涨到 ~54, 远超 anchor 上限, 于是整行框一起崩。
//
// 做法: 沿**牌面自己的两个轴**重采样 (resample_aff_to_i8), 把字行转正。
// 角度从 ② 自己的输出量 —— 7 个字框中心对 x 做最小二乘, 与尺度自适应同一个
// 套路: 不增加任何推理, 每轮修正一次。
//
// 两个必须记住的点:
//   (1) 校正之后量到的是**残差**, 不是总角度。 所以新角度 = 本轮已用的角度
//       + 残差。 直接拿残差当角度会来回摆 (转正 -> 残差 0 -> 转回去)。
//   (2) 角度小于 MIN 时**不启用**仿射通路, 仍然走 resample_rect_to_i8 ——
//       竖直的车牌逐像素等于冻结基线, 这一改对它零影响。
#define YOLO_ROLL_MIN      0.008f  // 0.46 度: 以下不动
#define YOLO_ROLL_MAX      0.30f   // 17 度: 再多就不是横滚了, 是框错了
#define YOLO_ROLL_MIX      0.65f   // 每轮朝新目标走 65% (增益 < 1, 不会过冲)
// ---- 两道合理性闸 (2026-10-20) -------------------------------------------
// 2026-10-20 那份"转牌"采集把这条反馈环的毛病暴露出来了: 只要 ② 的整行框
// 崩一次, 中心最小二乘就给出 slope = -0.509 (320 空间 27 度) 这种数; 它被
// 原样累加进 roll (权重 0.65), 一轮把角度推了 8 度 —— 下一轮的取样轴跟着
// 歪, 框更崩, slope 继续大。 日志上是:
//
//     vp ... -509,-54    ->  roll -144 -> -177 -> -186 -> -194 -> -203 -> -206
//     撞上 ±17 度的硬顶, 然后在 -201 和 +94 之间来回横跳
//
// 所以累加器必须能被拒绝, 而不只是被夹住: YOLO_ROLL_MAX 夹的是**总角度**,
// 挡不住"每轮 +8 度"这种错误输入。
//
//   (1) |slope| 比 0.35 (320 空间 19 度) 大 = 框错了, 这一轮不量, 沿用上一次
//       的目标。 手转牌到不了这个量级。
//   (2) 单轮改动封顶 2 度: 就算残差是真的, 一帧也转不了 5 度。
//
// 两道都是"宁可不修": 不修的代价是继续歪着, 修错的代价是把 ② 的整行框带崩。
#define YOLO_ROLL_SLOPE_MAX  0.35f   // 320 空间 slope 上限 (19 度)
#define YOLO_ROLL_STEP_MAX   0.035f  // 单轮最多改 2 度

static float s_cas_roll      = 0.0f;  // **本轮生效**的横滚 (rad, 帧空间; 正 = 右边低)
static float s_cas_roll_used = 0.0f;  // 只给日志: 本轮真正用上的角度
static float s_cas_roll_tgt  = 0.0f;  // 最近一次量到的**目标**角度

// 用 7 个字框的中心量字行横滚, 折回帧空间后累加到已用角度上。
// 只在 n == 7 时调用 (6 字/8 字的位次对不上, 斜率没有意义)。
static void roll_update(const YoloBox* ch, int cw, int chh)
{
    if (cw <= 0 || chh <= 0) return;

    float sx = 0.0f, sy = 0.0f, sxx = 0.0f, sxy = 0.0f;
    for (int i = 0; i < 7; i++) {
        const float x = (ch[i].x1 + ch[i].x2) * 0.5f;
        const float y = (ch[i].y1 + ch[i].y2) * 0.5f;
        sx += x; sy += y; sxx += x * x; sxy += x * y;
    }
    const float d = 7.0f * sxx - sx * sx;
    if (d <= 1e-3f) return;

    const float s320 = (7.0f * sxy - sx * sy) / d;
    s_cas_slope_meas = s320;                                  // 日志照旧打 320 空间的数
    if (s320 != s320) return;                                 // NaN 兜底
    if (fabsf(s320) > YOLO_ROLL_SLOPE_MAX) return;            // 框错了, 这一轮不量

    // 320 空间 -> 帧空间: x 方向按 cw/320 缩放、y 方向按 ch/320, 比值就是 ch/cw。
    // 这一行的视觉重要性高于它的长度: 少了它, 6.5 度会被当成 20 度去转。
    const float s_frame = s320 * (float)chh / (float)cw;

    // 累加的一定是**这一轮真正用上的**角度, 不能是 s_cas_roll: 当 |角度| 还
    // 没到 MIN、走的是轴对齐通路时, 实际转的是 0, 若拿 s_cas_roll 去加, 每轮
    // 都多算一次残差 —— 一块本来只有 0.2 度的牌会把角度越推越大。
    float r = s_cas_roll_used + atanf(s_frame);               // 已用的 + 残余
    // 单轮封顶 2 度 (见 YOLO_ROLL_STEP_MAX): 这一条挡的是"残差本身离谱"。
    // 夹在**增量**上而不是总角度上, 所以角度大是真的转过来了也照样跟得上,
    // 只是每轮最多追 2 度。
    if (r > s_cas_roll_used + YOLO_ROLL_STEP_MAX) r = s_cas_roll_used + YOLO_ROLL_STEP_MAX;
    if (r < s_cas_roll_used - YOLO_ROLL_STEP_MAX) r = s_cas_roll_used - YOLO_ROLL_STEP_MAX;
    if (r >  YOLO_ROLL_MAX) r =  YOLO_ROLL_MAX;
    if (r < -YOLO_ROLL_MAX) r = -YOLO_ROLL_MAX;
    s_cas_roll_tgt = r;
}

// 每轮一次: 把当前角度朝最近的目标推一步。 没量到过目标就什么都不做。
static void roll_tick(void)
{
    s_cas_roll = s_cas_roll * (1.0f - YOLO_ROLL_MIX)
               + s_cas_roll_tgt * YOLO_ROLL_MIX;
    if (fabsf(s_cas_roll) < 1e-5f) s_cas_roll = 0.0f;
}

