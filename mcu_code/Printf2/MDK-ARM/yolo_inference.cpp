// ---------------------------------------------------------------------------
// Depthwise convolution on the GPU.
//
// The operator itself is in gpu.c (gpu_dw_conv) and everything measured about
// what this silicon can express is in the long comment above it and in gpu.h.
// This file owns only the TFLM side: which nodes qualify, where the quantisation
// parameters come from, and what happens when the GPU disagrees with the CPU.
//
// THE RULE THIS IS BUILT ON: the GPU is an accelerator, not a prerequisite.  A
// node that does not qualify, a bias that would not fit the hardware's nine-bit
// field, a scale that would not encode, a GPU that never came up - all of them
// end in s_dw_stock.invoke() and the board carries on.  There is no path here
// that returns an error because the GPU had a problem.
//
// The design is deliberately a REPLACEMENT of one field of one struct:
// TFLMRegistration is a POD (micro_common.h:23), so s_dw_impl is s_dw_stock with
// invoke (and prepare, for the reason below) swapped.  init/free/prepare/reset
// keep running the stock implementation, which allocates its OpData in the arena
// exactly as before - so the stock invoke is always valid to fall back to.
// ---------------------------------------------------------------------------
extern "C" {
#include "gpu.h"
}

#define DW_MAX_CH     128
#define DW_MAX_LAYER  32
#define DW_CHK_PX     8192

// How far the GPU answer may drift from the CPU's on the same activations
// before this layer is handed back for good.
//
// Not 0, and not 1.  The activation is quantised to five bits on the way in -
// there is no wider entry into the kernel, measured - so an error of up to +-3.5
// per tap is expected against weights that reach 127, and a spread of several
// LSB is the design working, not a bug.  What is NOT acceptable is a systematic
// error, and that is what the count of pixels outside this bound catches: a
// wrong operator moves many pixels a long way, quantisation noise moves most of
// them a little.  `worst` is printed unconditionally whether or not this bound
// is met, because it is the number that says how much the 5-bit entry actually
// cost here.
#define DW_GAP_MAX    8

static TFLMRegistration s_dw_impl;
static TFLMRegistration s_dw_stock;

struct DwQ {
    int   filt;                 // node->inputs->data[1]: the layer's filter tensor
    int   fin;                  // node->inputs->data[0]: the layer's INPUT tensor
    int   c;
    int   ready;
    // Everything the GPU call needs that is only reachable from a TfLiteTensor.
    // Captured in prepare, because that is the only point at which TFLM
    // guarantees the TfLiteTensor form (and its quantization params) still
    // exists; see the note on dw_temp_in().
    float isc;                  // input activation scale  - per-tensor here
    float osc;                  // output activation scale - per-tensor here
    int   izp;                  // input zero point  - see dw_eligible()
    int   ozp;                  // output zero point
    float wsc[DW_MAX_CH];       // per-channel weight scales
};

static DwQ    s_dwq[DW_MAX_LAYER];
static int    s_dwq_n = 0;
static float  s_dw_inscale[DW_MAX_CH];
static int8_t s_dw_ref[DW_CHK_PX];

// 0 = the check below has not run yet for that class, 1 = it passed single
// pass, 2 = it passed ONLY with the hi/lo split, -1 = it failed at both and
// every layer of THAT CLASS is on the CPU for the rest of the session.
// Indexed by stride, and there is no index 0, so [1] is the stride-1 SAME
// layers and [2] the stride-2 VALID ones.
//
// Two verdicts rather than one, because the two classes are two different
// claims.  A stride-1 layer rests on the SAME padding rule and one UV origin; a
// stride-2 layer rests on a different UV origin and has no padding at all.  A
// single verdict would have had to choose one of them to trust blindly, and
// whichever it chose, the other class's first layer would run unverified for a
// whole session.  One failure now takes down one class and leaves the other
// running - which is the same conservatism, applied per geometry.
//
// The third outcome (2) is per class and not per layer: the split costs a
// second packing pass and a second draw per channel, so it is paid only by the
// geometry that needs it, and only after the cheap form has been measured to
// fail there.  Which class needs it is not a prediction - it is measured, on
// the first eligible layer of the class, at detection time.
static int s_dw_check[3] = { 0, 0, 0 };

// The same (filter, input) key as conv_q(), and for the same reason -- see the
// block comment there.  THIS MODEL has no depthwise collision (the tool that
// reads the .tflite, tools/conv_filter_index.py, checks both operators and
// reports none), so the change is bit-for-bit inert here: for a node whose
// filter index is unique it finds the same record it always did.  It is here
// because the two operators are the same design and the failure would be as
// silent as the conv one was, and because a .tflite re-export can introduce a
// collision without anyone touching this file.
static DwQ* dw_q(int filt, int fin)
{
    for (int i = 0; i < s_dwq_n; i++) {
        if (s_dwq[i].filt == filt && s_dwq[i].fin == fin) { return &s_dwq[i]; }
    }
    return nullptr;
}

// Reading a TfLiteTensor is NOT free, and this is the trap the first version of
// this glue fell into:
//
//   inline TfLiteTensor* MicroContextGetTensor(const TfLiteContext* context,
//                                              int tensor_idx) {
//     return GetMicroContext(context)->AllocateTempTfLiteTensor(tensor_idx);
//   }
//
// That is the function `ctx->GetTensor` points at, so every call takes a buffer
// out of the arena's temp pool and bumps a counter, and every one of them has to
// be handed back before the node's prepare returns.  Leaving even one alive makes
// FinishPrepareNodeAllocations() - which opens with
// TF_LITE_ENSURE_STATUS(ResetTempAllocations()) - return early for that node, and
// THAT node's scratch-buffer requests are then never given a node_idx.  The
// unassigned requests accumulate on a single counter across the whole graph, and
// once twelve of them are outstanding the allocator refuses a request that has
// nothing to do with any of this.  The depthwise change surfaced as
// `Node CONV_2D (number 64) failed to prepare with status 1' at init.
//
// So the arena is touched in exactly one place (prepare, where the release is
// mandatory anyway) and the two helpers below are the only things that touch it.
// In Eval nothing is allocated at all: a TfLiteEvalTensor is a fixed lookup, and
// whatever a node needs from the TfLiteTensor form - the quantization params in
// this case - was snapshotted into its DwQ entry at prepare time.
static TfLiteTensor* dw_temp_in(tflite::MicroContext* mc, const TfLiteNode* node,
                                int idx)
{
    if (node->inputs == nullptr || idx < 0 || idx >= node->inputs->size) {
        return nullptr;
    }
    if (node->inputs->data[idx] == kTfLiteOptionalTensor) { return nullptr; }
    return mc->AllocateTempTfLiteTensor(node->inputs->data[idx]);
}

static TfLiteTensor* dw_temp_out(tflite::MicroContext* mc, const TfLiteNode* node,
                                 int idx)
{
    if (node->outputs == nullptr || idx < 0 || idx >= node->outputs->size) {
        return nullptr;
    }
    if (node->outputs->data[idx] == kTfLiteOptionalTensor) { return nullptr; }
    return mc->AllocateTempTfLiteTensor(node->outputs->data[idx]);
}

// prepare, wrapped only to capture the per-channel weight scales.
//
// Every depthwise filter in this model is per-channel quantised - 27 of 27,
// measured offline with tools/dw_quant_check.py - so TfLiteTensor.params.scale,
// which is one float, is 0 for all of them and useless here.  The array lives in
// the tensor's TfLiteAffineQuantization, and TFLM micro is free to release that
// once AllocateTensors() has finished; whether this pack does is a pack-version
// detail rather than a promise.  So it is read here, in prepare, which runs
// before any release, and not in invoke where it may already be gone.
//
// Not being able to read it is not an error.  The layer is marked ineligible and
// the stock CPU invoke runs it, the same as for every other reason a layer might
// not qualify - read the fallback as "unknown", not as "the GPU is broken".
static TfLiteStatus dw_gpu_prepare(TfLiteContext* ctx, TfLiteNode* node)
{
    TfLiteStatus st = s_dw_stock.prepare(ctx, node);
    if (st != kTfLiteOk) { return st; }

    if (s_dwq_n >= DW_MAX_LAYER) { return kTfLiteOk; }

    tflite::MicroContext* mc = tflite::GetMicroContext(ctx);
    TfLiteTensor* fin  = dw_temp_in(mc, node, 0);
    TfLiteTensor* filt = dw_temp_in(mc, node, 1);
    TfLiteTensor* fout = dw_temp_out(mc, node, 0);

    // One exit, so the three releases below cannot be skipped by a `return` that
    // someone adds later.  Getting this wrong does not look like a depthwise bug
    // - it surfaces as an unrelated operator being refused at AllocateTensors.
    DwQ* taken = nullptr;

    if (fin != nullptr && filt != nullptr && fout != nullptr &&
        filt->dims != nullptr && filt->dims->size == 4) {
        const int C = filt->dims->data[3];
        if (C > 0 && C <= DW_MAX_CH &&
            fin->params.scale > 0.0f && fout->params.scale > 0.0f) {
            DwQ* q = &s_dwq[s_dwq_n];
            q->filt  = node->inputs->data[1];
            q->fin   = node->inputs->data[0];
            q->c     = C;
            q->ready = 0;
            q->isc   = fin->params.scale;
            q->osc   = fout->params.scale;
            q->izp   = fin->params.zero_point;
            q->ozp   = fout->params.zero_point;

            if (filt->quantization.type == kTfLiteAffineQuantization &&
                filt->quantization.params != nullptr) {
                const TfLiteAffineQuantization* aq =
                    (const TfLiteAffineQuantization*)filt->quantization.params;
                if (aq->scale != nullptr && aq->scale->size == C) {
                    for (int i = 0; i < C; i++) { q->wsc[i] = aq->scale->data[i]; }
                    q->ready = 1;
                }
            }
            if (!q->ready && filt->params.scale > 0.0f) {
                // A per-tensor filter lands here and is just as usable; this
                // model has none, but the branch is what makes the fallback a
                // fallback and not a guess about the model.
                for (int i = 0; i < C; i++) { q->wsc[i] = filt->params.scale; }
                q->ready = 1;
            }
            if (q->ready) { taken = q; }
        }
    }

    if (fin  != nullptr) { mc->DeallocateTempTfLiteTensor(fin); }
    if (filt != nullptr) { mc->DeallocateTempTfLiteTensor(filt); }
    if (fout != nullptr) { mc->DeallocateTempTfLiteTensor(fout); }

    // The slot is only consumed if it was actually filled, so a layer that could
    // not be read leaves s_dwq_n where it was rather than burning a slot on a
    // half-written entry.
    if (taken != nullptr) { s_dwq_n++; }
    return kTfLiteOk;
}

// The eligibility test.
//
// Written as "prove this is the shape I implement" rather than as a list of
// known-bad cases, because a layer this does not recognise is a layer it must
// not touch.  Everything rejected here runs on the CPU and produces the same
// answer it always did.
//
// "Ineligible" is the NORMAL answer for the 8 five-by-five layers of the
// model's 27 depthwise layers, so it is not a failure and it prints nothing.
// That distinction is what this function exists to make explicit.  An earlier
// version returned the same 0 for "not my shape" and "the GPU refused to draw",
// and because the FIRST depthwise node in execution order is op5 - a stride-2
// layer - the one-time check bailed on it and disabled the whole feature for the
// session.  All 13 eligible layers ran on the CPU and the log said only
// `L0 D0 R0`; the answers were in `gpu dw call q27 e1 s4 d1` all along, in the
// form of everything being right.
//
// Two shapes are eligible now, 3x3, depth_multiplier 1, no fused activation,
// and between them 19 of the model's 27 depthwise layers:
//
//     stride 1 + SAME   output == input                      13 layers
//     stride 2 + VALID  output == ((input - 3) / 2) + 1       6 layers
//
// The stride-2 layers are VALID over an input a preceding PAD op has already
// padded (op4 pads to 82x82 so op5 can take 82x82 to 40x40), so every tap of
// every output pixel is inside the plane.  They go through the same 9-tap
// kernel and the same four CLUT words as the stride-1 layers; the only
// difference is where the window is centred, which is the UV origin and the
// du/dx step - see gpu_dw_conv()'s stride branch for the measurement that
// settled that.
//
// Still out: the 8 five-by-five layers.  Their RELU turns out to be a no-op
// (their output zero point is -128, and TFLM's int8 RELU is max(y, out_zp),
// which at -128 is the identity), but their kernel needs nine CLUT words per
// channel instead of four, and 9 x 72 channels = 648 is past the 512 the part
// gives us.
//
// What this resolves, so the caller does not have to re-derive it: which layer,
// which tensors, and the geometry gpu_dw_conv() is about to be handed.  The
// check and the draw both use the same DwJob, so they cannot disagree about
// what "this layer" means.
struct DwJob {
    const TfLiteEvalTensor* fin;
    const TfLiteEvalTensor* filt;
    const TfLiteEvalTensor* bias;
    const TfLiteEvalTensor* fout;
    DwQ* q;
    int  h, w, c;      // input plane
    int  oh, ow;       // output plane
    int  stride;
};

// ===========================================================================
// THE CHAIN FINGERPRINT - where does one inference stop agreeing with the last?
// ===========================================================================
//
// WHY THIS EXISTS.  `gpu dw gpudiff` answered its own question on both stride
// classes (`worst 0 bad 0`): ONE DRAW IS REPRODUCIBLE.  A layer drawn twice,
// back to back, from the same source through the same CLUT into the same
// destination reads back byte-identical, which closes the whole of
// gpu_dw_conv() and dw_pass_bc() as the home of the instability.  But two runs
// of ONE frozen frame decode differently - four `i` presses gave four plates
// and four box sets - so the divergence is in the CHAIN: somewhere at or
// before some layer, two runs stop carrying the same activations.
//
// The instrument below localises that, and it is the cheapest one that can.
// For every ELIGIBLE depthwise layer, in execution order, it hashes the layer's
// INPUT and its OUTPUT.  One column per inference, indexed by position.  Two
// `i` presses therefore give two indexable columns, and the FIRST POSITION THAT
// DIFFERS is the first depthwise layer that is not reproducible.
//
// THE INPUT HASH IS THE CHANGE THIS VERSION MAKES, and the first version's
// reading is why.  That one hashed the input of the FIRST eligible layer only,
// and on 2026-10-10 it came back `inF06CD255` in all three inferences while all
// nineteen outputs differed.  So the chain's input is byte-identical and the
// first eligible layer's output is not, which says that layer is not a pure
// function of its input - and `gpu dw gpudiff` had already read
// `worst 0 bad 0` on the first eligible layer of each stride class, i.e. that a
// back-to-back redraw IS byte-identical.  Both cannot hold for a draw that is a
// function of its operands, so the difference between runs is in the STATE the
// draw reads or in one of the two scratch planes it sits between - and gpudiff,
// which redraws with no pack and no unpack in between, is structurally blind to
// both.
//
// Per position, then:
//
//   `i` differs -> this layer's operand moved, so whatever moved it is at or
//       before the previous position.  This layer is a bystander.
//   `i` matches and `o` differs -> this layer's own draw is not a function of
//       its operands.  That is the position that matters.
//
// WHAT IT IS NOT.  It does not compare against the CPU - the per-class check
// does that - and it does not say which of two disagreeing numbers is right.
// It says only WHERE two runs stop agreeing, which is the one thing missing.
//
// COST.  Two bounded samples per layer, on the CPU, once per inference.  No GPU
// work, no extra draw, nothing that can reach the arithmetic.  Inert unless `g`
// has been pressed, because a layer that is not eligible is never hashed.
#define DW_HASH_SAMP  4096

static uint32_t s_dw_hi[DW_MAX_LAYER];
static uint32_t s_dw_h[DW_MAX_LAYER];
static int      s_dw_hn       = 0;
static int      s_dw_ord_last = -1;

// FNV-1a over a spread sample rather than the first N bytes, because a
// depthwise output is NHWC: the first N bytes are the first few pixels of the
// first channel, so a divergence confined to a later channel - which is
// exactly what a per-channel CLUT or per-channel bias fault produces - would
// not be seen at all.  `step` is n / DW_HASH_SAMP, so the sample always spans
// the whole tensor however large it is.
static uint32_t dw_hash_tensor(const int8_t* p, const TfLiteEvalTensor* t)
{
    uint32_t h = 2166136261u;
    int      i, n = 1, step;

    if (p == nullptr || t == nullptr || t->dims == nullptr) { return 0u; }
    for (i = 0; i < t->dims->size; i++) { n *= t->dims->data[i]; }
    if (n <= 0) { return 0u; }

    step = (n > DW_HASH_SAMP) ? (n / DW_HASH_SAMP) : 1;
    for (i = 0; i < n; i += step) {
        h = (h ^ (uint32_t)(uint8_t)p[i]) * 16777619u;
    }
    return h;
}

static void dw_hash_rec(const DwJob* j)
{
    if (j == nullptr || j->fout == nullptr) { return; }
    if (s_dw_hn >= DW_MAX_LAYER)            { return; }
    s_dw_h[s_dw_hn] = dw_hash_tensor(j->fout->data.int8, j->fout);
    s_dw_hn++;
}

// One line per position and not four to a line: there are two hashes per
// position now, so four of them no longer fit in Message[]'s 160 bytes - and a
// line per position is what makes the first disagreement findable by eye
// without counting columns.
static void dw_hash_flush(void)
{
    int k;

    if (s_dw_hn <= 0) { return; }

    sprintf(Message, "gpu dw H n%d\r\n", s_dw_hn);
    UART_SendString(Message);

    for (k = 0; k < s_dw_hn; k++) {
        sprintf(Message, "gpu dw H %d i%08X o%08X\r\n",
                k, (unsigned)s_dw_hi[k], (unsigned)s_dw_h[k]);
        UART_SendString(Message);
    }

    s_dw_hn = 0;
}

// Called once per eligible layer, BEFORE it draws, and it does two jobs: it
// reports the inference that just finished, and it seeds the new one.
//
// A new inference begins when the layer ordinal stops increasing, and that
// test is exact here for the same reason the withdrawn auto-trace's boundary
// detection was exact: prepare filled s_dwq[] in model order, the layers are
// visited in model order within one inference, and j.q is always in s_dwq[]
// because dw_eligible() put it there.  Layer ordinals of the ineligible
// layers (the eight 5x5) are skipped rather than printed, so a divergence
// entering at one of those shows up as the next eligible layer disagreeing,
// which is still a localisation - just a one-layer-wide one.
//
// Printing the PREVIOUS inference's column here, rather than at the end of the
// inference it describes, is what makes the last inference of a run need one
// more keypress before it is reported.  There is no end-of-inference hook to
// use instead, and this costs nothing else.
static void dw_hash_wrap(const DwJob* j)
{
    const int ord = (int)(j->q - s_dwq);

    if (ord <= s_dw_ord_last) { dw_hash_flush(); }
    s_dw_ord_last = ord;

    if (s_dw_hn < DW_MAX_LAYER) {
        s_dw_hi[s_dw_hn] = dw_hash_tensor(j->fin->data.int8, j->fin);
    }

    // The first two eligible layers of an inference are the two gpudiff tested
    // (one per stride class, each checked once per boot), so they are the two
    // whose disagreement with gpudiff would mean something - and the plane
    // probe is a UART burst inside the draw sequence, so it is not free.  See
    // gpu_dw_plane_arm().
    if (s_dw_hn < 2) { gpu_dw_plane_arm(); }
}

static int dw_eligible(TfLiteContext* ctx, TfLiteNode* node, DwJob* j)
{
    const TfLiteDepthwiseConvParams* p =
        (const TfLiteDepthwiseConvParams*)node->builtin_data;

    // The master switch, and it is checked before anything else because
    // "switched off" has to mean the layer never touches the per-class state,
    // never runs the one-time check, and never counts as an eligible layer.
    // Read as a variable rather than compiled out - see gpu.h - so the same
    // binary can be measured both ways on the same still scene.  0 is the
    // reset value, so an un-flipped board runs the stock CPU kernel on every
    // layer, which is the pipeline the product had before the GPU work.
    if (g_gpu_dw_on == 0u)               { return 0; }

    if (p == nullptr)                    { return 0; }
    if (p->depth_multiplier != 1)        { return 0; }
    if (p->dilation_width_factor  != 1)  { return 0; }
    if (p->dilation_height_factor != 1)  { return 0; }
    if (p->activation != kTfLiteActNone) { return 0; }

    // The two shapes, and nothing in between.  Stride is checked as a pair with
    // padding because the padding is what makes each one correct: SAME at
    // stride 1 preserves the size, VALID at stride 2 halves it.  A layer that
    // is SAME at stride 2 or VALID at stride 1 is a third geometry that
    // gpu_dw_conv() does not draw, and drawing the wrong geometry is a wrong
    // answer rather than a refusal - so it is refused here.
    if (p->stride_width != p->stride_height) { return 0; }
    if (p->stride_width == 1)
    {
        if (p->padding != kTfLitePaddingSame) { return 0; }
    }
    else if (p->stride_width == 2)
    {
        if (p->padding != kTfLitePaddingValid) { return 0; }
    }
    else
    {
        return 0;
    }

    // Eval tensors, not TfLiteTensors: this runs during invoke, and nothing here
    // may allocate.  The TfLiteTensor form was only ever needed to reach the
    // quantization params, and prepare has already captured those into the DwQ
    // entry, so the invoker's own ResetTempAllocations() - which is called
    // WITHOUT TF_LITE_ENSURE_STATUS at micro_interpreter_graph.cpp and so fails
    // silently - always finds the temp pool clean and actually rewinds it.
    const TfLiteEvalTensor* fin  = ctx->GetEvalTensor(ctx, node->inputs->data[0]);
    const TfLiteEvalTensor* filt = ctx->GetEvalTensor(ctx, node->inputs->data[1]);
    const TfLiteEvalTensor* bias = ctx->GetEvalTensor(ctx, node->inputs->data[2]);
    const TfLiteEvalTensor* fout = ctx->GetEvalTensor(ctx, node->outputs->data[0]);
    if (fin == nullptr || filt == nullptr || bias == nullptr || fout == nullptr) {
        return 0;
    }

    if (fin->type  != kTfLiteInt8)  { return 0; }
    if (filt->type != kTfLiteInt8)  { return 0; }
    if (bias->type != kTfLiteInt32) { return 0; }
    if (fout->type != kTfLiteInt8)  { return 0; }
    if (fin->dims  == nullptr || fin->dims->size  != 4) { return 0; }
    if (filt->dims == nullptr || filt->dims->size != 4) { return 0; }
    if (fout->dims == nullptr || fout->dims->size != 4) { return 0; }
    // 3x3 only, and this is the last depthwise batch - the eight 5x5 layers are
    // NOT a matter of unfinished work.  They were emulated offline against this
    // model and this exact detection frame (tools/dw_gpu_emulate.py, which the
    // 3x3 class validates: it reproduces the measured stride-2 worst 25 as 26
    // and the measured split result worst 4 as 4, exactly), and they cannot be
    // drawn by gpu_dw_conv() for two independent reasons:
    //
    //   HALF OF THEM, in_zp != -128 (measured: -2, 10, 22 and 8 against -128 for
    //   all nineteen 3x3 layers).  Packing `in_q - in_zp` instead clips 44% of
    //   the input to 0 and measures 90 LSB of error on 3034 pixels; keeping
    //   +128 and moving (128 + in_zp)*sum(w) into the texture bias needs +-1523
    //   in a field nine bits wide, [-256, 255].  Both forms are measured, not
    //   estimated - the second one is what the first was derived to avoid.
    //
    //   THE OTHER HALF have ~67% of their output sitting at the BOTTOM of the
    //   byte range (their RELU floor: out_zp is -128, so the fused RELU is the
    //   byte clamp and the floor is byte 0).  Pass 1 clips there, and once it
    //   has, the split's correction is unrecoverable - it is added against a
    //   saturated byte.  Measured worst 18 with 79..115 pixels over the
    //   threshold, against the 3x3 class's 4.
    //
    // The split's arithmetic is NOT what fails: with the clamp removed from both
    // passes it is exact to 1 LSB on all 27 layers.  And lifting pass 1 with the
    // free half of the bias split was swept rather than argued - the best
    // constant lift is 0 for six of the eight, and where it is not it moves the
    // clip to the top where far more data lives.  There is no 16-bit destination
    // to escape into either; L_8 is the widest single-value one the driver has.
    //
    // WHAT ACTUALLY SEPARATES THE TWO CLASSES IS SATURATION, and that is the
    // thing to measure before believing the split on a layer: pass 1 never lands
    // on an end of 0..255 for ANY of the 19 3x3 layers, and does for every one
    // of the 5x5.  The bound in gpu_dw_bound() does not predict this - stride 1's
    // bound (9) exceeds DW_GAP_MAX (8), and the measured result went the OTHER
    // way from what that suggests: stride 1's single pass turned out to fail
    // once every channel was compared, so both 3x3 classes now run the split and
    // only the saturation count ever sorted them apart.
    if (filt->dims->data[1] != 3 || filt->dims->data[2] != 3) { return 0; }

    const int h = fin->dims->data[1];
    const int w = fin->dims->data[2];
    const int C = fin->dims->data[3];
    if (C <= 0 || C > DW_MAX_CH)      { return 0; }
    if (h <= 0 || w <= 0)             { return 0; }
    if (filt->dims->data[3] != C)     { return 0; }
    // The output shape the stride implies, derived here and then CHECKED
    // against the tensor rather than taken from it: reading oh/ow off fout and
    // handing them to gpu_dw_conv() would make the validation there a
    // tautology, and the point of it is to catch a layer whose declared output
    // does not match what the stride says.
    const int oh = (p->stride_width == 1) ? h : (((h - 3) / 2) + 1);
    const int ow = (p->stride_width == 1) ? w : (((w - 3) / 2) + 1);
    if (oh <= 0 || ow <= 0)           { return 0; }
    if (fout->dims->data[1] != oh)    { return 0; }
    if (fout->dims->data[2] != ow)    { return 0; }
    if (fout->dims->data[3] != C)     { return 0; }
    if (fin->data.int8 == nullptr)    { return 0; }
    if (filt->data.int8 == nullptr)   { return 0; }
    if (bias->data.i32 == nullptr)    { return 0; }
    if (fout->data.int8 == nullptr)   { return 0; }

    DwQ* q = dw_q(node->inputs->data[1], node->inputs->data[0]);
    if (q == nullptr || !q->ready || q->c != C) { return 0; }

    // The pack is `in_q + 128`, which is `in_q - in_zp` with in_zp assumed to be
    // -128, and that is the only shift the texel can carry: it is an UNSIGNED
    // five bits, so the code has to be non-negative.  All 19 3x3 layers in this
    // model do have in_zp = -128, but that is a property of how the converter
    // quantised them and not of any test above, so it is asserted here rather
    // than relied on.  A layer with any other zero point would be drawn WRONG -
    // not refused - and a wrong answer is the one outcome the fallback exists to
    // prevent.  See the 5x5 note above the kernel-size test for what it costs
    // when it is not -128.
    if (q->izp != -128) { return 0; }

    j->fin  = fin;
    j->filt = filt;
    j->bias = bias;
    j->fout = fout;
    j->q    = q;
    j->h    = h;
    j->w    = w;
    j->c    = C;
    j->oh    = oh;
    j->ow    = ow;
    j->stride = p->stride_width;
    return 1;
}

// The GPU pass itself, split out so the caller can tell the two answers apart:
// a 0 here is the GPU refusing to draw, and that is the only thing worth
// disabling the feature over.
static int dw_draw(const DwJob* j, int split)
{
    // Scales and the output zero point come from the snapshot taken in prepare,
    // which is the only place they were reachable.  gpu_dw_conv() takes the
    // input scale per channel; in this model they are all the same number.
    for (int i = 0; i < j->c; i++) { s_dw_inscale[i] = j->q->isc; }

    return (gpu_dw_conv(j->fin->data.int8, j->filt->data.int8, j->bias->data.i32,
                        s_dw_inscale, j->q->wsc, j->q->osc, j->q->ozp,
                        j->h, j->w, j->c, j->stride, j->oh, j->ow, split,
                        j->fout->data.int8) == 0) ? 1 : 0;
}

// The one-time real-activation check, run on the first depthwise node of each
// stride class that is ELIGIBLE, and never again for that class except to try
// the split.  The caller has already established eligibility and hands over the
// DwJob it resolved, so this function cannot run on a layer the GPU does not
// draw - which is exactly the mistake it used to make, on op5, the first
// depthwise node, whose stride is 2.
//
// Two classes and not one, because eligibility widened and the first eligible
// node changed with it: op5 is now eligible, so a single check would sample the
// stride-2 path and then vouch for the 13 stride-1 layers it never ran on.  The
// two paths differ in the UV they hand gpu_dw_conv(), so a reading from one is
// not evidence about the other.
//
// `split` is the mode being measured, and it is a PARAMETER rather than
// something read from s_dw_check, because the caller runs this twice on the
// same layer when the cheap mode fails and the second run has to be able to ask
// for the expensive one.  It sets s_dw_check to 1 or 2 according to what passed
// and leaves the escalation decision to the caller.
//
// Same discipline as gpu_selftest(): the CPU answer is the reference, and the
// comparison is on real activations rather than on synthetic data, because that
// is the only version of the question that matters.  It is a sample and not the
// whole tensor - the first min(np*C, DW_CHK_PX) entries of the contiguous NHWC
// tensor, i.e. every channel of the first few hundred pixels - because the
// reference has to be copied out of the tensor before the GPU pass overwrites
// it, and a window that fits a small static buffer is worth more than a whole
// tensor that does not.
//
// The sample used to be `src[i * C]` - channel 0 of the first 8192 PIXELS - and
// that was not a smaller version of this check, it was a different one: the cap
// never bound, channel 0 was compared in full, and channels 1..C-1 were never
// looked at.  On 2026-09-17 that turned out to hide a real failure.  Stride 1
// read `worst 4 bad 0` on channel 0 and reads `worst 9 bad 1` over all channels;
// it had been passing single-pass on a sample that could not see the pixel that
// fails it.  So the coverage is part of the answer here, not a detail of it.
//
// Note what this does NOT prove: it says the first eligible layer of each class
// matched, on the sample above.  The rest of the layers are trusted on the
// strength of it, which is why `worst` is printed rather than just a verdict - a
// reading of 1 across the board is evidence, and a reading of 1 that is really
// 1-because-we-clamped-it is what DW_GAP_MAX exists to expose.
// Every bail in dw_run_check names itself, and there are only two left: the
// stock CPU invoke failing ("cpu") and the GPU refusing to draw ("gpu").  Both
// are real.  An ineligible layer no longer reaches here at all - see the note on
// dw_eligible() for why that mattered.
//
// The first version of this function set s_dw_check to -1 and returned from four
// different places without printing anything, and the whole visible symptom was
// a detection coming back `L0 D0 R0` with not one line in the log to say which
// of the four had fired.  A guard that disables the feature for the session has
// to say so.
static void dw_chk_bail(int s, const char* why)
{
    s_dw_check[s] = -1;
    sprintf(Message, "gpu dw chk bail s%d %s\r\n", s, why);
    UART_SendString(Message);
}

static void dw_run_check(TfLiteContext* ctx, TfLiteNode* node, const DwJob* j,
                         int split)
{
    const int C  = j->c;
    const int s  = j->stride;
    // The OUTPUT plane, not the input one.  These were j->h * j->w while every
    // eligible layer was stride 1 and the two were the same number; at stride 2
    // the output is a quarter of the input, and walking h*w pixels of an oh*ow
    // tensor would read past the end of it.
    const int np = j->oh * j->ow;

    // CPU first: it is the reference, and the GPU pass that follows writes over
    // the tensor it lives in, which is why the sample is copied out first.
    if (s_dw_stock.invoke(ctx, node) != kTfLiteOk) { dw_chk_bail(s, "cpu"); return; }

    // Interior and border are counted separately, not averaged into one number.
    //
    // They are two different claims: TFLM pads SAME with the input zero point,
    // the GPU pads with the border colour, and whether those agree is worth
    // knowing but is not what DW_GAP_MAX is about.  Measured on op21, the first
    // version of this check reported `worst 42 bad 1560` where the three sample
    // pixels it printed were all in column 0 - one number with a border-shaped
    // error in it cannot say whether the arithmetic moved or the edge did.
    //
    // For a stride-2 VALID layer there is no border at all: every tap of every
    // output pixel is inside the plane.  The classification below is still
    // applied, so both numbers print - but out there "border" is just more
    // interior, and both are expected to read the same small number.
    //
    // The sample is CONTIGUOUS, and that is what puts every channel in the
    // evidence.  It used to be `src[i * C]` - pixel i, channel 0, for the first
    // 8192 pixels - and since the largest eligible plane is 40x40 = 1600, the cap
    // never bound and channel 0 was compared in full while channels 1..C-1 were
    // never looked at.  The arithmetic is per-channel-identical (the emulation
    // checks all 27 layers on all channels and finds the split exact to 1 LSB),
    // but the HARDWARE that differs between channels is the CLUT base this
    // operator steps by GPU_DW_QUAD words per channel.  An off-by-one there
    // gives a channel the wrong taps and channel 0 cannot see it.
    //
    // In NHWC the first min(np*C, DW_CHK_PX) entries are exactly (pixel, channel)
    // pairs already, so this is the same buffer with the stride removed: the
    // layers whose tensors fit inside the cap - every 48- and 96-channel one -
    // are now compared over the WHOLE tensor, all channels, and the 24-channel
    // 40x40 ones get their first 341 pixels of every channel instead of all 1600
    // of one.  Same 8 KB, far more of the operator in it.
    const int total = np * C;
    const int n     = (total < DW_CHK_PX) ? total : DW_CHK_PX;
    const int8_t* src = j->fout->data.int8;
    for (int i = 0; i < n; i++) { s_dw_ref[i] = src[i]; }

    // The UV sweep that used to run here is gone, and what it measured is why:
    // all eight candidate windows were drawn against this reference and every
    // one of them was worse than the derived UV (worst 25 against 28, 30, 32,
    // 32, 93 and 113 for the others; the derived one also had the fewest pixels
    // over the threshold).  The window was never the fault.  gpu_dw_uv_set()
    // and its friends stay in gpu.c because they are the instrument, and a
    // stride-2 layer that stops matching after some future change should be
    // swept with them again before anything else is believed.
    if (!dw_draw(j, split)) { dw_chk_bail(s, "gpu"); return; }

    const int W = j->ow;           // the OUTPUT width: the loop strides the output
    int bad = 0, worst = 0;        // interior: the arithmetic
    int ebad = 0, eworst = 0;      // border ring: the padding rule
    int nin = 0, ned = 0;

    for (int i = 0; i < n; i++) {
        const int p = i / C;       // the PIXEL, since the sample is contiguous
        const int y = p / W;
        const int x = p - (y * W);
        int d = (int)src[i] - (int)s_dw_ref[i];
        if (d < 0) { d = -d; }

        if (x < 2 || y < 2 || x >= W - 2 || y >= j->oh - 2) {
            ned++;
            if (d > eworst) { eworst = d; }
            if (d > DW_GAP_MAX) { ebad++; }
        } else {
            nin++;
            if (d > worst) { worst = d; }
            if (d > DW_GAP_MAX) { bad++; }
        }
    }

    // Which mode earned the verdict is part of the verdict: 1 means the cheap
    // single-pass draw met the tolerance for this class, 2 means it did not and
    // the split did.  The caller reads it back to decide how to draw from here
    // on, so it is not a label - it is the switch.
    // The WHOLE plane decides it now, ring included.  This used to be `bad`
    // alone - the ring was reported but did not turn the feature off, because it
    // was failing on the border colour and an operator that is right everywhere
    // but the edge is still worth having.  That is no longer the situation: the
    // ring was the ARGB8888 border colour, dw_pass_bc() fixed it, and both
    // classes now measure `ed worst 4 bad 0` - identical to their interior, as
    // they should be, since a SAME layer's border is the same arithmetic with a
    // zero tap.  Keeping the exemption after that would only mean a future
    // border regression is reported and not acted on, which is the one shape of
    // failure this check is supposed to make impossible.
    s_dw_check[s] = ((bad + ebad) == 0) ? (split ? 2 : 1) : -1;

    // What the five-bit texel alone can cost THIS layer, independent of any
    // window: max over channels of m*3.5*sum|w|, which is the bound on the
    // truncation residual that is not compensated by the bias.  Printed for
    // every run so that the split's two lines can be read against each other -
    // the bound does not change between them, only `worst` does, and that
    // difference is the whole evidence that the residual was the cause.
    sprintf(Message, "gpu dw uvb s%d sp %d m35sumw %d worst %d gapmax %d\r\n",
            s, split, (int)(gpu_dw_bound() + 0.5f), worst, (int)DW_GAP_MAX);
    UART_SendString(Message);

    // Both numbers always, pass or fail: a border that is wrong while the
    // arithmetic is right is a different finding from the reverse, and printing
    // only on failure hides the case where the interior is clean and the ring is
    // not - which is exactly the state this check was in until 2026-09-17.
    // Tagged with the stride class, because both classes print this line now and
    // two unlabelled pairs of numbers from two different geometries would be
    // unreadable in the log.
    sprintf(Message, "gpu dw chk s%d in n %d worst %d bad %d\r\n", s, nin, worst, bad);
    UART_SendString(Message);
    sprintf(Message, "gpu dw chk s%d ed n %d worst %d bad %d\r\n", s, ned, eworst, ebad);
    UART_SendString(Message);

    // The shape of the error, not just its size.  A constant offset shows as two
    // ranges of equal width, a scale error as a GPU range that is the CPU range
    // multiplied, and saturation as a GPU range pinned to -128/127 - and the
    // pairs tell the three apart in one line.
    //
    // The three samples are the first, middle and last PIXEL of whatever the
    // sample actually covers, not of the plane.  They used to be the plane's
    // centre and three rows below it, named by pixel index; with the sample now
    // contiguous and capped at DW_CHK_PX, a plane-indexed pixel can fall outside
    // it and read past the buffer, so the sampled range is what they name.  Both
    // sides are read through the SAME index, which the contiguous sample made
    // true: s_dw_ref[j] and src[j] are both (pixel j/C, channel j%C).
    if (s_dw_check[s] < 0) {
        const int npx  = n / C;
        const int last = (npx - 1) * C;
        const int mid  = (npx / 2) * C;
        const int ci3[3] = { 0, mid, last };

        int cl = s_dw_ref[0], ch = s_dw_ref[0];
        int gl = src[0],      gh = src[0];
        for (int i = 0; i < 3; i++) {
            const int k = ci3[i];
            if (s_dw_ref[k] < cl) { cl = s_dw_ref[k]; }
            if (s_dw_ref[k] > ch) { ch = s_dw_ref[k]; }
            if (src[k] < gl) { gl = src[k]; }
            if (src[k] > gh) { gh = src[k]; }
        }
        sprintf(Message, "gpu dw rng c %d..%d g %d..%d\r\n", cl, ch, gl, gh);
        UART_SendString(Message);

        sprintf(Message, "gpu dw d %d %d %d %d %d %d\r\n",
                (int)s_dw_ref[0], (int)src[0],
                (int)s_dw_ref[mid], (int)src[mid],
                (int)s_dw_ref[last], (int)src[last]);
        UART_SendString(Message);
    }

    // Printed at detection time, not at init: the boot trace before
    // `yolo init ERROR` is kept clean on purpose.  The verdict covers the whole
    // plane, ring included - see the note at the assignment.  `n`/`worst`/`bad`
    // on the line remain the INTERIOR's, because that is the arithmetic and the
    // number to compare against a previous run; the ring's pair is printed above.
    //
    // `sp` is in the verdict line as well as the bound line.  It reads 1 for
    // every class now that both are measured on the split form (see the note at
    // the call), so `OK sp 0` is no longer a line this code can produce - but the
    // field stays, because it is what made the old two-verdict log readable and
    // because a log from before that change still has to be read correctly.
    sprintf(Message, "gpu dw check s%d %s sp %d n %d worst %d bad %d\r\n",
            s, (s_dw_check[s] == 1) ? "OK" : ((s_dw_check[s] == 2) ? "OK2" : "FALLBACK"),
            split, nin, worst, bad);
    UART_SendString(Message);

    // ================= IS ONE DRAW DETERMINISTIC? =========================
    //
    // WHY. The product's depthwise output is unstable BETWEEN RUNS of one
    // frozen frame: `x` then `i` x4 on one retained rgb[] gave four different
    // plates and four different box sets, every box `cls 0`, with the drain
    // counters CLEAN (`strt0 nz0 bus001 to0`, only the one `keep ms0` IDLE
    // sighting) - so it is not a start, not the fetch gate and not a timeout.
    // The check above passes (`worst 6` / `worst 4`) on both classes and is
    // stable across boots, which means the ONE draw it measures is fine and
    // says nothing about the other seventeen layers.
    //
    // So the question this line answers is the one that splits the remaining
    // two candidates, and it needs a second draw of THIS layer and no new
    // instrument: draw the same layer twice, back to back, same source, same
    // CLUT, same destination, same uv, and compare the two GPU results.
    //
    //   `gpudiff worst 0`   -> one draw IS deterministic, so the instability
    //                          enters BETWEEN draws - between layers, i.e. in
    //                          state one layer leaves for the next.
    //   `gpudiff worst > 0` -> a single draw is not reproducible from the same
    //                          inputs. That is the race, and it is inside
    //                          gpu_dw_conv/dw_pass_bc, not in the chain.
    //
    // FREE, and it cannot change the product. dw_run_check()'s draws are
    // ALWAYS overwritten: the caller draws this layer again at its own call
    // site (the `s_dw_check < 0` test is followed by `dw_draw`), so the layer's
    // final output is the caller's draw either way. This is one extra draw on
    // ONE layer per stride class per boot, and only when the verdict passed -
    // a failed class is already going to the CPU and must not be drawn again.
    //
    // s_dw_ref is reused rather than dedicating another 8 KB: every reader of
    // it above (the CPU comparison, `rng`, `d`) has already run. A draw that
    // gives up here is reported, not acted on: the same give-up has already
    // latched s_dw_gpu_dead inside gpu.c, so every later layer is refused
    // whatever this line prints.
    if (s_dw_check[s] >= 0) {
        int gw = 0, gbad = 0;

        for (int i = 0; i < n; i++) { s_dw_ref[i] = src[i]; }

        if (dw_draw(j, split)) {
            for (int i = 0; i < n; i++) {
                int d = (int)src[i] - (int)s_dw_ref[i];
                if (d < 0) { d = -d; }
                if (d > gw) { gw = d; }
                if (d > DW_GAP_MAX) { gbad++; }
            }
            sprintf(Message, "gpu dw gpudiff s%d n %d worst %d bad %d\r\n",
                    s, n, gw, gbad);
        } else {
            sprintf(Message, "gpu dw gpudiff s%d refused\r\n", s);
        }
        UART_SendString(Message);
    }
}

static TfLiteStatus dw_gpu_invoke(TfLiteContext* ctx, TfLiteNode* node)
{
#if GPU_ENABLE
    // Once, on the first depthwise node of the first inference.  `q` is how many
    // layers prepare managed to capture (0 means prepare never ran or never got
    // past its guards); `e/s/d` are the eval-tensor access this whole path is
    // built on.  Without this line, "invoke is never reached" and "invoke runs
    // and bails" look identical in the log.
    {
        static int once = 0;
        if (once == 0) {
            /* 2026-10-12: the LATCH is outside the gate (once = 1 runs either way),
               only this one-shot report is behind BOOT_VERBOSE - it fires on the
               first inference, i.e. right after `boot ok`, so at 0 the delivered
               log goes straight from `boot ok` to `#1 plate: ...`. */
            once = 1;
#if BOOT_VERBOSE
            {
                const TfLiteEvalTensor* e = ctx->GetEvalTensor(ctx, node->outputs->data[0]);
                sprintf(Message, "gpu dw call q%u e%u s%u d%u\r\n",
                        (unsigned)s_dwq_n, (unsigned)(e != nullptr),
                        (unsigned)((e != nullptr && e->dims != nullptr) ? e->dims->size : 9u),
                        (unsigned)((e != nullptr && e->data.int8 != nullptr) ? 1u : 0u));
                UART_SendString(Message);
            }
#endif
        }
    }

    // Asked first because it is free and it is what decides whether anything
    // below matters: an ineligible layer never touches the per-class state.
    DwJob j;
    if (!dw_eligible(ctx, node, &j)) { return s_dw_stock.invoke(ctx, node); }

    // Reports the previous inference's fingerprint and seeds this one's - see
    // the block above.  Placed here, after eligibility, because it needs j.q,
    // and before every exit below so that a layer which falls back to the CPU
    // still occupies its column: a column that silently vanished would shift
    // every position after it and make two runs look different for a reason
    // that is not the operator's.
    dw_hash_wrap(&j);

    // The tail cut, and it is asked AFTER eligibility on purpose - see gpu.h on
    // g_gpu_dw_tail.  Two reasons it is not folded into dw_eligible(): a layer
    // refused here is refused for this reason alone and reads as such, and the
    // per-class one-time check below still runs on the first layer that is
    // ACTUALLY offloaded rather than on the first one that happens to be
    // eligible, which is what makes a high threshold a valid measurement of the
    // layers that remain.
    //
    // The ordinal is the layer's index into s_dwq[], which prepare filled in
    // model order - so it increases with depth, and `>=` takes a contiguous tail
    // of the network.  j.q is always in s_dwq[] here: dw_eligible() fills it
    // through dw_q() or returns 0.
    if ((g_gpu_dw_tail != 0u) &&
        ((uint32_t)(j.q - s_dwq) < g_gpu_dw_tail)) {
        dw_hash_rec(&j);
        return s_dw_stock.invoke(ctx, node);
    }

    // The verdict is per stride class, and so is the run.  s_dw_check[j.stride]
    // == 0 means that class's one-time real-activation comparison has not run
    // yet; it runs on the first layer of that class that is actually eligible -
    // which is op5 (stride 2) and op21 (stride 1) in this model - and never
    // again.  A class that has failed is on the CPU for the rest of the session
    // while the other class keeps running.
    if (s_dw_check[j.stride] == 0) {
        // The SPLIT form is measured, unconditionally, for both stride classes.
        // The single-pass form used to be tried first and kept wherever it
        // passed, on the reasoning that it is half the packing and half the
        // draws.  What killed that is not an opinion about the two forms: it is
        // that stride 1's residual bound (9) EXCEEDS DW_GAP_MAX (8), so the
        // class can only pass single-pass on a frame that does not reach its own
        // bound, and the verdict therefore depended on which frame happened to
        // be in front of the camera.  Same binary, two runs: `worst 8 bad 0` ->
        // OK -> 1368 draws / 3.26 s, and `worst 9 bad 1` -> FALLBACK -> escalate
        // -> 2208 draws / 4.57 s.  A number that changes between runs of one
        // binary is not a baseline, and this stage is counted in draws on the
        // GPU, so the form that always runs is measured.
        //
        // Nothing else about the check changes.  It is still the GPU-versus-CPU
        // byte comparison on real activations, still runs once per class on the
        // first eligible layer of that class, still decides the fallback, and a
        // class whose split fails it still goes to the CPU permanently - which
        // is the constraint that matters more than any of the above.
        dw_run_check(ctx, node, &j, 1);
    }
    if (s_dw_check[j.stride] < 0) { dw_hash_rec(&j); return s_dw_stock.invoke(ctx, node); }

    // The split is per class and sticky for the session - the check above is
    // what decided it, and its verdict is what is read back here.
    // Which layer this is, and on which geometry, in execution order - printed
    // BEFORE the draw so that the last line of a log names the layer a run died
    // in rather than the last one it survived.
    //
    // This is not a progress bar, and it is here because of a specific reading
    // mistake.  From `gpu dw call` (once per session) and the two class checks
    // (once per class) onward the log is SILENT for the rest of the inference,
    // so a run that dies in the third GPU layer prints the same last line as a
    // run that dies in the seventeenth.  Two logs of two different deaths were
    // read as one death at one place.  Nineteen extra lines per inference buys
    // the difference between "somewhere in the inference" and "layer N".
    //
    // SINCE 2026-09-24 THE PAIR IS A KEY (`y`, g_gpu_dw_trace) and not
    // automatic, because the automatic form could not be measured - which is
    // the only thing it had to do.
    //
    // It was automatic once per boot: print on the first inference after
    // g_gpu_dw_on goes to 1, with the frame boundary detected by the layer
    // ordinal going BACKWARDS (exact here - the layers are visited in model
    // order within one inference, prepare filled s_dwq[] in model order, and
    // j.q is always in s_dwq[] because dw_eligible() put it there).  The intent
    // was to keep 38 lines a frame out of the interval the `gpu dw L.. D.. R..`
    // summary reports.  The intent failed on its own terms: the only frame the
    // trace ever printed on is ALSO the frame that runs the two class checks,
    // which cost ~1.16 s by themselves (capture A: the check frame 4886 ms
    // against 3724 production), so the trace's cost came out anywhere between
    // 0.2 s and 1.1 s a frame depending on which cross-boot comparison was
    // used, and no comparison could settle it.  Re-arming cost a power cycle,
    // so it could not be A/B'd within a boot either.  Same defect as a guard
    // whose sample coverage is part of its answer.
    //
    // Now: while g_gpu_dw_trace is 1 EVERY frame prints its 19 pairs.  That is
    // what makes the cost measurable - `x` a few times, `y`, `x` a few more,
    // one boot, one scene, one operator set, class checks already latched out
    // of the way after the first frame.  The 38 lines are then paid knowingly.
    //
    // SETTLED 2026-09-24 BY THE FIRST BOOT THAT COULD BEAR IT, and the key to it
    // was pricing the give-up in gpu.c (`cy820422647` = 1.367 s, measured,
    // against the "about a third of a second" the estimate had implied).  The
    // frame that carried both the trace and the stall stopped being unpriceable
    // once the stall had a price.  One boot, one scene, three equations:
    //
    //     no trace, 19 layers on the GPU       4016.2 ms  (frames 2-4, all R0)
    //     trace, stall, 17 drawn / 2 refused   5345.4 ms  (frame 5)
    //     trace, latched, 19 layers on the CPU 1803.8 ms  (frames 6-7)
    //
    // -> the GPU costs 127.9 ms a layer, independently matching the 128.4 ms a
    // layer this file's own arm measurement recorded, which is what makes the
    // solution trustworthy rather than merely exact.  THE TRACE IS 217.6 ms A
    // FRAME, 5.7 ms a line.  So "~8 ms a line" was a 30% estimate after all and
    // the cross-boot 1.1 s was the artifact: that FALSIFIED verdict is WITHDRAWN.
    // The same paragraph's claim that UART_SendString() is not costing byte-time
    // goes with it - 217.6 ms over 38 lines of ~20 characters is ~0.29 ms a
    // character against 87 us of wire time at 115200, which is ordinary byte time
    // plus a constant per call and nothing more exotic than that.  The two class
    // checks cost 597.8 ms in the same boot (frame 1 at 4614.0 against those
    // 4016.2); use that rather than capture A's cross-boot 1.16 s.
    //
    // `gpu dw drn .. cy..` in gpu.c is the same question about the drain, and it
    // is answered the same way now: 38.06 cycles a poll, 0.43 ms an honest drain,
    // which is under 1% of what the offload costs a frame - so the depthwise
    // price is the DRAWING and not the waiting, measured rather than assumed.
    //
    // `L<n> cpu` is a REFUSAL, not part of the shape of a run, and it is
    // printed even when the trace is off: the aggregate `R` in the `gpu dw`
    // summary says the trace was off, never that nothing was refused.
    //
    // `ow x oh` is the OUTPUT width times height, which is also the geometry the
    // destination plane is addressed with - at stride 1 it equals the input's,
    // at stride 2 it is the quarter-size one.  The trailing fields are what the
    // refusal logic in gpu_dw_conv() is decided on.
    {
        static unsigned s_dw_run = 0u;
        unsigned        idx = s_dw_run;

        const unsigned trace = (g_gpu_dw_trace != 0u) ? 1u : 0u;

        s_dw_run++;
        if (trace != 0u) {
            sprintf(Message, "gpu dw L%u %ux%u c%u s%d\r\n", idx,
                    (unsigned)j.ow, (unsigned)j.oh, (unsigned)j.c, j.stride);
            UART_SendString(Message);
        }

        if (!dw_draw(&j, (s_dw_check[j.stride] == 2) ? 1 : 0)) {
            // Two words, and they are the difference between three different
            // deaths.  `L<n>` alone says the layer was ENTERED; a log that ends
            // there cannot say whether the draw ran, whether the GPU refused it
            // and the CPU took over, or whether the operator finished and the
            // eleven CPU operators that follow (CONV_2D, CONCATENATION,
            // TRANSPOSE, RESHAPE, GATHER - printed by tools/op_sequence.py) are
            // where it stopped.  Those three have different causes and only one
            // of them is in gpu_dw_conv().  Unconditional, unlike the pair
            // above: this is the branch that says the layer did NOT draw.
            //
            // `sy` is the hardware sync id, and on THIS line it is the one place
            // the wedge can be read.  The drain's own `drain dead` line prints
            // the register twice and both words are equal by construction (the
            // loop falls through only while it has NOT moved), so that line
            // cannot say whether the counter moved during its twenty million
            // polls - and that is the difference between a GPU that STOPPED and
            // one that was merely BEHIND a job.  These refusals are free: a
            // latched refusal touches no hardware, the line is printed anyway,
            // and it keeps being printed for every remaining layer of every
            // remaining frame.  A column of them across the rest of a boot is
            // therefore a sampled trace of the register, at no cost and with no
            // polling - if the counter ever moves again, the GPU was never dead.
            //
            // 2026-09-24, FIRST READING: `sy10454` on both refusals of frame 5
            // and on all 38 of frames 6-7 - identical across ~11 s of wall time.
            // So the answer is STOPPED, and the caveat is what makes the reading
            // work rather than a hole in it: after the latch NOTHING is
            // submitted, so the only thing that could have moved this register
            // is the PENDING job completing.  It did not, within 11 s of a
            // give-up that had itself already waited 1.367 s.  A GPU merely
            // twelve seconds behind a job is not a reading to build on.
            sprintf(Message, "gpu dw L%u cpu sy%u\r\n", idx, (unsigned)gpu_sync_id());
            UART_SendString(Message);
            dw_hash_rec(&j);
            return s_dw_stock.invoke(ctx, node);
        }

        if (trace != 0u) {
            sprintf(Message, "gpu dw L%u drew\r\n", idx);
            UART_SendString(Message);
        }
    }

    dw_hash_rec(&j);

    return kTfLiteOk;
#else
    // GPU_ENABLE 0: the body is a stub onto the STOCK CMSIS-NN kernel, which is
    // exactly the arm the GPU path falls back to on every ineligible layer.  The
    // registration in yolo_plate_init is deliberately left untouched (see gpu.h's
    // GPU_ENABLE block), so the depthwise impl still points here - and the point
    // of the stub is that nothing in this function refers to gpu.o, which is the
    // property the map check reads.  Do not "simplify" this away by removing the
    // registration instead: the registration is what keeps the two builds' op
    // ordering identical.
    return s_dw_stock.invoke(ctx, node);
#endif
}

// ===========================================================================
// CONV_2D (pointwise) GPU offload
// ===========================================================================
//
// The same shape as the depthwise block above, deliberately: ConvQ is a DwQ
// sibling, conv_gpu_prepare is dw_gpu_prepare, conv_eligible is dw_eligible,
// conv_run_check is dw_run_check, and conv_gpu_invoke replaces one field of one
// TFLMRegistration exactly the way dw_gpu_invoke does.  Anything here that
// differs from its depthwise counterpart differs for a reason that is written
// down at the difference; nothing differs because it was easier.
//
// The operator itself is in gpu.c (gpu_conv), which owns every dhd_* call and
// includes no TFLM header.  What this block owns is the TFLM side: which layers
// qualify, the quantization parameters, and the one-time byte comparison that
// decides whether a layer is ever allowed on the GPU again.
//
// THE PER-LAYER CHECK, AND WHY IT IS PER LAYER HERE
//
// The depthwise check is per stride CLASS - two runs vouch for 19 layers,
// because those 19 layers are one geometry drawn by one code path and a
// measurement of one of them is evidence about all of them.  That argument does
// NOT hold for these 52 layers.  They differ in cin (3..288, so 1 to 9 chunks),
// in cout (3..96), in their quantization scales, and in which of the two
// designs' failure modes they sit near.  Offline emulation of exactly this
// model on exactly this detection frame (tools/conv_gpu_emulate.py) says 38 of
// them are structurally clean at the chunk this operator draws, 4 are clean
// only after narrowing the chunk, and 10 are walls - so a per-class verdict
// would vouch for 52 layers on the strength of a number that is already known
// to be wrong for a fifth of them.  Hence: each layer is measured once, on real
// activations, and a layer that fails is on the CPU for the rest of the
// session while every other layer carries on.
//
// That is also why `n` - the ConvQ slot - is the check's key rather than a
// class index: the verdict has to be per layer, so it has to be indexed by
// something that names one layer.
//
// The cost of measuring every layer is one CPU convolution per layer on the
// FIRST inference only (the stock invoke runs first because it is the
// reference), i.e. that inference costs about twice a normal one.  Every
// inference after it is the GPU's, and there is no way to learn this per layer
// without paying it once.

// The chunk this operator draws with is FIXED at 32 (two texture units, 16 taps
// each) - it is not a parameter, unlike the depthwise split - so K is not a
// choice the glue makes and is only computed here to report it.
#define CV_MAX_CIN    320      // gpu.c's GPU_CV_MAXCIN; kept in step by CV_MAX_CIN_CHK
#define CV_MAX_COUT   128
#define CV_MAX_LAYER  64
#define CV_CHK_PX     8192

// The layer the three-way dump fires on, once per boot - see gpu_cv_dump().
//
// n47 HELD THIS SPOT AND IS NOW SPENT.  It was chosen as the model's smallest
// inspectable failure - op210, 72->3 at 10x10, 300 output bytes - and it did its
// job twice over: the dump proved the firmware's per-(co, chunk) constants agree
// with the offline model FIELD FOR FIELD, nine of nine sets, and at PLANE 128 it
// now passes (`chk n47 worst 9 bad 0 OK`).  A passing layer has no disagreement
// left for a dump to find, so the target moves to one that is still failing.
//
// n43 IS THE NEW TARGET - op201, 72->12 at 20x20 - and it is chosen for the
// SHAPE of its error, which is the opposite of n47's and easier to fit:
//
//   * 1043 bad of 4800 compared bytes, worst 17.  That is a fifth of the plane
//     over the lim12 line by only 5, so there are a thousand samples to fit a
//     line to.  Every other failing head layer is a handful of pixels off by
//     ~68, where the only fit available is one pixel's worth of evidence.
//   * `sat c0 g0` on its rng line - NOTHING clamps anywhere in this layer, and
//     its planes read at0 0 at255 0 with mx 130-140.  So the fault is not a
//     rail and not a clipped texture unit, which removes the two mechanisms
//     every previous head investigation was spent on.
//   * its per-unit bias pair is the most extreme in the model.  `bu -68 -17`
//     against every passing layer's `~64 ~64`, a NEGATIVE hi pair total
//     (`b -85 121` where a passing layer reads ~128 128), and `bsum 50600`
//     against everyone else's ~77000.  The window is being driven hardest here,
//     and the field is 9 bits: if the window algebra is wrong anywhere, this is
//     the layer that has to show it.
//
// The two knobs the offline model has were both tested before asking for a
// flash and BOTH ARE EXONERATED: CV_REP=0, CV_GAIN=0 and the shipped default
// leave all 14 cin-72 head layers at `fix_draw` worst 5 bad 0, so neither the
// 5-bit replication nor the declined `1/(1+g)` - which the census does catch
// happening, `g0 raw396 inv1000` on n38 - is what the board is failing on.  A
// model that cannot express the fault cannot be asked which change fixes it, so
// the next reading has to be the board's own bytes.
// -1: OFF, and for the first time in this round the reason is not that the
// target is spent but that the question moved off the byte plane.
//
// WHAT n47 AND n43 BETWEEN THEM SETTLED.  The dump is a spend of one layer per
// boot and ~8 KB of serial, so it has to be answered for:
//
//   * the fold is EXACT.  Recomputed from the board's own six dumped planes,
//     `rnd(net - bsum + SUM_k pl_k)` reproduces the board's own `gpu` blob 400
//     of 400 bytes, worst 0 - so `pstride 512`, `cw 6`, `bsum 505.00` and
//     `net -85.73` are all right and the planes ARE what the operator returned.
//   * the per-(co, chunk) constants agree with the offline model field for
//     field.  The reconciliation printed 411 MIRROR-RECON lines over 12
//     channels x 3 chunks once the print was made wall-safe.
//   * the fault is ONE PLANE and it is pl0.  Board vs mirror per plane: pl0
//     +7.35 mean with a +0.028 slope on the value and 0 of 400 bytes exact,
//     while pl1..pl5 are within 1-3 bytes with 100-253 exact.  pl0 is the only
//     plane in the layer whose bias pair total is negative (-85) and the only
//     one where neither unit comes near a rail (post-bias minima +59, +58), so
//     it is the one plane that reports the hi digit's scale with no clamp in
//     the way.  Its deficit is 3.16% / 3.01% of the plane's partial content for
//     k0/k1 against those chunks' own g of 3.06% / 2.84%.
//   * BOTH of the model's knobs are exonerated on the board's own K=3 rung.
//     Three-way sum deficit: shipped +11.408, CV_GAIN=0 +13.970, CV_REP=0
//     +12.213.  The shipped setting is the best of the three, so the hardware
//     DOES apply the 5-bit replication gain and the firmware's inv is right.
//
// WHAT IS OWED INSTEAD, and why it cannot be this dump.  The next question is
// not what a plane contains - it is whether the product still DETECTS with the
// conv path on, which no log in this round has ever confirmed.
//
// The expense is not the argument for turning it off, and saying it was would
// be wrong.  `gpu_cv_dump()` rides `conv_run_check`, and the `s_cv_check` latch
// runs that ONCE per layer per boot, so the dump fired once per boot and not
// once per frame: for n43 it is `in` 72*400 = 28800 B + six planes 2400 B +
// `out` 4800 B, plus the glue's `cpu` and `gpu` blobs 9600 B, so ~1.4k lines
// and ~4 s of UART, once.  The argument is that the READING is spent - the fold
// is proved exact from these very planes and the per-(co, chunk) constants are
// proved equal to the offline model - so the one plane still disagreeing has
// nothing left to say that its own byte trace has not already said, while the
// detection question has never been asked at all.  One boot, one question.
//
// WHEN TO ARM IT AGAIN.  The pl0 gap is still open and it is a real correctness
// defect on a layer the head depends on.  The next reading that would move it is
// not one layer's bytes but a per-(layer, channel) six-plane census across the
// whole shipped set, so that one boot names every layer carrying the anomaly
// instead of one layer per build - see the note on `CV_DUMP_N`'s replacement.
#define CV_DUMP_N     (-1)

// How far the GPU answer may sit from the CPU's on the same activations before
// the layer is handed back for good.
//
// Not a single number's worth of arithmetic - it is the sum of three things
// that are known and one that is not:
//   * the 5-bit entry.  Every activation is quantised to a 5-bit unsigned field
//     on the way in, so a tap is off by up to 3.5 against weights that reach
//     127.  This is the design working, not a bug.
//   * the truncation floor.  Each of the 2*K digits truncates instead of
//     rounding, and the floor that buys is measured per layer offline: 2..5 LSB
//     at chunk 32 across this model.
//   * two truncations per digit, not one.  Each texture unit truncates its OWN
//     partial sum before the colour ADD sums them, so where the emulator models
//     one truncation the hardware has two - always downward, worth up to 1 LSB
//     per unit, i.e. up to 2 per digit.  The emulator cannot see this and gpu.h
//     says so at the contract.
//   * the drift `corr` deliberately does not model: the mean of each digit's
//     fractional part.  Measuring it needs a full CPU convolution per layer,
//     which is the thing this whole path exists to avoid; what is known is that
//     every digit is CENTRED, so its fractional part straddles zero and its
//     mean is small by symmetry.
//
// 12 is the depthwise bound (8) with the last two terms priced in.  It is a
// single number for 52 layers with different floors rather than a table,
// because a table would have to be regenerated every time the model changes and
// a wrong table fails in the direction of trusting the GPU more.  A layer whose
// real floor is near the bound is refused, which costs draws, not correctness.
#define CV_GAP_MAX    12

static TFLMRegistration s_conv_impl;
static TFLMRegistration s_conv_stock;

struct ConvQ {
    int   filt;                 // node->inputs->data[1]: the layer's filter tensor
    int   fin;                  // node->inputs->data[0]: the layer's INPUT tensor
    int   n;                    // its own slot: the key s_cv_check is indexed by
    int   cin;
    int   cout;
    int   ready;
    // The same snapshot as DwQ, and for the same reason: the TfLiteTensor form
    // is only reachable in prepare, and reading one allocates.
    float isc;                  // input activation scale  - per-tensor here
    float osc;                  // output activation scale - per-tensor here
    int   izp;                  // input zero point  - NOT required to be -128
    int   ozp;                  // output zero point - decides whether RELU is free
    float wsc[CV_MAX_COUT];     // per-output-channel weight scales
};

static ConvQ  s_cvq[CV_MAX_LAYER];
static int    s_cvq_n = 0;
static int8_t s_cv_ref[CV_CHK_PX];

// 0 = this layer's one-time check has not run yet, 1 = it passed, -1 = it failed
// and the layer is on the CPU for the rest of the session.  Indexed by ConvQ
// slot; see the per-layer note above for why this is not indexed by class.
static signed char s_cv_check[CV_MAX_LAYER];

// The census budget lived here.  It is gone on purpose: the census now rides the
// production draw on channel 0 for every layer (see conv_run_check), so there is
// nothing to bound - it costs one byte walk per plane and no draw at all, and
// bounding it is what made only four of 51 layers comparable with the offline
// table.  tools/conv_gpu_emulate.py's row for a layer is what a census line is
// checked against; a census that skips layers throws away oracles.

// THE KEY IS (filter tensor, input tensor), AND `filt` ALONE IS NOT ENOUGH.
//
// This was `conv_q(filt)`, matching on `node->inputs->data[1]` alone.  It cost
// three layers of the model, and the way it cost them is worth stating exactly
// because nothing printed for them at all:
//
//   tools/conv_filter_index.py reads the shipped .tflite and finds three filter
//   tensor indices used by TWO CONV_2D ops each -- tensor 48 by op191 (72->3,
//   20x20) and op210 (72->3, 10x10), tensor 45 by op194/op213 (72->70), tensor
//   34 by op201/op220 (72->12).  Slot 39 and 47, 40 and 48, 43 and 51.  The
//   board's 20x20 half of every pair printed; the 10x10 half printed NOTHING,
//   in two consecutive boots, with an explicit `held` line added between them.
//
// Why the silence was total rather than loud: the later node resolves to the
// EARLIER node's record, so it inherits that record's verdict.  `s_cv_check[39]`
// is -1, so the later node took the `held` path, whose line is de-duped per
// layer -- and slot 39 had already printed its own.  `conv_run_check` was never
// called for slot 47, so no `chk` line; and `s_cv_check` has exactly two
// writers, both of which print, so a record holding garbage was impossible.
// The nodes were simply never reached under their own number.
//
// The one guard that could have caught it is the `quant C mismatch` test in
// conv_eligible(), and it passes here precisely because each colliding pair has
// the same (Cin, Cout) -- 72->3, 72->70, 72->12.  What DOES differ is the thing
// each node reads: the 20x20 head branch eats a 20x20 tensor and the 10x10 one a
// 10x10 tensor.  Hence `fin`.
//
// This is not a hypothetical hazard.  op210/op213/op220 are the detection head's
// 3-channel, 70-channel and 12-channel branches at the small scale, and the
// plan requires op210 on the GPU.  Had slot 39 passed its check instead of
// failing it, op210 would have been DRAWN with slot 39's per-channel weight
// scales -- `wsc` is the whole reason a per-channel quantised layer can be drawn
// at all -- and wrong power-of-two scales do not look like a crash.
//
// The key is strictly tighter, so a model with no collision behaves bit-for-bit
// as before, and tools/conv_filter_index.py confirms the pair is unique for all
// 52 of this model's conv layers.
static ConvQ* conv_q(int filt, int fin)
{
    for (int i = 0; i < s_cvq_n; i++) {
        if (s_cvq[i].filt == filt && s_cvq[i].fin == fin) { return &s_cvq[i]; }
    }
    return nullptr;
}

// WHY A LAYER IS SILENT, SAID OUT LOUD.
//
// conv_eligible() refuses a layer by returning 0 and conv_gpu_invoke() then runs
// the stock kernel - correctly, silently, by design.  That silence cost a whole
// flash round: the board printed nothing for its slots n47 and n48 (this file's
// op210 and op213, the detection head among them), the offline eligibility table
// said both SHOULD be taken, and there was no way to tell a refusal from a
// capture failure without guessing.  A refusal is a decision, so it gets a line.
//
// Once per layer per boot, so a 52-layer model with a permanently refused layer
// prints 52 lines at most and never repeats them on the next inference.  CV_MAX_
// LAYER is 64 and the mask is 64 bits, which is why this is one integer and not an
// array.  n < 0 means the filter tensor has no ConvQ slot at all - the layer was
// never captured - and that is one line, not one per layer.
static unsigned long long s_cv_skip_seen = 0u;
static int                s_cv_skip_anon = 0;

static void cv_skip(int n, const char* why)
{
    if (n < 0) {
        if (s_cv_skip_anon != 0) { return; }
        s_cv_skip_anon = 1;
        sprintf(Message, "gpu cv skip n? %s\r\n", why);
        UART_SendString(Message);
        return;
    }
    if (n >= CV_MAX_LAYER) { return; }
    if ((s_cv_skip_seen & (1ull << n)) != 0u) { return; }
    s_cv_skip_seen |= (1ull << n);
    sprintf(Message, "gpu cv skip n%d %s\r\n", n, why);
    UART_SendString(Message);
}

// The layer's own slot, for cv_skip().  Safe to call before anything has been
// validated: it checks the node shape and returns -1 rather than dereferencing.
static int conv_layer_no(const TfLiteNode* node)
{
    // `node->inputs->data` is TfLiteIntArray's own inline `int data[1]`, so
    // testing it against nullptr is always false and the compiler says so.  The
    // size check below is what actually guards the index.
    if (node->inputs == nullptr) { return -1; }
    if (node->inputs->size < 2) { return -1; }
    ConvQ* q = conv_q(node->inputs->data[1], node->inputs->data[0]);
    return (q != nullptr) ? q->n : -1;
}

// prepare, wrapped only to capture the per-output-channel weight scales.
//
// Every CONV_2D filter in this model is per-output-channel quantised - 52 of 52,
// measured offline - so TfLiteTensor.params.scale, which is one float, is 0 for
// all of them.  The array lives in the TfLiteAffineQuantization, and TFLM micro
// is free to release that once AllocateTensors() has finished, so it is read
// here and not in invoke.  The reasoning, and the eleven-line failure it avoids
// when a temp tensor is not handed back, are in the comment on dw_temp_in().
static TfLiteStatus conv_gpu_prepare(TfLiteContext* ctx, TfLiteNode* node)
{
    TfLiteStatus st = s_conv_stock.prepare(ctx, node);
    if (st != kTfLiteOk) { return st; }

    if (s_cvq_n >= CV_MAX_LAYER) { return kTfLiteOk; }
    if (node->inputs == nullptr || node->outputs == nullptr) { return kTfLiteOk; }
    if (node->inputs->size < 3) { return kTfLiteOk; }

    tflite::MicroContext* mc = tflite::GetMicroContext(ctx);
    TfLiteTensor* fin  = dw_temp_in(mc, node, 0);
    TfLiteTensor* filt = dw_temp_in(mc, node, 1);
    TfLiteTensor* fout = dw_temp_out(mc, node, 0);

    // One exit, for the same reason dw_gpu_prepare has one.
    ConvQ* taken = nullptr;

    if (fin != nullptr && filt != nullptr && fout != nullptr &&
        filt->dims != nullptr && filt->dims->size == 4) {
        const int CI = filt->dims->data[3];
        const int CO = filt->dims->data[0];
        if (CI > 0 && CI <= CV_MAX_CIN && CO > 0 && CO <= CV_MAX_COUT &&
            fin->params.scale > 0.0f && fout->params.scale > 0.0f) {
            ConvQ* q = &s_cvq[s_cvq_n];
            q->filt  = node->inputs->data[1];
            q->fin   = node->inputs->data[0];
            q->n     = s_cvq_n;
            q->cin   = CI;
            q->cout  = CO;
            q->ready = 0;
            q->isc   = fin->params.scale;
            q->osc   = fout->params.scale;
            q->izp   = fin->params.zero_point;
            q->ozp   = fout->params.zero_point;

            if (filt->quantization.type == kTfLiteAffineQuantization &&
                filt->quantization.params != nullptr) {
                const TfLiteAffineQuantization* aq =
                    (const TfLiteAffineQuantization*)filt->quantization.params;
                if (aq->scale != nullptr && aq->scale->size == CO) {
                    for (int i = 0; i < CO; i++) { q->wsc[i] = aq->scale->data[i]; }
                    q->ready = 1;
                }
            }
            if (!q->ready && filt->params.scale > 0.0f) {
                for (int i = 0; i < CO; i++) { q->wsc[i] = filt->params.scale; }
                q->ready = 1;
            }
            if (q->ready) { taken = q; }
        }
    }

    if (fin  != nullptr) { mc->DeallocateTempTfLiteTensor(fin); }
    if (filt != nullptr) { mc->DeallocateTempTfLiteTensor(filt); }
    if (fout != nullptr) { mc->DeallocateTempTfLiteTensor(fout); }

    if (taken != nullptr) { s_cvq_n++; }
    return kTfLiteOk;
}

// What this resolves, so the caller does not have to re-derive it: which layer,
// which tensors, and the geometry gpu_conv() is about to be handed.  The check
// and the draw both use the same ConvJob, so they cannot disagree about what
// "this layer" means.
struct ConvJob {
    const TfLiteEvalTensor* fin;
    const TfLiteEvalTensor* filt;
    const TfLiteEvalTensor* bias;
    const TfLiteEvalTensor* fout;
    ConvQ* q;
    int  h, w;         // input plane == output plane
    int  cin, cout;
};

// The eligibility test.  Same discipline as dw_eligible: it proves "this is the
// shape I implement" rather than listing known-bad cases, because a layer it
// does not recognise is a layer it must not touch.
//
// There is exactly ONE eligible shape:
//
//     1x1 SAME stride 1, output == input
//
// which is 51 of this model's 52 CONV_2D layers.  The 52nd is op1, 3x3 stride 2
// VALID 160x160 -> 80x80, refused by the filter-size test below and left to the
// CPU.  It is not a matter of unfinished work in the sense that matters: a 3x3
// kernel cannot be expressed by a row of taps that also walks the channels, so
// it needs a different decomposition, and the offline table says it is the
// single cheapest layer in the model (Cin 3, 48 draws).  It is Step 3's second
// item, not a defect here.
//
// What is deliberately NOT tested, and this is the one place this function is
// less restrictive than dw_eligible:
//
//   in_zp.  dw_eligible refuses any layer whose input zero point is not -128,
//   because the depthwise pack is `in_q - in_zp` written into an UNSIGNED 5-bit
//   texel, so a zero point above -128 clips the input.  The pointwise pack is
//   `in_q + 128`, which is non-negative for every int8 and clips nothing, and
//   the `in_zp` that TFLM's accumulator subtracts is given back by the fold
//   instead (see gpu_conv's `net` term).  So the restriction does not apply, and
//   imposing it anyway would refuse layers for no reason.
// `why` is set at every refusal and reported by the caller (see cv_skip).  It is
// never read when this returns 1, and the master-switch refusal is not reported
// at all - see the caller.
static int conv_eligible(TfLiteContext* ctx, TfLiteNode* node, ConvJob* j,
                         const char** why)
{
    const TfLiteConvParams* p = (const TfLiteConvParams*)node->builtin_data;

    if (p == nullptr)                    { *why = "no params";     return 0; }
    if (p->dilation_width_factor  != 1)  { *why = "dilated";       return 0; }
    if (p->dilation_height_factor != 1)  { *why = "dilated";       return 0; }
    if (p->stride_width  != 1)           { *why = "stride";        return 0; }
    if (p->stride_height != 1)           { *why = "stride";        return 0; }
    if (p->padding != kTfLitePaddingSame) { *why = "not SAME";     return 0; }

    if (node->inputs == nullptr || node->outputs == nullptr) { *why = "node shape"; return 0; }
    if (node->inputs->size < 3)          { *why = "node shape";    return 0; }

    // Eval tensors, not TfLiteTensors: this runs during invoke and nothing here
    // may allocate.  The quantization params were captured in prepare.
    const TfLiteEvalTensor* fin  = ctx->GetEvalTensor(ctx, node->inputs->data[0]);
    const TfLiteEvalTensor* filt = ctx->GetEvalTensor(ctx, node->inputs->data[1]);
    const TfLiteEvalTensor* bias = ctx->GetEvalTensor(ctx, node->inputs->data[2]);
    const TfLiteEvalTensor* fout = ctx->GetEvalTensor(ctx, node->outputs->data[0]);
    if (fin == nullptr || filt == nullptr || bias == nullptr || fout == nullptr) {
        *why = "no eval tensor";
        return 0;
    }

    if (fin->type  != kTfLiteInt8)  { *why = "tensor type";  return 0; }
    if (filt->type != kTfLiteInt8)  { *why = "tensor type";  return 0; }
    if (bias->type != kTfLiteInt32) { *why = "tensor type";  return 0; }
    if (fout->type != kTfLiteInt8)  { *why = "tensor type";  return 0; }
    if (fin->dims  == nullptr || fin->dims->size  != 4) { *why = "tensor rank"; return 0; }
    if (filt->dims == nullptr || filt->dims->size != 4) { *why = "tensor rank"; return 0; }
    if (fout->dims == nullptr || fout->dims->size != 4) { *why = "tensor rank"; return 0; }

    // 1x1 only.  TFLM stores a CONV_2D filter as [cout, kh, kw, cin].
    if (filt->dims->data[1] != 1 || filt->dims->data[2] != 1) {
        *why = "kernel not 1x1";
        return 0;
    }

    const int h = fin->dims->data[1];
    const int w = fin->dims->data[2];
    const int CI = fin->dims->data[3];
    const int CO = filt->dims->data[0];
    if (h <= 0 || w <= 0)             { *why = "bad H/W";        return 0; }
    if (CI <= 0 || CI > CV_MAX_CIN)   { *why = "Cin out of range"; return 0; }
    if (CO <= 0 || CO > CV_MAX_COUT)  { *why = "Cout out of range"; return 0; }
    if (filt->dims->data[3] != CI)    { *why = "filter Cin";     return 0; }

    // The output shape the stride and padding imply, derived here and then
    // CHECKED against the tensor rather than taken from it - reading oh/ow off
    // fout and handing them to gpu_conv() would make the validation there a
    // tautology, and the point of it is to catch a layer whose declared output
    // does not match what 1x1 SAME stride 1 says it must be.
    if (fout->dims->data[1] != h)     { *why = "output shape";   return 0; }
    if (fout->dims->data[2] != w)     { *why = "output shape";   return 0; }
    if (fout->dims->data[3] != CO)    { *why = "output shape";   return 0; }

    if (fin->data.int8  == nullptr)   { *why = "null data";      return 0; }
    if (filt->data.int8 == nullptr)   { *why = "null data";      return 0; }
    if (bias->data.i32  == nullptr)   { *why = "null data";      return 0; }
    if (fout->data.int8 == nullptr)   { *why = "null data";      return 0; }

    ConvQ* q = conv_q(node->inputs->data[1], node->inputs->data[0]);
    if (q == nullptr || !q->ready)    { *why = "no quant record"; return 0; }
    if (q->cin != CI || q->cout != CO) { *why = "quant C mismatch"; return 0; }
    if (q->n < 0 || q->n >= CV_MAX_LAYER) { *why = "slot out of range"; return 0; }

    // The fused activation, checked against the output zero point rather than on
    // its own - which is what makes it a real test instead of a formality.
    //
    // TFLM's int8 RELU is max(y, out_zp).  The fold in gpu_conv() ends with a
    // clamp to [0, 255] in the byte domain and subtracts 128, i.e. it produces
    // the full int8 range, so it does NOT apply a RELU.  At out_zp == -128 that
    // does not matter: max(y, -128) is the identity on an int8, and the RELU is
    // a no-op the two paths agree about.  At any other zero point it is not the
    // identity and a layer with RELU would be drawn WRONG - not refused - so it
    // is refused here.
    if (p->activation == kTfLiteActNone) {
        // nothing to do
    } else if (p->activation == kTfLiteActRelu) {
        if (q->ozp != -128) { *why = "relu at zp"; return 0; }
    } else {
        *why = "activation";
        return 0;
    }

    j->fin  = fin;
    j->filt = filt;
    j->bias = bias;
    j->fout = fout;
    j->q    = q;
    j->h    = h;
    j->w    = w;
    j->cin  = CI;
    j->cout = CO;
    return 1;
}

// The GPU pass itself, split out so the caller can tell the answers apart - and
// it returns gpu_conv()'s OWN CODE now rather than a boolean:
//
//    0  the layer was drawn
//   -1  refused, and the refusal is about THIS DRAW: too many chunks for the
//       scratch plane, a scale outside its field, a drain that ran out of time
//   -2  refused, and the refusal is about THE LAYER: the 9-bit bias field cannot
//       hold this layer's centring at all, whatever chunk is chosen.  Found in
//       pass 2 before anything is drawn, so `out` is untouched by a -2
//
// The two refusals used to collapse into one 0, which made a layer the offline
// mirror REJECTS look in the log exactly like one that merely did not fit this
// draw.  The caller still treats both as "put the layer back on the CPU" - that
// is unchanged - but `cv_chk_bail()` can now name which one it was, and `wall`
// is a checkable prediction: the mirror's `bias field WALL` list says which
// layers it must appear on.
//
// `in_scale` is passed as the address of the ConvQ field because gpu_conv() reads
// only in_scale[0] - this model's conv inputs are quantised per tensor, so one
// float is the whole array and a separate staging array would be a second copy
// of the same number.
static int conv_draw(const ConvJob* j)
{
    return gpu_conv(j->fin->data.int8, j->filt->data.int8, j->bias->data.i32,
                    &j->q->isc, j->q->wsc, j->q->osc,
                    j->q->izp, j->q->ozp,
                    j->h, j->w, j->cin, j->cout,
                    j->fout->data.int8);
}

// Every bail names itself.  There are now three, and the third is new: the stock
// CPU invoke failing ("cpu"), the GPU refusing to draw ("gpu"), and the LAYER
// being undrawable at any chunk ("wall", the offline table's `bwall`).  A guard
// that takes a layer off the GPU for the session has to say so, and it has to
// say WHY, or the visible symptom is a layer that is silently on the CPU forever
// and a log that cannot tell "this layer's centring cannot be written down from
// "this layer did not fit" - which are different answers about the hardware.
static void cv_chk_bail(int n, const char* why)
{
    s_cv_check[n] = -1;
    sprintf(Message, "gpu cv chk bail n%d %s\r\n", n, why);
    UART_SendString(Message);
}

// The one-time real-activation check for ONE layer, run the first time that
// layer is reached and never again.  See the block comment above for why this
// is per layer where the depthwise one is per class.
//
// Same discipline as dw_run_check: the CPU answer is the reference, the
// comparison is on real activations rather than synthetic data, and the sample
// is CONTIGUOUS from the start of the NHWC output so that every channel is in
// the evidence.  For this operator that coverage is not a detail: the thing
// that differs between output channels here is the per-channel weight scale and
// the CLUT offset, so a sample that could not see channels other than 0 would be
// measuring a different operator.
//
// Note what this does NOT prove: it says THIS layer matched on the sample above.
// The other layers are measured too - that is the point of the design - and
// `worst` is printed for each rather than just a verdict, because a reading of 0
// that is really 0-because-we-clamped-it is what CV_GAP_MAX exists to expose.
static void conv_run_check(TfLiteContext* ctx, TfLiteNode* node, const ConvJob* j)
{
    const int n    = j->q->n;
    const int np   = j->h * j->w;
    const int total = np * j->cout;

    // CPU first: it is the reference, and the GPU pass that follows writes over
    // the tensor it lives in, which is why the sample is copied out first.
    if (s_conv_stock.invoke(ctx, node) != kTfLiteOk) { cv_chk_bail(n, "cpu"); return; }

    const int cnt = (total < CV_CHK_PX) ? total : CV_CHK_PX;
    const int8_t* ref = j->fout->data.int8;
    for (int i = 0; i < cnt; i++) { s_cv_ref[i] = ref[i]; }

    // THE CENSUS GOES AROUND THE PRODUCTION DRAW, on CHANNEL 0, for EVERY
    // layer.  Two changes from the bounded form it replaces, and both are about
    // making the offline model usable as an oracle rather than about this run:
    //
    //   * channel 0, not the channel the first bad pixel landed in, because
    //     tools/conv_gpu_emulate.py's census table is channel 0 for all 52
    //     layers.  Naming the failing channel bought one interesting channel per
    //     failing layer and cost the ability to compare ANY of them: of the four
    //     layers the last build censused, three had `fch` != 0, so three of the
    //     four rows had nothing to be compared against - and the one that did
    //     (n5, ch 0) matched the model's `bsum`, `net` and lo plane to 1-2 LSB
    //     while its hi plane did not, which is the most specific fault this
    //     operator has ever had pointed at it.
    //
    //   * no re-draw.  The planes are written by the draw that was going to
    //     happen anyway, so reading them here costs one byte walk and no GPU
    //     work at all - where the old form spent a whole second draw per
    //     censused layer and, worse, left plane 0 holding the DIG's output for
    //     every layer censused after the dig had run, which is why the `pl0`
    //     line never once described the production hi plane.
    //
    // The cost is 2K lines per layer instead of 2K lines per failing layer: on
    // this model ~200 lines per boot, which is 1.6 s of UART at 115200 and no
    // GPU time.  Turn it off by deleting the one call.
    gpu_cv_census(1, 0, n);
    // Armed for one layer and one draw: gpu_conv() has no layer number of its
    // own, so the dump rides the same variable the census travels in, and it
    // disarms itself the moment it has taken the input.  Print only, and it
    // changes no arithmetic - a refused layer still falls back to s_conv_stock.
    if (n == CV_DUMP_N) { gpu_cv_dump(n); }
    const int draw_rc = conv_draw(j);
    if (draw_rc < 0) {
        gpu_cv_census(0, 0, -1);
        cv_chk_bail(n, (draw_rc == -2) ? "wall" : "gpu");
        return;
    }
    gpu_cv_census(0, 0, -1);

    // THE FOLD'S OWN CLAMP COUNTS, read here because this is the call whose
    // planes they describe and the verdict below is what consumes them.  They
    // are about the PLANE the colour pass wrote and NOT about a texture unit:
    // the two units are clamped individually INSIDE that pass and only their SUM
    // reaches the plane, so a unit leaving the byte range is invisible from here
    // - and from every other place the board can look.  That one is the offline
    // table's `sat`; this is its `rail`/`at255`.  See s_cv_rail in gpu.c.
    uint32_t rail = 0u, at0 = 0u;
    gpu_cv_fold_stat(&rail, &at0);

    int worst = 0, bad = 0;
    // `n8` is the offline table's OWN column of the same name
    // (tools/conv_gpu_emulate.py:1448, `count_nonzero(err > 8)`), so the board's
    // row and the mirror's row can be held against each other column by column.
    // What differs is the COVERAGE, not the definition: the mirror counts over
    // the whole plane and this counts over the sample below, so a layer whose
    // only over-8 pixels sit past the sample reads n8 0 here and n8 > 0 there
    // without either being wrong.
    //
    // REPORTED AND NOT JUDGED, on the mirror's own evidence: a flat 8 is exactly
    // what put op186 and op205 in ITS wall list, for exceeding a threshold by 1
    // and by 0, when their error IS their floor and no chunk or a_scale recovers
    // it (conv_gpu_emulate.py:1464-1468).  The board has no `floor` to compare
    // against, so gating on `n8 == 0` would be STRICTER than the mirror and
    // would refuse layers the mirror keeps - so it stays a column.
    int n8 = 0;
    // The three error shapes the rng line below names - a constant offset, a
    // scale error, saturation - were only ever inferred from a THREE-SAMPLE min
    // and max, which cannot tell "one pixel pinned at -128" from "half the layer
    // pinned there".  These three counts can, and they cost a comparison each:
    //
    //   csat  the CPU's own byte is pinned at -128 or 127 (the reference is
    //         clipping, so any GPU error there is not the GPU's to explain)
    //   gsat  the GPU's byte is pinned
    //   bsat  a pixel over the bound AND the CPU pinned at an end - the signature
    //         of the 5-bit hi plane clipping, where the two-plane identity
    //         byte1+byte2-128 == m*Sigma(w*code) STOPS HOLDING
    //
    // bsat near bad means the layer is outside the split's safe set, which is a
    // verdict and not a bug; bsat near zero with a large bad means something
    // else is wrong and the search continues.
    int csat = 0, gsat = 0, bsat = 0;
    // WHERE the bad pixels are, because the counts above cannot say.  A fault
    // that is per-channel (a CLUT offset, a weight row, a per-channel scale)
    // puts every bad pixel in a few channels, so `same` - how many bad pixels
    // share the first bad one's channel - equals `bad`.  A fault in the source
    // layout puts them in a contiguous run, which `first`/`last` bracket.  And
    // a handful of isolated pixels, which is what the cin72 K3 layers show, is
    // neither, and that is itself the answer.
    int fb = -1, lb = -1, same = 0;
    for (int i = 0; i < cnt; i++) {
        const int cv = (int)s_cv_ref[i], gv = (int)ref[i];
        int d = gv - cv;
        if (d < 0) { d = -d; }
        if (d > worst) { worst = d; }
        if (d > 8) { n8++; }
        if (d > CV_GAP_MAX) {
            bad++;
            if (fb < 0) { fb = i; }
            lb = i;
        }
        const bool cend = (cv == -128) || (cv == 127);
        if (cend)                              { csat++; }
        if ((gv == -128) || (gv == 127))       { gsat++; }
        if (cend && (d > CV_GAP_MAX))          { bsat++; }
    }
    // The channel the first bad pixel is in, and how many of the bad pixels are
    // in it.  Walked with the sample's own stride so it stays NHWC-correct
    // whatever the sample's length is.
    int fch = 0;
    if (fb >= 0) {
        fch = fb % j->cout;
        for (int i = fch; i < cnt; i += j->cout) {
            int d = (int)ref[i] - (int)s_cv_ref[i];
            if (d < 0) { d = -d; }
            if (d > CV_GAP_MAX) { same++; }
        }
    }
    // THE MIRROR'S `rail` GATE, which the board was not applying.  A plane byte
    // the hardware wrote as 255 means the two units - each already clamped on
    // its own - summed to at least 255, i.e. the colour overflowed the byte it
    // is added into.  What the write cuts off at the top is not in the byte the
    // fold reads back, so it is an error the sample's own |gpu-cpu| can only
    // sometimes see; it is a property of the LAYER.
    //
    // It is a SUPERSET of the mirror's own test and that is deliberate: the
    // mirror asks for sum > 255, a byte can only report sum >= 255.  So a digit
    // plane landing exactly on 255 is refused here and kept there - the same
    // trade CV_GAP_MAX already makes ("a layer whose real floor is near the
    // bound is refused, which costs draws, not correctness"), and it errs
    // towards the CPU.  The mirror's own direction of evidence agrees: in the
    // 2026-09-22 capture, all 11 layers with at255 > 0 read FALLBACK and no
    // layer with at255 == 0 reached a worst of 255.
    //
    // The gate costs drawn layers, which is a real cost against the aim of this
    // stage - they are the layers the mirror refuses too, so it is a correctness
    // trade and not a regression, but it is a trade.
    //
    // A `bu_min > CV_GAP_MAX` CLAUSE WAS TRIED HERE ON 2026-10-09 AND REVERTED
    // THE SAME DAY, ON THE FIELD CAPTURE THAT FIRST EXERCISED IT.  The claim was
    // that an annihilated texture unit costs the plane that unit's own `b_u`, so
    // a layer whose smallest |b_u| does not clear CV_GAP_MAX could ship a
    // corrupted plane with `bad 0` and `rail 0`.  It reads well and it is wrong:
    // cv_digit() sets `b_u` so that the unit's post-bias mean is ALWAYS 64
    // (`mean(p_u) = cen_u + b_u = cen_u + 64 - cen_u`), so what a lost unit costs
    // does not depend on `b_u` at all - it is that mean, ~PLANE/2.  The two
    // readings coincide only where `b_u` happens to be ~64, which is every unit
    // of the 2026-09-29 capture that the claim was generalised from.
    //
    // The cost was NOT zero, which is what the offline estimate said: on the
    // first capture (f off, c on, g on) `bad 0 rail 0` held on 13 of 51 layers
    // and min|b_u| was 0..6 on ten of them - so the clause cut the conv offload
    // from 13 layers to the 3 the log's own `gpu cv l3` shows.  The offline
    // estimate had read ONE (channel 0, chunk 0) `bu` row per layer; the board's
    // minimum is over every channel, and small |b_u| turns out to be common
    // rather than rare.
    //
    // `bu` SURVIVES AS A COLUMN on the chk line (see gpu_cv_bias_min) because it
    // costs nothing and is the reading the mechanism question still needs.  What
    // must not come back without a measurement is the VERDICT.
    int32_t bu_min = -1;
    gpu_cv_bias_min(&bu_min);
    s_cv_check[n] = (bad == 0 && rail == 0u) ? 1 : -1;

    // K is sizeof the chunk this layer's layer actually needs, and it is the
    // number that explains most of the cost, so it is on the line.
    //
    // `n8`, `rail` and `at0` GO AFTER THE VERDICT ON PURPOSE, and not because
    // the verdict reads better in the middle.  tools/conv_dump_diff.py parses
    // this line with `... bad (\d+) (\w+)` and is not anchored, so a column
    // inserted before the verdict does not fail the parse - it makes that `\w+`
    // capture "n8" and the tool then reports a verdict of `n8` with no error
    // anywhere.  Appending keeps the old tool reading the same line it always
    // did.  `n8` is |gpu-cpu| > 8 over this sample, `rail` and `at0` are the
    // fold's counts of plane bytes written as 255 and as 0 over the whole layer
    // (see gpu_cv_fold_stat) - they are the mirror's columns of the same names.
    // `bu` is the layer's smallest per-unit |b_u| (see gpu_cv_bias_min).  It is
    // a COLUMN and not part of the verdict; -1 means nothing was drawn.
    const unsigned K = ((unsigned)j->cin + 31u) / 32u;
    sprintf(Message, "gpu cv chk n%d cin%u cout%u K%u %ux%u px%u lim%d worst %d bad %d %s n8 %d rail %u at0 %u bu %d\r\n",
            n, (unsigned)j->cin, (unsigned)j->cout, K,
            (unsigned)(j->h), (unsigned)(j->w), (unsigned)cnt, (int)CV_GAP_MAX,
            worst, bad, (s_cv_check[n] == 1) ? "OK" : "FALLBACK",
            n8, (unsigned)rail, (unsigned)at0, (int)bu_min);
    UART_SendString(Message);

    // The other two thirds of the three-way dump, in the same `D <tag> +<off>
    // <hex>` format the operator's own halves use, so one script can diff the
    // four.  `cpu` is the stock operator's answer on THIS frame's real
    // activations - a reference the offline oracle cannot supply, because the
    // oracle runs on a jpg - and `gpu` is the very buffer the comparison above
    // read.  Printed after `chk` on purpose: the verdict comes first and the
    // bytes that have to justify it follow.
    if (n == CV_DUMP_N)
    {
        gpu_cv_hex("cpu", s_cv_ref, cnt);
        gpu_cv_hex("gpu", ref, cnt);
    }

    // The shape of the error, not just its size, and only when it failed - a
    // constant offset shows as a range of equal width shifted, a scale error as
    // a GPU range that is the CPU range multiplied, and saturation as a GPU
    // range pinned to -128/127.  Three samples of the same index on both sides,
    // which the contiguous sample makes meaningful.
    if (s_cv_check[n] < 0) {
        // THE CHANNEL THE FAULT IS IN, CENSUSED.
        //
        // Channel 0's numbers above are the offline table's oracle, and they are
        // why the per-layer constants are known to be right: `bsum` and `net` are
        // built from the weights and the calibration alone, so they do not depend
        // on the image, and 44 of 44 of them matched the offline model to the
        // printed digit.  The PLANES are image-dependent and cannot be compared
        // that way, so what is still unanswered is whether a failing layer's
        // fault is in its per-channel state - the weight scale, the CLUT offset,
        // the centring - or in the shared arithmetic.  `loc` already says which
        // channel the first bad pixel was in; this puts THAT channel's `b`,
        // `mult`, `sw`, `bsum` and `net` on the wire, and the offline model
        // prints a row for every channel of every layer to hold them against.
        //
        // Skipped when the bad channel IS channel 0, because the census above
        // already was that.  Costs one extra draw per failing layer, once per
        // boot, on the check path only.
        if (fch != 0) {
            gpu_cv_census(1, fch, n);
            (void)conv_draw(j);
            gpu_cv_census(0, 0, -1);
        }

        const int last = (cnt > 1) ? (cnt - 1) : 0;
        const int mid  = cnt / 2;
        int cl = s_cv_ref[0], ch = s_cv_ref[0];
        int gl = ref[0],      gh = ref[0];
        for (int i = 0; i < 3; i++) {
            const int k = (i == 0) ? 0 : ((i == 1) ? mid : last);
            if (s_cv_ref[k] < cl) { cl = s_cv_ref[k]; }
            if (s_cv_ref[k] > ch) { ch = s_cv_ref[k]; }
            if (ref[k] < gl)      { gl = ref[k]; }
            if (ref[k] > gh)      { gh = ref[k]; }
        }
        sprintf(Message, "gpu cv rng n%d c %d..%d g %d..%d sat c%d g%d bad%d\r\n",
                n, cl, ch, gl, gh, csat, gsat, bsat);
        UART_SendString(Message);

        // The `rng` range above is THREE samples - index 0, cnt/2, cnt-1 - and
        // so is nearly worthless on its own; these three are over the whole
        // sample.  (`same == bad` is a per-channel fault; `first`..`last` a
        // contiguous run; a few isolated indices neither.)
        sprintf(Message, "gpu cv loc n%d ch%d same%d/%d first%d last%d of %d\r\n",
                n, fch, same, bad, fb, lb, cnt);
        UART_SendString(Message);

        // WHERE IN THE PLANE, which a byte index cannot say.  The output is
        // NHWC, so byte i is pixel i/cout and that pixel is row y = px/w,
        // column x = px%w.  Three verdicts separate this way:
        //
        //   * a fault in the 16-tap window's geometry can only touch the first
        //     or last row and column, because that is where the window overruns
        //     the texture and the border colour is read instead;
        //   * a fault in the pack, or in a weight row, is interior;
        //   * a fault that follows the source's own edge lands on the column
        //     each row starts at, and nowhere else.
        //
        // Counted PER BYTE, exactly like `bad`, so the four edges plus `in` add
        // up to `bad` and a reader can check that.
        //
        // `npx` is how many whole pixels the 8192-byte sample reaches, and
        // `rows` how much of the plane that is.  This is the number that stops
        // "no bad pixel in the interior" from being read as "the interior is
        // clean": for n1 the sample covers 8 rows of a 40-row plane, so the
        // interior it reports on is partial.  Printed for that reason, not as
        // decoration.
        {
            const int npx    = (j->cout > 0) ? (cnt / j->cout) : 0;
            const int rowspan = (j->w > 0) ? ((npx + j->w - 1) / j->w) : 0;
            int e0 = 0, eL = 0, eT = 0, eB = 0, ein = 0;
            int fx = -1, fy = -1;
            for (int i = 0; i < cnt; i++) {
                int d = (int)ref[i] - (int)s_cv_ref[i];
                if (d < 0) { d = -d; }
                if (d <= CV_GAP_MAX) { continue; }
                const int px = (j->cout > 0) ? (i / j->cout) : 0;
                const int x  = (j->w > 0) ? (px % j->w) : 0;
                const int y  = (j->w > 0) ? (px / j->w) : 0;
                int onedge = 0;
                if (fx < 0)          { fx = x; fy = y; }
                if (x == 0)          { e0++; onedge = 1; }
                if (x == j->w - 1)   { eL++; onedge = 1; }
                if (y == 0)          { eT++; onedge = 1; }
                if (y == j->h - 1)   { eB++; onedge = 1; }
                if (!onedge)         { ein++; }
            }
            sprintf(Message,
                    "gpu cv edge n%d npx%d rows%d/%d x0 %d x%d %d y0 %d y%d %d in %d\r\n",
                    n, npx, rowspan, (int)j->h,
                    e0, (int)j->w - 1, eL, eT, (int)j->h - 1, eB, ein);
            UART_SendString(Message);
            sprintf(Message, "gpu cv fbad n%d x%d y%d\r\n", n, fx, fy);
            UART_SendString(Message);
        }

        // ONE CHANNEL'S DIGIT PLANES, for a bounded number of failing layers.
        // The offline model of this operator cannot name this fault - it already
        // says this shape of layer is clean, at worst 4 - so the board has to
        // hand over the four numbers the model prints for the same channel: the
        // plane's min, its max, and how many bytes sit at exactly 0 and at
        // exactly 255.
        //
        // THE CENSUS NO LONGER HAPPENS HERE.  It used to, as a second draw of
        // this layer with the census armed on `fch`.  The draw is gone: the
        // census now rides the production draw (see conv_run_check) on channel
        // 0, for every layer, so nothing needs re-drawing and every layer has
        // the model's own channel-0 row to be compared against.  `fch` is still
        // printed on the `loc` line above, which is where it belongs - it names
        // the channel the first bad pixel was in, and now that is all it is for.
    }
}

// How many layers this inference put on the GPU and how many draws they cost.
// Reset before Invoke and read after it by yolo_plate_detect(), which prints one
// line - so the evidence for "the operator really ran on the GPU" is per
// inference and costs one line, not 52.
static unsigned s_cv_turn_layers = 0u;
static unsigned s_cv_turn_draws  = 0u;

// ...but that line does NOT print on every inference, and this is the latch that
// makes it so.  It printed on EVERY inference until the conv switch became a
// default rather than something a key turns on.  A line per frame on the healthy
// path is the thing this product does not do - the DVP heartbeat was deleted for
// exactly that - and the reading cannot change between two inferences of one boot
// anyway, because the per-layer verdicts are latched for the whole boot, so the
// set and its draw count are fixed from the first inference on.  The first
// inference is also the only one that runs the per-layer checks, so its numbers
// are the only ones with anything new in them.
//
// ONE EXCEPTION, and it is the `tail` knob: changing it changes WHICH layers are
// eligible, so it changes l/d - the one input that can move this line's numbers
// within a boot.  Without the second condition a `t` sweep would print the cut
// (in the key echo) and never the count it produced, which is the number this
// whole stage is judged by, so the same log would carry one stale l/d and 13
// cuts beside it.  s_cv_sum_tail holds the tail the line was last printed under,
// so the sweep gets exactly one line per cut and no more.
static int s_cv_sum_done = 0;
static uint32_t s_cv_sum_tail = 0xFFFFFFFFu;   // not a legal cut (wraps at 60)

static TfLiteStatus conv_gpu_invoke(TfLiteContext* ctx, TfLiteNode* node)
{
#if GPU_ENABLE
    // Once per session, on the first conv node of the first inference.  Without
    // this line "prepare never captured anything" and "invoke is never reached"
    // look identical in the log - the same reading mistake the depthwise
    // `gpu dw call` line exists to prevent.
    {
        static int once = 0;
        if (once == 0) {
            /* Same split as the depthwise one (2026-10-12): the latch stays
               unconditional, only the report is gated. */
            once = 1;
#if BOOT_VERBOSE
            sprintf(Message, "gpu cv call q%u\r\n", (unsigned)s_cvq_n);
            UART_SendString(Message);
#endif
        }
    }

    // Asked first because it is free and it is what decides whether anything
    // below matters: an ineligible layer never touches the per-layer state.
    //
    // The master switch is tested HERE and not inside conv_eligible(), so that
    // "off" means exactly what it says: no per-layer state, no one-time check,
    // and no cv_skip line for any of the 52 layers.  An un-flipped board is
    // byte-for-byte the firmware without this operator in it.
    if (g_gpu_conv_on == 0u) { return s_conv_stock.invoke(ctx, node); }

    ConvJob j;
    const char* why = nullptr;
    if (!conv_eligible(ctx, node, &j, &why)) {
        cv_skip(conv_layer_no(node), (why != nullptr) ? why : "?");
        return s_conv_stock.invoke(ctx, node);
    }

    // The tail cut, asked AFTER eligibility and BEFORE the one-time check, so
    // that a layer this refuses (a) is refused for this reason alone, and (b) is
    // never measured or recorded - the check below runs on the first layer that
    // is ACTUALLY offloaded, which is what makes a high threshold a measurement
    // of the layers that remain rather than of the layers that were eligible.
    // See gpu.h on g_gpu_conv_tail for why a tail and not a subset.
    if ((g_gpu_conv_tail != 0u) && (j.q->n < g_gpu_conv_tail)) {
        return s_conv_stock.invoke(ctx, node);
    }

    // The one-time measurement of THIS layer, and its verdict is what is read
    // back below.  A layer that fails is on the CPU for the rest of the session
    // while every other layer keeps running - which is the constraint that
    // matters more than any of the above.
    if (s_cv_check[j.q->n] == 0) { conv_run_check(ctx, node, &j); }
    // NAMED, because the only way to read a negative here is that a verdict was
    // recorded earlier - and every verdict records itself with a `chk` or a
    // `chk bail` line.  So this line can only ever be VISIBLE in the anomalous
    // case, which is exactly the case that cost a flash round: three slots
    // (n47, n48, n51) printed nothing at all, and a silent return here cannot be
    // told from a layer that was never reached, a lost UART line, or a
    // duplicate ConvQ slot colliding on `n`.  cv_skip() de-dups per layer, so a
    // normal run still prints nothing here.
    if (s_cv_check[j.q->n] < 0)  { cv_skip(j.q->n, "held"); return s_conv_stock.invoke(ctx, node); }

    if (conv_draw(&j) < 0) {
        // The GPU refused to draw this layer.  `gpu_conv()` has already latched
        // its own dead flag if the refusal was a drain timeout, so this is the
        // ordinary "this layer cannot be drawn" case - too many chunks for the
        // scratch plane, a scale outside the field, a bias that will not fit.
        // The stock kernel rewrites every byte of `out`, which is what makes a
        // partial fold safe to fall back from (see the contract in gpu.h).
        //
        // -2 lands here too, and it is the one refusal that is NOT about this
        // draw: the layer's centring cannot be written into the bias field at
        // any chunk, so it will refuse identically for the rest of the session.
        // Same handling, different meaning - which is why conv_run_check()
        // examines the code where it can afford to.
        return s_conv_stock.invoke(ctx, node);
    }

    s_cv_turn_layers++;
    // Per OUTPUT CHANNEL, because one draw is one (co, chunk) pair: `gpu_conv()`
    // sets its own scale, CLUT offset and bias per co, so the two units of a
    // draw can only ever carry one channel's weights.  The first version counted
    // `2*K` - the draws of one channel - which read 48 where the GPU really made
    // 1152, and understated the operator by a factor of Cout, i.e. by everything
    // that makes this stage worth measuring.  It is the one number in the log
    // that is direct evidence for "the convolution ran on the GPU".
    s_cv_turn_draws += (unsigned)j.cout * 2u * (((unsigned)j.cin + 31u) / 32u);
    return kTfLiteOk;
#else
    // GPU_ENABLE 0: the conv stub, the twin of the depthwise one above and for
    // the same reason - the registration stays, the body becomes the stock
    // CMSIS-NN kernel, and no gpu.o symbol is reachable from here.
    return s_conv_stock.invoke(ctx, node);
#endif
}

