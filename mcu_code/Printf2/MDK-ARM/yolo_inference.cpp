int yolo_cascade_plate_raw(YoloBox* dst, int max)
{
    const int n = s_plate_raw_n;

    if ((dst != nullptr) && (max > 0))
    {
        const int c = (n < max) ? n : max;
        for (int i = 0; i < c; i++)
        {
            dst[i] = s_plate_raw[i];
        }
    }
    return n;
}

