#define YOLO_PLATE_MAXBOX 16   // a plate has <= 8 glyphs; ignore boxes past this

// ---------------------------------------------------------------------------
// The plate-cluster filter.  Key 'v', yolo_plate_geo_set(); resets to 0.
//
// THE PROBLEM IT SOLVES.  yolo_plate_read() below concatenates EVERY box with
// class_id > 0, so anything the detector hallucinates anywhere in the frame
// becomes a character in the plate string.  On 11 frames of one scene
// (mcu_code/log/log.txt, key 'b', 2026-10-12) the firmware produced 8 DISTINCT
// strings for ONE plate, and a box spanning the whole frame - ~600x250 px in
// the camera's space, classified '8', score 0.49..0.75 - appeared in ELEVEN of
// ELEVEN of them and, being the leftmost, contributed a leading '8' each time.
//
// WHY A CONFIDENCE THRESHOLD IS NOT THE FIX, which is the reason this is
// geometric: the junk is not WEAK.  In that capture every box that reached the
// string scored 0.374..0.917 - the LOWEST score in the whole set belonged to
// the largest box, while a real 粤 sat below three others at 0.557.  No score
// separates them.  A size does.
//
// THE RULE, chosen by scoring five candidates on those 11 frames with
// tools/_plate_rule.py (which reads the log and can be re-run on any capture):
//
//   (a) SIZE.  A glyph is a glyph.  Drop a candidate whose height is outside
//       [0.6, 1.6] x the median candidate height, or whose width is outside
//       [0.5, 1.6] x the median candidate width.  Medians and not means,
//       because the outliers are exactly what is being measured.
//   (b) DUPLICATE.  Greedy in score order - which is the order boxes[] arrives
//       in, because nms() sorted it - drop a candidate whose x-interval
//       overlaps a KEPT candidate's by more than half of the shorter one, when
//       the two also share rows.  This is what removes the doubled 粤: two
//       detections of one glyph at 41% IoU survive YOLO_NMS_THRESH 0.45f, and
//       nms is class-agnostic so it will never merge them.  The 0.5 is
//       load-bearing and was measured: 0.3 over-merges and returns 6 glyphs
//       where the plate has 7.
//
// WHAT IT IS NOT ALLOWED TO DO.  A same-row gate was tested and DROPPED: every
// candidate already shared one row on all 11 frames, so it fired 0 times, and a
// clause that never fires is a knob that is not set.  The filter only runs at
// all with 4 or more candidates, and it falls back to the unfiltered set if the
// size gate would leave fewer than 2 - so a plate with two or three detections
// is assembled exactly as before rather than gutted.
//
// MEASURED EFFECT, the same 11 frames: 8 distinct strings -> 4; the plate's own
// 7 glyphs in 10 of 11 frames; 粤 first in 11 of 11.  What it does NOT fix is
// the model - R is read as A or 9 and G as 8 on every frame either way.  This
// removes characters.  It never adds one.
//
// IT ONLY EVER REMOVES, so with the switch off yolo_plate_read() is
// byte-for-byte what it was - which is also what keeps tools/chain_emulate.py
// honest, since it decodes through this function.
// ---------------------------------------------------------------------------
static int s_plate_geo_on = 0;     // key-gated, resets to 0

extern "C" void yolo_plate_geo_set(int on) { s_plate_geo_on = (on != 0) ? 1 : 0; }
extern "C" int  yolo_plate_geo_get(void)   { return s_plate_geo_on; }

// Sorts a scratch copy and returns the middle one.
static int plate_med(int* v, int n)
{
    for (int i = 1; i < n; i++) {
        const int key = v[i];
        int j = i - 1;
        while (j >= 0 && v[j] > key) { v[j + 1] = v[j]; j--; }
        v[j + 1] = key;
    }
    return v[n / 2];
}

// Rewrites idx[0..m-1] in place, returns the new count.  Ratios only, so it does
// not care which space the boxes are in - camera_map_box() is a pure per-axis
// scale, so the detector's square 320 and the camera's 800x480 agree.
static int plate_geo_filter(const YoloBox* boxes, int* idx, int m)
{
    if (m < 4) return m;                       // too few to measure: leave it

    int h[YOLO_PLATE_MAXBOX], w[YOLO_PLATE_MAXBOX];
    int hs[YOLO_PLATE_MAXBOX], ws[YOLO_PLATE_MAXBOX];
    for (int i = 0; i < m; i++) {
        h[i] = hs[i] = (int)(boxes[idx[i]].y2 - boxes[idx[i]].y1);
        w[i] = ws[i] = (int)(boxes[idx[i]].x2 - boxes[idx[i]].x1);
    }
    const int mh = plate_med(hs, m);           // scratch copies: h[]/w[] survive
    const int mw = plate_med(ws, m);
    if (mh <= 0 || mw <= 0) return m;

    int keep[YOLO_PLATE_MAXBOX];
    int k = 0;
    for (int i = 0; i < m; i++) {              // (a) size
        if (h[i] * 10 > mh * 16 || h[i] * 10 < mh * 6) continue;
        if (w[i] * 10 > mw * 16 || w[i] * 10 < mw * 5) continue;
        keep[k++] = idx[i];
    }
    if (k < 2) return m;                       // the gate emptied it: leave it

    int res[YOLO_PLATE_MAXBOX];
    int r = 0;
    for (int i = 0; i < k; i++) {              // (b) duplicates, in score order
        const YoloBox* b = &boxes[keep[i]];
        const float bw = b->x2 - b->x1;
        int dup = 0;
        for (int j = 0; j < r; j++) {
            const YoloBox* c = &boxes[res[j]];
            const float ox = (b->x2 < c->x2 ? b->x2 : c->x2) -
                             (b->x1 > c->x1 ? b->x1 : c->x1);
            const float oy = (b->y2 < c->y2 ? b->y2 : c->y2) -
                             (b->y1 > c->y1 ? b->y1 : c->y1);
            if (oy <= 0.0f) continue;          // different row: not a duplicate
            const float cw = c->x2 - c->x1;
            if (ox * 2.0f > (bw < cw ? bw : cw)) { dup = 1; break; }
        }
        if (dup == 0) res[r++] = keep[i];
    }

    for (int i = 0; i < r; i++) idx[i] = res[i];
    return r;
}

int yolo_plate_read(const YoloBox* boxes, int n, char* buf, int buf_size)
{
    int idx[YOLO_PLATE_MAXBOX];
    int m = 0;
    for (int i = 0; i < n && m < YOLO_PLATE_MAXBOX; i++) {
        if (boxes[i].class_id > 0) idx[m++] = i;   // 0 = the plate outline itself
    }

    // The plate-cluster filter, off by default - see the block above.  It runs
    // BEFORE the sort on purpose: the greedy duplicate rule needs the
    // score-descending order, which is what boxes[] arrives in.
    if (s_plate_geo_on != 0) m = plate_geo_filter(boxes, idx, m);

    // insertion sort the indices by x1 (ascending)
    for (int i = 1; i < m; i++) {
        const int key = idx[i];
        const float kx = boxes[key].x1;
        int j = i - 1;
        while (j >= 0 && boxes[idx[j]].x1 > kx) { idx[j + 1] = idx[j]; j--; }
        idx[j + 1] = key;
    }

    if (buf_size < 1) return 0;
    int len = 0;
    for (int i = 0; i < m; i++) {
        const int cid = boxes[idx[i]].class_id;
        uint8_t text[2];
        int tn = 0;
        if (cid >= 1 && cid <= 34) {
            text[tn++] = (uint8_t)CHARS[cid - 1];
        } else if (cid >= 35 && cid <= 69) {
            text[0] = PROV_GBK[cid - 35][0];
            text[1] = PROV_GBK[cid - 35][1];
            tn = 2;
        } else {
            continue;                              // class 0 was filtered above
        }
        if (len + tn > buf_size - 1) break;        // keep room for '\0'
        for (int k = 0; k < tn; k++) buf[len++] = (char)text[k];
    }
    buf[len] = '\0';
    return len;
}

