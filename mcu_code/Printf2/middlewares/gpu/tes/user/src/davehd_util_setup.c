/* Setup triangle with attributes for rendering. This function can setup primitive information (bounding box),*/
/* edges, UV, RHW and depth interpolants for any triangle. Depending on what pointers are passed the desired*/
/* data is generated. The input vertices are passed as pointers to dhd_util_vertex_t, but depending on*/
/* the output that is requested only a part of that structure has to contain valid information. If e.g.*/
/* only primitive and edge edata is requested, only the m_x and m_y members need to contain data and*/
/* thus pointers into an array of dhd_int32_t (casted to dhd_util_vertex_t) would work as well.*/
/* */
/* */
/* */
/* The required members for each output are:*/
/* <table>*/
/* Requested output       Required members of dhd_util_vertex_t*/
/* ---------------------  --------------------------------------*/
/* pout (primitive out)   m_x, m_y*/
/* eout (edge out)        m_x, m_y*/
/* uvout (uv out)         m_x, m_y, m_u, m_v*/
/* rhwout (rhw out)       m_x, m_y, m_rhw*/
/* depthout (depth out)   m_x, m_y, m_z*/
/* </table>*/
/* */
/* All combinations of output data can be generated with the following restrictions : When edge data is*/
/* requested primitive data has to be generated as well and clipping is applied only when primitive data*/
/* is generated. It is possible (and actually usefull) to generate only UV/RHW data based on a triangle*/
/* even when the mapped geometry is different (e.g. a quad or infinite plane).*/
/* */
/* The recommended use is setting up a batch of triangles before rendering them with a single call to*/
/* dhd_draw_array.*/
/*                                                                                                       */
/* Note:*/
/*  Screenspace coordinates (m_x, m_y) are expected to be integers with 4bit subpixel precision while all*/
/*  vertex varyings are expected to be floats. This includes the depth (m_z).*/
/**/
/**/
/*  Setup works regardless of the triangle winding order (clockwise or counter clockwise) by automatically*/
/*  setting the edge inversion bits (E_DHD_INVERT) in case of a counter clockwise triangle.*/
/*                                                                                                       */
/* Parameters:*/
/*  a_device :    Driver context handle (as returned by dhd_init).*/
/*  a_v0 :        First triangle vertex (see dhd_util_vertex_t)*/
/*  a_v1 :        Second triangle vertex (see dhd_util_vertex_t)*/
/*  a_v2 :        Third triangle vertex (see dhd_util_vertex_t)*/
/*  a_pout :      Pointer to dhd_prim_data_t receiving bounding box and edge control flags (can be null)*/
/*  a_eout :      Pointer to dhd_edge_data_t[3] receiving edge information (can be null)*/
/*  a_uvout :     Pointer to dhd_uv_data_t receiving uv information (can be null)*/
/*  a_rhwout :    Pointer to dhd_rhw_data_t receiving rhw information (can be null)*/
/*  a_depthout :  Pointer to dhd_depth_data_t receiving depth information (can be null)*/
/*  a_clipmode :  Specify to what region the geometry shall be clipped (see dhd_util_clipmode_t)*/
/*                                                                                                       */
/* Returns:*/
/*  DHD_TRUE if resulting triangle is visible DHD_FALSE if resulting triangle was entirely clipped*/
/*  and should not be drawn                                                                        */
dhd_bool_t dhd_setup_tri_attributes(dhd_handle_t a_device, const dhd_util_vertex_t *a_v0, const dhd_util_vertex_t *a_v1, const dhd_util_vertex_t *a_v2,
                                    dhd_prim_data_t *a_pout, dhd_edge_data_t *a_eout, dhd_uv_data_t *a_uvout, dhd_rhw_data_t *a_rhwout, dhd_depth_data_t *a_depthout, dhd_util_clipmode_t a_clipmode) {  
  dhd_int32_t w,dx1,dy1,dx2,dy2;
  dhd_float32_t fdx1,fdy1,fdx2,fdy2,id;
  const dhd_float32_t ifix16 = 1.0f / 16.0f;   /* required to scale integer 4bit fixedpoint coordinates to floating point*/

  /* triangle edge deltas*/
  dx1 = a_v1->m_x - a_v2->m_x;    
  dy1 = a_v1->m_y - a_v2->m_y;    
  dx2 = a_v0->m_x - a_v2->m_x;  
  dy2 = a_v0->m_y - a_v2->m_y;  
  /* compute winding (has to be done in integer)*/
  w = (dx2 * dy1) - (dx1 * dy2);     

  if (a_pout != 0) {
    /* find bounding box*/
    dhd_bound_tri(a_pout, a_v0->m_x, a_v0->m_y, a_v1->m_x, a_v1->m_y, a_v2->m_x, a_v2->m_y);
    if (!dhd_clip_bbox(a_device, a_pout, a_clipmode)) {
      return DHD_FALSE;      
    }
    if (w >= 0) {
      /* clockwise triangle*/
      a_pout->m_edgecontrol = DHD_EDGE0(E_DHD_IEDGE) | DHD_EDGE1(E_DHD_IEDGE) | DHD_EDGE2(E_DHD_IEDGE);        
    } else {
      /* counter clockwise triangle - needs edge inversion*/
      a_pout->m_edgecontrol = DHD_EDGE0(E_DHD_IEDGE | E_DHD_INVERT) | DHD_EDGE1(E_DHD_IEDGE | E_DHD_INVERT) | DHD_EDGE2(E_DHD_IEDGE | E_DHD_INVERT);       
    }

    if (a_eout != 0) {      
      dhd_int32_t xo,yo;    
      /* setup edges for start at xmin,ystart      */
      xo = a_pout->m_xmin   << 4;
      yo = a_pout->m_ystart << 4;    
      dhd_setup_edge_noaa(&a_eout[0], a_v0->m_x,a_v0->m_y, a_v1->m_x,a_v1->m_y, xo,yo);  
      dhd_setup_edge_noaa(&a_eout[1], a_v1->m_x,a_v1->m_y, a_v2->m_x,a_v2->m_y, xo,yo);
      dhd_setup_edge_noaa(&a_eout[2], a_v2->m_x,a_v2->m_y, a_v0->m_x,a_v0->m_y, xo,yo); 
    }
  }

  /* convert to float if we need any interpolant to be setup (if the system does not have */
  /* an FPU there are faster ways but as the core expects input in float anyway we assume*/
  /* using the FPU is efficient on the target platform)*/
  if ((a_uvout != 0) || (a_rhwout != 0) || (a_depthout != 0)) {    
    fdx1 = (dhd_float32_t) dx1; 
    fdy1 = (dhd_float32_t) dy1;
    fdx2 = (dhd_float32_t) dx2; 
    fdy2 = (dhd_float32_t) dy2;
    if(w == 0) {
      /* value of id will not matter as there may only be some subpixels visible*/
      id = 16.0f;
    } else {
      id = 16.0f / (dhd_float32_t) w;                                                             /* inverse denominator (premultiplied with 16 / see above)*/
    }
  }

  /* Note: The code below was actually readable before it went through misra ((which(forced)(((and unneeded casts)parenthesis)(around))(everything))*/
  /* PRQA S 3353 28 *//* $Misra: Misra tool unable to determine controlflow correctly $*/
  if (a_uvout != 0) {
    /* setup UVs */
    a_uvout[0].m_dux = (((a_v0->m_u - a_v2->m_u) * fdy1) - ((a_v1->m_u - a_v2->m_u) * fdy2)) * id;
    a_uvout[0].m_duy = (((a_v1->m_u - a_v2->m_u) * fdx2) - ((a_v0->m_u - a_v2->m_u) * fdx1)) * id;
    a_uvout[0].m_dvx = (((a_v0->m_v - a_v2->m_v) * fdy1) - ((a_v1->m_v - a_v2->m_v) * fdy2)) * id;  
    a_uvout[0].m_dvy = (((a_v1->m_v - a_v2->m_v) * fdx2) - ((a_v0->m_v - a_v2->m_v) * fdx1)) * id;
    a_uvout[0].m_u0 = a_v2->m_u - ((((dhd_float32_t) a_v2->m_x * a_uvout[0].m_dux) + ((dhd_float32_t) a_v2->m_y * a_uvout[0].m_duy)) * ifix16);  
    a_uvout[0].m_v0 = a_v2->m_v - ((((dhd_float32_t) a_v2->m_x * a_uvout[0].m_dvx) + ((dhd_float32_t) a_v2->m_y * a_uvout[0].m_dvy)) * ifix16); 
  }
  
  if (a_rhwout != 0) {
    /* setup RHWs */
    a_rhwout[0].m_dx = (((a_v0->m_rhw - a_v2->m_rhw) * fdy1) - ((a_v1->m_rhw - a_v2->m_rhw) * fdy2)) * id;
    a_rhwout[0].m_dy = (((a_v1->m_rhw - a_v2->m_rhw) * fdx2) - ((a_v0->m_rhw - a_v2->m_rhw) * fdx1)) * id;
    a_rhwout[0].m_start = a_v2->m_rhw - ((((dhd_float32_t) a_v2->m_x * a_rhwout[0].m_dx) + ((dhd_float32_t) a_v2->m_y * a_rhwout[0].m_dy)) * ifix16);
  }

  if (a_depthout != 0) {
    /* setup Depths*/
    a_depthout[0].m_dzx = (((a_v0->m_z - a_v2->m_z) * fdy1) - ((a_v1->m_z - a_v2->m_z) * fdy2)) * id;
    a_depthout[0].m_dzy = (((a_v1->m_z - a_v2->m_z) * fdx2) - ((a_v0->m_z - a_v2->m_z) * fdx1)) * id;
    a_depthout[0].m_z0  = a_v2->m_z - ((((dhd_float32_t)  a_v2->m_x * a_depthout[0].m_dzx) + ((dhd_float32_t) a_v2->m_y * a_depthout[0].m_dzy)) * ifix16);
    a_depthout[0].m_dwx  = 0.0f;
    a_depthout[0].m_dwy  = 0.0f;
    a_depthout[0].m_rhw0 = 1.0f;
  }
  
  return DHD_TRUE;
}

