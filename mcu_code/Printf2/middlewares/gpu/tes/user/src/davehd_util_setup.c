/* Setup simple antialiased triangle. This function works like dhd_setup_tri_noaa but it does enable the*/
/* use of antialiased triangle edges. If not all edges shall be antialiased a_edgeflags can be used to*/
/* select the shared (not antialiased) edges by specifying a combination of DHD_EDGE0(E_DHD_SHARED),*/
/* DHD_EDGE1(E_DHD_SHARED) and DHD_EDGE2(E_DHD_SHARED) flags.*/
/* For shared edges also invert flags can be specified as in dhd_setup_tri_noaa.*/
/* The input data is expected as pointer to dhd_util_vertex_t but only the m_x and m_y members are actually*/
/* used, so it is safe e.g. to use an dhd_int32_t array and cast it to dhd_util_vertex_t.*/
/**/
/* */
/* */
/*   - DHD_EDGE0 is defined from vertex a_v0 to vertex a_v1*/
/*   - DHD_EDGE1 is defined from vertex a_v1 to vertex a_v2*/
/*   - DHD_EDGE2 is defined from vertex a_v2 to vertex a_v0*/
/* */
/* \Parameters a_pout and a_eout are not optional and can not be null (as in dhd_setup_tri_attributes).*/
/*                                                                                                       */
/* Parameters:*/
/*  a_device :     Driver context handle (as returned by dhd_init).*/
/*  a_v0 :         First triangle vertex (see dhd_util_vertex_t)*/
/*  a_v1 :         Second triangle vertex (see dhd_util_vertex_t)*/
/*  a_v2 :         Third triangle vertex (see dhd_util_vertex_t)*/
/*  a_pout :       Pointer to dhd_prim_data_t receiving bounding box and edge control flags*/
/*  a_eout :       Pointer to dhd_edge_data_t[3] receiving edge information*/
/*  a_edgeflags :  Combination of shared and invert flags or 0 (see dhd_edge_flag_t)*/
/*  a_clipmode :   Specify to what region the geometry shall be clipped (see dhd_util_clipmode_t)*/
/*                                                                                                       */
/* Returns:*/
/*  DHD_TRUE if resulting triangle is visible DHD_FALSE if resulting triangle was entirely clipped and*/
/*  should not be drawn     */
dhd_bool_t dhd_setup_tri_aa(dhd_handle_t a_device, const dhd_util_vertex_t *a_v0, const dhd_util_vertex_t *a_v1, const dhd_util_vertex_t *a_v2,
                            dhd_prim_data_t *a_pout, dhd_edge_data_t *a_eout, dhd_enum_t a_edgeflags, dhd_util_clipmode_t a_clipmode) {
  dhd_int32_t xo,yo;    

  /* validate inputs*/
  if ((a_pout == 0) || (a_eout == 0)) {
    return DHD_FALSE;
  }

  /* get triangle bounding box and clip it*/
  dhd_bound_tri(a_pout, a_v0->m_x, a_v0->m_y, a_v1->m_x, a_v1->m_y, a_v2->m_x, a_v2->m_y);
  if (!dhd_clip_bbox(a_device, a_pout, a_clipmode)) {
    return DHD_FALSE;      
  }
  /* base edgeflags plus user supplied additions (for inverts and shares)*/
  a_pout->m_edgecontrol = DHD_EDGE0(E_DHD_ENABLE | E_DHD_USE_ENUM) | DHD_EDGE1(E_DHD_ENABLE | E_DHD_USE_ENUM) | DHD_EDGE2(E_DHD_ENABLE | E_DHD_USE_ENUM) | a_edgeflags;        
    
  /* setup edges for start at xmin,ystart      */
  xo = a_pout->m_xmin   << 4;
  yo = a_pout->m_ystart << 4;    
  if ((a_edgeflags & DHD_EDGE0( E_DHD_SHARED )) != 0) {
    dhd_setup_edge_noaa(&a_eout[0], a_v0->m_x,a_v0->m_y, a_v1->m_x,a_v1->m_y, xo,yo);  
  } else {
    dhd_setup_edge_aa(&a_eout[0], a_v0->m_x,a_v0->m_y, a_v1->m_x,a_v1->m_y, xo, yo, 1.0f);  
  }
  if ((a_edgeflags & DHD_EDGE1( E_DHD_SHARED )) != 0) {
    dhd_setup_edge_noaa(&a_eout[1], a_v1->m_x,a_v1->m_y, a_v2->m_x,a_v2->m_y, xo,yo);
  } else {
    dhd_setup_edge_aa(&a_eout[1], a_v1->m_x,a_v1->m_y, a_v2->m_x,a_v2->m_y, xo,yo, 1.0f);
  }
  if ((a_edgeflags & DHD_EDGE2( E_DHD_SHARED )) != 0) {
    dhd_setup_edge_noaa(&a_eout[2], a_v2->m_x,a_v2->m_y, a_v0->m_x,a_v0->m_y, xo,yo); 
  } else {
    dhd_setup_edge_aa(&a_eout[2], a_v2->m_x,a_v2->m_y, a_v0->m_x,a_v0->m_y, xo,yo, 1.0f);
  }

  return DHD_TRUE;
}

