/* Define utility cliprect. The utility function dhd_clip_bbox supports constraining geometry to a*/
/* rectangular region (clip rect). This can be either the entire framebuffer (default) or the overlap of*/
/* framebuffer and an arbitrary rectangle defined by this function.*/
/* Note that this region is not communicated to the HW, it is a pure software feature used by several*/
/* utility functions like dhd_clip_bbox, dhd_setup_tri_attributes.*/
/* All borders are inclusive.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init).*/
/*  a_xmin : Left border of cliprect (integer pixel position) */
/*  a_ymin : Top border of cliprect (integer pixel position)*/
/*  a_xmax : Right border of cliprect (integer pixel position) */
/*  a_ymax : Bottom border of cliprect (integer pixel position)*/
/**/
/* See Also:*/
/*  dhd_clip_bbox, dhd_set_bbox*/
void dhd_set_util_cliprect(dhd_handle_t a_device, dhd_uint16_t a_xmin, dhd_uint16_t a_ymin, dhd_uint16_t a_xmax, dhd_uint16_t a_ymax) {
  dhd_device_data_t *device = dhd_get_device( a_device ); 

  device->m_util_xmin = a_xmin;
  device->m_util_ymin = a_ymin;
  device->m_util_xmax = a_xmax;
  device->m_util_ymax = a_ymax;
}

