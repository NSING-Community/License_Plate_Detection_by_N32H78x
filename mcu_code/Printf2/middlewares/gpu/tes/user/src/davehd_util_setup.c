/* Setup a simple box. A box is an axis aligned rectangle. The function will use four edges (DHD_EDGE0*/
/* to DHD_EDGE3).*/
/* */
/* \Parameters a_pout and a_eout are not optional and can not be null (as in dhd_setup_tri_attributes).*/
/* */
/* */
/* */
/* Also note that non antialiased edges are limited to a width/height of 2048 pixels (see <link !!Basics_Geometry, Specifying Geometry>).*/
/*                                                                                                         */
/* Parameters:*/
/*  a_device :    Driver context handle (as returned by dhd_init).*/
/*  a_xmin :      Left border of box (4bit subpixel precision)*/
/*  a_ymin :      Top border of box (4bit subpixel precision)*/
/*  a_xmax :      Right border of box (4bit subpixel precision)*/
/*  a_ymax :      Bottom border of box (4bit subpixel precision)*/
/*  a_pout :      Pointer to dhd_prim_data_t receiving bounding box and edge control flags*/
/*  a_eout :      Pointer to dhd_edge_data_t[4] receiving edge information*/
/*  a_clipmode :  Specify to what region the geometry shall be clipped (see dhd_util_clipmode_t)*/
/*                                                                                                         */
/* Returns:*/
/*  DHD_TRUE if resulting box is visible DHD_FALSE if resulting box was entirely clipped and should not*/
/*  be drawn                                                                                                                             */
dhd_bool_t dhd_setup_box_noaa(dhd_handle_t a_device, dhd_fx28_4_t a_xmin, dhd_fx28_4_t a_ymin, dhd_fx28_4_t a_xmax, dhd_fx28_4_t a_ymax,
                              dhd_prim_data_t *a_pout, dhd_edge_data_t *a_eout, dhd_util_clipmode_t a_clipmode) {
  dhd_int32_t xo,yo;  
                       
  /* validate inputs*/
  if ((a_pout == 0) || (a_eout == 0)) {
    return DHD_FALSE;
  }

  /* store as bounding box integer grid    */
  a_pout->m_xmin = (dhd_uint16_t) (a_xmin >> 4);         /* PRQA S 0502 *//* $Misra: #ARITHMETIC_SHIFT_RIGHT_NECESSARY $*/
  a_pout->m_ymin = (dhd_uint16_t) (a_ymin >> 4);         /* PRQA S 0502 *//* $Misra: #ARITHMETIC_SHIFT_RIGHT_NECESSARY $*/
  a_pout->m_xmax = (dhd_uint16_t) ((a_xmax + 15) >> 4);  /* PRQA S 0502 *//* $Misra: #ARITHMETIC_SHIFT_RIGHT_NECESSARY $*/
  a_pout->m_ymax = (dhd_uint16_t) ((a_ymax + 15) >> 4);  /* PRQA S 0502 *//* $Misra: #ARITHMETIC_SHIFT_RIGHT_NECESSARY $*/  
  a_pout->m_ystart = a_pout->m_ymin;
  a_pout->m_edgecontrol = DHD_EDGE0(E_DHD_IEDGE) | DHD_EDGE1(E_DHD_IEDGE) | DHD_EDGE2(E_DHD_IEDGE) | DHD_EDGE3(E_DHD_IEDGE);       

  if (!dhd_clip_bbox(a_device, a_pout, a_clipmode)) {
    return DHD_FALSE;      
  }

  /* setup edges for start at xmin,ystart      */
  xo = a_pout->m_xmin   << 4;
  yo = a_pout->m_ystart << 4;    
  a_eout[0].m_dx =  0; 
  a_eout[0].m_dy =  (1<<18);
  a_eout[1].m_dx = -(1<<18); 
  a_eout[1].m_dy =  0;
  a_eout[2].m_dx =  0; 
  a_eout[2].m_dy = -(1<<18);
  a_eout[3].m_dx =  (1<<18); 
  a_eout[3].m_dy =  0;    
  /* PRQA S 4131 4 *//* $Misra: Arithmetic left shift used for performance reasons. And why is this even considered a warning? $*/  
  a_eout[0].m_start = ( (yo - a_ymin) << 14) + ((1<<18)/2);        /* [<< 14] is [* (1<<18) / 16];*/
  a_eout[1].m_start = (-(xo - a_xmax) << 14) + ((1<<18)/2);
  a_eout[2].m_start = (-(yo - a_ymax) << 14) + ((1<<18)/2);
  a_eout[3].m_start = ( (xo - a_xmin) << 14) + ((1<<18)/2);
  
  return DHD_TRUE;
}

