/* Setup an antialiased box. A box is an axis aligned rectangle. The function will use four edges */
/* (DHD_EDGE0 to DHD_EDGE3). The output is identical to dhd_setup_box_noaa but defaults to an*/
/* antialiased edgecontrol word.*/
/* */
/* \Parameters a_pout and a_eout are not optional and can not be null (as in dhd_setup_tri_attributes).*/
/*                                                                                                       */
/* Parameters:*/
/*  a_device :     Driver context handle (as returned by dhd_init).*/
/*  a_xmin :       Left border of box (4bit subpixel precision)*/
/*  a_ymin :       Top border of box (4bit subpixel precision)*/
/*  a_xmax :       Right border of box (4bit subpixel precision)*/
/*  a_ymax :       Bottom border of box (4bit subpixel precision)*/
/*  a_pout :       Pointer to dhd_prim_data_t receiving bounding box and edge control flags*/
/*  a_eout :       Pointer to dhd_edge_data_t[4] receiving edge information*/
/*  a_clipmode :   Specify to what region the geometry shall be clipped (see dhd_util_clipmode_t)*/
/*                                                                                                       */
/* Returns:*/
/*  DHD_TRUE if resulting box is visible DHD_FALSE if resulting box was entirely clipped and*/
/*  should not be drawn    */
dhd_bool_t dhd_setup_box_aa(dhd_handle_t a_device, dhd_fx28_4_t a_xmin, dhd_fx28_4_t a_ymin, dhd_fx28_4_t a_xmax, dhd_fx28_4_t a_ymax, 
                            dhd_prim_data_t *a_pout, dhd_edge_data_t *a_eout, dhd_util_clipmode_t a_clipmode) {
  dhd_bool_t res;

  res = dhd_setup_box_noaa(a_device, a_xmin, a_ymin, a_xmax, a_ymax, a_pout, a_eout, a_clipmode);
  if (res == DHD_TRUE) {
    /* only change is setting the edgecontrol differently*/
    a_pout->m_edgecontrol = DHD_EDGE0(E_DHD_OEDGE) | DHD_EDGE1(E_DHD_OEDGE) | DHD_EDGE2(E_DHD_OEDGE) | DHD_EDGE3(E_DHD_OEDGE);       
  }
  return res;
}

