/* Setup thin line geometry. A thin not antialiased line is very fast to setup. The function will use*/
/* two edges (DHD_EDGE0 and DHD_EDGE1) both parallel to the line and offset by one pixel in either X or*/
/* Y direction. Additional edges to cap the endpoints are not necessary in the thin nonantialiased case.*/
/* */
/* \Parameters a_pout and a_eout are not optional and can not be null.*/
/* */
/* */
/* */
/* Also note that non antialiased edges are limited to a width/height of 2048 pixels (see <link !!Basics_Geometry, Specifying Geometry>).*/
/*                                                                                                         */
/* Parameters:*/
/*  a_device :    Driver context handle (as returned by dhd_init).*/
/*  a_x1 :        X position of first point (4bit subpixel precision)*/
/*  a_y1 :        Y position of first point (4bit subpixel precision)*/
/*  a_x2 :        X position of second point (4bit subpixel precision)*/
/*  a_y2 :        Y position of second point (4bit subpixel precision)*/
/*  a_pout :      Pointer to dhd_prim_data_t receiving bounding box and edge control flags*/
/*  a_eout :      Pointer to dhd_edge_data_t[2] receiving edge information*/
/*  a_clipmode :  Specify to what region the geometry shall be clipped (see dhd_util_clipmode_t)*/
/*                                                                                                         */
/* Returns:*/
/*  DHD_TRUE if resulting line is visible DHD_FALSE if resulting line was entirely clipped and should not*/
/*  be drawn                                                                                                                             */
dhd_bool_t dhd_setup_line_noaa(dhd_handle_t a_device, dhd_fx28_4_t a_x1, dhd_fx28_4_t a_y1, dhd_fx28_4_t a_x2, dhd_fx28_4_t a_y2,
                               dhd_prim_data_t *a_pout, dhd_edge_data_t *a_eout, dhd_util_clipmode_t a_clipmode) {
  dhd_int32_t xo,yo,adx,ady;  
                       
  /* validate inputs*/
  if ((a_pout == 0) || (a_eout == 0)) {
    return DHD_FALSE;
  }
  
  /* get bounds*/
  dhd_bound_aab(a_pout, a_x1, a_y1, a_x2, a_y2);
  if (!dhd_clip_bbox(a_device, a_pout, a_clipmode)) {
    return DHD_FALSE;      
  }
  /* setup edges for start at xmin,ystart      */
  xo = a_pout->m_xmin   << 4;
  yo = a_pout->m_ystart << 4;  

  /* create edge exactly on line */
  dhd_setup_edge_noaa_notie(&a_eout[0], a_x1,a_y1, a_x2,a_y2, xo,yo);
  /* use shifted copy. using L1 norm is faster and avoids division but is also necessary */
  /* to ensure a gapless thin line.*/
  a_eout[1] = a_eout[0];
  adx = a_eout[0].m_dx;
  ady = a_eout[0].m_dy;
  if (adx < 0) {
    adx = -adx;
  }
  if (ady < 0) {
    ady = -ady;
  }
  if (adx > ady) {    
    a_eout[1].m_start -= adx;
  } else {    
    a_eout[1].m_start -= ady;
  }
  a_pout->m_edgecontrol = DHD_EDGE0(E_DHD_IEDGE) | DHD_EDGE1(E_DHD_IEDGE | E_DHD_INVERT);    

  return DHD_TRUE;
}

/* ----------------------------------------------------------------------------------------------------------------------------*/
/* Setup wide or antialiased line geometry. Antialiased lines support an arbitary width by default. The*/
/* function will use four edges (DHD_EDGE0 to DHD_EDGE3). The first two are parallel to the line and*/
/* each offset by width/2 pixels. The last two are end caps perpendicular to the base line.*/
/* */
/* \Parameters a_pout and a_eout are not optional and can not be null.*/
/* */
/* */
/* */
/* By default the line end caps pass directly through the specified endpoints. In order to extend them*/
/* by width pixels outwards simply do this after setup:*/
/* <code>*/
/* a_eout[2].m_start += a_width \<\< (18 - 4); ** convert width from 4bit to 18bit fixedpoint*/
/* a_eout[3].m_start -= a_width \<\< (18 - 4);*/
/* </code>*/
/* */
/* If for some reason the line should be rendered without antialiasing, simply modify the edgecontrol*/
/* after setup like this:*/
/* <code>*/
/* a_pout-\>m_edgecontrol |= DHD_EDGE0(E_DHD_IEDGE) | DHD_EDGE1(E_DHD_IEDGE) | DHD_EDGE2(E_DHD_IEDGE) | DHD_EDGE3(E_DHD_IEDGE);*/
/* </code>*/
/* */
/*                                                                                                       */
/* Parameters:*/
/*  a_device :    Driver context handle (as returned by dhd_init).*/
/*  a_x1 :        X position of first point (4bit subpixel precision)*/
/*  a_y1 :        Y position of first point (4bit subpixel precision)*/
/*  a_x2 :        X position of second point (4bit subpixel precision)*/
/*  a_y2 :        Y position of second point (4bit subpixel precision)*/
/*  a_width :     Linewidth (4bit subpixel precision)*/
/*  a_pout :      Pointer to dhd_prim_data_t receiving bounding box and edge control flags*/
/*  a_eout :      Pointer to dhd_edge_data_t[4] receiving edge information*/
/*  a_clipmode :  Specify to what region the geometry shall be clipped (see dhd_util_clipmode_t)*/
/*                                                                                                       */
/* Returns:*/
/*  DHD_TRUE if resulting line is visible DHD_FALSE if resulting line was entirely clipped and should not*/
/*  be drawn                                                                                                                   */
dhd_bool_t dhd_setup_line_aa(dhd_handle_t a_device, dhd_fx28_4_t a_x1, dhd_fx28_4_t a_y1, dhd_fx28_4_t a_x2, dhd_fx28_4_t a_y2, dhd_uint32_t a_width,
                             dhd_prim_data_t *a_pout, dhd_edge_data_t *a_eout, dhd_util_clipmode_t a_clipmode) {
  dhd_int32_t xo,yo,dx,dy;  
  dhd_int32_t w = (dhd_int32_t) a_width;
                       
  /* validate inputs*/
  if ((a_pout == 0) || (a_eout == 0)) {
    return DHD_FALSE;
  }
  
  /* PRQA S 0502 21 *//* $Misra: #ARITHMETIC_SHIFT_RIGHT_NECESSARY $*/  
  /* get bounds (needs special code to handle wide line)*/
  if (a_x1 < a_x2) {
    /* x1 is xmin*/
    a_pout->m_xmin = (dhd_uint16_t) ((a_x1 - w) >> 4);
    a_pout->m_xmax = (dhd_uint16_t) ((a_x2 + w + 15) >> 4);
    a_pout->m_ystart = (dhd_uint16_t) ((a_y1 - w) >> 4);
  } else {
    /* x2 is xmin*/
    a_pout->m_xmin = (dhd_uint16_t) ((a_x2 - w) >> 4);
    a_pout->m_xmax = (dhd_uint16_t) ((a_x1 + w + 15) >> 4);
    a_pout->m_ystart = (dhd_uint16_t) ((a_y2 - w) >> 4);
  }
  if (a_y1 < a_y2) {
    /* y1 is ymin*/
    a_pout->m_ymin = (dhd_uint16_t) ((a_y1 - w) >> 4);
    a_pout->m_ymax = (dhd_uint16_t) ((a_y2 + w + 15) >> 4);
  } else {
    /* y2 is ymin*/
    a_pout->m_ymin = (dhd_uint16_t) ((a_y2 - w) >> 4);
    a_pout->m_ymax = (dhd_uint16_t) ((a_y1 + w + 15) >> 4);
  }
  if (!dhd_clip_bbox(a_device, a_pout, a_clipmode)) {
    return DHD_FALSE;      
  }
  /* setup edges for start at xmin,ystart      */
  xo = a_pout->m_xmin   << 4;
  yo = a_pout->m_ystart << 4;  

  /* create edge exactly on line (extra precision needed)*/
  dhd_setup_edge_aa2(&a_eout[0], a_x1,a_y1, a_x2,a_y2, xo,yo, 1.0f);
  a_eout[0].m_start -= (1 << 18) / 2; /* undo internal bias of setup_edge*/

  /* PRQA S 0502,4131 12 *//* $Misra: #ARITHMETIC_SHIFT_RIGHT_NECESSARY $*/  
  /* copy, shift and rotate base edge to create all 4 line edges*/
  a_eout[1] = a_eout[0];
  a_eout[2] = a_eout[0];  
  a_eout[0].m_start += w << (18 - 4);    /* bring width from 4 fractional to 18 fractional bits*/
  a_eout[1].m_start -= w << (18 - 4);
  /* create end caps ('butt' style)*/
  dx =  a_eout[0].m_dy;
  dy = -a_eout[0].m_dx;
  a_eout[2].m_dx = dx;
  a_eout[2].m_dy = dy;
  dx = dx >> 4;                          /* reducing deltas from 18bit to 14bit to ensure 32bit multiplies won't overflow*/
  dy = dy >> 4;                          /* as Xn,Yn,Xo,Yo are 4bit fractional the end result again has 18bit fraction*/
  a_eout[2].m_start = (-(a_x1-xo)*dx) - ((a_y1-yo)*dy);
  a_eout[3] = a_eout[2];
  a_eout[3].m_start = (-(a_x2-xo)*dx) - ((a_y2-yo)*dy);
  
  a_pout->m_edgecontrol = DHD_EDGE0(E_DHD_OEDGE) | DHD_EDGE1(E_DHD_OEDGE | E_DHD_INVERT) | DHD_EDGE2(E_DHD_OEDGE) | DHD_EDGE3(E_DHD_OEDGE | E_DHD_INVERT);

  return DHD_TRUE;
}
