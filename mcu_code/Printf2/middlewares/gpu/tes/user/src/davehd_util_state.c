/*----------------------------------------------------------------------------------------------------------*/
/* Find the log base 2 of an integer.*/
/* */
/* Parameters:  */
/*  a_val : 32-bit word to find the log base 2 of*/
/* */
/* Returns:*/
/*  log base 2 of a_val*/
/**/
static dhd_uint32_t dhd_lg(dhd_uint32_t a_val) {
  dhd_uint32_t res, shift;
  
  /* PRQA S 4104 11 *//* $Misra: Direct use of comparison in arithmetic operation is intended $*/  
  res   = (a_val > 0xFFFFu) << 4; 
  a_val =  a_val >> res;
  shift = (a_val > 0xFFu  ) << 3; 
  a_val =  a_val >> shift; 
  res   =  res | shift;
  shift = (a_val > 0xFu   ) << 2; 
  a_val = a_val >> shift; 
  res   = res | shift;
  shift = (a_val > 0x3u   ) << 1; 
  a_val = a_val >> shift; res |= shift;
  res   = res | (a_val >> 1u);

  return res;
}


