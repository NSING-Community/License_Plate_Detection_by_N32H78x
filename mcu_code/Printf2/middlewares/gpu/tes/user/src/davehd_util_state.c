/* Quickly set common blendmode. To make usage easier the most common blendmodes can be setup using this*/
/* function. When more complexity is required use the real blend control functions (see below).*/
/* */
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_blendmode : Requested blendmode (see dhd_util_blendmode_t)*/
/* See Also:*/
/*  dhd_set_blend_func, dhd_set_color_blending, dhd_set_alpha_blending, dhd_set_coverage_blend, dhd_set_read_decision*/
void dhd_util_blend(dhd_handle_t a_device, dhd_util_blendmode_t a_blendmode) {
  switch (a_blendmode) {    
    case E_DHD_UTIL_REPLACE:
      dhd_set_blend_func( a_device, E_DHD_BLEND, E_DHD_BLEND );
      dhd_set_color_blending( a_device, E_DHD_ONE, E_DHD_ZERO );  
      dhd_set_alpha_blending( a_device, E_DHD_ONE, E_DHD_ZERO );  
      dhd_set_coverage_blend( a_device, DHD_FALSE );
      dhd_set_read_decision( a_device, E_DHD_READ_NEVER, DHD_FALSE );  
      break;
    case E_DHD_UTIL_BLEND:
      dhd_set_blend_func( a_device, E_DHD_BLEND, E_DHD_BLEND );
      dhd_set_color_blending( a_device, E_DHD_SRC_ALPHA, E_DHD_ONE_MINUS_SRC_ALPHA );  
      dhd_set_alpha_blending( a_device, E_DHD_ONE, E_DHD_ONE_MINUS_SRC_ALPHA );  
      dhd_set_coverage_blend( a_device, DHD_TRUE );
      dhd_set_read_decision( a_device, E_DHD_USING_ONE_MINUS_ALPHA, DHD_TRUE );  
      break;
    default:
      break;
  }
}

