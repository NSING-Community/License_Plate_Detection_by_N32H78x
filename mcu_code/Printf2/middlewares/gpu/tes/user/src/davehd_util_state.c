/* Set texture address, format, size and wrapmode from buffer. Selecting a texture usually requires a*/
/* series of state changes (see e.g. dhd_set_texture_address, dhd_set_texture_format,*/
/* dhd_get_texture_size). With this function all relevant states can be changed according to the content*/
/* of the given buffer. For this to work the optional m_format member of dhd_buffer_t has to be*/
/* specified and if the given format is a texture format (dhd_texel_org_t) the optional members*/
/* m_access, m_uaxis_wrap and m_vaxis_wrap also have to be specified.*/
/* */
/* */
/* */
/* If the buffer is describing a framebuffer or zsa buffer (determined by it's m_format member*/
/* containing a type from dhd_pixel_org_t or dhd_depth_org_t) the function will automatically choose the*/
/* texture format that matches the data best. In this case m_access, m_uaxis_wrap and m_vaxis_wrap are*/
/* ignored and assumed to be E_DHD_ACCESS_LINEAR and E_DHD_TEX_CLAMP.*/
/* */
/* */
/* */
/* When mapping a zsa buffer the function will try to map stencil to the alpha channel, global alpha to*/
/* the red channel (when present) and depth to the remaining channels.*/
/*                                                                                                       */
/* Parameters:*/
/*  a_device :  Driver context handle (as returned by dhd_init).*/
/*  a_buffer :  Pointer to an allocated dhd_buffer_t with m_format description (see dhd_alloc_buffer)*/
/*                                                                                                       */
/* Returns:*/
/*  E_DHD_OK if successful E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/*  E_DHD_ERROR_NO_BUFFER if the buffer is invalid or has not yet been allocated*/
/*  E_DHD_ERROR_NOT_SUPPORTED if the buffers m_format member does not contain a valid format id*/
/*                                                                                                       */
/* See Also:*/
/*  dhd_set_texture_address, dhd_set_texture_format, dhd_set_texture_size, dhd_set_texture_wrap            */
dhd_enum_t dhd_set_buffer_as_texture(dhd_handle_t a_device, dhd_buffer_t *a_buffer) {  /* PRQA S 3673 *//* $Misra: #NECESSARY_FOR_API $*/
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_gpu_ptr_t base;
  dhd_uint32_t format;
  dhd_texel_org_t target_format, old_f;
  dhd_address_mode_t address_mode, old_am;
  dhd_bool_t old_da;
  dhd_uint32_t old_w, old_h, old_p;
  dhd_wrap_mode_t wrapu, wrapv, old_wu, old_wv;

  /* validate arguments*/
  if (( dhd_validate_device(device) != E_DHD_OK ) || (a_buffer == 0))  {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }
  if ((a_buffer->m_internal == 0) || (a_buffer->m_memory.m_size == 0)) {
    return E_DHD_ERROR_NO_BUFFER;
  }  

  /* get buffer parameters for use as a texture*/
  switch (a_buffer->m_format & DHD_BUFFERORG_MASK) {
    case DHD_PIXEL_ORG_FLAG: 
      /* convert framebuffer format id to texture format id*/
      format = (a_buffer->m_format & DHD_PIXEL_ORG_FORMAT_MASK) | DHD_PIXEL_ORG_FLAG;
      switch(format) {
         default:
            /* formats are identical up to AL44*/
            break;
         case E_DHD_PIXEL_ORG_A_8:
         case E_DHD_PIXEL_ORG_L_8:
            format = E_DHD_TEXEL_ORG_AL_8;    /* A8 and L8 are mapped to AL_8*/
            break;
         case E_DHD_PIXEL_ORG_AL_17:
            format = E_DHD_TEXEL_ORG_AL_17;   /* AL17 is mapped differently in pixel and texel org*/
            break;
         case E_DHD_PIXEL_ORG_BGR_888:
            format = E_DHD_TEXEL_ORG_BGR_888;
            break;
         case E_DHD_PIXEL_ORG_RGB_888:
            format = E_DHD_TEXEL_ORG_RGB_888;
            break;
//         case E_DHD_PIXEL_ORG_RGB565_A8:
//            format = E_DHD_TEXEL_ORG_RGB565_A8;
//            break;
//         case E_DHD_PIXEL_ORG_A8_RGB565:
//            format = E_DHD_TEXEL_ORG_A8_RGB565;
//            break;
      }
      /* add DHD_PREMULTIPLY_LIMIT_RGB if it was present and convert to texel org*/
      target_format = (dhd_texel_org_t)  (format | (a_buffer->m_format & DHD_PREMULTIPLY_LIMIT_RGB) | DHD_TEXEL_ORG_FLAG);
      address_mode = E_DHD_ACCESS_LINEAR;
      wrapu = E_DHD_TEX_CLAMP;
      wrapv = E_DHD_TEX_CLAMP;
      break;
    case DHD_DEPTH_ORG_FLAG: 
      /* convert depthbuffer format id to texture format id*/
      switch (a_buffer->m_format) {
        case E_DHD_DEPTH_ORG_S8A0Z24: 
        case E_DHD_DEPTH_ORG_S8A8Z16:   
          target_format = E_DHD_TEXEL_ORG_ARGB_8888; 
          break;        
        case E_DHD_DEPTH_ORG_S1A5Z10:
        case E_DHD_DEPTH_ORG_S1A0Z15: 
          target_format = E_DHD_TEXEL_ORG_ARGB_1555; 
          break;
        case E_DHD_DEPTH_ORG_S8A8Z0:  
          target_format = E_DHD_TEXEL_ORG_AL_88;
          break;        
        case E_DHD_DEPTH_ORG_S1A7Z0:  
          target_format = E_DHD_TEXEL_ORG_AL_17;
          break;        
        case E_DHD_DEPTH_ORG_S8A0Z0:  
        case E_DHD_DEPTH_ORG_S0A8Z0:  
        default:
          target_format = E_DHD_TEXEL_ORG_AL_8;
          break; 
      }
      address_mode = E_DHD_ACCESS_LINEAR;
      wrapu = E_DHD_TEX_CLAMP;
      wrapv = E_DHD_TEX_CLAMP;
      break;
    case DHD_TEXEL_ORG_FLAG:    
      /* buffer is specified as texture, can directly use the format*/
      target_format = (dhd_texel_org_t) a_buffer->m_format;
      address_mode = a_buffer->m_access;
      wrapu = a_buffer->m_uaxis_wrap;
      wrapv = a_buffer->m_vaxis_wrap;
      break;
    default:
      /* some illegal content in m_format (maybe not filled out?)*/
      return E_DHD_ERROR_NOT_SUPPORTED;
  }
  /* change states only when necessary (could be determined more efficiently on application level but since*/
  /* this is a utility, direct checking is as good as we can get).*/
  base = dhd_get_buffer_gpuptr( a_buffer );
  if (dhd_get_texture_address(a_device, 0) != base) {
    dhd_set_texture_address(a_device, base, 0);
  }
  old_f = dhd_get_texture_format(a_device, &old_am, &old_da);
  if ((old_f != target_format) || (old_am != address_mode) || (old_da != DHD_FALSE)) {    
    dhd_set_texture_format(a_device, target_format, address_mode, DHD_FALSE);
  }
  dhd_get_texture_size(a_device, &old_w, &old_h, &old_p);
  if ((old_w != a_buffer->m_width) || (old_h != a_buffer->m_height) || (old_p != a_buffer->m_pitch)) {
    dhd_set_texture_size(a_device, a_buffer->m_width, a_buffer->m_height, a_buffer->m_pitch);
  }
  dhd_get_texture_wrap(a_device, &old_wu, &old_wv);
  if ((old_wu != wrapu) || (old_wv != wrapv)) {
    dhd_set_texture_wrap(a_device, wrapu, wrapv); 
  }

  return E_DHD_OK;
}

