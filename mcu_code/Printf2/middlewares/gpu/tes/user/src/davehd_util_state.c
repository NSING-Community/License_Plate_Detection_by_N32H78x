/* Set the optimal stripe width to draw a rotated texture.*/
/* */
/* Parameters:  */
/*  a_device : Driver context handle (as returned by dhd_init).*/
/*  a_tex_bpp : Bytes per pixel of the texture to be drawn*/
/*  a_fb_bpp : Bytes per pixel of the framebuffer */
/*  a_address_mode : Address mode to be used*/
/*  a_bbox_x : Rendering bounding-box x-position*/
/*  a_tex_scale : Texture scale factor*/
/* */
/* Returns:*/
/*  E_DHD_OK if successful E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
dhd_enum_t dhd_set_psu_stripes_optimized(dhd_handle_t a_device, dhd_uint32_t a_tex_bpp, dhd_uint32_t a_fb_bpp, dhd_address_mode_t a_address_mode, dhd_uint16_t a_bbox_x, dhd_float32_t a_tex_scale) {
  dhd_device_data_t *device = dhd_get_device( a_device );
  dhd_float32_t       fstripe_width;
  dhd_uint32_t        stripe_width, stripe_offset, tile_width, tile_height, shorter_side, pixel_per_word;
  dhd_uint32_t        bus_width_in_bytes    = device->m_description.m_bus_width;                     /* Number of bytes in MBI bus word (e.g. 8)*/
  dhd_uint32_t        cacheline_length      = (dhd_uint32_t) DHD_PARAM_L1_TEXCACHE_LINE_LENGTH;     /* words per cacheline (e.g. 16)*/
  dhd_uint32_t        cacheline_size        = bus_width_in_bytes * cacheline_length; /* in bytes (e.g. 8 * 16 = 128)*/
  dhd_uint32_t        texels_per_cacheline;
  dhd_uint32_t        lines_per_set         = (dhd_uint32_t) DHD_PARAM_L1_TEXCACHE_LINES_PER_SET;   /* e.g. 4 lines*/

  /* Avoid division by zero*/
  if((a_tex_bpp == 0) || (a_fb_bpp == 0) || (bus_width_in_bytes < a_fb_bpp))
  {
      return E_DHD_ERROR_INVALID_ARGUMENT;
  }
  else
  {
      texels_per_cacheline  = cacheline_size / a_tex_bpp; /* (e.g. ARGB8888: 128 / 4 = 32)*/
  }

  /* compute width and height of the rectangular block of texels in one cache line, called 'tile' here*/
  switch (a_address_mode) {

    case E_DHD_ACCESS_SWIZZLE_4:        /* 4*4 swizzled blocks, stored linearly*/
                                        if (texels_per_cacheline < 4*4) {
                                          /* less than 1 4x4 block in the cache line -> consider swizzling only*/
                                          tile_width  = 1u << ((dhd_lg(texels_per_cacheline) + 1) / 2);
                                          /* Division by zero impossible: tile_width is at least 1*/
                                          tile_height = texels_per_cacheline / tile_width;
                                        } else {
                                          /* one or multiple blocks of 4 texels height*/
                                          tile_height = 4;
                                          tile_width  = texels_per_cacheline / tile_height;
                                        }
                                        break;
    case E_DHD_ACCESS_SWIZZLE_16:       /* 16*16 swizzled blocks, stored linearly*/
                                        if (texels_per_cacheline < 16*16) {
                                          /* less than 1 16x16 block in the cache line -> consider swizzling only*/
                                          tile_width  = 1u << ((dhd_lg(texels_per_cacheline) + 1) / 2);
                                          /* Division by zero impossible: tile_width is at least 1*/
                                          tile_height = texels_per_cacheline / tile_width;
                                        } else {
                                          /* one or multiple blocks of 16 texels height*/
                                          tile_height = 16;
                                          tile_width  = texels_per_cacheline / tile_height;
                                        }
                                        break;
    case E_DHD_ACCESS_SWIZZLE_FULL:     /* tile size is either x*x (square) or 2x*x (twice as wide as high)*/
                                        tile_width  = 1u << ((dhd_lg(texels_per_cacheline) + 1) / 2);
                                        /* Division by zero impossible: tile_width is at least 1*/
                                        tile_height = texels_per_cacheline / tile_width;
                                        break;
    case E_DHD_ACCESS_VIRTUAL_TILED_2:  /* texels_per_cacheline / 2 * 2*/
                                        tile_height = 2;
                                        tile_width  = texels_per_cacheline / tile_height;
                                        break;
    case E_DHD_ACCESS_VIRTUAL_TILED_4:  /* texels_per_cacheline / 4 * 4*/
                                        tile_height = 4;
                                        tile_width  = texels_per_cacheline / tile_height;
                                        break;
    case E_DHD_ACCESS_VIRTUAL_TILED_8:  /* texels_per_cacheline / 8 * 8*/
                                        tile_height = 8;
                                        tile_width  = texels_per_cacheline / tile_height;
                                        break;
    case E_DHD_ACCESS_VIRTUAL_TILED_16: /* texels_per_cacheline / 16 * 16*/
                                        tile_height = 16;
                                        tile_width  = texels_per_cacheline / tile_height;
                                        break;
    default: /* E_DHD_ACCESS_LINEAR:    ** no tiles -> maximum stripe length*/
                                        dhd_set_psu_stripes(a_device, 0, 0);
                                        return E_DHD_OK;
  }
  shorter_side = (tile_width < tile_height) ? tile_width : tile_height;
  /* We can only use the lines per set here, not all the lines in the cache:*/
  /* In worst case, we enumerate in the direction of the shorter side and the tiles of texels we hit in one*/
  /* enumeration line all share the same set.*/
  fstripe_width = ((dhd_float32_t)(shorter_side * (lines_per_set-1))) * a_tex_scale;

  /* The result should be a multiple of pixels-per-word*/
  /* Division by zero prohibited: see parameter check above*/
  pixel_per_word = bus_width_in_bytes / a_fb_bpp;
  /* Division by zero prohibited: see parameter check above*/
  stripe_width   = ((dhd_uint32_t) (fstripe_width / (dhd_float32_t)pixel_per_word)) * pixel_per_word; 

  /* Compute stripe offset*/
  stripe_offset = a_bbox_x & (pixel_per_word - 1);

  dhd_set_psu_stripes(a_device, stripe_offset, stripe_width);

  return E_DHD_OK;
}

