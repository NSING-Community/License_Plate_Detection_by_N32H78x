/**/
dhd_enum_t dhd_release_job_memory(const dhd_device_data_t *a_device, dhd_gpu_job_t *a_job) {
  dhd_enum_t res = E_DHD_OK;
  dhd_gpu_call_data_t gpucall;
  
  /* release mapping */
  if (a_job->m_memory.m_cpu_address != 0) {
    gpucall.m_unmap_mem.m_client = a_device->m_kernel_mode_handle;
    gpucall.m_unmap_mem.m_memory = &a_job->m_memory;
    gpucall.m_unmap_mem.m_access = E_DHD_WRITE_ACCESS;
    res = dhd_gpu_call( a_device->m_bridge, E_DHD_CALL_UNMAP_MEM, &gpucall );
  } 
  /* release memory*/
  if ((a_job->m_memory.m_gpu_address != 0) && (res == E_DHD_OK)) {
    gpucall.m_free_mem.m_client = a_device->m_kernel_mode_handle;
    gpucall.m_free_mem.m_memory = &a_job->m_memory;
    res = dhd_gpu_call( a_device->m_bridge, E_DHD_CALL_FREE_MEM, &gpucall );
  }
  return res;
}


