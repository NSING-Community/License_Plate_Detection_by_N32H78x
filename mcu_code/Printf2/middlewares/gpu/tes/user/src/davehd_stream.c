#define DHD_JOB_MEMORY_TAG    42

/*----------------------------------------------------------------------------------------------------------*/
static dhd_enum_t dhd_alloc_job_memory(dhd_device_data_t *a_device, dhd_uint32_t a_size); /* for MISRA 8.1 */
static dhd_enum_t dhd_get_free_job(dhd_device_data_t *a_device, dhd_gpu_job_t **a_freejob_out);  /* for MISRA 8.1 */

