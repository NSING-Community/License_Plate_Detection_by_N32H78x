/* Convert a texel into an ARGB32 color. When no valid format is specified, the function returns 0.*/
/**/
/* Parameters:*/
/*  a_format : source texture format (see dhd_texel_org_t).*/
/*  a_color  : texel to convert (padded with 0 bits in case of a format smaller than 32bit)*/
/**/
/* Returns:*/
/*  Color in ARGB32 format*/
/**/
/* See Also: dhd_convert_argb2pixel, dhd_convert_pixel2argb, dhd_convert_texelorpixel2argb, dhd_convert_argb2pixel, dhd_convert_argb2texel, dhd_convert_argb2texelorpixel*/
dhd_uint32_t dhd_convert_texel2argb(dhd_texel_org_t a_format, dhd_uint32_t a_color) {

   struct res_s {
      dhd_uint8_t a, r, g, b;
   } res;
   dhd_uint32_t lum;

   switch(a_format) {

      default:
         res.a = res.r = res.g = res.b = 0u;
         break;

      case E_DHD_TEXEL_ORG_ARGB_8888:
         res.a = (a_color >> 24) & 255u;
         res.r = (a_color >> 16) & 255u;
         res.g = (a_color >>  8) & 255u;
         res.b = (a_color >>  0) & 255u;
         break;

      case E_DHD_TEXEL_ORG_RGBA_8888:
         res.a =  (a_color >>  0) & 255u;
         res.r =  (a_color >> 24) & 255u;
         res.g =  (a_color >> 16) & 255u;
         res.b =  (a_color >>  8) & 255u;
         break;

      case E_DHD_TEXEL_ORG_ARGB_4444:
         res.a = loc_replicate((a_color >> 12) & 15u, 4);
         res.r = loc_replicate((a_color >>  8) & 15u, 4);
         res.g = loc_replicate((a_color >>  4) & 15u, 4);
         res.b = loc_replicate((a_color >>  0) & 15u, 4);
         break;

      case E_DHD_TEXEL_ORG_RGBA_4444:
         res.a = loc_replicate((a_color >>  0) & 15u, 4);
         res.r = loc_replicate((a_color >> 12) & 15u, 4);
         res.g = loc_replicate((a_color >>  8) & 15u, 4);
         res.b = loc_replicate((a_color >>  4) & 15u, 4);
         break;

      case E_DHD_TEXEL_ORG_ARGB_1555:
         res.a = loc_replicate((a_color >> 15) & 1u,  1);
         res.r = loc_replicate((a_color >> 10) & 31u, 5);
         res.g = loc_replicate((a_color >>  5) & 31u, 5);
         res.b = loc_replicate((a_color >>  0) & 31u, 5);
         break;

      case E_DHD_TEXEL_ORG_RGBA_5551:
         res.a = loc_replicate((a_color >>  0) & 1u, 1);
         res.r = loc_replicate((a_color >> 11) & 31u, 5);
         res.g = loc_replicate((a_color >>  6) & 31u, 5);
         res.b = loc_replicate((a_color >>  1) & 31u, 5);
         break;

      case E_DHD_TEXEL_ORG_RGB_565:
         res.a = 255u;
         res.r = loc_replicate((a_color >> 11) & 31u, 5);
         res.g = loc_replicate((a_color >>  5) & 63u, 6);
         res.b = loc_replicate((a_color >>  0) & 31u, 5);
         break;

      case E_DHD_TEXEL_ORG_AL_88:
         res.a = (a_color >>  8) & 255u;
         res.r = (a_color >>  0) & 255u;
         res.g = (a_color >>  0) & 255u;
         res.b = (a_color >>  0) & 255u;
         break;

      case E_DHD_TEXEL_ORG_AL_44:
         res.a = loc_replicate((a_color >> 4) & 15u, 4);
         {
            dhd_uint8_t lum = loc_replicate(a_color & 15u, 4);
            res.r = lum;
            res.g = lum;
            res.b = lum;
         }
         break;

      case E_DHD_TEXEL_ORG_AL_17:
         res.a = loc_replicate((a_color >> 7) & 1u, 1);
         lum = loc_replicate(a_color & 127u, 7);
         res.r = lum;
         res.g = lum;
         res.b = lum;
         break;

      case E_DHD_TEXEL_ORG_AL_8:
         res.a = (a_color) & 255u;
         res.r = (a_color) & 255u;
         res.g = (a_color) & 255u;
         res.b = (a_color) & 255u;
         break;

      case E_DHD_TEXEL_ORG_AL_4:
         res.a = loc_replicate((a_color >> 0) & 15u, 4);
         lum = loc_replicate(a_color & 15u, 4);
         res.r = lum;
         res.g = lum;
         res.b = lum;
         break;

      case E_DHD_TEXEL_ORG_AL_2:
         res.a = loc_replicate((a_color >>  0) & 3u, 2);
         lum = loc_replicate(a_color & 3u, 2);
         res.r = lum;
         res.g = lum;
         res.b = lum;
         break;

      case E_DHD_TEXEL_ORG_AL_1:
         res.a = a_color & 1 ? 255u : 0u;
         lum = loc_replicate(a_color & 1u, 1);
         res.r = lum;
         res.g = lum;
         res.b = lum;
         break;

      case E_DHD_TEXEL_ORG_ARGB_2222:
         res.a = loc_replicate((a_color >> 6) & 3u, 2);
         res.r = loc_replicate((a_color >> 4) & 3u, 2);
         res.g = loc_replicate((a_color >> 2) & 3u, 2);
         res.b = loc_replicate((a_color >> 0) & 3u, 2);
         break;

      case E_DHD_TEXEL_ORG_RGBA_2222:
         res.r = loc_replicate((a_color >> 6) & 3u, 2);
         res.g = loc_replicate((a_color >> 4) & 3u, 2);
         res.b = loc_replicate((a_color >> 2) & 3u, 2);
         res.a = loc_replicate((a_color >> 0) & 3u, 2);
         break;

      case E_DHD_TEXEL_ORG_RGB_888:
         res.a = 255u;
         res.r = (a_color & 255u);
         res.g = ((a_color >>  8) & 255u);
         res.b = ((a_color >> 16) & 255u);
         break;

      case E_DHD_TEXEL_ORG_BGR_888:
         res.a = 255u;
         res.r = ((a_color >> 16) & 255u);
         res.g = ((a_color >> 8) & 255u);
         res.b = (a_color & 255u);
         break;

//      case E_DHD_TEXEL_ORG_A8_RGB565:
//         res.a = (a_color & 255u);
//         res.r = loc_replicate((a_color >> 19) & 31u, 5);
//         res.g = loc_replicate((a_color >> 13) & 63u, 6);
//         res.b = loc_replicate((a_color >>  8) & 31u, 5);
//         break;

//      case E_DHD_TEXEL_ORG_RGB565_A8:
//         res.r = loc_replicate((a_color >> 11) & 31u, 5);
//         res.g = loc_replicate((a_color >>  5) & 63u, 6);
//         res.b = loc_replicate((a_color >>  0) & 31u, 5);
//         res.a = ((a_color >> 16) & 255u);
//         break;

   }

   dhd_uint32_t c32 = (res.a << 24) | (res.r << 16) | (res.g << 8) | (res.b << 0);
   return c32;
}

