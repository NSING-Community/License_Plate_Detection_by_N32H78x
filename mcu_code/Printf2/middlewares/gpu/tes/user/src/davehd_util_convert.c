/* Decompress a compressed texture using the hardware.*/
/* The compressed data must be accessible in CPU memory. It will be loaded to GPU memory and decompressed*/
/* into a new texture buffer. The compressed data includes a header (dhd_compressed_texture_header_t)*/
/* describing the textures' size and attributes.*/
/* The caller may set any framebuffer pixel format as the destination format.*/
/**/
/* \Note that dhd_decompress_texture will allocate the output_buffer using dhd_alloc_buffer. After it has*/
/* returned with E_DHD_OK this buffer is owned by the application and has to be released (using*/
/* dhd_free_buffer) at some point later. Furthermore the function will modify the internal driver state,*/
/* so use dhd_getstate/dhd_setstate to backup and restore the original driver state!*/
/**/
/* In case the HW is not capable of decompressing BC1 the CPU will be used instead (slower).*/
/**/
/* Parameters:*/
/*  a_device :  Driver context handle (as returned by dhd_init).*/
/*  a_input :   Pointer to compressed \input data*/
/*  a_output :  Output buffer struct (must have valid m_format/m_bpp members)*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful,*/
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter,*/
/*  E_DHD_ERROR_NO_MEMORY if there was not enough video memory,*/
/*  E_DHD_ERROR_NOT_SUPPORTED when the input format could not be read*/
