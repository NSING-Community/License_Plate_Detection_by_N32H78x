        dhd_uv_data_t uv_alpha;
        uv_alpha.m_dux = 1.0f / (dhd_float32_t)hd->m_width;
        uv_alpha.m_duy = 0;
        uv_alpha.m_dvx = 0;
        uv_alpha.m_dvy = 1.0f / (dhd_float32_t)hd->m_height;
        uv_alpha.m_u0 = uv.m_dux / 2.0f;
        uv_alpha.m_v0 = uv.m_dvy / 2.0f;
