/* Convert an ARGB color to a given pixel format. If no valid format is specified the input value is*/
/* returned unmodified.*/
/**/
/* Parameters:*/
/*  a_format : target framebuffer format (see dhd_pixel_org_t).*/
/*  a_color : 32bit ARGB color to convert.*/
/**/
/* Returns:*/
/*  Color in target format (padded with 0 bits in case of a format smaller than 32bit)*/
/**/
/* See Also: dhd_convert_argb2texelorpixel, dhd_convert_argb2texel, dhd_convert_pixel2argb, dhd_convert_texel2argb, dhd_convert_texelorpixel2argb*/
dhd_uint32_t dhd_convert_argb2pixel(dhd_pixel_org_t a_format, dhd_uint32_t a_color) {
  dhd_uint32_t  r,g,b,a;

  /* decompose color*/
  a = (a_color & 0xff000000u) >> 24;
  r = (a_color & 0x00ff0000u) >> 16;
  g = (a_color & 0x0000ff00u) >> 8;
  b = (a_color & 0x000000ffu);

  /* recombine channels for target format*/
  switch ( ((dhd_enum_t)a_format & DHD_PIXEL_ORG_FORMAT_MASK) | DHD_PIXEL_ORG_FLAG ) {
    case E_DHD_PIXEL_ORG_ARGB_8888:
      return a_color;
    case E_DHD_PIXEL_ORG_RGBA_8888:
      return (r << 24) | (g << 16) | (b << 8) | a;
    case E_DHD_PIXEL_ORG_ARGB_4444:
      return ((a & 0xf0) << 8) | ((r & 0xf0) << 4) | (g & 0xf0) | ((b & 0xf0) >> 4);
    case E_DHD_PIXEL_ORG_RGBA_4444:
      return ((r & 0xf0) << 8) | ((g & 0xf0) << 4) | (b & 0xf0) | ((a & 0xf0) >> 4);
    case E_DHD_PIXEL_ORG_ARGB_1555:
      return ((a & 0x80) << 8) | ((r & 0xf8) << 7) | ((g & 0xf8) << 2) | ((b & 0xf8) >> 3);
    case E_DHD_PIXEL_ORG_RGBA_5551:
      return ((r & 0xf8) << 8) | ((g & 0xf8) << 3) | ((b & 0xf8) >> 2) | ((a & 0x80) >> 7);
    case E_DHD_PIXEL_ORG_RGB_565:
      return ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | ((b & 0xf8) >> 3);
    case E_DHD_PIXEL_ORG_AL_88:
      return (a << 8) | b;
    case E_DHD_PIXEL_ORG_AL_44:
      return (a & 0xf0) | ((b & 0xf0) >> 4);
    case E_DHD_PIXEL_ORG_AL_17:
      return (a & 0x80) | ((b & 0xfe) >> 1);
    case E_DHD_PIXEL_ORG_A_8:
      return a;
    case E_DHD_PIXEL_ORG_L_8:
      return b;
    case E_DHD_PIXEL_ORG_ARGB_2222:
       return ( ((a & 0xC0u) ) | ((r & 0xC0u) >> 2) | ((g & 0xC0u) >> 4) | ((b & 0xC0u) >> 6) );
    case E_DHD_PIXEL_ORG_RGBA_2222:
       return ( ((r & 0xC0u) ) | ((g & 0xC0u) >> 2) | ((b & 0xC0u) >> 4) | ((a & 0xC0u) >> 6) );
    case E_DHD_PIXEL_ORG_BGR_888:
       return (b | (g << 8) | (r << 16));
    case E_DHD_PIXEL_ORG_RGB_888:
       return (r | (g << 8) | (b << 16));
//    case E_DHD_PIXEL_ORG_RGB565_A8:
//       return ((r & 0xf8u) << 8) | ((g & 0xfcu) << 3) | ((b & 0xf8u) >> 3) | (a << 16);
//    case E_DHD_PIXEL_ORG_A8_RGB565:
//       return (a | ((r & 0xf8u) << 16) | ((g & 0xfcu) << 11) | ((b & 0xf8u) << 5));
    default:
      return a_color;
  }
}

