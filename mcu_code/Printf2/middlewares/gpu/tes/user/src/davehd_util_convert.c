/* Internal function to decode the next word from an 16bit RLE stream.*/
/**/
static dhd_uint16_t getRLEword( dhd_rle_stream_t *a_stream ) {
  dhd_uint16_t data;

  if ( a_stream->m_count == 0 ) {
    /* parse a new block header*/
    dhd_uint8_t header = a_stream->m_data[ 0 ];
    a_stream->m_data += 1;
    a_stream->m_count = (header & 0x7f) + 1;
    a_stream->m_repeat = (header & 0x80);
  }
  /* return the next data word*/
  a_stream->m_count -= 1;
  data = *((dhd_uint16_t *) a_stream->m_data);
  if ( (a_stream->m_repeat == 0) || (a_stream->m_count == 0) ) {
    /* literal blocks increment the src pointer. repeated runs dont until count=0*/
    a_stream->m_data += 2;
  }
  return data;
}

/* --------------------------------------------------------------------------------------------------------*/
/* Internal function to decode the next byte from an 8bit RLE stream.*/
/**/
static dhd_uint8_t getRLEbyte( dhd_rle_stream_t *a_stream ) {
  dhd_uint8_t data;

  if ( a_stream->m_count == 0 ) {
    /* parse a new block header*/
    dhd_uint8_t header = a_stream->m_data[ 0 ];
    a_stream->m_data += 1;
    a_stream->m_count = (header & 0x7f) + 1;
    a_stream->m_repeat = (header & 0x80);
  }
  /* return the next data word*/
  a_stream->m_count -= 1;
  data = a_stream->m_data[0];
  if ( (a_stream->m_repeat == 0) || (a_stream->m_count == 0) ) {
    /* literal blocks increment the src pointer. repeated runs dont until count=0*/
    a_stream->m_data += 1;
  }
  return data;
}

/* --------------------------------------------------------------------------------------------------------*/
/* Internal function to convert an RGB565 color to xRGB8888.*/
/* This is using the exact 31/255 and 63/255 fractions instead of just bit replication.*/
/**/
static dhd_uint32_t rgb565torgb32( dhd_uint32_t a_in ) {
  dhd_uint16_t r = (a_in & 0xF800u) >> 8;
  dhd_uint16_t g = (a_in & 0x07E0u) >> 3;
  dhd_uint16_t b = (a_in & 0x001Fu) << 3;
  r = ((r << 2) + (r << 7)) >> 7;
  g = ((g << 1) + (g << 7)) >> 7;
  b = ((b << 2) + (b << 7)) >> 7;
  return ((r & 0xFFu) << 16) | ((g & 0xFFu) << 8) | ((b & 0xFFu));
}

/* --------------------------------------------------------------------------------------------------------*/
/* Internal function to interpolate between two xRGB8888 colors.*/
/* Returns a new color that is (1-w)*x + w*y at 8 bit precision. W is [0..256]. Applies rounding.*/
/**/
static dhd_uint32_t lerpColor( dhd_uint32_t a_colx, dhd_uint32_t a_coly, dhd_uint32_t a_w ) {
  dhd_uint32_t xrb = a_colx & 0xff00ffu;
  dhd_uint32_t xg  = a_colx & 0x00ff00u;
  dhd_uint32_t yrb = a_coly & 0xff00ffu;
  dhd_uint32_t yg  = a_coly & 0x00ff00u;

  dhd_uint32_t rb = ((xrb * (256 - a_w) + yrb * a_w + 0x7f007fu) >> 8u) & 0xff00ffu;
  dhd_uint32_t g  = ((xg  * (256 - a_w) + yg  * a_w + 0x007f00u) >> 8u) & 0x00ff00u;
  return rb | g;
}

