      dhd_set_texture_format(a_device, E_DHD_TEXEL_ORG_AL_2, E_DHD_ACCESS_LINEAR, DHD_FALSE);
      dhd_set_texture_size(a_device, aligned_width, aligned_height, aligned_width);
      dhd_set_texture_filter(a_device, DHD_FALSE, DHD_FALSE);
      dhd_set_texture_unit_enable(a_device, 2);
      dhd_set_uv(a_device, 1, &uv);

      /* Use COL to use TEX1 alpha and TEX0 colors */
      /* Color unit is preconfigured for replace of TEX0, so just reconfigure alpha */
      dhd_set_alpha_op1a(a_device, E_DHD_INPUT_TEXTURE_1, E_DHD_CHANNEL_A, E_DHD_INPUT_DIRECT);

      /* Setup blending so we have (1-box) * A + (box) * B and write a fully opaque alpha */
      dhd_set_alpha_blending(a_device, E_DHD_ZERO, E_DHD_ONE);
      dhd_set_blend_func(a_device, E_DHD_BLEND, E_DHD_MULTIPLY_ADD); /* 0 * src + 1 */
      dhd_set_color_blending(a_device, E_DHD_SRC_ALPHA, E_DHD_ONE_MINUS_SRC_ALPHA);
      dhd_set_read_decision(a_device, E_DHD_USING_ONE_MINUS_ALPHA, DHD_FALSE);
