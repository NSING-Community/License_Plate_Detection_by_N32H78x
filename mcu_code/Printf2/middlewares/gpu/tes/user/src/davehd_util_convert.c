/* Convert MQC compressed framebuffer to another uncompressed format via the CPU.*/
/**/
/*  (note) "dstBPP" is bytes per pixel minus 1 (=> 0..3)*/
/**/
static void loc_convert_buffer_cpu_mqc_simple(const dhd_uint8_t *s, dhd_uint8_t *d,
                                              const dhd_enum_t dstFormat,
                                              const dhd_uint32_t srcStride, const dhd_uint32_t dstStride, 
                                              const dhd_uint32_t dstBPP,
                                              const dhd_uint32_t w, const dhd_uint32_t h
                                              ) {
   dhd_uint8_t ca = 255u;
   dhd_uint8_t cr = 0u;
   dhd_uint8_t cg = 0u;
   dhd_uint8_t cb = 0u;

   for(dhd_uint32_t y = 0u; y < h; y++) {

      for(dhd_uint32_t x = 0u, k = 0u; x < w; x++) {

         dhd_uint32_t c32;
         dhd_uint8_t c8 = s[x];

         if(0u == (y & 1u)) {
            /* odd lines: G,B,G,B,..*/
            if(0u == (x & 1u)) {
               cg = c8;
               if( (y > 0u) && ( (y + 1u) < h ) ) {

                  cr = (s[x - srcStride - 2u] +
                        s[x - srcStride + 0u] ) >> 1;

                  cb = (s[x - 1u] +
                        s[x + 1u] ) >> 1;
               }
            }
            else {
               cb = c8;
               if( (y > 0u) && ( (y + 1u) < h ) ){

                  cr = (s[x - srcStride - 1u] +
                        s[x - srcStride + 1u] ) >> 1;

                  cg = (s[x - 1u] +
                        s[x + 1u] ) >> 1;
               }
            }
         }
         else {
            /* even lines: R,G,R,G,..*/
            if(0u == (x & 1u)) {
               cr = c8;

               if( (y > 0u) && ( (y + 1u) < h ) ) {

                  cg = (s[x - 1u] +
                        s[x + 1u] ) >> 1;
                  cb = (s[x - srcStride + 1u] +
                        s[x - srcStride - 1u] ) >> 1;
               }
            }
            else {
               cg = c8;
               if( (y > 0u) && ( (y + 1u) < h ) ) {

                  cr = (s[x - 1u] +
                        s[x + 1u] ) >> 1;

                  cb = (s[x - srcStride - 2u] +
                        s[x - srcStride + 0u] ) >> 1;
               }
            }
         }

         c32 = (ca << 24) | (cr << 16) | (cg << 8) | cb;

         switch(dstBPP & 3u) {
            default:
               /* not reachable*/
               break;

               /* -------- 8 bit output --------*/
            case 0u:
               {
                  d[x] = (dhd_uint8_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
               break;

            /* -------- 16 bit output --------*/
            case 1u:
               {
                  dhd_uint16_t *d16 = (dhd_uint16_t *)d;
                  d16[x] = (dhd_uint16_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
               break;
               
            /* -------- 24 bit output --------*/
            case 2u:
               {
                  d[k + 0u] = (dhd_uint8_t)(c32 & 255u);
                  d[k + 1u] = (dhd_uint8_t)((c32 >> 8) & 255u);
                  d[k + 2u] = (dhd_uint8_t)((c32 >> 16) & 255u);
                  k+= 3u;
               }
               break;
   
            /* -------- 32 bit output --------*/
            case 3u:
               {
                  dhd_uint32_t *d32 = (dhd_uint32_t *)d;
                  d32[x] = (dhd_uint32_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
               break;
         }
      }

      d += dstStride;
      s += srcStride;
   }
}

