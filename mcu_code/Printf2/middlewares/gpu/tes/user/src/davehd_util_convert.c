#error "DHD_PARAM_FBCACHE_LINE_LENGTH must be > 0!"
#endif

/*----------------------------------------------------------------------------------------------------------*/
/* Swizzle texture and store into another buffer.This is an internal function. Use dhd_convert_buffer with*/
/* a swizzled access mode to access this functionality.*/
/* It will enswizzle one buffer into another one and convert pitch and format on the fly if requested.*/
/* Destination buffer sizes must satisfy swizzle constraints (divisible by blocksize or square power of*/
/* two in case of a full swizzle).*/
/* The resulting buffer can then be used with the specified address mode (eg. E_DHD_ACCESS_SWIZZLE_16).*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init).*/
/*  a_src_address : Gpu buffer address of the source buffer (see dhd_get_buffer_gpuptr).*/
/*  a_src_width : Source width in pixels.*/
/*  a_src_height : Source height in pixels.*/
/*  a_src_pitch : Source buffer pitch.*/
/*  a_src_format : Source buffer texel format (see dhd_texel_org_t).*/
/*  a_dst_address : Gpu  buffer address of the destination buffer (see dhd_get_buffer_gpuptr).*/
/*  a_dst_width : Destination width in pixels.*/
/*  a_dst_height : Destination height in pixels.*/
/*  a_dst_pitch : Target pitch.*/
/*  a_dst_format : Target texel format (see dhd_texel_org_t).*/
/*  a_dst_address_mode : Desired swizzle (E_DHD_ACCESS_SWIZZLE_4, E_DHD_ACCESS_SWIZZLE_16 or E_DHD_ACCESS_SWIZZLE_FULL).*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful,*/
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameters or*/
/*  E_DHD_ERROR_INVALID_PTR in case of a misaligned destination pointer*/
/**/
/* Note:*/
/*  The framebuffer will be set the match the destination surface. Calling function has to store/restore it*/
/*  if required.*/
/**/
/* See Also: dhd_convert_buffer*/
dhd_enum_t dhd_swizzle_texture(dhd_handle_t a_device, dhd_gpu_ptr_t a_src_address, dhd_uint32_t a_src_width, dhd_uint32_t a_src_height, dhd_uint32_t a_src_pitch, dhd_texel_org_t a_src_format,
                               dhd_gpu_ptr_t a_dst_address, dhd_uint32_t a_dst_height, dhd_uint32_t a_dst_pitch, dhd_texel_org_t a_dst_format, dhd_address_mode_t a_dst_address_mode) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_uint32_t src_bpp, dst_bpp;
  dhd_uint32_t block_height, x, y, dst_width;
  dhd_float32_t fx, fy;
  dhd_uint32_t tex_off, fb_off;
  dhd_uv_data_t uv;
  dhd_uint32_t fbc_line_length;
  dhd_enum_t res;

  /* validate device handle*/
  if ( dhd_validate_device(device) != E_DHD_OK ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* get source and destination bpp and check for invalid texel format*/
  src_bpp = dhd_get_texel_bits_per_pixel( a_src_format );
  dst_bpp = dhd_get_texel_bytes_per_pixel( a_dst_format );
  if ((src_bpp == 0) || (dst_bpp == 0)) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* Get framebuffer cache line length to be able to check for certain pitch constraints.
   *
   * fbc_line_length > 0, since:
   *
   * device->m_description.m_bus_width is > 0 (computed by a left shift of 1, therefore at least 1).
   * DHD_CONFIG_FBCACHE_LINE_LENGTH > 0 is ensured above.
   */
  fbc_line_length = (dhd_uint32_t)(device->m_description.m_bus_width * DHD_PARAM_FBCACHE_LINE_LENGTH);

  /* validate parameters*/
  switch (a_dst_address_mode) {
    case E_DHD_ACCESS_SWIZZLE_4:
      block_height = 4;
      if (((a_dst_height % 4) != 0) || ((a_dst_pitch % 4) != 0)) {    /* requirement: divideable by 4*/
        return E_DHD_ERROR_INVALID_ARGUMENT;
      }
      /* Division uncritical, see fbc_line_length above. */
      if (((a_dst_pitch*dst_bpp*4) % fbc_line_length) != 0) {         /* requirement: FBC cacheline aligned every 4 lines*/
        return E_DHD_ERROR_INVALID_ARGUMENT;
      }
      break;
    case E_DHD_ACCESS_SWIZZLE_16:
      block_height = 16;
      if (((a_dst_height % 16) != 0) || ((a_dst_pitch % 16) != 0)) {  /* requirement: divideable by 16*/
        return E_DHD_ERROR_INVALID_ARGUMENT;
      }
      /* Division uncritical, see fbc_line_length above. */
      if (((a_dst_pitch*dst_bpp*16) % fbc_line_length) != 0) {         /* requirement: FBC cacheline aligned every 16 lines*/
        return E_DHD_ERROR_INVALID_ARGUMENT;
      }
      break;
    case E_DHD_ACCESS_SWIZZLE_FULL:
      block_height = 16;
      if (! ((a_dst_height == a_dst_pitch) &&                          /* requirements: square*/
            ((a_dst_height & (a_dst_height-1)) == 0)  &&               /*               power of two*/
             (a_dst_height >= 32))) {                                  /*               larger than 32*/
           return E_DHD_ERROR_INVALID_ARGUMENT;
      }
      break;
    default:
      return E_DHD_ERROR_INVALID_ARGUMENT;
  };

  /* If the source width is greater than the destination pitch, limit destination width to the pitch*/
  if (a_dst_pitch < a_src_width) {
    dst_width = a_dst_pitch;  /* Destination pitch is always aligned.*/
    /* If the source width is smaller than the destination pitch, limit destination*/
    /* width to the nearest next aligned block of the source. This saves some effort.*/
  } else {
    dst_width = (a_src_width + (block_height-1)) & ~(block_height-1);
  }
  /* clip dest height if it is larger than src height*/
  if (a_dst_height > a_src_height) {
    /* align the texture height to the block (only necessary if we have clipped)*/
    a_dst_height = (a_src_height + (block_height-1)) & ~(block_height-1);
  }

  /* Check parameter to avoid division by zero*/
  if(dst_width == 0)
  {
      return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* set uv mapping*/
  fx = 1.0f / (dhd_float32_t)block_height; /* Division by zero avoided: always set to 4 or 16*/
  fy = 1.0f / (dhd_float32_t)dst_width;    /* Division by zero avoided by means of parameter check*/
  uv.m_u0  = fx / 2.0f;
  uv.m_v0  = fy / 2.0f;
  uv.m_dux = fx;
  uv.m_dvx = 0.0f;
  uv.m_duy = 0.0f;
  uv.m_dvy = fy;
  dhd_set_uv(a_device, 0, &uv);

  /* programm blending for simple replace*/
  dhd_util_blend( a_device, E_DHD_UTIL_REPLACE );
  dhd_util_color_replace( a_device, E_DHD_INPUT_TEXTURE_0 );
  /* set source parameters*/
  dhd_active_texture_unit(a_device, 0);
  dhd_set_texture_size(a_device, block_height, dst_width, a_src_pitch);
  dhd_set_texture_filter(a_device, DHD_FALSE, DHD_FALSE);
  dhd_set_texture_wrap(a_device, E_DHD_TEX_CLAMP, E_DHD_TEX_CLAMP );
  if (block_height == 4) {
    dhd_set_texture_format(a_device, a_src_format, E_DHD_ACCESS_INVERSE_SWIZZLE_4, DHD_FALSE);
  } else {
    dhd_set_texture_format(a_device, a_src_format, E_DHD_ACCESS_INVERSE_SWIZZLE_16, DHD_FALSE);
  }
  dhd_set_texture_unit_enable(a_device, 1);
  /* set destination pitch (4 for swizzle_4, 16 otherwise)*/
  dhd_set_framebuffer_size(a_device, block_height, dst_width, block_height);
  dhd_set_framebuffer_format(a_device, (dhd_pixel_org_t) a_dst_format);
  dhd_set_write_mask(a_device, DHD_TRUE, DHD_TRUE, DHD_TRUE, DHD_TRUE);

  if (a_dst_address_mode == E_DHD_ACCESS_SWIZZLE_FULL) {
    /* Full swizzle - bbox is a single 16x32 block*/
    dhd_set_bbox( a_device, 0, 0, 15, 31, 0);
    /* Division by zero prohibited: block_height is set to 4 or 16 in preceding switch-case-clause.*/
    /* Loop over all 16x32-blocks*/
    for (y=0; y<(a_dst_height/block_height); y++) {
      for (x=0; x<(dst_width/32); x++) {
        tex_off = (((y*(16*a_src_pitch))+(x*32)) * src_bpp) / 8;
        fb_off =  swizzle_bits(x*32,y*16) * dst_bpp;
        /* blit box from src to dst. Even for subbyte formats, there will never be a bit offset*/
        /* because of the block width > 8 and block width % 8 == 0*/
        dhd_set_texture_address(a_device, DHD_INC_PTR(a_src_address, tex_off), 0);
        res = dhd_set_framebuffer_address(a_device, DHD_INC_PTR(a_dst_address, fb_off));
        if(res != E_DHD_OK) {
          return res;
        }
        dhd_draw(a_device, 0, 0, E_DHD_DRAW_FLAT);
      }
    }
  } else {
    /* Swizzle modes 4 and 16 - bbox is block-height and full width*/
    dhd_set_bbox( a_device, 0, 0, (block_height-1), (dst_width-1), 0);
    /* Division by zero prohibited: block_height is set to 4 or 16 in preceding switch-case-clause.*/
    /* Loop over all boxes row-wise*/
    for (y=0; y<(a_dst_height/block_height); y++) {
      tex_off = (y * a_src_pitch * block_height * src_bpp) / 8;
      fb_off =  y * a_dst_pitch * block_height * dst_bpp;
      /* blit box from src to dst. As buffer formats will never have a subbyte pitch, it is safe*/
      /* to assume a bit offset of 0.*/
      dhd_set_texture_address(a_device, DHD_INC_PTR(a_src_address, tex_off), 0);
      res = dhd_set_framebuffer_address(a_device, DHD_INC_PTR(a_dst_address, fb_off));
      if(res != E_DHD_OK) {
        return res;
      }
      dhd_draw(a_device, 0, 0, E_DHD_DRAW_FLAT);
    }
  }
  return E_DHD_OK;
}

/* --------------------------------------------------------------------------------------------------------*/
/* Convert a texture to another format or swizzle. This function will create a new texture with the same*/
/* content as the given source but a different texel format and/or swizzle mode. The desired destination*/
/* format and bpp have to be initialized in the a_output buffer struct. All other elements will be*/
/* filled out by dhd_convert_buffer. The target buffer pitch and physical size might have to be larger*/
/* than the original to enable the desired swizzle mode. dhd_convert_buffer will determine the smallest*/
/* size that fullfills all requirements and use that.*/
/**/
/**/
/**/
/* \Note that dhd_convert_buffer will allocate the output_buffer using dhd_alloc_buffer. After it has*/
/* returned with E_DHD_OK this buffer is owned by the application and has to be released (using*/
/* dhd_free_buffer) at some point later. Furthermore the function will modify the internal driver state,*/
/* so use dhd_getstate/dhd_setstate to backup and restore the original driver state!*/
/**/
/* Parameters:*/
/*  a_device :  Driver context handle (as returned by dhd_init).*/
/*  a_input :   \Input buffer struct (must have a valid m_format/m_bpp members)*/
/*  a_output :  Output buffer struct (must have valid m_format/m_bpp members)*/
/*  a_mode :    Desired memory layout for the output (E_DHD_ACCESS_LINEAR, E_DHD_ACCESS_SWIZZLE_4,*/
/*              E_DHD_ACCESS_SWIZZLE_16 or E_DHD_ACCESS_SWIZZLE_FULL)*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful,*/
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter,*/
/*  E_DHD_ERROR_NO_MEMORY if there was not enough video memory or*/
/*  E_DHD_ERROR_INTERNAL if internal structures were inconsistent*/
/**/
/* See Also: dhd_convert_buffer_cpu*/
/**/
dhd_enum_t dhd_convert_buffer(dhd_handle_t a_device, const dhd_buffer_t *a_input, dhd_buffer_t *a_output, dhd_address_mode_t a_mode) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_uint16_t w,h;
  dhd_enum_t res;
  dhd_bool_t swizzle;
  dhd_uint32_t dst_bpp;
  dhd_uint32_t align;  /* used for pitch alignment in certain cases*/

  /* validate device handle*/
  if ( dhd_validate_device(device) != E_DHD_OK ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* validate format vs. bpp of output buffer*/
  dst_bpp = dhd_get_texel_bytes_per_pixel( (dhd_texel_org_t) a_output->m_format );
  if ((dst_bpp == 0) || (dst_bpp != a_output->m_bpp)) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* input dimension*/
  w = a_input->m_width;
  h = a_input->m_height;

  /* choose target buffer dimension / pitch*/
  switch (a_mode) {
    case E_DHD_ACCESS_SWIZZLE_4:
      /* make divisible by 4*/
      a_output->m_width  = w;
      a_output->m_height = (h + 3) & ~3u;
      /* the pitch needs to be chosen such that every 4th line of the output buffer*/
      /* is aligned to the framebuffer cache line length again*/
      align = (dhd_uint32_t)(device->m_description.m_bus_width * DHD_PARAM_FBCACHE_LINE_LENGTH);  /* FBC line length*/
      /* Division by zero prohibited by preceding check.*/
      align /= dst_bpp*4;  /* consider alignment already reached by bpp and factor of 4 lines*/
      align = (align<4) ? 4 : align;  /* minimum alignment is 4 pixels*/
      align -= 1;  /* -1 for following alignment calculation*/
      a_output->m_pitch = (dhd_uint16_t)((w + align) & ~align);
      swizzle = DHD_TRUE;
      break;
    case E_DHD_ACCESS_SWIZZLE_16:
      /* make divisible by 16*/
      a_output->m_width  = w;
      a_output->m_height = (h + 15) & ~15u;
      /* the pitch needs to be chosen such that every 16th line of the output buffer*/
      /* is aligned to the framebuffer cache line length again*/
      align = (dhd_uint32_t)(device->m_description.m_bus_width * DHD_PARAM_FBCACHE_LINE_LENGTH);  /* FBC line length*/
      /* Division by zero prohibited by preceding check.*/
      align /= dst_bpp*16;  /* consider alignment already reached by bpp and factor of 16 lines*/
      align = (align<16) ? 16 : align;  /* minimum alignment is 16 pixels*/
      align -= 1;  /* -1 for following alignment calculation*/
      a_output->m_pitch = (dhd_uint16_t)((w + align) & ~align);
      swizzle = DHD_TRUE;
      break;
    case E_DHD_ACCESS_SWIZZLE_FULL:
      /* make square*/
      if (w < h) {
        w = h;
      }
      /* make power of two*/
      w -= 1;
      w |= w >> 1;
      w |= w >> 2;
      w |= w >> 4;
      w |= w >> 8;
      w += 1;
      a_output->m_width  = w;
      a_output->m_height = w;
      a_output->m_pitch  = w;
      swizzle = DHD_TRUE;
      break;
    default:  /* linear copy*/
      a_output->m_width  = w;
      a_output->m_height = h;
      a_output->m_pitch  = a_input->m_pitch;
      swizzle = DHD_FALSE;
      break;
  }

  /* create target buffer*/
  a_output->m_usage = E_DHD_MEMORY_TEXTURE;
  res = dhd_alloc_buffer( a_device, a_output, (dhd_buffer_flags_t)((dhd_uint8_t)E_DHD_BUFFER_NOLOCK | (dhd_uint8_t)E_DHD_BUFFER_STATIC) );
  if (res != E_DHD_OK) {
    return res;
  }

  /* swizzle the dizzle (or just blit)*/
  if (swizzle == DHD_TRUE) {
    res = dhd_swizzle_texture( a_device, dhd_get_buffer_gpuptr(a_input), a_input->m_width, a_input->m_height, a_input->m_pitch, (dhd_texel_org_t) a_input->m_format,
                               dhd_get_buffer_gpuptr(a_output), a_output->m_height, a_output->m_pitch, (dhd_texel_org_t) a_output->m_format, a_mode );
  } else {
    res = dhd_blit_texture( a_device, dhd_get_buffer_gpuptr(a_input), a_input->m_width, a_input->m_height, a_input->m_pitch, (dhd_texel_org_t) a_input->m_format,
                            dhd_get_buffer_gpuptr(a_output), a_output->m_pitch, (dhd_texel_org_t) a_output->m_format );
  }

  if (res != E_DHD_OK) {
    /* conversion failed. cleanup and return*/
    (void) dhd_free_buffer( a_device, a_output );
    return res;
  }

  /* Avoid new texture being used before conversion finished*/
  dhd_wait(device, E_DHD_WAIT_WRITEBACK);

  /* fix target buffers dimension (larger size is only needed in memory)*/
  a_output->m_width  = a_input->m_width;
  a_output->m_height = a_input->m_height;

  /* initialize all remaining fields in the output buffer struct*/
  a_output->m_access     = a_mode;
  a_output->m_uaxis_wrap = a_input->m_uaxis_wrap;
  a_output->m_vaxis_wrap = a_input->m_vaxis_wrap;

  return E_DHD_OK;
}

/* --------------------------------------------------------------------------------------------------------*/
/* Convert uncompressed framebuffer or texture to another uncompressed format via the CPU.*/
/**/
/*  (note) "BPP" is bytes per pixel minus 1 (=> 0..3)*/
/**/
static void loc_convert_buffer_cpu_uncompressed(const dhd_uint8_t *s, dhd_uint8_t *d,
                                                const dhd_enum_t srcFormat, const dhd_enum_t dstFormat,
                                                const dhd_uint32_t srcStride, const dhd_uint32_t dstStride, 
                                                const dhd_uint32_t srcBPP, const dhd_uint32_t dstBPP,
                                                const dhd_uint32_t w, const dhd_uint32_t h
                                                ) {

   for(dhd_uint32_t y = 0u; y < h; y++) {

      dhd_uint32_t c32;

      switch(srcBPP | (dstBPP<<2)) {
         default:
            /* not reachable*/
            break;

            /* -------- 8 bit output --------*/
         case (0u | (0u << 2)):
            /* 8bit => 8bit*/
            {
               for(dhd_uint32_t x = 0u; x < w; x++) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s[x]);
                  d[x] = (dhd_uint8_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         case (1u | (0u << 2)):
            /* 16bit => 8bit*/
            {
               const dhd_uint16_t *s16 = (const dhd_uint16_t *)s;
               for(dhd_uint32_t x = 0u; x < w; x++) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s16[x]);
                  d[x] = (dhd_uint8_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         case (2u | (0u << 2)):
            /* 24bit => 8bit*/
            {
               for(dhd_uint32_t x = 0u, k = 0u; x < w; x++, k += 3u) {
                  dhd_uint32_t c24 = s[k + 0u] | (s[k + 1u] << 8) | (s[k + 2u] << 16);
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, c24);
                  d[x] = (dhd_uint8_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         case (3u | (0u << 2)):
            /* 32bit => 8bit*/
            {
               const dhd_uint32_t *s32 = (const dhd_uint32_t *)s;
               //dhd_uint16_t *d16 = (dhd_uint16_t *)d;
               for(dhd_uint32_t x = 0u; x < w; x++) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s32[x]);
                  d[x] = (dhd_uint8_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         /* -------- 16 bit output --------*/
         case (0u | (1u << 2)):
            /* 8bit => 16bit*/
            {
               dhd_uint16_t *d16 = (dhd_uint16_t *)d;
               for(dhd_uint32_t x = 0u; x < w; x++) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s[x]);
                  d16[x] = (dhd_uint16_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         case (1u | (1u << 2)):
            /* 16bit => 16bit*/
            {
               dhd_uint16_t *d16 = (dhd_uint16_t *)d;
               const dhd_uint16_t *s16 = (const dhd_uint16_t *)s;
               for(dhd_uint32_t x = 0u; x < w; x++) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s16[x]);
                  d16[x] = (dhd_uint16_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         case (2u | (1u << 2)):
            /* 24bit => 16bit*/
            {
               dhd_uint16_t *d16 = (dhd_uint16_t *)d;
               for(dhd_uint32_t x = 0u, k = 0u; x < w; x++, k += 3u) {
                  dhd_uint32_t c24 = s[k + 0u] | (s[k + 1u] << 8) | (s[k + 2u] << 16);
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, c24);
                  d16[x] = (dhd_uint16_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         case (3u | (1u << 2)):
            /* 32bit => 16bit*/
            {
               dhd_uint16_t *d16 = (dhd_uint16_t *)d;
               const dhd_uint32_t *s32 = (const dhd_uint32_t *)s;
               for(dhd_uint32_t x = 0u; x < w; x++) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s32[x]);
                  d16[x] = (dhd_uint16_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         /* -------- 24 bit output --------*/
         case (0u | (2u << 2)):
            /* 8bit => 24bit*/
            {
               for(dhd_uint32_t x = 0u, k = 0u; x < w; x++, k += 3u) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s[x]);
                  c32 = dhd_convert_argb2texelorpixel(dstFormat, c32);
                  d[k + 0u] = (dhd_uint8_t)(c32 & 255u);
                  d[k + 1u] = (dhd_uint8_t)((c32 >> 8) & 255u);
                  d[k + 2u] = (dhd_uint8_t)((c32 >> 16) & 255u);
               }
            }
            break;

         case (1u | (2u << 2)):
            /* 16bit => 24bit*/
            {
               const dhd_uint16_t *s16 = (const dhd_uint16_t *)s;
               for(dhd_uint32_t x = 0u, k = 0u; x < w; x++, k += 3u) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s16[x]);
                  c32 = dhd_convert_argb2texelorpixel(dstFormat, c32);
                  d[k + 0u] = (dhd_uint8_t)(c32 & 255u);
                  d[k + 1u] = (dhd_uint8_t)((c32 >> 8) & 255u);
                  d[k + 2u] = (dhd_uint8_t)((c32 >> 16) & 255u);
               }
            }
            break;

         case (2u | (2u << 2)):
            /* 24bit => 24bit*/
            {
               for(dhd_uint32_t x = 0u, k = 0u; x < w; x++, k += 3u) {
                  dhd_uint32_t c24 = s[k + 0u] | (s[k + 1u] << 8) | (s[k + 2u] << 16);
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, c24);
                  c32 = dhd_convert_argb2texelorpixel(dstFormat, c32);
                  d[k + 0u] = (dhd_uint8_t)(c32 & 255u);
                  d[k + 1u] = (dhd_uint8_t)((c32 >> 8) & 255u);
                  d[k + 2u] = (dhd_uint8_t)((c32 >> 16) & 255u);
               }
            }
            break;

         case (3u | (2u << 2)):
            /* 32bit => 24bit*/
            {
               const dhd_uint32_t *s32 = (const dhd_uint32_t *)s;
               for(dhd_uint32_t x = 0u, k = 0u; x < w; x++, k += 3u) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s32[x]);
                  c32 = dhd_convert_argb2texelorpixel(dstFormat, c32);
                  d[k + 0u] = (dhd_uint8_t)(c32 & 255u);
                  d[k + 1u] = (dhd_uint8_t)((c32 >> 8) & 255u);
                  d[k + 2u] = (dhd_uint8_t)((c32 >> 16) & 255u);
               }
            }
            break;

         /* -------- 32 bit output --------*/
         case (0u | (3u << 2)):
            /* 8bit => 32bit*/
            {
               dhd_uint32_t *d32 = (dhd_uint32_t *)d;
               for(dhd_uint32_t x = 0u; x < w; x++) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s[x]);
                  d32[x] = (dhd_uint32_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         case (1u | (3u << 2)):
            /* 16bit => 32bit*/
            {
               dhd_uint32_t *d32 = (dhd_uint32_t *)d;
               const dhd_uint16_t *s16 = (const dhd_uint16_t *)s;
               for(dhd_uint32_t x = 0u; x < w; x++) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s16[x]);
                  d32[x] = (dhd_uint32_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         case (2u | (3u << 2)):
            /* 24bit => 32bit*/
            {
               dhd_uint32_t *d32 = (dhd_uint32_t *)d;
               for(dhd_uint32_t x = 0u, k = 0u; x < w; x++, k += 3u) {
                  dhd_uint32_t c24 = s[k + 0u] | (s[k + 1u] << 8) | (s[k + 2u] << 16);
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, c24);
                  d32[x] = (dhd_uint32_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;

         case (3u | (3u << 2)):
            /* 32bit => 32bit*/
            {
               dhd_uint32_t *d32 = (dhd_uint32_t *)d;
               const dhd_uint32_t *s32 = (const dhd_uint32_t *)s;
               for(dhd_uint32_t x = 0u; x < w; x++) {
                  c32 = dhd_convert_texelorpixel2argb(srcFormat, s32[x]);
                  d32[x] = (dhd_uint32_t)dhd_convert_argb2texelorpixel(dstFormat, c32);
               }
            }
            break;
      }

      d += dstStride;
      s += srcStride;
   }
}                                               

