/* Enable or disable the job checksum feature. This feature calculates a checksum of every stream command*/
/* generated using this drivers' context. The D/AVE HD core will generate an error interrupt whenever*/
/* the checksum of the stream does not match the expected value, which is checked at each register dump or*/
/* start of rendering. Errors will currently only be logged as a kernel error message and execution will*/
/* continue at the next job.*/
/* This feature will introduce a small performance impact as the checksum needs to be calculated on the CPU*/
/* and the generated stream will include two additional words per rendering and other relevant operations.*/
/* The feature will only be available when the driver is compiled with DHD_JOB_CHECKSUM_SUPPORTED which*/
/* itself leads to a small driver cpu performance hit.*/
/* */
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_enable : 1 to enable the checksum feature, 0 otherwise*/
/**/
dhd_enum_t dhd_set_job_checksum_enable(dhd_handle_t a_device, dhd_bool_t a_enable) {     /* PRQA S 3673 *//* $Misra: #NECESSARY_FOR_API $*/
#ifndef DHD_JOB_CHECKSUM_SUPPORTED
  return E_DHD_ERROR_NOT_SUPPORTED;
#else
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;  
  dhd_uint32_t *dst;
  dhd_stc_opcode_t op;
  dhd_uint32_t initial_checksum = 0;
  /* validate arguments*/
  if ( dhd_validate_device(device) != E_DHD_OK ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  if (device->m_checksum_enabled == a_enable) {
    return E_DHD_OK;
  }

  dst = dhd_stream_space(device, 2);
  op.m_fields.m_opcode = DHD_STCOP_CHECKSUM;
  op.m_fields.m_data_following = 1;
  op.m_fields.m_data_count = 1 - 1;
  op.m_fields.m_arguments = (DHD_CHECKSUM_MAGIC << 1) | (a_enable & 0x01);
  /* We never need to add checksum padding as turning checksum feature off does*/
  /* not verify it first and turning it on starts at the next word after this*/
  dst = dhd_stream_insert(device, dst, op.m_value, &initial_checksum, 1, DHD_FALSE);
  device->m_checksum_enabled = a_enable;
  device->m_checksum = initial_checksum;
  return E_DHD_OK;
  
#endif
}

/*----------------------------------------------------------------------------------------------------------*/
dhd_bool_t dhd_get_job_checksum_enable(dhd_handle_t a_device) {     /* PRQA S 3673 *//* $Misra: #NECESSARY_FOR_API $*/
#ifndef DHD_JOB_CHECKSUM_SUPPORTED
  return DHD_FALSE;
#else
  dhd_device_data_t *device = dhd_get_device( a_device );
  return (device->m_checksum_enabled) ? DHD_TRUE : DHD_FALSE;
#endif
}

