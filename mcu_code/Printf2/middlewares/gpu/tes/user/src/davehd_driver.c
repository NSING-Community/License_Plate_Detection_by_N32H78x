/* Write to clut memory. Allocated clut memory (see dhd_alloc_clut) can be written to at any time). The*/
/* writes are kept in sequence with draw commands so that every draw command will use the correct clut state.*/
/* If possible the clut should be updated in a single call to dhd_set_clut. Multiple small updates are less*/
/* efficient.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_data : Pointer to an array of 32bit ARGB colors to be uploaded into the CLUT */
/*  a_start : First clut register to write to*/
/*  a_size : Number of clut entries to write*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/**/
/* See Also:*/
/*  dhd_alloc_clut, dhd_free_clut*/
dhd_enum_t dhd_set_clut(dhd_handle_t a_device, const dhd_uint32_t *a_data, dhd_uint32_t a_start, dhd_uint32_t a_size) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_uint32_t *dst,count;
  dhd_stc_opcode_t op;

  /* validate argument*/
  if ( dhd_validate_device(device) != E_DHD_OK ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* we have to wait for all texture fetching primitives to finish before a clut change and there are no*/
  /* more clut reads from COL.*/
  dst = dhd_stream_space(device, 1);
  op.m_fields.m_opcode         = DHD_STCOP_WAIT;
  op.m_fields.m_data_following = 0;
  op.m_fields.m_data_count     = 0;
  op.m_fields.m_arguments      = E_DHD_WAIT_REG | E_DHD_WAIT_PSU | E_DHD_WAIT_TXI | E_DHD_WAIT_TEX | E_DHD_WAIT_COL;
  dst = dhd_stream_insert_word(device, dst, op.m_value);

  while (a_size > 0) {
    count = a_size;
    /* limit the amount of register writes to 64 in one call (to allow finer job granularity)*/
    if (count > 64) {
      count = 64;
    }    
    dst = dhd_stream_space(device, 1 + count);
    op.m_fields.m_opcode         = DHD_STCOP_WRITE;
    op.m_fields.m_data_following = 1;
    op.m_fields.m_data_count     = count - 1;
    op.m_fields.m_arguments      = DHD_PARAM_TEX_CLUT_REGISTER_ADDRESS + a_start;
    dst = dhd_stream_insert(device, dst, op.m_value, a_data, count, DHD_FALSE);         /*  WRITE, data*/
    /* to the next slice*/
    a_size -= count;
    a_start += count;
    a_data += count;
  }

  return E_DHD_OK;
}

