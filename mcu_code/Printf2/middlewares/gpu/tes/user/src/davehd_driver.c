/* Let the GPU write an arbitrary word to memory. In order to asynchronously query if the GPU has already*/
/* gone past a certain point in the command stream, you can use dhd_sync_signal to schedule the write of*/
/* an arbitrary 32bit data word to any GPU memory address. Note that only the write of the 32bit data word*/
/* is written to the command stream: No wait is inserted before in the stream and no flush is done afterwords.*/
/* When reading the value at a_dest after this call using the CPU you have to make sure that the CPU cache is*/
/* bypassed as it will not see the GPU write normally.*/
/**/
/* This function is a good alternative to using dhd_sync_mark as it allows querying the execution without*/
/* the need to use a driver call, e.g. from inside an ISR. If you want to wait until all processing has been*/
/* finished as dhd_sync_mark does it, you need to use the following sequence:*/
/* - dhd_wait(E_DHD_WAIT_WRITEBACK | E_DHD_WAIT_CLEAR | E_DHD_WAIT_STW);*/
/* - dhd_sync_signal();*/
/* - dhd_flush();*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_dest : GPU memory address (4 byte alignment is required)*/
/*  a_data : 32bit word to write*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/**/
/* See also:*/
/*  dhd_sync_mark*/
dhd_enum_t dhd_sync_signal(dhd_handle_t a_device, dhd_gpu_ptr_t a_dest, dhd_uint32_t a_data) {  /* PRQA S 3673 *//* $Misra: #NECESSARY_FOR_API $*/
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_uint32_t *dst;
  dhd_stc_opcode_t op;
  dhd_uint32_t buf[2];

  /* validate argument*/
  if ( dhd_validate_device(device) != E_DHD_OK ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* add commands to write a_data to a_dest when GPU reaches the current position in job*/
  dst = dhd_stream_space(device, 5 + dhd_checksum_get_padding_size(device));   /* reg write + data + dump + address + count*/
  op.m_fields.m_opcode         = DHD_STCOP_WRITE;
  op.m_fields.m_data_count     = 1-1;
  op.m_fields.m_data_following = 1;
  op.m_fields.m_arguments      = DHD_REG_STC_SYNC_ID_3;  
  dst = dhd_stream_insert(device, dst, op.m_value, &a_data, 1, DHD_FALSE);     /*  WRITE, data*/
  op.m_fields.m_opcode         = DHD_STCOP_DUMP;
  op.m_fields.m_data_following = 1;
  op.m_fields.m_data_count     = 2 - 1;
  op.m_fields.m_arguments      = DHD_REG_STC_SYNC_ID_3;
  buf[0] = (dhd_uint32_t) (dhd_size_t) a_dest;       /*  target address*/
  buf[1] = 1 - 1;                                    /*  data words*/
  dst = dhd_stream_insert(device, dst, op.m_value, buf, 2, DHD_TRUE);        /*  DUMP, params*/

  return E_DHD_OK;
}

