/* Register a callback for handling a driver panic.*/
/* */
/* The driver may get into a 'panic' situation in case an internal error occurs from which the driver can not*/
/* recover by itself. The driver will then print a message via the platform debug output function first*/
/* and pass the control on to the callback registered here afterwards.*/
/* Control must not return from the panic callback, as the driver is in a corrupt state when the panic callback*/
/* is called.*/
/* When no application side callback is registered here, the platform panic handler will handle the panic instead.*/
/*                                                                                                       */
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_callback : The panic callback function*/
/*                                                                                                       */
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input context handle*/
dhd_enum_t dhd_set_panic_callback(dhd_handle_t a_device, const dhd_panic_callback_t a_callback) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;

  /* validate argument*/
  if ( dhd_validate_device(device) != E_DHD_OK ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  device->m_panic_callback = a_callback;

  return E_DHD_OK;
}

