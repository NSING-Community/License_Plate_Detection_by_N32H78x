/* Waits for the execution of the given cmdlist.*/
/* This functions waits until all jobs of a given cmdlist have been executed by the HW and have*/
/* been reinserted into the cmdlist struct. After the function has returned successfully, the*/
/* cmdlist is ready for another execution or for deletion.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init).*/
/*  a_cmdlist : Command list whose execution should be waited for.*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful*/
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input context handle or cmdlist pointer*/
/*  E_DHD_ERROR_NO_MEMORY if there was not enough memory to process the request (should be impossible)*/
/*  E_DHD_ERROR_INTERNAL if the kernel driver rejected the job (e.g. due to an HW error)*/
/**/
static dhd_enum_t dhd_cmdlist_wait_for_exec(dhd_device_data_t *a_device, const dhd_cmdlist_t *a_cmdlist) {
  dhd_gpu_call_data_t gpucall;
  dhd_gpu_job_t *freejobs;
  dhd_enum_t res;

  /* return immediately if cmdlist to wait for has not been executed*/
  if (a_cmdlist->m_state != E_DHD_CMDLIST_EXECUTED) {
    return E_DHD_OK;
  }

  /* only call kernel for wait if the job is still of our generation*/
  if (dhd_get_job_generation(a_cmdlist->m_last_jobid) == a_cmdlist->m_last_jobgen) {
    gpucall.m_wait_for_job.m_client = a_device->m_kernel_mode_handle;
    gpucall.m_wait_for_job.m_id     = a_cmdlist->m_last_jobid;
    res = dhd_gpu_call( a_device->m_bridge, E_DHD_CALL_WAIT_FOR_JOB, &gpucall );
    DHD_ASSERT(res != E_DHD_ERROR_SCHEDULE_FOR_WAIT);  /* this would hint to an implementation error in the platform bridge*/
    if (res != E_DHD_OK) {
      return res;
    }
  } 

  /* Reclaim jobs (as the wait for cmdlists last job has finished, the full list is guaranteed to be back)  */
  gpucall.m_get_reclaimed_jobs.m_client = a_device->m_kernel_mode_handle;
  gpucall.m_get_reclaimed_jobs.m_out    = &freejobs;
  res = dhd_gpu_call( a_device->m_bridge, E_DHD_CALL_GET_RECLAIMED_JOBS, &gpucall );
  (void)dhd_reclaim_job_structs(a_device, freejobs);  /* we don't care how many job structs have been reclaimed*/

  return res;
}
