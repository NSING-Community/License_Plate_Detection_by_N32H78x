/* Internal function to put a job back into its parent cmdlist.*/
/* To be called when jobs are reclaimed.*/
/**/
/* Parameters:*/
/*  a_job : Pointer to the job structure of a cmdlist fragment*/
void dhd_cmdlist_return_job(dhd_gpu_job_t *a_job) {
  DHD_ASSERT(a_job->m_cmdlist != 0);  /* caller must never call us in this case!*/

  a_job->m_cmdlist_next = 0;

  if (a_job->m_cmdlist->m_job_end == 0) {
    a_job->m_cmdlist->m_job_start = a_job;
    a_job->m_cmdlist->m_job_end = a_job;
  } else {
    a_job->m_cmdlist->m_job_end->m_cmdlist_next = a_job;
    a_job->m_cmdlist->m_job_end = a_job;
  }
}

