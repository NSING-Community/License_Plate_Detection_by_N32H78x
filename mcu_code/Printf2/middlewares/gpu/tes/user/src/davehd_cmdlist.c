/**
 * REMARKS:
 *
 * Cmdlist are (somehow) made to be accessed by the DHD hardware in flash-rom
 * or other memories connected to the system. This brings up some require-
 * ments, like:
 *
 * - HW access to the memory
 * - UMA
 * - No MMU
 *
 * By setting the DHD_MEMORY_MMU define, cmdlists can also be used on system
 * with a MMU. Unfortunately, their implementation is currently not very
 * fast.
 * Every time a cmdlist is rendered, new jobs and video memory are allocated,
 * the data is uploaded and finally the allocated memory is freed. A final
 * implementation with an acceptable performance of this, would also contain
 * a new Kernel function, that creates new jobs with data from a given address.
 * The Kernel part has to decide if the address lies in a hardware accessible
 * range and has to take appropriate measures.
 *
 * Furthermore, the job and video memory should not be allocated for every
 * execution of a cmdlist. But this will require a final destroy for
 * flattened cmdlists, which is not the convention currently expected by the
 * API and therefore not implemented in applications.
 */

