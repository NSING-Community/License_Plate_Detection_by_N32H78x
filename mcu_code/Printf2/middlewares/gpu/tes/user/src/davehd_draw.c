/* Render a single primitive. The data for edges and attribute (e.g UV) mappings is read from the*/
/* respective buffers (see dhd_set_edge_buffer, dhd_set_uv_buffer etc.). The amount of data to be read*/
/* from attribute buffers is specified using the a_attributes flag, which is usually a combination of*/
/* bits from dhd_drawattribute_flag_t. An alternative to the enums from dhd_drawattribute_flag_t are the*/
/* DHD_DRAW_UV(n), DHD_DRAW_RHW(n) and DHD_DRAW_COL(n) macros which can be used if the number of UV*/
/* pairs per primitive is a dynamic value.*/
/* */
/* */
/* */
/* \Note that the attribute parameter specifies how much data is read from the attribute buffers per*/
/* primitive, it does not trigger usage of that attribute (e.g. texturing). Also if an attribute has*/
/* been set explicitly (by e.g. dhd_set_uv) it should <b>not</b> be listed as an attribute flag, as that*/
/* would overwrite the specified value with data from a buffer.*/
/* */
/* */
/* */
/* Also note that non antialiased edges are limited to a width/height of 2048 pixels (see <link !!Basics_Geometry, Specifying Geometry>).*/
/* */
/* * Attribute examples **/
/* <table>*/
/* Usecase                                   Draw attribute flags*/
/* ----------------------------------------  ---------------------------------------------------*/
/* Render without attributes                 E_DHD_DRAW_FLAT*/
/* Render with one texture                   E_DHD_DRAW_UV or E_DHD_DRAW_1UVS or DHD_DRAW_UV(1)*/
/* Render with two textures                  E_DHD_DRAW_2UVS or DHD_DRAW_UV(2)*/
/* Render with one texture and perspective   E_DHD_DRAW_UV | E_DHD_DRAW_RHW or DHD_DRAW_UV(1) |*/
/*                                            DHD_DRAW_RHW(1)*/
/* Render with four textures and depth       E_DHD_DRAW_UV(4) | E_DHD_DRAW_DEPTH*/
/* </table>*/
/*                                                                                                         */
/* Parameters:*/
/*  a_device :       Driver context handle (as returned by dhd_init)*/
/*  a_edgecontrol :  Bits that describe the active geometry edges. (see <link !!UMD_Section_EdgeMacros, Edge Macros>)*/
/*  a_edgecount :    Number of edges to read from edge buffer (as specified by dhd_set_edge_buffer)*/
/*  a_attributes :   Number of attributes to be read from attribute buffers (see dhd_drawattribute_flag_t)*/
/*                                                                                                         */
/* See Also:*/
/*  dhd_set_bbox, dhd_set_edge_buffer, dhd_set_uv_buffer, dhd_set_rhw_buffer, dhd_set_col_buffer,*/
/*  dhd_set_depth_buffer                                                                                                                 */
void dhd_draw(dhd_handle_t a_device, dhd_uint32_t a_edgecontrol, dhd_uint32_t a_edgecount, dhd_drawattribute_flag_t a_attributes) {
  dhd_device_data_t *device = dhd_get_device( a_device );
  dhd_uint32_t *dst;
  dhd_stc_opcode_t op;  
  dhd_uint32_t blocksize;
  dhd_uint32_t a_uvcount  = ( (dhd_uint32_t) a_attributes) & 0xf;
  dhd_uint32_t a_rhwcount = (((dhd_uint32_t) a_attributes) >> 4u) & 0xf;
  dhd_uint32_t a_colcount = (((dhd_uint32_t) a_attributes) >> 8u) & 0xf;
  dhd_uint32_t a_flags = ((dhd_uint32_t) a_attributes) & 0xf000; 

  /* validate parameter counts*/
  if ( (a_edgecount > device->m_description.m_num_edges)
       || (a_uvcount > device->m_description.m_num_tex_units)
       || (a_rhwcount > device->m_description.m_num_tex_units)
       || (a_colcount > device->m_description.m_num_col_units) )  {
    return; /* error*/
  }

  /* make sure all pending registers are written before the draw call*/
  (void)dhd_flush_state(device);

  /* get space in stream */
  blocksize = 1 + 1 + dhd_get_blocksize(a_edgecount, a_uvcount, a_rhwcount, a_colcount, a_flags) + dhd_checksum_get_padding_size(device);  /* 1 write + ctrldata + (limiterdata)*/
  dst = dhd_stream_space(device, blocksize);

  /* add limiter writes*/
  dhd_setup_limiters(device, &dst, 0, a_edgecount, a_uvcount, a_rhwcount, a_colcount, a_flags );

  /* add write to limcontrol (starts rendering)*/
  op.m_fields.m_opcode         = DHD_STCOP_WRITE;
  op.m_fields.m_data_following = 1;
  op.m_fields.m_data_count     = 1 - 1;
  op.m_fields.m_arguments      = DHD_REG_PSU_LIM_CTRL;
  (void)dhd_stream_insert(device, dst, op.m_value, &a_edgecontrol, 1, DHD_TRUE);
}

