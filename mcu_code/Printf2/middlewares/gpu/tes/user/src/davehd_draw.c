/* Render an array of primitives. As repeated calls to dhd_draw are inefficient, a batch of primitives*/
/* can be rendered in one call using this function. In this case edgecontrol, bounding box and Ystart*/
/* data is no longer specified by 'set' methods but defined in a dhd_prim_data_t structure (one element*/
/* per primitive). All primitives must have the same number of edges and the same number of attributes*/
/* uv pairs, rhws etc.*/
/* */
/* */
/* */
/* dhd_draw_array is the most efficient and thus recommended way of rendering any geometry. As in*/
/* dhd_draw the data for edges and attributes is read from the respective buffers (see*/
/* dhd_set_edge_buffer, dhd_set_uv_buffer etc.). The amount of data that is read from each buffer*/
/* depends on the attribute flags (for an explanation and examples of a_attributes see dhd_draw) or the*/
/* edgecount (in case of the edge buffer) multiplied by the primcount, as each primitive requires its*/
/* own set of edges / attributes.*/
/* */
/* */
/* */
/* See the following examples :*/
/* <table>*/
/* a_primcount   a_edgecount   a_attributes      entries read from   entries read from*/
/*                                                edge_buffer         uv_buffer*/
/* ------------  ------------  ----------------  ------------------  ------------------*/
/* 1             3             E_DHD_DRAW_UV     3                   1*/
/* 10            3             E_DHD_DRAW_UV     30                  10*/
/* 10            4             E_DHD_DRAW_2UVS   40                  20*/
/* 2             3             E_DHD_DRAW_FLAT   6                   0*/
/* </table>*/
/* */
/* There is a special attribute flag E_DHD_DRAW_STRIPE which is only valid for dhd_draw_array calls.*/
/* When set it will instruct the driver to use the psu_stripe_width and stripe_offset fields inside*/
/* dhd_prim_data_t to update the striping parameters for each primitive. Otherwise these fields are*/
/* ignored.*/
/*                                                                                                         */
/* Note:*/
/*  It is important that all buffers referenced by the a_attributes flag actually contain valid data,*/
/*  otherwise the call might lead to undefined behavior.*/
/*  */
/*  Also note that non antialiased edges are limited to a width/height of 2048 pixels (see <link !!Basics_Geometry, Specifying Geometry>).*/
/*                                                                                                         */
/* Parameters:*/
/*  a_device :      Driver context handle (as returned by dhd_init)*/
/*  a_primcount :   Number of primitives to draw*/
/*  a_prims :       Array of dhd_prim_data_t elements (at least a_primcount elements)*/
/*  a_primpitch :   Additional spacing between the dhd_prim_data_t structures (usually 0)*/
/*  a_edgecount :   Number of edges for each primitive*/
/*  a_attributes :  Number of attributes to be read from attribute buffers (see*/
/*                  dhd_drawattribute_flag_t)*/
/*                                                                                                         */
/* See Also:*/
/*  dhd_set_edge_buffer, dhd_set_uv_buffer, dhd_set_rhw_buffer, dhd_set_col_buffer, dhd_set_depth_buffer                                  */
void dhd_draw_array(dhd_handle_t a_device, dhd_uint32_t a_primcount, dhd_prim_data_t *a_prims, dhd_int32_t a_primpitch, 
                    dhd_uint32_t a_edgecount, dhd_drawattribute_flag_t a_attributes) {
  dhd_device_data_t *device = dhd_get_device( a_device );
  dhd_uint32_t *dst;
  dhd_stc_opcode_t op;
  dhd_uint32_t blocksize, i;
  dhd_uint32_t a_uvcount  = ( (dhd_uint32_t) a_attributes) & 0xf;
  dhd_uint32_t a_rhwcount = (((dhd_uint32_t) a_attributes) >> 4u) & 0xf;
  dhd_uint32_t a_colcount = (((dhd_uint32_t) a_attributes) >> 8u) & 0xf;
  dhd_uint32_t a_flags = ((dhd_uint32_t) a_attributes) & 0xf000; 

  /* validate parameter counts*/
  if ( (a_edgecount > device->m_description.m_num_edges)
       || (a_uvcount > device->m_description.m_num_tex_units)
       || (a_rhwcount > device->m_description.m_num_tex_units)
       || (a_colcount > device->m_description.m_num_col_units) )  {
    return; /* error*/
  }

  if ((a_flags & E_DHD_DRAW_COMMONBOX) == 0) {
    /* if draw_array call sets the bounding box directly, we can ignore any pending boxes*/
    device->m_pending_mask.m_named.m_psu_lim_bbox_min = 0;
    device->m_pending_mask.m_named.m_psu_lim_bbox_max = 0;
    device->m_pending_mask.m_named.m_psu_lim_start    = 0;
  }

  /* make sure all pending registers are written before the draw calls*/
  (void)dhd_flush_state(device);

  /* prepare register write opcode*/
  op.m_fields.m_opcode         = DHD_STCOP_WRITE;
  op.m_fields.m_data_following = 1;  

  blocksize = 1 + 1 + dhd_get_blocksize(a_edgecount, a_uvcount, a_rhwcount, a_colcount, a_flags) + dhd_checksum_get_padding_size(device); /* 1 write + ctrl data + (limiterdata)*/
  if ((a_flags & E_DHD_DRAW_COMMONBOX) == 0) {
    blocksize += 1 + 3;                  /* 1 write + bbox data*/
  }
  if ((a_flags & E_DHD_DRAW_STRIPE) != 0) {
    blocksize += 1 + 1;                  /* 1 write + stripedata*/
  }

  for (i=0; i<a_primcount; i++) {
    /* get space in stream */
    dst = dhd_stream_space(device, blocksize);

    /* add limiter writes*/
    dhd_setup_limiters(device, &dst, i, a_edgecount, a_uvcount, a_rhwcount, a_colcount, a_flags );

    /* output bounding information if not supressed*/
    if ((a_flags & E_DHD_DRAW_COMMONBOX) == 0) {
      op.m_fields.m_data_count     = 3 - 1;
      op.m_fields.m_arguments      = DHD_REG_PSU_LIM_BBOX_MIN;
      dst = dhd_stream_insert_word(device, dst, op.m_value);         /*  WRITE*/
      dst = dhd_stream_insert_word(device, dst, a_prims->m_xmin | ((dhd_uint32_t)(a_prims->m_ymin) << 16));      /*  LIM_BBOX_MIN*/
      dst = dhd_stream_insert_word(device, dst, a_prims->m_xmax | ((dhd_uint32_t)(a_prims->m_ymax) << 16));      /*  LIM_BBOX_MAX*/
      dst = dhd_stream_insert_word(device, dst, (dhd_uint32_t)(a_prims->m_ystart) << 16);                        /*  LIM_START*/
    }

    /* output stripe information if requested*/
    if ((a_flags & E_DHD_DRAW_STRIPE) != 0) {
      op.m_fields.m_data_count     = 1 - 1;
      op.m_fields.m_arguments      = DHD_REG_PSU_LIM_STRIPE;
      dst = dhd_stream_insert_word(device, dst, op.m_value);         /*  WRITE*/
      dst = dhd_stream_insert_word(device, dst, a_prims->m_stripe_width | ((dhd_uint32_t)(a_prims->m_stripe_offset) << 16));  /*  PSU_LIM_STRIPE*/
    }

    /* add write to limcontrol (starts rendering)*/
    op.m_fields.m_data_count = 1 - 1;
    op.m_fields.m_arguments  = DHD_REG_PSU_LIM_CTRL;
    dst = dhd_stream_insert(device, dst, op.m_value, &a_prims->m_edgecontrol, 1, DHD_TRUE);         /*  WRITE, LIM_CTRL*/

    /* next prim struct is a_primpitch + sizeof(dhd_prim_data_t) bytes further*/
    a_prims++;
    a_prims = (dhd_prim_data_t *)( &((dhd_uint8_t*)a_prims)[a_primpitch] );
  }  
}

