/* Clear a rectangular region. The hardware has a dedicated clear unit. It can be used to quickly fill*/
/* a rectangular region with any data word. Clearing will always be executed in sync with rendering*/
/* explicit barriers (dhd_wait_fill) are no longer necessary.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_address : Framebuffer start address*/
/*  a_x : Target rectangle horizontal pixel position (left)*/
/*  a_y : Target rectangle vertical pixel position (top)*/
/*  a_width : Width of the rectangle in pixels */
/*  a_height : Height of the rectangle in pixels */
/*  a_pitch : Number of pixels in one line of the target buffer */
/*  a_bpp : Bytes per pixel*/
/*  a_data : Pixel data to fill into the memory (raw bits must match the target pixel organization).*/
/*  a_mask : One bit per byte write enable. To write all bytes use 0xf.*/
/*  a_clr_org: Compressed framebuffer organization. Pass E_DHD_PIXEL_CLR_ORG_PLAIN when framebuffer is not compressed.*/
void dhd_fill(dhd_handle_t a_device, dhd_gpu_ptr_t a_address, dhd_uint32_t a_x, dhd_uint32_t a_y,
              dhd_uint32_t a_width, dhd_uint32_t a_height,  /* PRQA S 3673 *//* $Misra: #NECESSARY_FOR_API $*/
              dhd_uint32_t a_pitch, dhd_uint32_t a_bpp, dhd_uint32_t a_data, dhd_uint32_t a_mask, dhd_pixel_clr_org_t a_clr_org) {
  dhd_device_data_t *device = dhd_get_device( a_device );
  dhd_uint32_t *dst;
  dhd_stc_opcode_t op;  
  dhd_reg_clr_ctrl_t ctrl;
  dhd_uint32_t buf[4];

  /* as the clear unit is totally independent we don't have to flush the register state*/
  /* (this is also why the function is not called dhd_draw_xxx)*/

  /* setup byte based pitch and width and replicate data when necessary*/
  switch (a_bpp) {
    case 1:
       if(E_DHD_PIXEL_CLR_ORG_PLAIN == a_clr_org) {
          a_data = (a_data & 0xff) | ((a_data & 0xff) << 8) | ((a_data & 0xff) << 16) | ((a_data & 0xff) << 24);      
          if(0u != (a_mask & 1u)) {
             a_mask = 15u;
          } else {
             a_mask = 0u;
          }
       }
       a_address = (dhd_gpu_ptr_t)(((dhd_uint8_t*)a_address) + (a_x * 1u) + (a_y * a_pitch));
       break;

    case 2:
       if(E_DHD_PIXEL_CLR_ORG_PLAIN == a_clr_org) {
          a_data = (a_data & 0xffffu) | ((a_data & 0xffffu) << 16);
          a_mask = (a_mask & 3u) | ((a_mask & 3u) << 2);
       }
       a_width *= 2u;
       a_pitch *= 2u;
       a_address = (dhd_gpu_ptr_t) (((dhd_uint8_t*)a_address) + (a_x * 2u) + (a_y * a_pitch));
       break;

    case 3:
      /* (note) 'a_data' bits 24..31 are unused, bits 0..23 are repeated*/
       if(E_DHD_PIXEL_CLR_ORG_PLAIN == a_clr_org) {
          a_mask &= 7u;
       }
       a_width *= 3u;
       a_pitch *= 3u;
       a_address = (dhd_gpu_ptr_t) (((dhd_uint8_t*)a_address) + (a_x * 3u) + (a_y * a_pitch));
       break;

    case 4:
      a_width *= 4u;
      a_pitch *= 4u;
      a_address = (dhd_gpu_ptr_t) (((dhd_uint8_t*)a_address) + (a_x * 4u) + (a_y * a_pitch));
      break;

    default:
      /* deprecated special case (a_bpp == 0): treat a_pitch as byte pitch instead of pixel pitch*/
      a_bpp = 4u;
      break;
  }

  /* get space in stream for 2 WAITS + 1 WRITEs + 4 data words*/
  dst = dhd_stream_space(device, 2 + 1 + 4 + dhd_checksum_get_padding_size(device) );

  /* need to ensure rendering pipeline is empty when clearing starts (see issue 456)*/
  op.m_fields.m_opcode = DHD_STCOP_WAIT;
  op.m_fields.m_data_count = 0;
  op.m_fields.m_data_following = 0;
  op.m_fields.m_arguments = E_DHD_WAIT_WRITEBACK; 
  dst = dhd_stream_insert_word(device, dst, op.m_value);

  /* build a write command to trigger clear unit*/
  op.m_fields.m_opcode         = DHD_STCOP_WRITE;
  op.m_fields.m_data_following = 1;
  op.m_fields.m_data_count     = 4 - 1;
  op.m_fields.m_arguments      = DHD_REG_CLR_VALUE;  

  buf[0] = a_data;
  buf[1] = (a_width - 1) | (a_pitch << 16);       /* CLR_LINE_CONFIG*/
  ctrl.m_value = 0;
  ctrl.m_fields.m_clr_num_lines = (a_height-1);
  ctrl.m_fields.m_clr_mask = a_mask;
  ctrl.m_fields.m_clr_bpp  = (a_bpp - 1u) & 3u;
  buf[2] = ctrl.m_value;                          /* CLR_CTRL*/
  buf[3] = (dhd_uint32_t) (dhd_size_t) a_address; /* CLR_START_ADDRESS*/
  dst = dhd_stream_insert(device, dst, op.m_value, buf, 4, DHD_TRUE);         /*  WRITE + data*/

  /* immediately wait for clear (as the clearunit will fully saturate the bus running it in*/
  /* parallel does not make much sense. This also avoids issue 456)*/
  op.m_fields.m_opcode = DHD_STCOP_WAIT;
  op.m_fields.m_data_count = 0;
  op.m_fields.m_data_following = 0;
  op.m_fields.m_arguments = E_DHD_WAIT_REG | E_DHD_WAIT_CLEAR; /* clear unit or registerfile busy */
  dst = dhd_stream_insert_word(device, dst, op.m_value);
}

