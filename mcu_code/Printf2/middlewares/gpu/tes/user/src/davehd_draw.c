/* Wait for a specific HW pipeline stage. Any combination of pipeline wait conditions can be specified. */
/* The following commands will be processed only when all specified stages are ready. */
/* Note that the GPU wait is only scheduled, it does not block the CPU. */
/**/
/* When waiting for the clear unit dhd_wait_fill should be used instead.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_wait : Combination of flags from (dhd_wait_flags_t)*/
/**/
/* See Also:*/
/*  dhd_fill*/
void dhd_wait(dhd_handle_t a_device, dhd_wait_flags_t a_wait) {
  dhd_device_data_t *device = dhd_get_device( a_device );
  dhd_stc_opcode_t op;
  dhd_uint32_t *dst;

  /* add a wait command for exactly the user specified mask*/
  op.m_fields.m_opcode = DHD_STCOP_WAIT;
  op.m_fields.m_data_count = 0;
  op.m_fields.m_data_following = 0;
  op.m_fields.m_arguments = a_wait;           

  dst = dhd_stream_space(device, 1);
  dst = dhd_stream_insert_word(device, dst, op.m_value);
}
