/* Specify a fixed edge function. Usually edges are passed in buffers or as parameters to dhd_draw. But special*/
/* edges that are not to be changed frequently (e.g. a constant clipping plane) should be set up using this */
/* function rather specified again for each primitive.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_edgeid : Index of the hardware edge to update (0..6)*/
/*  a_edge : Pointer to edge data (see dhd_edge_data_t)*/
void dhd_set_edge(dhd_handle_t a_device, dhd_uint32_t a_edgeid, const dhd_edge_data_t *a_edge) {
  dhd_device_data_t *device = dhd_get_device( a_device );
  dhd_uint32_t regindex;

  /* validate edge index*/
  if (a_edgeid >= device->m_description.m_num_edges) {
    return; /* error*/
  }

  /* get register index of DHD_REG_PSU_LIM_VSTART_n relative to group2 start*/
  regindex = (DHD_REG_PSU_LIM_VSTART_0 + (a_edgeid * 3)) - (2 * 64);

  device->m_shadow_state.m_groups.m_group2[ regindex + 0 ] = (dhd_uint32_t)(a_edge->m_start);
  device->m_shadow_state.m_groups.m_group2[ regindex + 1 ] = (dhd_uint32_t)(a_edge->m_dx);
  device->m_shadow_state.m_groups.m_group2[ regindex + 2 ] = (dhd_uint32_t)(a_edge->m_dy);

  /* set relevant pending bits (3 consecutive bits)*/
  device->m_pending_mask.m_groups.m_group2[ 0 ] |= 0x7u << regindex; 
}

/*----------------------------------------------------------------------------------------------------------*/
/* Specify a fixed uv mapping. Similar to dhd_set_edge when an uv mapping does not change frequently it can*/
/* be set up using this function rather than beeing repeated for each primitive.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_unitid : Index of the texture unit to update (0..7)*/
/*  a_uv : Pointer to uv data (see dhd_uv_data_t)*/
void dhd_set_uv(dhd_handle_t a_device, dhd_uint32_t a_unitid, const dhd_uv_data_t *a_uv) {
  dhd_device_data_t *device = dhd_get_device( a_device );  
  dhd_uint32_t regindex, lowmask;
#if  DHD_REGFILE_GROUP_SIZE(3) > 32
  dhd_uint32_t highmask;
#endif
  dhd_uint32_t *uvlim;
  const dhd_internal_uv_data_t *uv_i = (dhd_internal_uv_data_t *) a_uv;

  /* validate uv unit index*/
  if (a_unitid >= device->m_description.m_num_tex_units) {
    return; /* error*/
  }

  /* get register index of DHD_REG_TXA_U_OFFSET_n relative to group3 start*/
  regindex = (DHD_REG_TXA_U_OFFSET_0 + (a_unitid * 6)) - (3 * 64);
  uvlim = & device->m_shadow_state.m_groups.m_group3[ regindex ];
  uvlim[ 0 ] = uv_i->m_uint32.m_u0_i;
  uvlim[ 1 ] = uv_i->m_uint32.m_v0_i;
  uvlim[ 2 ] = uv_i->m_uint32.m_dux_i;
  uvlim[ 3 ] = uv_i->m_uint32.m_duy_i;
  uvlim[ 4 ] = uv_i->m_uint32.m_dvx_i;
  uvlim[ 5 ] = uv_i->m_uint32.m_dvy_i;

  /* set relevant pending bits (6 consecutive bits, may cross 32bit boundary)*/
  if (regindex < 32) {
    lowmask = 0x3fu << regindex;           /* using a left shift to cut off high bits if req.*/
  } else {
    lowmask = 0;
  }  
  device->m_pending_mask.m_groups.m_group3[ 0 ] |= lowmask;

#if  DHD_REGFILE_GROUP_SIZE(3) > 32
  if (regindex > (32-6)) {
    regindex = (32 + (32-6)) - regindex;    
    highmask = 0xfc000000u >> regindex;    /* using a right shift to cut off low bits if req.*/
  } else {
    highmask = 0;
  }
  if(highmask > 0) {
    device->m_pending_mask.m_groups.m_group3[ 1 ] |= highmask;
  }
#endif
}

