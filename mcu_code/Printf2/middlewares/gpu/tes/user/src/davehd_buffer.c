/* Lock the entire buffer for CPU access. After a lock has been aquired the CPU side address can be received*/
/* using a call to dhd_get_lockedbuffer_ptr.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_buffer : Pointer to an allocated dhd_buffer_t (see dhd_alloc_buffer)*/
/*  a_access : The required access level (either E_DHD_READ_ACCESS or E_DHD_WRITE_ACCESS or both)*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/*  E_DHD_ERROR_NO_BUFFER the buffer is invalid or has not yet been allocated*/
/*  E_DHD_ERROR_ALREADY_LOCKED when the buffer was already locked*/
/**/
dhd_enum_t dhd_lock_buffer(dhd_handle_t a_device, dhd_buffer_t *a_buffer, dhd_enum_t a_access) {
  /* pass call to dhd_lock_buffer_region*/
  if (a_buffer != 0) {
    return dhd_lock_buffer_region(a_device, a_buffer, a_access, 0, 0, a_buffer->m_width, a_buffer->m_height);
  } else {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }
}

/*----------------------------------------------------------------------------------------------------------*/
/* Lock a part of the buffer for CPU access. After a lock has been aquired the CPU side address of the region */
/* can be received using a call to dhd_get_lockedbuffer_ptr.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_buffer : Pointer to an allocated dhd_buffer_t (see dhd_alloc_buffer)*/
/*  a_access : The required access level (either E_DHD_READ_ACCESS or E_DHD_WRITE_ACCESS or both)*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/*  E_DHD_ERROR_NO_BUFFER the buffer is invalid or has not yet been allocated*/
/*  E_DHD_ERROR_ALREADY_LOCKED when the buffer was already locked*/
/**/
dhd_enum_t dhd_lock_buffer_region(dhd_handle_t a_device, dhd_buffer_t *a_buffer, dhd_enum_t a_access, dhd_uint16_t a_x, dhd_uint16_t a_y, dhd_uint16_t a_w, dhd_uint16_t a_h) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_buffer_internal_t *bufint;
  dhd_gpu_call_data_t gpucall;

  /* validate arguments*/
  if (( dhd_validate_device(device) != E_DHD_OK ) || (a_buffer == 0) || ((a_x+a_w) > a_buffer->m_width) || ((a_y+a_h) > a_buffer->m_height) || (a_access == 0))  {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }
  if ((a_buffer->m_internal == 0) || (a_buffer->m_memory.m_size == 0)) {
    return E_DHD_ERROR_NO_BUFFER;
  }  
  bufint = a_buffer->m_internal;

  /* validate access request*/
  if (bufint->m_locked != 0) {
    return E_DHD_ERROR_ALREADY_LOCKED;
  }
  if ((bufint->m_flags == E_DHD_BUFFER_NOLOCK) || 
     ((bufint->m_flags & E_DHD_BUFFER_CPUREAD_ONLY) && (a_access & E_DHD_WRITE_ACCESS)) ||  /* PRQA S 4106 *//* $Misra: #MISRA_LOGICAL_AND_IS_INTENDED_NOT_BITWISE_AND $*/
     ((bufint->m_flags & E_DHD_BUFFER_CPUWRITE_ONLY) && (a_access & E_DHD_READ_ACCESS))) {  /* PRQA S 4106 *//* $Misra: #MISRA_LOGICAL_AND_IS_INTENDED_NOT_BITWISE_AND $*/
    return E_DHD_ERROR_ACCESS_DENIED;
  }

  /* store new lock details  */
  bufint->m_locked = a_access;
  bufint->m_lock_x = a_x;
  bufint->m_lock_y = a_y;
  bufint->m_lock_w = a_w;
  bufint->m_lock_h = a_h;

  /* create a memory mapping*/
  gpucall.m_map_mem.m_client = device->m_kernel_mode_handle;
  gpucall.m_map_mem.m_memory = &a_buffer->m_memory;
  gpucall.m_map_mem.m_access = a_access;
  if ( dhd_gpu_call( device->m_bridge, E_DHD_CALL_MAP_MEM, &gpucall ) == E_DHD_OK ) {
    /* mapping possible. the easy case (no shadow required)*/
    bufint->m_shadow_address = 0;
    return E_DHD_OK;
  }

  /* mapping failed, have to create a shadow memory*/
  if (bufint->m_shadow_address == 0) {
    bufint->m_shadow_address = (dhd_uint8_t*) dhd_alloc( E_DHD_ALLOC_CLINE, DHD_CSIZE( a_buffer->m_memory.m_size ), DHD_CACHELINE_SIZE );
  } else {
    /* we already have a shadow. if this buffer is gpu readonly than the old shadow must still be accurate and we can skip the download*/
    if ((((dhd_uint32_t)(bufint->m_flags)) & E_DHD_BUFFER_GPUREAD_ONLY) != 0) {
      return E_DHD_OK;
    }
  }

  /* if read access is requested we have to populate the shadow*/
  gpucall.m_download.m_client = device->m_kernel_mode_handle;
  gpucall.m_download.m_src    = a_buffer->m_memory.m_gpu_address;
  gpucall.m_download.m_dest   = bufint->m_shadow_address;
  gpucall.m_download.m_size   = a_buffer->m_memory.m_size;
  return dhd_gpu_call( device->m_bridge, E_DHD_CALL_DOWNLOAD, &gpucall );
}

/*----------------------------------------------------------------------------------------------------------*/
/* Release an existing lock. Changes made by the CPU (if the lock had write access) will only be visible to*/
/* the GPU after the lock has been released. If the buffer is already unlocked the function is a no op and */
/* will return E_DHD_OK.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_buffer : Pointer to an allocated dhd_buffer_t (see dhd_alloc_buffer)*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/*  E_DHD_ERROR_NO_BUFFER the buffer is invalid or has not yet been allocated*/
/*  E_DHD_ERROR_INTERNAL if internal structures were inconsistent*/
/**/
dhd_enum_t dhd_unlock_buffer(dhd_handle_t a_device, dhd_buffer_t *a_buffer) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_buffer_internal_t *bufint;
  dhd_enum_t res;
  dhd_gpu_call_data_t gpucall;

  /* validate arguments*/
  if (( dhd_validate_device(device) != E_DHD_OK ) || (a_buffer == 0))  {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }
  if ((a_buffer->m_internal == 0) || (a_buffer->m_memory.m_size == 0)) {
    return E_DHD_ERROR_NO_BUFFER;
  }  
  bufint = a_buffer->m_internal;

  /* nothing to do if not locked*/
  if (bufint->m_locked == 0) {
    return E_DHD_OK;
  }

  /* check if we have a memory mapping to release*/
  if (a_buffer->m_memory.m_cpu_address != 0) {    
    /* add a TLIST only upload command to ensure the transfer is correctly stored*/
    if ((device->m_flag_tlist_enabled) && ((bufint->m_locked & E_DHD_WRITE_ACCESS) != 0)) {
      gpucall.m_upload.m_client    = device->m_kernel_mode_handle;
      gpucall.m_upload.m_src       = a_buffer->m_memory.m_cpu_address;
      gpucall.m_upload.m_dest      = a_buffer->m_memory.m_gpu_address;
      gpucall.m_upload.m_size      = a_buffer->m_memory.m_size;
      gpucall.m_upload.m_tlistonly = DHD_TRUE;
      res = dhd_gpu_call( device->m_bridge, E_DHD_CALL_UPLOAD, &gpucall );
    } else {
      res = E_DHD_OK;
    }
    gpucall.m_unmap_mem.m_client = device->m_kernel_mode_handle;
    gpucall.m_unmap_mem.m_memory = &a_buffer->m_memory;
    gpucall.m_unmap_mem.m_access = bufint->m_locked;
    if (res == E_DHD_OK) {
      res = dhd_gpu_call( device->m_bridge, E_DHD_CALL_UNMAP_MEM, &gpucall );
    } else {  /* first error has precedence*/
      (void)dhd_gpu_call( device->m_bridge, E_DHD_CALL_UNMAP_MEM, &gpucall );
    }
    bufint->m_locked = 0;
    return res;
  }

  if (bufint->m_shadow_address == 0) {
    return E_DHD_ERROR_INTERNAL; /* can never be 0 on a locked buffer that has no mapping*/
  }
  /* using shadow memory, if locked for write access we need an upload*/
  if ((bufint->m_locked & E_DHD_WRITE_ACCESS) != 0) {
    gpucall.m_upload.m_client    = device->m_kernel_mode_handle;
    gpucall.m_upload.m_src       = bufint->m_shadow_address;
    gpucall.m_upload.m_dest      = a_buffer->m_memory.m_gpu_address;
    gpucall.m_upload.m_size      = a_buffer->m_memory.m_size;
    gpucall.m_upload.m_tlistonly = DHD_FALSE;
    res = dhd_gpu_call( device->m_bridge, E_DHD_CALL_UPLOAD, &gpucall );
  } else {
    res = E_DHD_OK;
  }

  /* if this is a static buffer we will now free the shadow memory (will be recreated on next lock if required again)*/
  /* for dynamic buffers we keep it for performance reasons.*/
  if ((((dhd_uint32_t)(bufint->m_flags)) & E_DHD_BUFFER_STATIC) != 0) {
    dhd_free(a_buffer->m_internal->m_shadow_address);
    a_buffer->m_internal->m_shadow_address = 0;
  }
  bufint->m_locked = 0;

  return res;
}

/*----------------------------------------------------------------------------------------------------------*/
/* Return CPU pointer to locked buffer region. If the buffer is not locked or an error occurrs 0 is */
/* returned. */
/**/
/* Parameters:*/
/*  a_buffer : Pointer to an allocated and locked dhd_buffer_t (see dhd_alloc_buffer)*/
/**/
/* Returns:*/
/*  A pointer to the first byte of the locked region. */
/**/
dhd_uint8_t *dhd_get_lockedbuffer_ptr(const dhd_buffer_t *a_buffer) {
  dhd_uint8_t *base;
  dhd_buffer_internal_t *bufint;
  dhd_uint32_t x,y;

  /* validate parameters*/
  if ((a_buffer == 0) || (a_buffer->m_internal == 0) || (a_buffer->m_internal->m_locked == 0)) {
    return 0;
  }
  bufint = a_buffer->m_internal;

  /* get cpu side base address*/
  base = a_buffer->m_memory.m_cpu_address;
  if (base == 0) {
    base = bufint->m_shadow_address;   
  }

  /* find locked region base address*/
  x = bufint->m_lock_x;
  y = bufint->m_lock_y;
  return &base[ (x + (y * a_buffer->m_pitch)) * a_buffer->m_bpp ];
}

/*----------------------------------------------------------------------------------------------------------*/
/* Fill an entire buffer with arbitrary data. The function is equivalent to a dhd_fill operation on the full buffer surface and*/
/* a subsequent dhd_wait_fill. Therefore other draw operations can be issued directly after a fill_buffer*/
/* call, without the need for additional synchronization.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_buffer : Pointer to an allocated dhd_buffer_t (see dhd_alloc_buffer)*/
/*  a_data : Pixel data to fill into the memory (raw bits must match the target pixel organization).*/
/*  a_mask : One bit per byte write enable. To write all bytes use 0xf.*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/*  E_DHD_ERROR_NO_BUFFER the buffer is invalid or has not yet been allocated*/
/**/
/* See Also: */
/*  dhd_fill_buffer_color*/
dhd_enum_t dhd_fill_buffer(dhd_handle_t a_device, const dhd_buffer_t *a_buffer, dhd_uint32_t a_data, dhd_uint32_t a_mask) {  
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_pixel_clr_org_t clrOrg;

  /* validate arguments*/
  if (( dhd_validate_device(device) != E_DHD_OK ) || (a_buffer == 0))  {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }
  if ((a_buffer->m_internal == 0) || (a_buffer->m_memory.m_size == 0)) {
    return E_DHD_ERROR_NO_BUFFER;
  }  

  /* issue fill and wait*/
  clrOrg = dhd_get_pixel_clr_org((dhd_pixel_org_t)a_buffer->m_format);
  dhd_fill(a_device, a_buffer->m_memory.m_gpu_address, 0u, 0u, a_buffer->m_width, a_buffer->m_height, a_buffer->m_pitch, a_buffer->m_bpp, a_data, a_mask, clrOrg);
  dhd_wait_fill(a_device);

  return E_DHD_OK;
}

/*----------------------------------------------------------------------------------------------------------*/
/* Fill an entire buffer with a color. This function works like dhd_fill_buffer but it will use the optional*/
/* m_format field inside the given buffer to convert the ARGB input color into pixel data. */
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_buffer : Pointer to an allocated dhd_buffer_t (see dhd_alloc_buffer)*/
/*  a_color : ARGB 32bit color data.*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/*  E_DHD_ERROR_NO_BUFFER the buffer is invalid or has not yet been allocated*/
/**/
