#define DHD_MAX_BUFFER_WIDTH    32768       /* Maximum accepted buffer width (used for buffer sanity checks)*/
#define DHD_MAX_BUFFER_HEIGHT   32768       /* Maximum accepted buffer height (used for buffer sanity checks)*/

/*----------------------------------------------------------------------------------------------------------*/
/* Allocate video memory for a buffer. The a_buffer struct must be initialized prior to calling this */
/* function. If successful the buffer can be used for other operations (e.g. data uploads / downloads).*/
/**/
/* The following fields of dhd_buffer_t have to be initialized prior to calling alloc_buffer:*/
/*  - m_width, m_height*/
/*  - m_pitch*/
/*  - m_bpp*/
/*  - m_usage*/
/**/
/* For subbyte formats, m_format has also to be initialized.*/
/**/
/* For the most common cases of a simple rectangular buffer that is to be used as texture, framebuffer or*/
/* zsabuffer the function dhd_alloc_buffer_simple can be used instead, which does not need an initialzed*/
/* buffer description struct.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_buffer : Pointer to an initialized dhd_buffer_t struct*/
/*  a_flags : A combination of dhd_buffer_flags_t indicating how the buffer is going to be accessed*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/*  E_DHD_ERROR_NO_MEMORY if there was no large enough continuous piece of video memory */
/*  E_DHD_ERROR_INTERNAL if internal structures were inconsistent*/
/**/
/* See Also:*/
/*  dhd_alloc_buffer_simple*/
dhd_enum_t dhd_alloc_buffer(dhd_handle_t a_device, dhd_buffer_t *a_buffer, dhd_buffer_flags_t a_flags) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_uint32_t linear_size;
  dhd_enum_t res;
  dhd_uint32_t bpp;
  
  /* validate arguments*/
  if (( dhd_validate_device(device) != E_DHD_OK ) || (a_buffer == 0))  {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* sanity check parameters*/
  if ((a_buffer->m_width == 0) || (a_buffer->m_height == 0) ||
      (a_buffer->m_width > DHD_MAX_BUFFER_WIDTH) ||
      (a_buffer->m_height > DHD_MAX_BUFFER_HEIGHT) ||
      (a_buffer->m_width > a_buffer->m_pitch)) {
    return E_DHD_ERROR_INVALID_ARGUMENT; 
  }

  bpp = a_buffer->m_bpp * 8;
  if(bpp == 0) {
    bpp = dhd_get_bits_per_pixel(a_buffer->m_format);
    if(bpp >= 8) {
      /* No bpp set but format indicates a format where bpp is > 0*/
      return E_DHD_ERROR_INVALID_ARGUMENT;
    }
  }
  
  /* create internal data*/
  a_buffer->m_internal = (dhd_buffer_internal_t *) dhd_alloc( E_DHD_ALLOC_BUFFER, 1, 0 );
  if (a_buffer->m_internal == 0) {
    return E_DHD_ERROR_NO_MEMORY;
  }
  a_buffer->m_internal->m_locked = 0;
  a_buffer->m_internal->m_shadow_address = 0;
  a_buffer->m_internal->m_flags = a_flags;

  /* allocate memory*/
  linear_size = ((a_buffer->m_pitch * a_buffer->m_height * bpp) + 7) / 8;
  res = dhd_alloc_vidmem(a_device, linear_size, DHD_CACHELINE_SIZE, a_buffer->m_usage, &a_buffer->m_memory);
  if (res != E_DHD_OK) {
    dhd_free(a_buffer->m_internal);
    a_buffer->m_internal = 0;
  }
  return res;
}

/*----------------------------------------------------------------------------------------------------------*/
/* Allocate video memory buffer based on only format and size. Specifying a dhd_buffer_t struct and creating*/
/* a buffer for it using dhd_alloc_buffer enables the maximum flexibility - but for the most common cases*/
/* dhd_alloc_buffer_simple can be used instead which will need only the size and format as input parameters.*/
/**/
/* The dhd_buffer_t struct will be automatically fully populated (also optional fields) based on the format*/
/* and size data. Buffer type is determined by a_format containing a type from dhd_pixel_org_t, dhd_texel_org_t  */
/* or dhd_depth_org_t). This means that if you pass a dhd_pixel_org_t the buffer is assumed to be used*/
/* as a framebuffer.*/
/**/
/* Optional parameters for wrapping and access modes are initialized to default values (linear memory storage*/
/* and clamped access) but can be changed after allocation at any time.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_buffer : Pointer to a dhd_buffer_t struct that will receive the buffer data (can be uninitialized)*/
/*  a_format : Target buffer pixel organisation (from dhd_pixel_org_t, dhd_texel_org_t or dhd_depth_org_t)*/
/*  a_width : Width in pixels*/
/*  a_height : Height in pixels*/
/*  a_flags : A combination of dhd_buffer_flags_t indicating how the buffer is going to be accessed*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter (e.g. invalid format)*/
/*  E_DHD_ERROR_NO_MEMORY if there was no large enough continuous piece of video memory */
/*  E_DHD_ERROR_INTERNAL if internal structures were inconsistent*/
/**/
/* See Also:*/
/*  dhd_alloc_buffer*/
dhd_enum_t dhd_alloc_buffer_simple(dhd_handle_t a_device, dhd_buffer_t *a_buffer, dhd_enum_t a_format, dhd_uint16_t a_width, dhd_uint16_t a_height, dhd_buffer_flags_t a_flags) {

  /* validate arguments*/
  if (a_buffer == 0)  {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* setup buffer information required for alloc_buffer*/
  a_buffer->m_format = a_format;
  a_buffer->m_width = a_width;
  a_buffer->m_height = a_height;
  a_buffer->m_pitch = ((dhd_uint16_t) (a_width + 3)) & ~3u;     /* we will slightly pitch each line up to multiples of 4 to minimally align scanline starts */
  a_buffer->m_bpp = (dhd_uint16_t) dhd_get_bytes_per_pixel( a_format );
  a_buffer->m_access = E_DHD_ACCESS_LINEAR;   /* defaults. caller can change this later*/
  a_buffer->m_uaxis_wrap = E_DHD_TEX_CLAMP;   
  a_buffer->m_vaxis_wrap = E_DHD_TEX_CLAMP;   

  /* determine usage*/
  switch (a_format & DHD_BUFFERORG_MASK) {
    case DHD_PIXEL_ORG_FLAG:
    case DHD_DEPTH_ORG_FLAG:
      a_buffer->m_usage = E_DHD_MEMORY_TARGET;
      break;
    case DHD_TEXEL_ORG_FLAG:
      a_buffer->m_usage = E_DHD_MEMORY_TEXTURE;
      break;    
    default:
      /* incorrect a_format specifier*/
      return E_DHD_ERROR_INVALID_ARGUMENT;
  }  

  /* pass call to real alloc_buffer*/
  return dhd_alloc_buffer(a_device, a_buffer, a_flags);
}

/*----------------------------------------------------------------------------------------------------------*/
/* Release memory of a buffer. When a buffer has been successfully allocated by dhd_alloc_buffer it has to*/
/* be released using this function. Note that the buffer struct can be reused e.g. in another call to */
/* dhd_alloc_buffer after it has been released.*/
/**/
/* Note: The underlaying memory may be reused directly after this call. Ensure that no references to*/
/*  this buffers' content are in use during this call or will be used afterwards.*/
/*  If unsure about ongoing gpu operations and in an timing uncritical path, call dhd_finish to wait for*/
/*  gpu to complete.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_buffer : Pointer to an allocated dhd_buffer_t (see dhd_alloc_buffer)*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/*  E_DHD_ERROR_INTERNAL if internal structures were inconsistent*/
/**/
dhd_enum_t dhd_free_buffer(dhd_handle_t a_device, dhd_buffer_t *a_buffer) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;

  /* validate arguments*/
  if (( dhd_validate_device(device) != E_DHD_OK ) || (a_buffer == 0))  {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* release internal data*/
  if (a_buffer->m_internal != 0) {
    /* release shadow buffer if one exists*/
    if (a_buffer->m_internal->m_shadow_address != 0) {
      dhd_free(a_buffer->m_internal->m_shadow_address);
    }
    dhd_free(a_buffer->m_internal);
    a_buffer->m_internal = 0;
  }

  /* release associated buffer*/
  return dhd_free_vidmem(a_device, &a_buffer->m_memory); 
}

/*----------------------------------------------------------------------------------------------------------*/
/* Change the buffer flags. Buffer flags describe how the buffer is going to be accessed by both the CPU*/
/* and GPU. They are used to steer internal optimizations. E.g. changing a buffer that had frequent updates*/
/* (E_DHD_BUFFER_DYNAMIC) to E_DHD_BUFFER_STATIC can lead to memory beeing released that was kept to speed*/
/* up the updating.*/
/* The flagscan only be changed if there is not currently a lock on the buffer.*/
/**/
/* Parameters:*/
/*  a_device : Driver context handle (as returned by dhd_init)*/
/*  a_buffer : Pointer to an allocated dhd_buffer_t (see dhd_alloc_buffer)*/
/*  a_flags : A combination of dhd_buffer_flags_t indicating how the buffer is going to be accessed*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful */
/*  E_DHD_ERROR_INVALID_ARGUMENT in case of an invalid input parameter*/
/*  E_DHD_ERROR_NO_BUFFER the buffer is invalid or has not yet been allocated*/
/*  E_DHD_ERROR_ALREADY_LOCKED when an attempt was made to modify the flags of a locked buffer*/
/**/
dhd_enum_t dhd_change_buffer_flags(dhd_handle_t a_device, dhd_buffer_t *a_buffer, dhd_buffer_flags_t a_flags) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;

  /* validate arguments*/
  if (( dhd_validate_device(device) != E_DHD_OK ) || (a_buffer == 0))  {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }
  if ((a_buffer->m_internal == 0) || (a_buffer->m_memory.m_size == 0)) {
    return E_DHD_ERROR_NO_BUFFER;
  } 
  if (a_buffer->m_internal->m_locked != 0) {
    return E_DHD_ERROR_ALREADY_LOCKED; /* may not be locked when change occurs*/
  }

  /* simply update the flag field*/
  /* could also drop shadow / close mapping when changing to a lower frequency access)*/
  a_buffer->m_internal->m_flags = a_flags;
  return E_DHD_OK;
}

