/*  dhd_fill_buffer*/
dhd_enum_t dhd_fill_buffer_color(dhd_handle_t a_device, const dhd_buffer_t *a_buffer, dhd_uint32_t a_color) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_uint32_t newcol;
  dhd_enum_t format;

  if (( dhd_validate_device(device) != E_DHD_OK ) || (a_buffer == 0))  {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }
  if ((a_buffer->m_internal == 0) || (a_buffer->m_memory.m_size == 0)) {
    return E_DHD_ERROR_NO_BUFFER;
  }  

  format = a_buffer->m_format;

  /* Color conversion*/
  switch (format & DHD_BUFFERORG_MASK) {
    case DHD_PIXEL_ORG_FLAG:   /* Convert color format for dhd_pixel_org_t*/
      newcol = dhd_convert_argb2pixel( (dhd_pixel_org_t) format, a_color);
      break;
    case DHD_TEXEL_ORG_FLAG:   /* Convert color format for dhd_texel_org_t*/
      newcol = dhd_convert_argb2texel( (dhd_texel_org_t) format, a_color);
      break;
    default:
      return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* Call fill buffer function*/
  return dhd_fill_buffer(device, a_buffer, newcol, 0xf);
}

