/* Debug code for heap memory profiling when DHD_PROFILE_MEM_USAGE is defined*/
/**/
typedef struct {
  dhd_uint32_t    m_allocatedBytes;
  dhd_uint32_t    m_allocatedObjects;
  dhd_uint32_t    m_maxAllocatedBytes;
  dhd_uint32_t    m_maxAllocatedObjects;
  dhd_uint32_t    m_totalAllocatedBytes;
  dhd_uint32_t    m_totalAllocatedObjects;

  dhd_uint32_t    m_mallocCalls;
  dhd_uint32_t    m_freeCalls;

  dhd_uint32_t    m_mallocFails;

} dhd_mem_info_t;

static dhd_mem_info_t  s_memInfo = {0};

/* Local debug declarations*/
static void dhd_update_peaks(void);


/*----------------------------------------------------------------------------------------------------------*/
/* Check if a new maximum is reached, if so save the peak value*/
static void dhd_update_peaks(void) {
  if (s_memInfo.m_allocatedBytes > s_memInfo.m_maxAllocatedBytes) {
    s_memInfo.m_maxAllocatedBytes   = s_memInfo.m_allocatedBytes;
  }
  if (s_memInfo.m_allocatedObjects > s_memInfo.m_maxAllocatedObjects) {
    s_memInfo.m_maxAllocatedObjects = s_memInfo.m_allocatedObjects;
  }
}
#endif /* DHD_PROFILE_MEM_USAGE*/

/*----------------------------------------------------------------------------------------------------------*/
/**/
void *dhd_alloc(dhd_alloc_element_t a_element, dhd_uint32_t a_count, dhd_uint32_t a_alignment) {
#ifdef DHD_PROFILE_MEM_USAGE
  void *p;
  dhd_uint32_t size = dhd_get_alloc_size(a_element, a_count);

  (void) a_alignment;  

  s_memInfo.m_mallocCalls++;
  p = malloc(size + sizeof(dhd_uint32_t));
  if (0 == p) {
    s_memInfo.m_mallocFails++;
  }
  else {
    s_memInfo.m_allocatedBytes += size;
    s_memInfo.m_allocatedObjects++;
    s_memInfo.m_totalAllocatedBytes += size;
    s_memInfo.m_totalAllocatedObjects++;
    dhd_update_peaks();
    /* store size of allocated memory block in first word*/
    *((dhd_uint32_t*)p) = size; 
    p = (void*) ((dhd_uint32_t*)p + 1);
  }

  return p;
#else
  (void) a_alignment;

  //return malloc( dhd_get_alloc_size(a_element, a_count) );
	//return pvPortMalloc(dhd_get_kalloc_size(a_element));
	return pvPortMalloc( dhd_get_alloc_size(a_element, a_count) );
#endif /* DHD_PROFILE_MEM_USAGE  */
}

/*----------------------------------------------------------------------------------------------------------*/
/**/
void dhd_free(void *a_memory) {
#ifdef DHD_PROFILE_MEM_USAGE
  if (a_memory != 0) {
    s_memInfo.m_freeCalls++;
    s_memInfo.m_allocatedBytes -= *((dhd_uint32_t*)a_memory-1);
    s_memInfo.m_allocatedObjects--;
    free((dhd_uint32_t*)a_memory - 1);
  }
#else
  //free(a_memory);
  vPortFree(a_memory);

#endif /* DHD_PROFILE_MEM_USAGE*/
}

