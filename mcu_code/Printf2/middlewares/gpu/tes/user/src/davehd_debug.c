/* Activate tlist dumping for this client.*/
/* A tlist contains the stream content that is executed by the GPU and register writes executed by the driver.*/
/* The dumps are written to a platform*/
/* specific memory or file.*/
/* passing tlist requests to kernel is always possible, but noop if kernel is not compiled with*/
/* DHD_KERNEL_TLIST_SUPPORT*/
/**/
dhd_enum_t dhd_tlist_enable(dhd_handle_t a_device, const dhd_char_t *a_file) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;
  dhd_enum_t result;
  dhd_gpu_call_data_t gpucall;

  /* validate argument*/
  if ( dhd_validate_device(device) != E_DHD_OK ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* check if this is a request to turn tlist dumping on or off*/
  if (a_file == 0) {
    if (device->m_flag_tlist_enabled == 0) {
      /* turn off an already disabled flag is a noop*/
      return E_DHD_OK;
    }
    device->m_flag_tlist_enabled = 0;
  } else {
    if (device->m_flag_tlist_enabled == 1) {
      /* turn on again while running is an error*/
      return E_DHD_ERROR_ALREADY_RUNNING;
    }
    device->m_flag_tlist_enabled = 1;
  }

  /* let kernel handle the real work*/
  gpucall.m_tlist_enable.m_client = device->m_kernel_mode_handle;
  gpucall.m_tlist_enable.m_file   = a_file;
  result = dhd_gpu_call( device->m_bridge, E_DHD_CALL_TLIST_ENABLE, &gpucall );
  if (result != E_DHD_OK) {
    /* failed requests can never result in enabled logging*/
    device->m_flag_tlist_enabled = 0;
  }

  return result;
}

