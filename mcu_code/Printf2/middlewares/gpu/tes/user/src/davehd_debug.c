dhd_enum_t dhd_debug_switch_memorymodel(dhd_handle_t a_device) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;  
  dhd_gpu_call_data_t gpucall;
  dhd_vidmem_t dummy;

  /* validate argument*/
  if ( dhd_validate_device(device) != E_DHD_OK ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }
 
  dummy.m_block = 0;
  dummy.m_cpu_address = 0;
  dummy.m_gpu_address = (dhd_gpu_ptr_t) 0x44415645;
  dummy.m_size = 1024;
  gpucall.m_map_mem.m_client = device->m_kernel_mode_handle;
  gpucall.m_map_mem.m_memory = &dummy;
  gpucall.m_map_mem.m_access = E_DHD_READ_ACCESS;
  return dhd_gpu_call( device->m_bridge, E_DHD_CALL_MAP_MEM, &gpucall );
}

