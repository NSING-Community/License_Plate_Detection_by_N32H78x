/* Write a custom string to the current clients' tlist.*/
/**/
/* Parameters:*/
/*   a_string: The string to append to the tlist.*/
dhd_enum_t dhd_tlist_write(dhd_handle_t a_device, const dhd_char_t *a_string) {
  return dhd_tlist_write_kernel(a_device, a_string, DHD_FALSE);
}

/*----------------------------------------------------------------------------------------------------------*/
/* Write a custom string to the current clients' tlist or to the global kernel mode tlist.*/
/* In addition to client tlists, the driver also supports dumping a merged tlist that also includes*/
/* synchronisation and context switches to replay complete GPU activity.*/
/* Kernel level tlists have to be enabled via a compile time switch.*/
/* */
/* Parameters:*/
/*   a_string: The string to append to the tlist*/
/*   to_kernel: When DHD_TRUE, the string will be appended to the global tlist*/
/**/
/* See Also: dhd_tlist_write*/
dhd_enum_t dhd_tlist_write_kernel(dhd_handle_t a_device, const dhd_char_t *a_string, dhd_bool_t to_kernel) {
  dhd_device_data_t *device = (dhd_device_data_t *) a_device;  
  dhd_gpu_call_data_t gpucall;

  /* validate argument*/
  if ( dhd_validate_device(device) != E_DHD_OK ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* do nothing if tlist writing is not enabled*/
  if ((!to_kernel) && (device->m_flag_tlist_enabled == 0)) {
    return E_DHD_OK;
  }

  /* let kernel handle the real work*/
  gpucall.m_tlist_write.m_client = device->m_kernel_mode_handle;
  gpucall.m_tlist_write.m_string = a_string;
  gpucall.m_tlist_write.m_to_kernel_tlist = to_kernel;
  return dhd_gpu_call( device->m_bridge, E_DHD_CALL_TLIST_WRITE, &gpucall );
}

