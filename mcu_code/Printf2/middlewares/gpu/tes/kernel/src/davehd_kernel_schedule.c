/* Read the current HW sync ID. Depending on the a_direct parameter the HW is queried or the latest cached*/
/* value (updated by the IRQ) is used. Usually direct reads are not necessary.*/
/**/
dhd_uint32_t dhd_gpu_query_jobsync(const dhd_gpu_device_data_t *a_device, dhd_bool_t a_direct) {
  if (a_direct != 0) {
    void *registerbase = a_device->m_gpu_config.m_register_base_address;
    /* query the HW*/
    return dhd_gpu_read_reg(registerbase, DHD_REG_STC_SYNC_ID_1);
  } else {
    /* return the latest value that has actually been processed by the IRQ*/
    return a_device->m_last_sync_code;
  }
}

