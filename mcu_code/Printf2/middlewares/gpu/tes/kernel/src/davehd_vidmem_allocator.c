/* a_client can be 0 if the allocation is directly from kernel driver.*/
/* note: not thread safe, locking has to be done on higher level*/
/**/
dhd_enum_t dhd_internal_free_vidmem(dhd_gpu_vidmem_heap_t *a_heap, dhd_gpu_connection_t *a_client, dhd_vidmem_t *a_memory) {
  dhd_gpu_vidmem_block_t *block = a_memory->m_block;
  dhd_gpu_vidmem_block_t *previous, *following;
  #ifndef DHD_KERNEL_DUMB_ALLOCATOR
  dhd_uint32_t fl, sl;
  #endif

  /* validate that a_memory is a heap managed chunk*/
  if (block == 0) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* validate that the memory is indeed allocated from our heap*/
  if (! dhd_internal_is_on_heap( a_heap, a_memory->m_gpu_address )) {    
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* update client memory usage counter*/
  if (a_client != 0) {
    a_client->m_used_memory -= a_memory->m_size;
  }
  
  #ifdef DHD_KERNEL_MEMORY_PATTERN
  dhd_internal_fill_block(block, DHD_VIDMEM_FREEPATTERN);
  #endif

  /* check if the adjacent blocks are free, so we can coalesce them*/
  previous = block->m_prevadr;
  if (previous->m_free == DHD_TRUE) {    /* PRQA S 3760 *//* $Misra: MISRA-Checker bug: Both sides of the comparison here are of the same unsigned type 'dhd_bool_t'. $*/
    /* grow previous block and drop ours*/
    #ifndef DHD_KERNEL_DUMB_ALLOCATOR
    /* drop previous block from it's free list (as its size will change)*/
    dhd_find_indices_insert(previous->m_size, &fl, &sl);
    dhd_remove_block_from_freelist(a_heap, previous, fl, sl);
    #endif
    previous->m_size += block->m_size;
    dhd_remove_vidmem_block(block);
    dhd_free_blocknode(a_heap, block);
    block = previous;
  }
  following = block->m_nextadr;
  if (following->m_free == DHD_TRUE) {    /* PRQA S 3760 *//* $Misra: MISRA-Checker bug: Both sides of the comparison here are of the same unsigned type 'dhd_bool_t'. $*/
    /* grow our block and drop following*/
    #ifndef DHD_KERNEL_DUMB_ALLOCATOR
    /* drop following block from it's free list (as its size will change)*/
    dhd_find_indices_insert(following->m_size, &fl, &sl);
    dhd_remove_block_from_freelist(a_heap, following, fl, sl);
    #endif
    block->m_size += following->m_size;
    dhd_remove_vidmem_block(following);
    dhd_free_blocknode(a_heap, following);    
  }

  /* mark as free*/
  block->m_free = DHD_TRUE;
  #ifndef DHD_KERNEL_DUMB_ALLOCATOR
  /* put (merged) block into freelist*/
  dhd_find_indices_insert(block->m_size, &fl, &sl);
  dhd_add_block_to_freelist(a_heap, block, fl, sl);
  #endif

  /* null original memory reference to avoid double free*/
  a_memory->m_block = 0;
  a_memory->m_cpu_address = 0;
  a_memory->m_gpu_address = 0;
  a_memory->m_size = 0;
  
  return E_DHD_OK;
}

