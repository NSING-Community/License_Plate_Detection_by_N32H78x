/* allocate a chunk 'count' of block structures. */
/**/
static dhd_gpu_vidmem_block_t *dhd_get_block_chunk(void) {
  dhd_gpu_vidmem_block_t *chunk;
   dhd_uint32_t count = DHD_VIDMEM_CHUNKSIZE;

  chunk = (dhd_gpu_vidmem_block_t *) dhd_kalloc( E_DHD_KALLOC_VMEMBLOCK, 0 );
  if (chunk != 0) {
    /* initialize chunk by chaining all blocks */
    dhd_uint32_t i;

    for (i=0; i<(count-1); i++) {
      chunk[i].m_nextfree = &chunk[i+1];
      chunk[i].m_head = DHD_FALSE;
    }
    chunk[i].m_nextfree = 0;
    chunk[i].m_head = DHD_FALSE;
    /* first chunk is the only one that gets a 'head' tag*/
    chunk[0].m_head = DHD_TRUE;    
  }

  return chunk;
}

