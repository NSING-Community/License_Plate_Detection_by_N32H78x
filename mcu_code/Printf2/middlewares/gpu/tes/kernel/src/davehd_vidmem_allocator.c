/**/
void dhd_internal_debug_heap(dhd_gpu_device_data_t *a_device, dhd_gpu_vidmem_heap_t *a_heap) {
#ifdef DHD_KERNEL_DEBUG_MEMORY
  dhd_gpu_vidmem_block_t *block;
  dhd_gpu_vidmem_block_t *end = &a_heap->m_memory_list;  
  dhd_uint32_t fbcount, bcount;
  dhd_uint32_t fsize, usize;
  dhd_gpu_ptr_t cont;

  if ((a_heap->m_sizeof != sizeof(dhd_gpu_vidmem_heap_t)) || (a_heap->m_size == 0)) {
    dhd_gpu_debug_note(a_device, "ERROR: heap %p is corrupted", a_heap);
    dhd_gpu_debug_flush(a_device, DHD_TRUE);
    return;
  }

  /* count free blocks */
  block = a_heap->m_free_block;
  fbcount = 0;
  while (block) {
    fbcount++;   
    block = block->m_nextfree;
  }
  dhd_gpu_debug_note(a_device, "Heap %p (base: 0x%08x / size: 0x%08x) has %d unused headers", 
                     a_heap, a_heap->m_base_address, a_heap->m_size, fbcount);

  /* walk heap blocks and dump content*/
  block = a_heap->m_memory_list.m_nextadr;
  bcount = 0;
  fsize = 0;
  usize = 0;
  cont = a_heap->m_base_address;
  while (block != end) {
    /* mark entry with a '*' if it is not continous or out of order in the address list*/
    dhd_gpu_debug_note(a_device, "  Block %p is %s (base: 0x%08x / size: 0x%08x) %c", block, (block->m_free)?"FREE":"USED", block->m_address, block->m_size, (block->m_address == cont)?' ':'*');
    cont = DHD_INC_PTR(cont, block->m_size);
    bcount++;
    if (block->m_free) {
      fsize += block->m_size;
    } else { 
      usize += block->m_size;
    }
    block = block->m_nextadr;
  }
  dhd_gpu_debug_note(a_device, "  total block count: %d / free bytes: 0x%08x / used bytes: 0x%08x\n", bcount, fsize, usize);

  /* flush the debug output*/
  dhd_gpu_debug_flush(a_device, DHD_TRUE);
#endif
}
