/*----------------------------------------------------------------------------------------------------------*/
/* Fill videomemory with a specific debug pattern. Used only in DHD_KERNEL_MEMORY_PATTERN mode.*/
/* Does not work if GPU memory is not directly accessible by CPU.*/
/**/
static void dhd_internal_fill_block( dhd_gpu_vidmem_block_t *a_block, dhd_uint32_t a_value ) {
  dhd_uint32_t *dst = a_block->m_address;
  dhd_uint32_t i;

  for (i=0; i<a_block->m_size / sizeof(dhd_uint32_t); i++) {
    *dst = a_value;
    dst++;
  }
}
#endif

