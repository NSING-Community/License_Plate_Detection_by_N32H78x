/* a_client can be 0 if the allocation is directly from kernel driver.*/
/* note: not thread safe, locking has to be done on higher level.*/
/**/
dhd_enum_t dhd_internal_alloc_vidmem(dhd_gpu_vidmem_heap_t *a_heap, dhd_gpu_connection_t *a_client, dhd_uint32_t a_size, 
                                     dhd_size_t a_alignment, dhd_uint32_t a_tag, dhd_uint32_t a_usage, dhd_vidmem_t *a_result) {
  dhd_gpu_ptr_t found = 0;      
  dhd_gpu_vidmem_block_t *minblock = 0;
  dhd_int32_t minspace = (dhd_int32_t)(a_heap->m_size);
  #ifdef DHD_KERNEL_DUMB_ALLOCATOR
  dhd_gpu_vidmem_block_t *end   = &a_heap->m_memory_list;    
  dhd_gpu_vidmem_block_t *block = a_heap->m_memory_list.m_nextadr;  
  #else
  dhd_uint32_t fl, sl;
  #endif
  dhd_uint32_t aligned_size;

  /* validate parameters*/
  if (a_result == 0) {
    return E_DHD_ERROR_INVALID_PTR;
  }
  if (a_alignment > 256) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* turn alignment into next higher power of 2 (1 in case of an input alignment of 0, 255 at most)  */
  if (a_alignment > 0) {
    a_alignment -= 1;  
    a_alignment |= a_alignment >> 1;
    a_alignment |= a_alignment >> 2;
    a_alignment |= a_alignment >> 4;    
  }
  a_alignment += 1;  
  #ifdef DHD_KERNEL_TLIST_SUPPORT
  if (a_alignment < 16) {   /* temporary: force 128 bit alignment for tlist dumps*/
    a_alignment = 16;
  }
  #endif

  /* consider additional alignment for size to be allocated only when it is larger than minimal alignment*/
  if (a_alignment > DHD_VIDMEM_MINALIGN) {
    aligned_size = a_size+(a_alignment-DHD_VIDMEM_MINALIGN);
  } else {
    aligned_size = a_size;
  }
  
  /* make final aligned size a multiple of DHD_VIDMEM_MINALIGN*/
  aligned_size = (aligned_size + DHD_VIDMEM_MINALIGN_MASK) & ~DHD_VIDMEM_MINALIGN_MASK;  

  if (aligned_size >= (1u << DHD_VIDMEM_FLINDEX_MAX)) {
    /* rejected due to too large request*/
    a_result->m_gpu_address = 0;
    a_result->m_cpu_address = 0;
    a_result->m_block = 0;
    a_result->m_size = 0;
    return E_DHD_ERROR_NO_MEMORY;
  }

  #ifndef DHD_KERNEL_DUMB_ALLOCATOR
  /* find free block that fits good (optimized algorithm)*/
  dhd_find_indices_search(aligned_size, &fl, &sl);
  minblock = dhd_find_suitable_block(a_heap, &fl, &sl);
  if (minblock != 0) {
    minspace = (dhd_int32_t)(minblock->m_size - aligned_size);
    dhd_remove_block_from_freelist(a_heap, minblock, fl, sl);
  }
  #else
  /* find free block that fits best (dumb algorithm)  */
  while (block != end) {
    dhd_int32_t space = block->m_size - aligned_size;
    if (( block->m_free ) && ( space >= 0 ) && ( space < minspace)) {
      /* new size minimum*/
      minspace = space;
      minblock = block;
      if (space == 0) {
        break;
      }      
    }
    block = block->m_nextadr;
  }
  #endif

  /* proceed if we found any block that fits the request*/
  if ( minblock != 0 ) {
    found = minblock->m_address;
    if ( minspace > 8 ) {
      /* create a new block for the 'still free' part*/
      dhd_gpu_vidmem_block_t *remaining = dhd_alloc_blocknode(a_heap);
      remaining->m_address = DHD_INC_PTR( minblock->m_address, aligned_size );
      remaining->m_size    = (dhd_uint32_t)minspace;
      remaining->m_free    = DHD_TRUE;
      /* add it into memory list (sorted by address)*/
      dhd_insert_vidmem_block(remaining, minblock);
      /* add it to correct freelist*/
      #ifndef DHD_KERNEL_DUMB_ALLOCATOR
      dhd_find_indices_insert((dhd_uint32_t)minspace, &fl, &sl);
      dhd_add_block_to_freelist(a_heap, remaining, fl, sl);
      #endif
      /* shrink found block to just the size we need      */
      minblock->m_size = aligned_size;
    }
    /* mark block as not free*/
    minblock->m_free = DHD_FALSE;
  }
  
  if (found != 0) {
    /* success*/
    found = (dhd_gpu_ptr_t) (((dhd_size_t) DHD_INC_PTR(found, a_alignment-1)) & ~(a_alignment-1)); /* apply alignment*/
    
    a_result->m_gpu_address = found;
    a_result->m_cpu_address = 0;
    a_result->m_block = minblock;
    a_result->m_size = a_size;  /* requested size*/

    #ifdef DHD_KERNEL_MEMORY_PATTERN
    dhd_internal_fill_block(minblock, DHD_VIDMEM_ALLOCPATTERN);
    #endif

    if (a_client != 0) {
      /* increment used memory if allocation was successful*/
      a_client->m_used_memory += a_size;

#ifdef DHD_VIDMEM_PROFILE
      if(a_client->m_used_memory > loc_max_used_memory)
      {
         loc_max_used_memory = a_client->m_used_memory;
         printf("[dbg] davehd_vidmem_allocator(malloc): max_used_memory=%u\n", loc_max_used_memory);
         fflush(stdout);
      }
#endif /* DHD_VIDMEM_PROFILE*/
    }
    return E_DHD_OK;
  } else {
    /* failed*/
    a_result->m_gpu_address = 0;
    a_result->m_cpu_address = 0;
    a_result->m_block = 0;
    a_result->m_size = 0;

    return E_DHD_ERROR_NO_MEMORY;
  }
}

/*----------------------------------------------------------------------------------------------------------*/
/* returns true if the address is inside heap region (does not care if it is currently allocated)*/
/**/
dhd_bool_t dhd_internal_is_on_heap(const dhd_gpu_vidmem_heap_t *a_heap, dhd_gpu_ptr_t a_address) {  /* PRQA S 3673 *//* $Misra: #NECESSARY_FOR_API $*/

  /* check if address is outside heap range*/
  if ((a_address < a_heap->m_base_address) || 
      (a_address >= (dhd_gpu_ptr_t)DHD_INC_PTR(a_heap->m_base_address, a_heap->m_size))) {
    return DHD_FALSE;
  }

  return DHD_TRUE;
}

