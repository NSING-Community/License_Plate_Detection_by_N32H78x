/* Prevent IRQ execution. After this call returned all IRQ processing is postponed until dhd_gpu_enable_irq*/
/* is called. Note that only the specified device is affected. IRQ execution should be suspended only for*/
/* very brief periods of time in order to minimise the effect on performance.*/
/**/
/* Parameters:*/
/*  a_device - Kernel device pointer */
void dhd_gpu_disable_irq(dhd_gpu_device_data_t *a_device) {
  void *base_address = a_device->m_gpu_config.m_register_base_address;
  dhd_reg_stc_control_t ctrl;

  /* disable IRQ's*/
  ctrl.m_value = a_device->m_stc_control; 
  ctrl.m_fields.m_stop_irq_enable = 0;    
  ctrl.m_fields.m_sync_irq_enable = 0;
  ctrl.m_fields.m_pause_irq_enable = 0;  
  a_device->m_stc_control = ctrl.m_value;
  /* dhd_gpu_write_reg_blocking should be implemented to assure that the interrupt line is masked*/
  /* befor the function returns*/
  dhd_gpu_write_reg_blocking(base_address, DHD_REG_STC_CONTROL, ctrl.m_value);

}

/* ----------------------------------------------------------------------------------------------------*/
/* Resume IRQ execution. Suspended IRQs (using dhd_gpu_disable_irq) are resumed. All interrupt requests*/
/* that occurred in the meantime are processed immediately.        */
/* Note that Pause irq is currently unused and intentionally left disabled.*/
/**/
/* Parameters:*/
/*  a_device - Kernel device pointer */
void dhd_gpu_enable_irq(dhd_gpu_device_data_t *a_device) {
  void *base_address = a_device->m_gpu_config.m_register_base_address;
  dhd_reg_stc_control_t ctrl;

  ctrl.m_value = a_device->m_stc_control; 
  #ifdef DHD_KERNEL_NON_LEVEL_IRQ  
  if ((ctrl.m_fields.m_stop_irq_enable == 0) || 
      (ctrl.m_fields.m_sync_irq_enable == 0)) {
    /* IRQ's were preiviously disabled. Run the handler once manually*/
    /* to process pending actions    */
    dhd_gpu_irq_handler(a_device);
  }
  #endif
  /* enable IRQ's  */
  ctrl.m_fields.m_stop_irq_enable = 1;
  ctrl.m_fields.m_sync_irq_enable = 1;
  ctrl.m_fields.m_pause_irq_enable = 0;
  a_device->m_stc_control = ctrl.m_value;
  dhd_gpu_write_reg(base_address, DHD_REG_STC_CONTROL, ctrl.m_value);
}

