/*----------------------------------------------------------------------------------------------------------*/
/* Determine size of allocation in bytes. Returns 0 if the input parameters were invalid.*/
/**/
dhd_uint32_t dhd_get_kalloc_size(dhd_kalloc_element_t a_element) {
  dhd_uint32_t element_size;

  switch (a_element) {
    case E_DHD_KALLOC_STATESTORE: element_size = sizeof( dhd_gpu_statestore_t );   break;
    case E_DHD_KALLOC_CONNECTION: element_size = sizeof( dhd_gpu_connection_t );   break;    
    case E_DHD_KALLOC_VMEMBLOCK:  element_size = sizeof( dhd_gpu_vidmem_block_t ) * DHD_VIDMEM_CHUNKSIZE; break;
    case E_DHD_KALLOC_VMEMHEAP:   element_size = sizeof( dhd_gpu_vidmem_heap_t );  break;

    default:
      element_size = 0;
      break;
  }

  return element_size;
}

