/*----------------------------------------------------------------------------------------------------------*/
/**/
dhd_enum_t dhd_kalloc_init() {
  dhd_uint32_t i;

  for (i=0; i<E_DHD_KALLOC_QUANTITY; i++) {
    dhd_kalloc_element_t element = (dhd_kalloc_element_t) i;
    dhd_kalloc_pool_t pool;
    dhd_enum_t res;    
    /* request details for memory pool from platform specific code*/
    res = dhd_kalloc_setup_pool(element, &pool);
    if (res != E_DHD_OK) {
      return res;
    }
    /* create a pool in the specified memory*/
    kernel_pools[i] = dhd_internal_create_kpool(pool.m_memory, pool.m_size, dhd_get_kalloc_size(element), pool.m_align);
    pool_alignments[i] = pool.m_align;
  }
  return E_DHD_OK;
}

/*----------------------------------------------------------------------------------------------------------*/
/**/
dhd_enum_t dhd_kalloc_shutdown() {
  dhd_uint32_t i;

  for (i=0; i<E_DHD_KALLOC_QUANTITY; i++) {
    dhd_kalloc_element_t element = (dhd_kalloc_element_t) i;
    dhd_kalloc_pool_t pool;
    /* recreate kalloc_pool data */
    pool.m_align  = pool_alignments[i];
    pool.m_size   = kernel_pools[i]->m_totalsize;
    pool.m_memory = (void*) kernel_pools[i];
    /* invalidate pool header*/
    kernel_pools[i]->m_firstfree = 0;
    kernel_pools[i]->m_nodesize  = 0;
    kernel_pools[i]->m_totalsize = 0;
    /* call for destruction */
    dhd_kalloc_shutdown_pool( element, &pool );
  }

  return E_DHD_OK;
}

