/* <combinewith tagdhd_gpu_call_data::m_upload>*/
/* Upload data to video memory. The function will transfer data from CPU ram to GPU ram. The destination*/
/* memory has to be inside a region allocated using dhd_gpu_alloc.*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_src - Pointer to the source memory region.*/
/*  m_dest - Pointer to the destination GPU memory region (note that this is not a dhd_vidmem_t structure).*/
/*  m_size - Size to transfer in bytes.*/
/*  m_tlistonly - When set to true the transfer will just generate a TLIST MEMCPY command and not actually */
/*  be executed (used by the driver to annotate uploads that result from shared memory access).*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful or*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if any input was invalid.*/
/**/
/* See Also: dhd_gpu_download*/
dhd_uint32_t dhd_gpu_upload(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client    = a_parameters->m_upload.m_client;
  const dhd_uint8_t *a_src = a_parameters->m_upload.m_src;
  dhd_gpu_ptr_t a_dest     = a_parameters->m_upload.m_dest;
  dhd_uint32_t a_size      = a_parameters->m_upload.m_size;
  dhd_bool_t a_tlistonly   = a_parameters->m_upload.m_tlistonly;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;  
  dhd_gpu_device_data_t *device;
  dhd_uint32_t instance;  

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 ) || (a_src == 0) || (a_dest == 0)) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* trivial case*/
  if (a_size == 0) {
    return E_DHD_OK;
  }
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  device = &s_devices[instance];
  /* validate that destination is on our heap (testing start and endpoint for inclusion is sufficient)*/
  if ((dhd_internal_is_on_heap(device->m_vidmem_heap, a_dest) == DHD_FALSE) ||  /* PRQA S 3415 *//* $Misra: #MISRA_BUG_RIGHT_HAND_OPERAND_HAS_NO_SIDE_EFFECT $*/
      (dhd_internal_is_on_heap(device->m_vidmem_heap, DHD_INC_PTR(a_dest, a_size) ) == DHD_FALSE)) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 

#ifdef DHD_KERNEL_TLIST_SUPPORT
  if ((con) && (con->m_tlist.m_tlist_file)) {
    (void) dhd_gpu_tlist_upload( &con->m_tlist, a_src, a_dest, a_size, 0 ); 
  }
#ifdef DHD_KERNEL_DUMP_KERNEL_TLIST
  (void) dhd_gpu_tlist_upload( &device->m_tlist, a_src, a_dest, a_size, 0 ); 
#endif
#endif

  /* do not do a real upload when tlistonly flag is set*/
  if (a_tlistonly != 0) {
    return E_DHD_OK;
  }

  /* forward verified parameters to internal function*/
  return dhd_gpu_internal_upload(device, a_src, a_dest, a_size);
}

