/* <combinewith tagdhd_gpu_call_data::m_alloc_mem>*/
/* Allocate a chunk of video memory. Memory has to be allocated for a specific client (connection).*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/* Videomemory allocations are not returned as a single address but fill a dhd_vidmem_t structure instead,*/
/* the GPU side address can be queried from that structure.*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_size - Requested size in bytes.*/
/*  m_alignment - Required minimum alignemnt in bytes.*/
/*  m_tag - Arbitary 32 identifier (currently unused).*/
/*  m_usage - The desired usage (see dhd_memory_usage_t).*/
/*  m_result - pointer to a dhd_vidmem_t structure recieving the allocation details.*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful,*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if input was invalid or*/
/*  E_DHD_ERROR_NO_MEMORY if the request could not be satisfied.*/
/**/
/* See Also: dhd_gpu_free_mem*/
dhd_uint32_t dhd_gpu_alloc_mem(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client = a_parameters->m_alloc_mem.m_client;
  dhd_uint32_t a_size = a_parameters->m_alloc_mem.m_size;
  dhd_size_t   a_alignment = a_parameters->m_alloc_mem.m_alignment;
  dhd_uint32_t a_tag = a_parameters->m_alloc_mem.m_tag;
  dhd_memory_usage_t a_usage = a_parameters->m_alloc_mem.m_usage;
  dhd_vidmem_t *a_result = a_parameters->m_alloc_mem.m_result;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;
  dhd_gpu_device_data_t *device;
  dhd_uint32_t  instance;
  dhd_enum_t res;

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 ) || (a_size == 0)) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    return E_DHD_ERROR_INTERNAL;
  }

  /* enforce minimum alignment of 'buswidth' for texture and buffer memorys*/
  device = &s_devices[instance];
  if ((a_usage == E_DHD_MEMORY_TEXTURE) || (a_usage == E_DHD_MEMORY_TARGET)) {
    dhd_size_t busmask = (((dhd_size_t)device->m_description.m_bus_width)- 1);
    if (a_alignment == 0) {
      a_alignment = 1;
    }
    a_alignment = (a_alignment + busmask) & ~busmask;
    #ifdef DHD_KERNEL_TLIST_SUPPORT
    /* enforce size and alignment of texture cache line*/
    a_size = (a_size + 127) & ~127u;
    #endif
  }

  /* call vidmem allocator (locked)  */
  dhd_enter_lock( s_allocatorLock );
  res = dhd_internal_alloc_vidmem(device->m_vidmem_heap, con, a_size, a_alignment, a_tag, (dhd_uint32_t)a_usage, a_result);  
  dhd_exit_lock( s_allocatorLock );

  /* call platform hook if requested (can change results)*/
  #ifdef DHD_KERNEL_VALLOC_HOOK
  if (res == E_DHD_OK) {
    res = dhd_gpu_internal_alloc_hook( device, a_size, a_alignment, a_tag, a_usage, a_result );
  }
  #endif

  /* dump videomem changes*/
  #ifdef DHD_KERNEL_DEBUG_MEMORY
  dhd_gpu_debug_note( device, "MEMORY: allocation of 0x%08x byte (alignment %d) returned 0x%08x (block %p)", a_size, a_alignment, a_result->m_gpu_address, a_result->m_block );
  #ifdef DHD_KERNEL_DEBUG_MEMORY_VERBOSE
  dhd_internal_debug_heap( device, device->m_vidmem_heap );
  #endif
  #endif

  /* log allocation in tlist */
  #ifdef DHD_KERNEL_TLIST_SUPPORT
  if ((con->m_tlist.m_tlist_file) && (res == E_DHD_OK)) {
    (void) dhd_gpu_tlist_alloc(&con->m_tlist, a_size, a_tag, a_usage, a_result);
  }
  #ifdef DHD_KERNEL_DUMP_KERNEL_TLIST
  if ((device->m_tlist.m_tlist_file) && (res == E_DHD_OK)) {
    (void) dhd_gpu_tlist_alloc(&device->m_tlist, a_size, a_tag, a_usage, a_result);
  }
  #endif
  #endif

  return res;
}

