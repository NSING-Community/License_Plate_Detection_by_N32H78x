/* <combinewith tagdhd_gpu_call_data::m_get_reclaimed_jobs>*/
/* Retrieve a list of free job buffers. After a job has been processed by the hardware its buffer can be*/
/* reused (see dhd_gpu_commit). Using this function the usermode can query and retrieve free buffers for*/
/* reusing.*/
/* If there are currently no free jobs, but the application needs one to continue - it should call*/
/* dhd_gpu_wait_for_job in order to sleep until at least one job has completed and retry dhd_gpu_get_reclaimed_jobs.*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_out - Pointer to a dhd_gpu_job_t pointer that will receive the free jobs.*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful or*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if any input was invalid.*/
/**/
/* See Also: dhd_gpu_commit, dhd_gpu_wait_for_job*/
dhd_uint32_t dhd_gpu_get_reclaimed_jobs(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client = a_parameters->m_get_reclaimed_jobs.m_client;
  dhd_gpu_job_t **a_out = a_parameters->m_get_reclaimed_jobs.m_out;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;   
  dhd_uint32_t instance;  
  dhd_gpu_job_t *freejobs;
  dhd_gpu_device_data_t *device;

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 )) {
    *a_out = 0;
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    *a_out = 0;
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  device = &s_devices[instance];
  dhd_enter_lock( s_deviceLock );    
#ifdef DHD_KERNEL_SOFT_IRQ
  dhd_enter_irq_lock();
#else 
  dhd_gpu_disable_irq(device);
#endif
  (void)dhd_gpu_mark_finished_jobs(device);
  freejobs = dhd_gpu_reclaim_jobs(device, con);
#ifdef DHD_KERNEL_SOFT_IRQ
  dhd_exit_irq_lock();
#else 
    dhd_gpu_enable_irq(device);
#endif		
  dhd_exit_lock( s_deviceLock );  

  *a_out = freejobs;
  return E_DHD_OK;
}

