/* <combinewith tagdhd_gpu_call_data::m_can_map_mem>*/
/* Check if a specific memory mapping is possible. The function will return E_DHD_OK if the specified memory */
/* mapping is possible without datatransfer.*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_memory - Pointer to the dhd_vidmem_t structure for the memory to be mapped (allocated by dhd_gpu_alloc_mem).*/
/*  m_access - Required memory access (either E_DHD_READ_ACCESS, E_DHD_WRITE_ACCESS or both)  */
/**/
/* Returns:*/
/*  E_DHD_OK if successful,*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if input was invalid or*/
/*  E_DHD_ERROR_NOT_SUPPORTED if the mapping was not possible.*/
/**/
/* See Also: dhd_gpu_map_mem, dhd_gpu_unmap_mem*/
dhd_uint32_t dhd_gpu_can_map_mem(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client  = a_parameters->m_can_map_mem.m_client;
  dhd_vidmem_t *a_memory = a_parameters->m_can_map_mem.m_memory;
  dhd_enum_t a_access    = a_parameters->m_can_map_mem.m_access;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;
  dhd_gpu_device_data_t *device;
  dhd_uint32_t instance;  

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 ) || (a_memory == 0) ||
      ((a_access & ~((dhd_enum_t)E_DHD_READ_ACCESS | (dhd_enum_t)E_DHD_WRITE_ACCESS)) != 0) ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  device = &s_devices[instance];

  /* forward verified parameters to internal function*/
  return dhd_gpu_internal_can_map_mem(device, a_memory, a_access);
}

