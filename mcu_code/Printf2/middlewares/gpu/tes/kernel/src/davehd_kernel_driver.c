/* <combinewith tagdhd_gpu_call_data::m_commit>*/
/* Register job for execution. Commited job buffers will be scheduled and added to the HW ringbuffer for*/
/* execution. After beeing commited a job is considered 'active' until the HW has signaled it's completion.*/
/* Completed jobs are 'free' and will be handed back to the user mode to be used again.*/
/* In order to reduce the amount of necessary user-kernel transitions every call to dhd_gpu_commit can also*/
/* return a set of free jobs - if there are any.*/
/* dhd_gpu_commit will update the assigned_id filed inside the job structure.*/
/* Of cource free jobs can also be polled at any time using dhd_gpu_get_reclaimed_jobs.*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_job - Pointer to the job to be commited.*/
/*  m_reclaimed_jobs - Pointer to a dhd_gpu_job_t pointer that will receive the free jobs (or 0 to indicate*/
/*                     that the application does not want to receive any free jobs on this call.*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful,*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if any input was invalid or*/
/*  E_DHD_ERROR_INTERNAL if an internal error occured.*/
/**/
/* See Also: dhd_gpu_get_reclaimed_jobs, dhd_gpu_wait_for_job*/
dhd_uint32_t dhd_gpu_commit(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client            = a_parameters->m_commit.m_client;
  dhd_gpu_job_t *a_job             = a_parameters->m_commit.m_job;
  dhd_gpu_job_t **a_reclaimed_jobs = a_parameters->m_commit.m_reclaimed_jobs;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;
  dhd_uint32_t instance;
  dhd_gpu_device_data_t *device;
  dhd_uint32_t res = E_DHD_OK;

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 ) || (a_job == DHD_INVALID_JOB)) {        
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {    
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* enter lock to make sure modification of joblist is atomic. */
  dhd_enter_lock( s_deviceLock );

  /* add job to chain*/
  device = &s_devices[instance];
  #ifdef DHD_KERNEL_SOFT_IRQ
  dhd_enter_irq_lock();
  #else 
  dhd_gpu_disable_irq((dhd_gpu_device_data_t *)device);
  #endif
  a_job->m_assigned_id = DHD_NOT_ASSIGNED;
  a_job->m_sender = con;

  #ifdef DHD_KERNEL_DEBUG_SCHEDULE
  dhd_gpu_debug_note(device, "COMMIT: accepted job %p (0x%08x)", a_job, a_job->m_memory.m_gpu_address);
  #endif

  a_job->m_next = 0;  
  if ( device->m_last_job != 0 ) {    
    device->m_last_job->m_next = a_job;
  } else {
    device->m_first_job = a_job;
  }
  device->m_last_job = a_job;

  /* flush cache if job has an active CPU mapping*/
  if ( a_job->m_memory.m_cpu_address != 0 ) {
    dhd_gpu_job_flush(device, con, &a_job->m_memory, a_job->m_size);
  }

  /* trigger scheduler here*/
  res = dhd_gpu_schedule_job( device );

  /* return list of reclaimed jobs if requested*/
  if (a_reclaimed_jobs != 0) {
    *a_reclaimed_jobs = dhd_gpu_reclaim_jobs(device, con);
  }
  
#ifdef DHD_KERNEL_SOFT_IRQ
  dhd_exit_irq_lock();
#else 
  dhd_gpu_enable_irq((dhd_gpu_device_data_t *)device);
#endif
  dhd_exit_lock( s_deviceLock );

  /* flush debug notes if there are any*/
  dhd_gpu_debug_flush( device, DHD_TRUE );
  
  return res;
}

/*----------------------------------------------------------------------------------------------------------*/
/* <combinewith tagdhd_gpu_call_data::m_get_sync>*/
/* Query latest completed job and clear id. The hardware maintains sync registers to indicate the ID of the*/
/* last job it has processed. As all job IDs are assigned strictly monotone and in scheduling order all jobs*/
/* with an ID lower or equal to the current sync id are known to be completed.*/
/* By setting either jobid or clid result pointers to 0 the caller can request only one of the two IDs.*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_jobid  - pointer to a dhd_uint32_t that will receive the last completed job id (or 0 if this is not requested).*/
/*  m_clid  - pointer to a dhd_uint32_t that will receive the last completed clear id (or 0 if this is not requested).*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful or*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if any input was invalid.*/
/**/
/* See Also: dhd_gpu_commit*/
dhd_uint32_t dhd_gpu_get_sync(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client = a_parameters->m_get_sync.m_client; 
  dhd_uint32_t *a_jobid = a_parameters->m_get_sync.m_jobid;
  dhd_uint32_t *a_clid  = a_parameters->m_get_sync.m_clid;

  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;   
  dhd_uint32_t instance;  
  dhd_gpu_device_data_t *device;

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 )) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  device = &s_devices[instance];

  /* read required sync registers*/
  if (a_jobid != 0) {
    *a_jobid = dhd_gpu_query_jobsync(device, DHD_FALSE);
  }
  if (a_clid != 0) {
    *a_clid = 0; /* clear IDs are no longer used*/
  }

  return E_DHD_OK;
}
      
