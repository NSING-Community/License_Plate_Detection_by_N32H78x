/* <combinewith tagdhd_gpu_call_data::m_download_state>*/
/* Retrieve HW state. The HW state is the set of all programmable registers (not including unused gaps in*/
/* the register address sapce). The function can deliver either the 'reset' state or the 'current' state.*/
/* The current state is polled asynchronously from the HW using direct register reads.*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_destination - Pointer to 'count' 32bit words that are to be filled with the state.*/
/*  m_count - Maximm number of register to write.*/
/*  m_flags - Either E_DHD_STATE_INITIAL or E_DHD_STATE_CURRENT.*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful or*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if any input was invalid.*/
dhd_uint32_t dhd_gpu_download_state(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client         = a_parameters->m_download_state.m_client;
  dhd_uint32_t *a_destination   = a_parameters->m_download_state.m_destination;
  dhd_uint32_t a_count          = a_parameters->m_download_state.m_count;
  dhd_gpu_state_flags_t a_flags = a_parameters->m_download_state.m_flags;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;
  dhd_uint32_t group, instance;  
  dhd_gpu_device_data_t *device;
  dhd_uint8_t grpsize[ 16 ] = {0};    

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 ) || (a_destination == 0)) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  device = &s_devices[instance];

  /* walk all known registers (group by group) and store up to a_count of selected state (initial or current)*/
  if (a_flags == E_DHD_STATE_INITIAL) {
    dhd_uint32_t i;
    for (i=0; i<a_count; i++) {
      *a_destination = dhd_reset_state[i];
      a_destination++;
    }
    return E_DHD_OK;
  }                           

  if (a_flags == E_DHD_STATE_CURRENT) { /* PRQA S 3355, 3358 *//* $Misra: Even if the result of the logical expression is always true it is safer for further development to check it. $*/
    /* update register file limits */
    grpsize[2] = 29;                           
    grpsize[3] = 0 + (6 * device->m_description.m_num_tex_units);    
    grpsize[4] = 8 + (3 * device->m_description.m_num_tex_units);    
    grpsize[6] = 4 + (2 * device->m_description.m_num_tex_units);    
    grpsize[8] = 6 + (1 * device->m_description.m_num_const_cols);   
    grpsize[10] = 0 + (7 * device->m_description.m_num_tex_units);  
    grpsize[11] = 0 + (6 * device->m_description.m_num_col_units);    
    grpsize[12] = 5;   
    for (group=0; group<16; group++) {
      dhd_uint32_t grpmax = grpsize[group];
      if (grpmax > 0) {
        dhd_uint32_t i;      
        for (i=0; (i<grpmax) && (a_count > 0); i++) {
          dhd_uint32_t regidx = (group*64) + i;
          if (regidx < DHD_MAX_CPU_REGISTER_ACCESS) {
            *a_destination = dhd_gpu_read_reg( device->m_gpu_config.m_register_base_address, regidx );
          } else {
            *a_destination = 0; /* inaccessible registers should return 0*/
          }
#ifdef DHD_KERNEL_TLIST_SUPPORT
          if (con->m_tlist.m_tlist_file) {
              (void)dhd_gpu_tlist_regread(&con->m_tlist, regidx, *a_destination, 0xffffffff, "dumped register");
          }
#endif

          a_destination++;
          a_count--;
        }
      }
    }
    return E_DHD_OK;
  }
  
  return E_DHD_ERROR_INVALID_ARGUMENT;
}

