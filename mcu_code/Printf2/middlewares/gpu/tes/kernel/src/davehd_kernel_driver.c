/* <combinewith tagdhd_gpu_call_data::m_alloc_pc>*/
/* Allocate a performance counter. HW performance counters have to be allocated exclusively by a usermode*/
/* client. Once allocated the client is free to use them in any way. Allocated counters need to be*/
/* released (using dhd_gpu_free_pc) once they are no longer needed.*/
/* If no more counters are available the function will return E_DHD_ERROR_NO_COUNTER and set the pcid to*/
/* DHD_INVALID_PCID.*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_pcid - Pointer to a dhd_uint8_t that will receive the allocated counter's ID or DHD_INVALID_PCID.*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful,*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if any input was invalid or*/
/*  E_DHD_ERROR_NO_COUNTER if no more counters are available.*/
/**/
/* See Also: dhd_gpu_free_pc*/
dhd_uint32_t dhd_gpu_alloc_pc(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client = a_parameters->m_alloc_pc.m_client;
  dhd_uint8_t *a_pcid = a_parameters->m_alloc_pc.m_pcid;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;
  dhd_uint32_t instance, mask;
  dhd_uint8_t i, id;  
  dhd_gpu_device_data_t *device;

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 ) || (a_pcid == 0)) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  device = &s_devices[instance];
  dhd_enter_lock( s_deviceLock );    
  /* scan for free performance counter*/
  mask = device->m_perfcount_allocmask;
  id = DHD_INVALID_PCID;
  for (i=0; i<device->m_description.m_num_perfcounters; i++) {
    if ((mask & (1u << i)) == 0) {
      /* found a counter*/
      id = i;
      break;
    }
  }  
  if (id != DHD_INVALID_PCID) {
    /* update the mask if allocation was successful*/
    device->m_perfcount_allocmask = mask | (1u << id);
  }
  dhd_exit_lock( s_deviceLock );  

  /* return allocated counter*/
  if (id == DHD_INVALID_PCID) {
    return E_DHD_ERROR_NO_COUNTER;
  }
  *a_pcid = id;

  return E_DHD_OK;
}

/*----------------------------------------------------------------------------------------------------------*/
/* <combinewith tagdhd_gpu_call_data::m_free_pc>*/
/* Free a performance counter. Counters allocated by dhd_gpu_alloc_pc need to be released using this */
/* function after the last job using them has been completed. */
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_pcid - ID of the performance counter to release (as returned by dhd_gpu_alloc_pc).*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful or*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if any input was invalid (also if an attempt was made*/
/*  to release a counter that was no longer allocated by the calling client).*/
/**/
/* See Also: dhd_gpu_alloc_pc*/
dhd_uint32_t dhd_gpu_free_pc(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client = a_parameters->m_free_pc.m_client;
  dhd_uint8_t a_pcid    = a_parameters->m_free_pc.m_pcid;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;
  dhd_uint32_t instance;  
  dhd_gpu_device_data_t *device;

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 )) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  device = &s_devices[instance];  
  dhd_enter_lock( s_deviceLock );    
  /* validate pc id*/
  if (a_pcid >= device->m_description.m_num_perfcounters) {
    a_pcid = DHD_INVALID_PCID;
  }
  if ((device->m_perfcount_allocmask & (1u << a_pcid)) == 0) {
    a_pcid = DHD_INVALID_PCID;
  }
  /* release the pc (if valid)*/
  if (a_pcid != DHD_INVALID_PCID) {
    device->m_perfcount_allocmask &= ~(1u << a_pcid);
  }  
  dhd_exit_lock( s_deviceLock );  

  /* return allocated counter*/
  if (a_pcid == DHD_INVALID_PCID) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } else {  
    return E_DHD_OK;
  }
}

