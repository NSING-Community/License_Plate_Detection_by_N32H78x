/* <combinewith tagdhd_gpu_call_data::m_free_mem>*/
/* Release a chunk of video memory. The memory must be released using the same connection handle it was allocated*/
/* from.*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_memory - Pointer to the dhd_vidmem_t that was filled out by dhd_gpu_alloc_mem.*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful, E_DHD_ERROR_INVALID_ARGUMENT if input was invalid.*/
/**/
/* See Also: dhd_gpu_alloc_mem*/
dhd_uint32_t dhd_gpu_free_mem(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client = a_parameters->m_free_mem.m_client;
  dhd_vidmem_t *a_memory = a_parameters->m_free_mem.m_memory;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;
  dhd_gpu_device_data_t *device;
  dhd_uint32_t instance;
  dhd_enum_t res;
  #ifdef DHD_KERNEL_DEBUG_MEMORY
  dhd_vidmem_t temp_memory;
  #endif

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 ) || (a_memory == 0)) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    return E_DHD_ERROR_INTERNAL;
  }

  
  device = &s_devices[instance];
  /* call platform hook if requested (can change results)*/
  #ifdef DHD_KERNEL_VALLOC_HOOK
  dhd_gpu_internal_free_hook( device, a_memory );  
  #endif

  /* log allocation in tlist */
  #ifdef DHD_KERNEL_TLIST_SUPPORT
  if (con->m_tlist.m_tlist_file) {
    (void) dhd_gpu_tlist_free(&con->m_tlist, a_memory);
  }
  #ifdef DHD_KERNEL_DUMP_KERNEL_TLIST
  if (device->m_tlist.m_tlist_file) {
    (void) dhd_gpu_tlist_free(&device->m_tlist, a_memory);
  }
  #endif
  #endif

  #ifdef DHD_KERNEL_DEBUG_MEMORY
  /* We need a temporary copy as the block will be zeroed*/
  temp_memory = *a_memory;
  #endif

  /* call vidmem deallocator (locked)*/
  dhd_enter_lock( s_allocatorLock );  
  res = dhd_internal_free_vidmem(device->m_vidmem_heap, con, a_memory);
  dhd_exit_lock( s_allocatorLock );

  /* dump videomem changes*/
  #ifdef DHD_KERNEL_DEBUG_MEMORY
  if (res == E_DHD_ERROR_INVALID_ARGUMENT) {
    dhd_gpu_debug_note( device, "MEMORY: ILLEGAL FREE of 0x%08x byte at 0x%08x (block %p)", temp_memory.m_size,temp_memory.m_gpu_address, temp_memory.m_block );
  } else {
    dhd_gpu_debug_note( device, "MEMORY: released of 0x%08x byte at 0x%08x (block %p)", temp_memory.m_size, temp_memory.m_gpu_address, temp_memory.m_block );
  }
  #ifdef DHD_KERNEL_DEBUG_MEMORY_VERBOSE
  dhd_internal_debug_heap( device, device->m_vidmem_heap );
  #endif
  #endif


  return res;
}

