/* <combinewith tagdhd_gpu_call_data::m_alloc_clut>*/
/* Allocate a part of the CLUT RAM. Convolution, colorspace conversion and palletized textures require some*/
/* entries in the internal CLUT RAM. A continous slice of CLUT entries can be allocated for exclusive use*/
/* by the calling client using this function.*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_size - Number of entries to allocate.*/
/*  m_clutindex - Pointer to a dhd_uint32_t that will receive the index of the first allocated entry (if successful).*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful,*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if any input was invalid or*/
/*  E_DHD_ERROR_NO_MEMORY if no more CLUT entries were available.*/
/**/
/* See Also: dhd_gpu_free_clut*/
dhd_uint32_t dhd_gpu_alloc_clut(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client = a_parameters->m_alloc_clut.m_client;
  dhd_uint32_t a_size = a_parameters->m_alloc_clut.m_size;
  dhd_uint32_t *a_clutindex = a_parameters->m_alloc_clut.m_clutindex;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;
  dhd_uint32_t instance, chunksize, chunkmask, allocmask, blockoffset, offset, i;  
  dhd_gpu_device_data_t *device;
  dhd_enum_t res;

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 ) || (a_size == 0) || (a_clutindex == 0)) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  device = &s_devices[instance];  
  dhd_enter_lock( s_deviceLock ); 

  /* check how many blocks we are going to need*/
  chunksize = (a_size + (device->m_clut_blocksize - 1)) / device->m_clut_blocksize;
  if (chunksize == 32) {
    chunkmask = ~0u; /* required because 1 << 32 is undefined*/
  } else {
    chunkmask = (1u << chunksize) - 1;
  }
  /* scan clut bitmap for a consecutive free sequence of this size*/
  allocmask = device->m_clut_usemask;
  blockoffset = 31+1; /* not found offset is one beyond maximum*/
  for (i=0; i<=(32 - chunksize); i++) {
    if ((allocmask & chunkmask) == 0) {
      /* found a position at i (currently using first fit. maybe best fit is better)*/
      blockoffset = i;
      break;
    }
    chunkmask <<= 1; /* try next position*/
  }
  offset = blockoffset * device->m_clut_blocksize;
  if ((offset + a_size) <= device->m_description.m_num_clut_entries) {
    /* found a valid sequence of free clut registers. mark them als allocated*/
    device->m_clut_usemask |= chunkmask;
    con->m_used_clutblocks |= chunkmask;
    *a_clutindex = offset;    
    res = E_DHD_OK;
  } else {
    res = E_DHD_ERROR_NO_MEMORY;
  }
  dhd_exit_lock( s_deviceLock );  

  return res;
}

/*----------------------------------------------------------------------------------------------------------*/
/* <combinewith tagdhd_gpu_call_data::m_free_clut>*/
/* Free a part of the CLUT RAM. CLUT entries allocated by dhd_gpu_alloc_clut need to be released using this */
/* function after the last job using them has been completed. */
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_client - Handle to a client connection (as returned by dhd_gpu_connect).*/
/*  m_size - Number of entries to be released.*/
/*  m_clutindex - Index of the first entry to be released (as returned by dhd_gpu_alloc_clut).*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful or*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if any input was invalid.*/
/**/
/* See Also: dhd_gpu_alloc_clut*/
dhd_uint32_t dhd_gpu_free_clut(const dhd_gpu_call_data_t *a_parameters) {
  dhd_handle_t a_client    = a_parameters->m_free_clut.m_client;
  dhd_uint32_t a_size      = a_parameters->m_free_clut.m_size;
  dhd_uint32_t a_clutindex = a_parameters->m_free_clut.m_clutindex;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;
  dhd_uint32_t instance, chunksize, chunkmask;  
  dhd_gpu_device_data_t *device;

  /* validate arguments */
  if (( dhd_validate_connection(con) != E_DHD_OK ) || ( s_deviceCount == 0 ) || (a_size == 0)) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  } 
  /* validate connection integrity*/
  instance = con->m_hw_instance;
  if ( instance >= DHD_MAX_GPU_COUNT ) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }
  device = &s_devices[instance];  

  /* create chunkmask on clutblock granularity*/
  if ((a_clutindex % device->m_clut_blocksize) != 0) {
    return E_DHD_ERROR_INVALID_ARGUMENT; /* given offset is not on a block granularity*/
  }
  chunksize = (a_size + (device->m_clut_blocksize - 1)) / device->m_clut_blocksize;
  if (chunksize == 32) {
    chunkmask = ~0u; /* required because 1 << 32 is undefined*/
  } else {
    chunkmask = (1u << chunksize) - 1;
  }
  chunkmask = chunkmask << (a_clutindex / device->m_clut_blocksize);  
  dhd_enter_lock( s_deviceLock ); 
  /* mark sequence as free again*/
  device->m_clut_usemask &= ~chunkmask;
  con->m_used_clutblocks &= ~chunkmask;
  dhd_exit_lock( s_deviceLock );  

  return E_DHD_OK;
}

