/* <combinewith tagdhd_gpu_call_data::m_shutdown>*/
/* Shutdown the kernel mode driver. Usually called by the OS at shutdown. Will also stop all HW activity.*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_instance : integer index of the HW instance to shut down.*/
/**/
/* Returns:*/
/*  E_DHD_OK if successful,*/
/*  E_DHD_ERROR_INVALID_ARGUMENT if input was invalid or*/
/*  E_DHD_ERROR_RESOURCE_LEAK if there was video memory not freed.*/
/**/
/* See Also: dhd_gpu_init*/
dhd_uint32_t dhd_gpu_shutdown(const dhd_gpu_call_data_t *a_parameters) {
  dhd_uint32_t a_instance = a_parameters->m_shutdown.m_instance;
  dhd_gpu_device_data_t *device;
  dhd_enum_t result = E_DHD_OK;
  dhd_enum_t hd_result = E_DHD_OK;

  /* validate argument*/
  if (( a_instance >= DHD_MAX_GPU_COUNT ) || ( s_deviceCount == 0 )) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* enter lock to make sure no devices are created now*/
  dhd_enter_lock( s_deviceLock );
  device = &s_devices[ a_instance ];

  /* check if device is initialized*/
  if ( device->m_initialized == 1 ) {
    dhd_gpu_vidmem_heap_t *heap;

    /* shutdown all hw activity*/
    result = dhd_gpu_hardware_shutdown( device );

    if ( device->m_ringbuffer.m_gpu_address != 0 ) {
      /* release ring buffer memory*/
      dhd_enter_lock( s_allocatorLock );
      (void) dhd_internal_free_vidmem( device->m_vidmem_heap, 0, &device->m_ringbuffer );
      dhd_exit_lock( s_allocatorLock );
    }

    /* dump final heap configuration*/
    #ifdef DHD_KERNEL_DEBUG_MEMORY
    dhd_gpu_debug_note( device, "MEMORY: final heap config..." );
    dhd_internal_debug_heap( device, device->m_vidmem_heap );
    #endif

    /* destruct resources*/
    heap = device->m_vidmem_heap;
    device->m_vidmem_heap = 0;
    hd_result = dhd_internal_destroy_heap( heap );
    #ifdef DHD_KERNEL_DEBUG_MEMORY
    if ( hd_result == E_DHD_ERROR_RESOURCE_LEAK ) {
      dhd_gpu_debug_note( device, "MEMORY: kernel LEAKED video memory!" );
    }
    #endif

    /* shutdown kernel debug module (if enabled)*/
    dhd_gpu_debug_shutdown( device );

    /* mark as uninitialized*/
    device->m_initialized = 0;

    /* device is down*/
    s_deviceCount--;   
  }

  /* exit lock or exit and destroy lock (if this was last device)*/
  if ( s_deviceCount == 0 ) {
    /* no need for global mutex anymore*/
    dhd_exit_lock( s_deviceLock );
    dhd_destroy_lock( s_deviceLock );
    dhd_destroy_lock( s_allocatorLock );
    s_deviceLock = (dhd_lock_t) 0;
    s_allocatorLock = (dhd_lock_t) 0;
  } else {
    dhd_exit_lock( s_deviceLock );
  }

  if(result == E_DHD_OK) {
    return hd_result;
  }
  else {
    return result;
  }
}

