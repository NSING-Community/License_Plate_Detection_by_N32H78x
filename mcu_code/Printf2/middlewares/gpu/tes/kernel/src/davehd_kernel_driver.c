/* <combinewith tagdhd_gpu_call_data::m_query_instance>*/
/* Query description of a specific HW instance.*/
/* The parameters are passed inside a dhd_gpu_call_data_t (see <link !!Bridge, Kernel Mode Interface> for details).*/
/**/
/* Parameters:*/
/*  m_instance : integer index of the HW instance to query.*/
/*  m_out :  pointer to a dhd_device_description_t recieving the instance description.*/
/**/
/* Returns:*/
/*   E_DHD_OK if successful, E_DHD_ERROR_INVALID_ARGUMENT otherwise*/
/*  */
/* See Also: dhd_gpu_get_instance_count*/
dhd_uint32_t dhd_gpu_query_instance(const dhd_gpu_call_data_t *a_parameters) {
  dhd_uint32_t a_instance         = a_parameters->m_query_instance.m_instance;
  dhd_device_description_t *a_out = a_parameters->m_query_instance.m_out;
  dhd_enum_t res;  

  /* validate arguments*/
  if (( a_instance >= DHD_MAX_GPU_COUNT ) || ( s_deviceCount == 0 )) {
    return E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* enter lock to make sure no devices are created/deleted now*/
  dhd_enter_lock( s_deviceLock );

  /* check if requested instance is valid*/
  if ( s_devices[ a_instance ].m_initialized == 1 ) {
    if ( a_out != 0 ) {
      /* copy description to 'out' (if 'out' is non zero)*/
      *a_out = s_devices[ a_instance ].m_description; 
    }
    /* signal that the instance is live    */
    res = E_DHD_OK;
  } else {
    /* signal that the instance is unused    */
    res = E_DHD_ERROR_INVALID_ARGUMENT;
  }

  /* done, can release lock*/
  dhd_exit_lock( s_deviceLock );
  return res;
}

