/* to be used with job buffers only.*/
/**/
static void dhd_gpu_job_flush(dhd_gpu_device_data_t *a_device, dhd_gpu_connection_t *a_client, dhd_vidmem_t const *a_memory, dhd_uint32_t a_size) {
  dhd_gpu_internal_cflush(a_device, (const dhd_uint8_t*) a_memory->m_cpu_address, a_size);

  /* need to encode a tlist memcpy for each cacheflush to capture memmapped transfers*/
  #ifdef DHD_KERNEL_TLIST_SUPPORT
  if ((0 != a_client) && (0 != a_client->m_tlist.m_tlist_file)) {
    dhd_stc_opcode_t op;
    /* TLIST jobs should contain a stream END following the real job data. The last word of each job is a normally NOP, which will be replaced*/
    /* by END in the TLIST dump*/
    op.m_fields.m_opcode         = DHD_STCOP_END;
    op.m_fields.m_data_following = 0;
    op.m_fields.m_data_count     = 0;
    op.m_fields.m_arguments      = 0x3ff;     

    (void)dhd_gpu_tlist_upload( &a_client->m_tlist, a_memory->m_cpu_address, a_memory->m_gpu_address, a_size, op.m_value ); 
  }
  #ifdef DHD_KERNEL_DUMP_KERNEL_TLIST
    (void)dhd_gpu_tlist_upload( &a_device->m_tlist, a_memory->m_cpu_address, a_memory->m_gpu_address, a_size, 0 ); 
  #endif
  #endif
}

