/*----------------------------------------------------------------------------------------------------------*/
dhd_uint32_t dhd_gpu_get_client_count(void) {
  dhd_uint32_t i, count = 0;

  /* enter lock to make sure no devices are created/deleted now*/
  dhd_enter_lock( s_deviceLock );

  /* get total client count (over all instances)*/
  for (i=0; i<s_deviceCount; i++) {
    if (s_devices[i].m_initialized == 1) {
      count += s_devices[i].m_connections;
    }
  }

  /* done, can release lock*/
  dhd_exit_lock( s_deviceLock );
  return count;
}

