void dhd_gpu_setup_irq(dhd_gpu_device_data_t *a_device, dhd_irq_t a_callback) {
  int irq = a_device->m_gpu_config.m_irq_index;
  if (a_callback!=0) {
    /* Connect IRQ*/
    // arch_connect_irq(irq, (void*)a_callback, a_device);  //tp 
    /* Enable IRQ*/
    arch_enable_irq( irq );
  } else {
    /* Disable IRQ*/
    arch_disable_irq(irq);
    /* Disconnect IRQ*/
    arch_disconnect_irq(irq);
  }
}

