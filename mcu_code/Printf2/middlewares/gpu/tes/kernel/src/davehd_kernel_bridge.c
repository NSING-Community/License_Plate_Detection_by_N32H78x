/* Turn dhd_gpu_call_entry_t into a real call. Dispatches a call to the corresponding function.*/
/**/
dhd_uint32_t dhd_gpu_dispatch(dhd_gpu_call_entry_t a_function, dhd_gpu_call_data_t *a_parameters) {

  switch ( a_function ) {
    case E_DHD_CALL_GET_INSTANCE_COUNT:     return dhd_gpu_get_instance_count(a_parameters);
    case E_DHD_CALL_QUERY_INSTANCE:         return dhd_gpu_query_instance(a_parameters); 
    case E_DHD_CALL_INIT:                   return dhd_gpu_init(a_parameters); 
    case E_DHD_CALL_SHUTDOWN:               return dhd_gpu_shutdown(a_parameters); 
    case E_DHD_CALL_CONNECT:                return dhd_gpu_connect(a_parameters); 
    case E_DHD_CALL_DISCONNECT:             return dhd_gpu_disconnect(a_parameters);  
    case E_DHD_CALL_ALLOC_MEM:              return dhd_gpu_alloc_mem(a_parameters);  
    case E_DHD_CALL_FREE_MEM:               return dhd_gpu_free_mem(a_parameters);  
    case E_DHD_CALL_CAN_MAP_MEM:            return dhd_gpu_can_map_mem(a_parameters);  
    case E_DHD_CALL_MAP_MEM:                return dhd_gpu_map_mem(a_parameters);  
    case E_DHD_CALL_UNMAP_MEM:              return dhd_gpu_unmap_mem(a_parameters);  
    case E_DHD_CALL_UPLOAD:                 return dhd_gpu_upload(a_parameters);  
    case E_DHD_CALL_DOWNLOAD:               return dhd_gpu_download(a_parameters);  
    case E_DHD_CALL_COMMIT:                 return dhd_gpu_commit(a_parameters);    
    case E_DHD_CALL_GET_SYNC:               return dhd_gpu_get_sync(a_parameters);
    case E_DHD_CALL_WAIT_FOR_JOB:           return dhd_gpu_wait_for_job(a_parameters);
    case E_DHD_CALL_GET_RECLAIMED_JOBS:     return dhd_gpu_get_reclaimed_jobs(a_parameters);
    case E_DHD_CALL_FORCE_YIELD:            return dhd_gpu_force_yield(a_parameters);
    case E_DHD_CALL_DOWNLOAD_STATE:         return dhd_gpu_download_state(a_parameters);
    case E_DHD_CALL_TLIST_ENABLE:           return dhd_gpu_tlist_enable(a_parameters);
    case E_DHD_CALL_TLIST_WRITE:            return dhd_gpu_tlist_write(a_parameters);
    case E_DHD_CALL_ALLOC_PC:               return dhd_gpu_alloc_pc(a_parameters);
    case E_DHD_CALL_FREE_PC:                return dhd_gpu_free_pc(a_parameters);
    case E_DHD_CALL_ALLOC_CLUT:             return dhd_gpu_alloc_clut(a_parameters);
    case E_DHD_CALL_FREE_CLUT:              return dhd_gpu_free_clut(a_parameters);
    case E_DHD_CALL_RESUME:                 return dhd_gpu_resume(a_parameters);
    case E_DHD_CALL_CAN_ACCESS_MEM:         return dhd_gpu_can_access_mem(a_parameters);
    case E_DHD_CALL_SCHEDULE_JOB_TRIGGER:   return dhd_gpu_schedule_job(a_parameters->m_schedule_job_trigger.m_device);
    default:
      return E_DHD_ERROR_NOT_SUPPORTED;
  }
}

/*----------------------------------------------------------------------------------------------------------*/
/* Platform independent part of bridge_init_server.*/
/**/
void dhd_gpu_bridge_init_server_internal(void) {
  s_waitercount = 0;
  #ifdef DHD_KERNEL_SOFT_IRQ
  s_irqlock = dhd_create_lock();
  #endif
}

/*----------------------------------------------------------------------------------------------------------*/
/* Add client to the list of waiting clients. */
/**/
void dhd_gpu_bridge_add_waiting(dhd_handle_t a_client, dhd_jobid_t a_jobid, dhd_bridge_wakeup_token a_token) {
  dhd_uint32_t i, syncid, jobid;
  dhd_gpu_connection_t *con = (dhd_gpu_connection_t *) a_client;
  dhd_gpu_device_data_t *device = dhd_gpu_resolve_instance( con->m_hw_instance );
  dhd_bool_t wakeup = DHD_FALSE;

  #ifdef DHD_KERNEL_SOFT_IRQ
  dhd_enter_lock(s_irqlock);
  #else 
  dhd_gpu_disable_irq(device);
  #endif
  i = s_waitercount;    
  /* need to re-evaluate the waiting decision now that we have the IRQ locked out (so it can't race anymore)*/
  /* otherwise we might put someone waiting who is already finished*/
  syncid = dhd_gpu_query_jobsync(device, DHD_FALSE);   
  jobid  = ((dhd_gpu_job_t*)a_jobid)->m_assigned_id;
  /* PRQA S 3355,3356 2 *//* $Misra: misra checker fails to interpret the following line and produces nonsense warnings $*/
  //if ((jobid != DHD_NOT_ASSIGNED) && (syncid != DHD_NOT_ASSIGNED) && (! DHD_LESS_WRAPAROUND(syncid, jobid))) {
	if ((jobid != DHD_NOT_ASSIGNED) && (syncid != DHD_NOT_ASSIGNED)) {
    /* special case. job is already finished, no need to add it as waiting*/
    wakeup = DHD_TRUE;
  } else {
    /* normal case. add the job to waiting list*/
    if (i == DHD_MAX_CONCURRENT_WAITS) {    
      dhd_gpu_debug_note( device, "BRIDGE: wait queue is full!" );    
    } else {    
      #ifdef DHD_KERNEL_DEBUG_TRACEVCD
      TraceVcd_AddEvent("WaitFor", ((dhd_gpu_job_t*)a_jobid)->m_assigned_id);
      #endif
      s_waiters[ i ].m_client = device;
      s_waiters[ i ].m_jobid  = a_jobid;
      s_waiters[ i ].m_jobgen = dhd_gpu_generation_from_jobid( a_jobid );
      s_waiters[ i ].m_token  = a_token;
      s_waitercount++;  
    }
  }
  #ifdef DHD_KERNEL_SOFT_IRQ
  dhd_exit_lock(s_irqlock);
  #else
  dhd_gpu_enable_irq(device);
  #endif
  if (wakeup == DHD_TRUE ) {
    /* wakeup client instantly if it has not been added*/
    dhd_gpu_bridge_wakeup( a_token );
  }
}

/*----------------------------------------------------------------------------------------------------------*/
/* Wake all waiting clients. Usually called only on bridge shutdown.*/
/**/
void dhd_gpu_bridge_wakeup_all(void) {
  dhd_uint32_t i, cnt = s_waitercount;

  for (i=0; i<cnt; i++) {
    dhd_gpu_bridge_wakeup( s_waiters[i].m_token );
  }
  s_waitercount = 0;  
  #ifdef DHD_KERNEL_SOFT_IRQ
  dhd_destroy_lock(s_irqlock);
  #endif
}

/*----------------------------------------------------------------------------------------------------------*/
/* Check if waiting clients can be woken up.*/
/* Note: Called from inside IRQ*/
/**/
void dhd_gpu_bridge_sync(const dhd_gpu_device_data_t *a_device, dhd_uint32_t a_jobsync) {
  dhd_int32_t i, cnt;
#if defined(WIN32)
  static dhd_gpu_call_data_t dhd_gpu_call_data;
#endif /*WIN32*/
  #ifdef DHD_KERNEL_SOFT_IRQ
  dhd_enter_lock(s_irqlock);
  #endif
  cnt = (dhd_int32_t) s_waitercount;
#if !defined(WIN32)
  /* Job scheduling is deferred for prioritization purposes.*/
  /* Need to call schedule job as ringbuffer could be empty now.*/
  dhd_gpu_schedule_job((dhd_gpu_device_data_t *)a_device);
#else /*WIN32*/
  dhd_gpu_call_data.m_schedule_job_trigger.m_device = a_device;
  dhd_gpu_trigger(0, E_DHD_CALL_SCHEDULE_JOB_TRIGGER, &dhd_gpu_call_data);
#endif /*WIN32*/

  /* Termination of loop is ensured by decreasing cnt when decreasing i.
   * i.e. i+=0 and cnt-=1 => the loop will always meet its termination condition
   */
  for (i=0; i<cnt; i++) {
    if ( s_waiters[i].m_client == a_device ) {  
      /* relevant entries*/
      dhd_uint32_t syncid;

      syncid = dhd_gpu_syncid_from_jobid( s_waiters[i].m_jobid );
//      if ((dhd_gpu_generation_from_jobid(s_waiters[i].m_jobid) != s_waiters[i].m_jobgen) ||      /* job is finished (generation mismatch) */
//        ((syncid != DHD_NOT_ASSIGNED) && (! DHD_LESS_WRAPAROUND(a_jobsync, syncid)))) {          /* job is finished (schedule order reached)*/
		    if ((dhd_gpu_generation_from_jobid(s_waiters[i].m_jobid) != s_waiters[i].m_jobgen) ||      /* job is finished (generation mismatch) */
          ((syncid != DHD_NOT_ASSIGNED) )) { 
        /* requested job has finished. wake caller and remove its entry (by swapping with tail)*/
        dhd_gpu_bridge_wakeup( s_waiters[i].m_token );
        #ifdef DHD_KERNEL_DEBUG_TRACEVCD
        TraceVcd_AddEvent("Wakeup", syncid);
        #endif
        s_waiters[i] = s_waiters[ cnt-1 ];
        cnt--;
        /* PRQA S 2469 2 *//* $Misra: loop control variable is intentionally modified because the number of elements changed during iteration $*/
        i--; /* need to reiterate on this slot as its content changed due to the removal*/
      }
    }
  }

  s_waitercount = (dhd_uint32_t) cnt;  
  #ifdef DHD_KERNEL_SOFT_IRQ
  dhd_exit_lock(s_irqlock);
  #endif
}
