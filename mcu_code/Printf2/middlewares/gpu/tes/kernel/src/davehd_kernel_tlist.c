/**/
dhd_enum_t dhd_gpu_tlist_alloc(dhd_tlist_t *a_tlist, dhd_uint32_t a_size, dhd_uint32_t a_tag, 
                               dhd_memory_usage_t a_usage,const dhd_vidmem_t *a_result) {
  const dhd_char_t *desc;

  /* decode usage*/
  switch (a_usage) {
    case E_DHD_MEMORY_GENERIC: desc = "generic"; break;
    case E_DHD_MEMORY_STREAM:  desc = "stream"; break;
    case E_DHD_MEMORY_TEXTURE: desc = "texture"; break;
    case E_DHD_MEMORY_TARGET:  desc = "target"; break;
    default:                   desc = "unknown"; break;
  }

  /* output annotated allocation command*/
  dhd_gpu_tlist_printf(a_tlist, "CMD_MEMALLOC 0x%08x 0x%08x          # %s buffer (tag 0x%x)\n", a_result->m_gpu_address, a_size, desc, a_tag);

  return E_DHD_OK;
}

