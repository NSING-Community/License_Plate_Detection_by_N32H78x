dhd_enum_t dhd_gpu_tlist_enable_internal(dhd_tlist_t *a_tlist, const dhd_char_t *a_file) {
  if (a_file == 0) {
    /* disable tlist logging*/
    return dhd_gpu_tlist_stop(a_tlist);    
  } else {
    /* enable tlist logging*/
    return dhd_gpu_tlist_start(a_tlist, a_file);    
  }
}

