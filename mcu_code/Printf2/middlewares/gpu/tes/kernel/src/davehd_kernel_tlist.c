/* when a_closure is non-zero the last dword will be replaced by a_closure in the memorydump (real memory*/
/* is not affected, only the dump output will be changed)*/
/* */
dhd_enum_t dhd_gpu_tlist_upload(dhd_tlist_t *a_tlist, const dhd_uint8_t *a_src, dhd_gpu_ptr_t a_dest, dhd_uint32_t a_size, dhd_uint32_t a_closure) {
  const dhd_uint32_t epl = 12; /* elements per line */
  dhd_uint32_t i, closure;    

  if ((0 != a_tlist->m_tlist_data) && (a_size > 0)) {
    dhd_uint32_t *src = (dhd_uint32_t *) a_src;
    dhd_uint32_t  aligned_size = (a_size+3)/4;
    dhd_gpu_tlist_printf(a_tlist, "CMD_MEMCPY 0x%08x 0x%08x\n", a_dest, aligned_size*4);        
    /* output all but the last dword*/
    for (i=1; i <= aligned_size - 1; i++) {
      dhd_gpu_tlist_printf(a_tlist, "0x%08x%c", *src, ((i%epl)==0)?'\n':' ' );   
      src++;
    }
    /* output final dword*/
    if (a_closure != 0) {
      closure = a_closure;
      src = &closure;
    }
    dhd_gpu_tlist_printf(a_tlist, "0x%08x\n", *src);
  }

  return E_DHD_OK;
}

