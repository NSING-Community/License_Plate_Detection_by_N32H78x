/**/
dhd_enum_t dhd_gpu_tlist_execute(dhd_tlist_t *a_tlist, dhd_gpu_ptr_t a_address, dhd_uint32_t a_size, dhd_uint32_t a_jobid ) {
  dhd_gpu_ptr_t end_address = DHD_INC_PTR( a_address, (a_size - sizeof(dhd_uint32_t)) + 4 );  /* + patched stream-end command*/
  dhd_reg_stc_control_t stc_control;
  dhd_reg_stc_interrupt_status_t stc_irq_status;

  /* enable stop IRQ (+ MBI error IRQ to get stopped when we have a bus error)*/
  stc_control.m_value = 0;
  stc_control.m_fields.m_stop_irq_enable = 1;
  stc_control.m_fields.m_mbierror_irq_enable = 1;
  
  /* expect stop IRQ + pause IRQ (we always pause at the stream end)*/
  stc_irq_status.m_value = 0;
  stc_irq_status.m_fields.m_stop_irq = 1;
  stc_irq_status.m_fields.m_pause_irq = 1;

  dhd_gpu_tlist_printf(a_tlist, "CMD_WRITE 0x%08x 0x%08x             # stack level 0 end address\n"
                                 "CMD_WRITE 0x%08x 0x%08x             # stack level 0 ret address\n"
                                 "CMD_WRITE 0x%08x 0x%08x             # pause address\n"   /* to hold STR at this address even if new end address is set*/
                                 "CMD_WRITE 0x%08x 0x%08x             # enable IRQ\n"
                                 "CMD_WAIT_INT_MASK 0x4                       # expect special IRQ\n"
                                 "CMD_WRITE 0x%08x 0x%08x             # running job %d\n"
                                 "CMD_WAIT_INT\n"
                                 "CMD_ASSERT 0x%08x 0x%08x 0xffffffff # confirm correct IRQ was triggered\n"
                                 "CMD_WRITE 0x%08x 0x%08x             # clear IRQ\n",
                                 DHD_REG_STC_CALL_STACK_ENTRY_0, end_address, 
                                 DHD_REG_STC_CALL_STACK_ENTRY_0+1, a_address, 
                                 DHD_REG_STC_RING_PAUSE_ADDRESS, end_address,
                                 DHD_REG_STC_CONTROL, stc_control.m_value,
                                 DHD_REG_STC_STREAM_ADDRESS, a_address, a_jobid,
                                 DHD_REG_STC_INTERRUPT_STATUS, stc_irq_status.m_value,
                                 DHD_REG_STC_INTERRUPT_CLEAR, stc_irq_status.m_value
                                 );

  return E_DHD_OK;
}

