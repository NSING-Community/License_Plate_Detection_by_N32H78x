/* Assumes that start of a_memory already fullfills a_align requirements.*/
/**/
dhd_gpu_pool_t *dhd_internal_create_kpool(void *a_memory, dhd_uint32_t  a_size, dhd_uint32_t a_nodesize, dhd_size_t a_align) {
  dhd_gpu_pool_t *pool = (dhd_gpu_pool_t *) a_memory;
  dhd_gpu_pool_freeblock_t *block;  
  dhd_uint32_t headsize = sizeof(dhd_gpu_pool_t);
  dhd_uint32_t padding, nodesize;

  /* alignment must be power of two and non zero (256 at most)*/
  if (a_align < 1) {
    a_align = 1;
  } else { 
    a_align -= 1;
    a_align |= a_align >> 1;
    a_align |= a_align >> 2;
    a_align |= a_align >> 4;
    a_align += 1;
  }

  /* ensure nodesize is large enough*/
  a_nodesize += sizeof(dhd_gpu_pool_usedblock_t);
  if (a_nodesize < sizeof(dhd_gpu_pool_freeblock_t)) {
    a_nodesize = sizeof(dhd_gpu_pool_freeblock_t);
  }
  /* align nodesize and headersize (header must padded to ensure blocks are aligned *after* their usedblock header)*/
  nodesize = (a_nodesize + (a_align - 1)) & ~(a_align - 1);  
  padding  = nodesize - a_nodesize;      
  headsize = (headsize + sizeof(dhd_gpu_pool_usedblock_t) + (a_align - 1)) & ~(a_align - 1);
  headsize -= sizeof(dhd_gpu_pool_usedblock_t) ; /* make the real user data aligned, instead of the metadata*/

  /* validate memory is large enough for at least 1 element*/
  if (a_size < (headsize + nodesize)) {
    return 0;
  }

  /* setup pool*/
  block = (dhd_gpu_pool_freeblock_t *) DHD_INC_PTR( pool, headsize );
  pool->m_nodesize = nodesize;
  pool->m_totalsize = a_size;
  pool->m_firstfree = block; 
  
  /* prelink all free blocks*/
  a_size -= headsize + nodesize;
  while (a_size >= nodesize) {        
    dhd_gpu_pool_freeblock_t *next = (dhd_gpu_pool_freeblock_t *) DHD_INC_PTR( block, nodesize );
    block->m_next = next;
    block = next;
    a_size -= nodesize;
  }
  block->m_next = 0;

  return pool;
}

/*----------------------------------------------------------------------------------------------------------*/
/**/
void *dhd_internal_alloc_kpool(dhd_gpu_pool_t *a_pool) {
  dhd_gpu_pool_freeblock_t *block = a_pool->m_firstfree;
  
  if (block) {
    dhd_gpu_pool_usedblock_t *used = (dhd_gpu_pool_usedblock_t *) block;
    a_pool->m_firstfree = block->m_next;
    used->m_pool = a_pool;
    block = (dhd_gpu_pool_freeblock_t *) DHD_INC_PTR(block, sizeof(dhd_gpu_pool_usedblock_t));
  }
  return block;
}

/*----------------------------------------------------------------------------------------------------------*/
/**/
void dhd_internal_free_kpool( void *a_memory ) {   

 if (a_memory) {
   dhd_gpu_pool_usedblock_t *used  = (dhd_gpu_pool_usedblock_t *) DHD_INC_PTR(a_memory, - (dhd_int32_t) sizeof(dhd_gpu_pool_usedblock_t));
   dhd_gpu_pool_freeblock_t *block = (dhd_gpu_pool_freeblock_t *) used; 
   dhd_gpu_pool_t *pool = used->m_pool;

   block->m_next = pool->m_firstfree;
   pool->m_firstfree = block;
 }
}

