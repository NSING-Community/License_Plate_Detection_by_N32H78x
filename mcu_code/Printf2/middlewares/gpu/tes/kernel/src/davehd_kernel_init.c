const dhd_uint32_t *dhd_gpu_get_group_defaults(dhd_uint32_t a_group) {
  dhd_uint32_t pos, i;

  if ((a_group < 2) || (a_group > 15)) {
    return 0; /* unknwon group index*/
  }
  pos = 0;  
  for (i=2; i<a_group; i++) {
    /* todo: add a switch/case here to let the compiler solve DHD_REGFILE_GROUP_SIZE at compiletime*/
    pos += DHD_REGFILE_GROUP_SIZE(i); /* PRQA S 3391, 3396 *//* $Misra: No possibility to fix because macro is defined in generated code. $*/
  }

  return &dhd_reset_state[pos];
}

