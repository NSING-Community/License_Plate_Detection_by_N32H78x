/**/
dhd_enum_t dhd_gpu_hardware_shutdown(dhd_gpu_device_data_t *a_device) {
  void *base_address = a_device->m_gpu_config.m_register_base_address;
  dhd_reg_stc_control_t ctrl;
  dhd_stc_opcode_t end;
  dhd_enum_t result;
  dhd_enum_t final_result = E_DHD_OK;  /* use a 'final' result, as we won't break, even when we get an error in between*/

  /* add an end to ring to shut it down properly, if core is still running (todo: use a 'halt' here to force shutdown)*/
  if (a_device->m_status == E_DHD_STATUS_ACTIVE) {
    end.m_fields.m_opcode = DHD_STCOP_END;
    end.m_fields.m_data_following = 0;
    end.m_fields.m_data_count = 0;
    end.m_fields.m_arguments = 0x3ff;
    final_result = dhd_gpu_write_to_ring(a_device, &end.m_value, 1);
  }

  /* make sure the hw is not running anymore*/
  result = dhd_gpu_wait_for_hw_status( a_device, E_DHD_STATUS_IDLE );
  if (final_result == E_DHD_OK) {
    final_result = result;
  }

  /* remove and disable irq's*/
  ctrl.m_value = a_device->m_stc_control;
  ctrl.m_fields.m_mbierror_irq_enable = 0;
  ctrl.m_fields.m_pause_irq_enable = 0;
  ctrl.m_fields.m_sync_irq_enable = 0;
  ctrl.m_fields.m_stop_irq_enable = 0;
  ctrl.m_fields.m_stall_irq_enable = 0;
  a_device->m_stc_control = ctrl.m_value;
  dhd_gpu_write_reg(base_address, DHD_REG_STC_CONTROL, ctrl.m_value);
  dhd_gpu_setup_irq( a_device, 0 );

  return final_result;
}

